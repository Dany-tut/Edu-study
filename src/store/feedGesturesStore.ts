// ─────────────────────────────────────────────────────────────────────────────
// Настройки ленты: жесты вместо кнопок.
//
// ПОЧЕМУ ЖЕСТ, А НЕ ЗНАЧОК. Строка действий под постом — четыре мишени по 30px
// в самой нижней трети экрана, и на телефоне до них ещё надо дотянуться
// большим пальцем, оторвав его от текста. Лайк — самое частое действие в
// ленте и самое дешёвое по смыслу; ему незачем занимать место под каждым
// постом. Свайп по карточке доступен в любой её точке, не требует прицела и
// не отнимает у поста ни пикселя.
//
// НО НАЗНАЧЕНИЕ — ЛИЧНОЕ ДЕЛО. У одного «влево» значит лайк, у другого палец
// левый и удобнее наоборот, третьему лайки не нужны вовсе, а нужен перевод в
// одно движение. Поэтому здесь не жёсткая раскладка, а карта «жест → действие»,
// которую человек собирает сам (экран — components/FeedGesturesSheet.tsx).
//
// ЖИВЁТ НА УСТРОЙСТВЕ, А НЕ В БАЗЕ: это настройка руки, а не учётной записи.
// На телефоне и на планшете она у одного и того же человека разная, и тащить
// её через аккаунт значило бы навязывать телефонную раскладку планшету.
// ─────────────────────────────────────────────────────────────────────────────

import { create } from 'zustand'
import { persist, createJSONStorage } from 'zustand/middleware'

/** Что жест делает с постом. `none` — жест выключен, карточка не поедет. */
export type FeedAction = 'none' | 'like' | 'comment' | 'translate' | 'listen'

/**
 * Чем это делают.
 *
 * НАЗВАНИЯ ПО НАПРАВЛЕНИЮ ПАЛЬЦА, А НЕ ПО КРАЮ ЭКРАНА: «swipeLeft» — палец
 * ведёт влево, значок при этом проявляется справа, из-под уезжающей карточки.
 * Обратный порядок («свайп от правого края») читается двусмысленно ровно до
 * первой попытки, а макет в настройках показывает направление наглядно.
 */
export type FeedGesture = 'swipeLeft' | 'swipeRight' | 'doubleTap' | 'longPress' | 'tap'

export interface FeedGesturesState {
  /** Показывать под постом строку с сердцем, репликами и числами. */
  engagement: boolean
  /** Жесты по карточке вообще. Выключены — пост ведёт себя как обычный текст. */
  gestures: boolean
  /** Звук и отдача в палец на жесте. */
  sound: boolean
  map: Record<FeedGesture, FeedAction>

  setAction: (g: FeedGesture, a: FeedAction) => void
  setFlag: (k: 'engagement' | 'gestures' | 'sound', v: boolean) => void
  reset: () => void
}

/**
 * Раскладка по умолчанию.
 *
 * Лайк на «влево» — под большой палец правой руки, самое лёгкое движение из
 * всех. Комментарий стоит сразу на трёх жестах (вправо, долгое нажатие, тап по
 * телу): это единственное действие, ради которого пост открывают, и человек
 * должен наткнуться на него, даже не читав никаких настроек. Двойной тап —
 * пустой: пока он ничего не значит, одиночный тап срабатывает СРАЗУ, без
 * ожидания второго (см. lib/useFeedGestures.ts).
 */
export const DEFAULT_MAP: Record<FeedGesture, FeedAction> = {
  swipeLeft: 'like',
  swipeRight: 'comment',
  doubleTap: 'none',
  longPress: 'comment',
  tap: 'comment',
}

export const useFeedGestures = create<FeedGesturesState>()(persist((set, get) => ({
  // Строка действий на телефоне выключена по умолчанию — ради неё всё и
  // затевалось. На настольной раскладке жестов нет, и там она стоит всегда
  // (см. lib/useFeedGestures.ts, touchDevice).
  engagement: false,
  gestures: true,
  sound: true,
  map: { ...DEFAULT_MAP },

  setAction: (g, a) => set({ map: { ...get().map, [g]: a } }),
  setFlag: (k, v) => set({ [k]: v } as Partial<FeedGesturesState>),
  reset: () => set({ engagement: false, gestures: true, sound: true, map: { ...DEFAULT_MAP } }),
}), {
  name: 'feed-gestures',
  storage: createJSONStorage(() => localStorage),
  version: 1,
  // Карта сливается с умолчаниями, а не подменяет их: добавится новый жест —
  // у тех, кто сохранил старую карту, он окажется не `undefined`, а своим
  // значением по умолчанию.
  merge: (saved, current) => {
    const s = (saved ?? {}) as Partial<FeedGesturesState>
    return { ...current, ...s, map: { ...DEFAULT_MAP, ...(s.map ?? {}) } }
  },
}))
