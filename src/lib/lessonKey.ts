// ─────────────────────────────────────────────────────────────────────────────
// Название урока: номер отдельно, тема отдельно
//
// ЗАЧЕМ. Номер в названии урока ставит не автор, а курс: он сквозной и съезжает,
// когда в середину вставляют юнит. Поэтому везде, где урок надо УЗНАТЬ (сверка с
// сидом, добор конспекта) или ПЕРЕНУМЕРОВАТЬ, работают не с сырым названием, а с
// его телом — темой без номера.
//
// ОТКУДА «1. 1 Хангыль». Тело раньше добывалось одним `replace(/^\d+\.\s*/)`, а
// у занятий-порций номер двойной: сид писал «1.2 Хангыль» (юнит и порция).
// Отрезалось только «1.», оставалось «2 Хангыль», сверка приписывала сквозной
// номер — и в списке выходило «7. 2 Хангыль: проверка перед стартом». Два числа
// подряд читаются как опечатка, а второе ещё и не совпадает с первым.
//
// РЕШЕНИЕ. У порции есть словесная запись — «Тема · часть 2», — и любая из трёх
// исторических форм приводится к ней. Одна функция и на показ, и на сверку:
// ключ совпадения — то же тело, что видно в списке, поэтому переименование
// старых курсов не выглядит для сверки как «132 урока пропали, 132 новых».
// ─────────────────────────────────────────────────────────────────────────────

/** Сквозной номер курса в начале названия: «7. », «7) ». */
const LEAD_NUMBER = /^\d+[.)]\s*/
/** Старая запись сида: «1.2 Тема» — номер юнита и номер порции. */
const DOTTED = /^(\d+)\.(\d+)\s+(.+)$/
/**
 * Осколок той же записи после снятия «1.»: «2 Тема».
 *
 * Отличить его от честной цифры в названии учителя («5 минут разговора») по
 * одной строке нельзя, и угадывать здесь незачем: ключ у чужого урока всё
 * равно ни с чем не сойдётся, а переписывать название чужому уроку никто и не
 * должен — за это отвечает вызывающая сторона (см. plainTitle и seedSync).
 */
const LEGACY_PART = /^([1-9])\s+(.+)$/
/** Нынешняя запись: «Тема · часть 2». */
const PART_SUFFIX = /^(.*?)\s+·\s+часть\s+(\d+)$/

/**
 * Тело названия: тема без сквозного номера, порция — словом.
 *
 * «7. 2 Правила чтения» → «Правила чтения · часть 2»
 * «2.1 Правила чтения»  → «Правила чтения · часть 1»
 * «7. Правила чтения»   → «Правила чтения»
 *
 * Пустое название остаётся пустым: это урок без темы, а не урок «часть 0».
 */
export function lessonBody(raw: string): string {
  let text = (raw ?? '').trim()
  let part = ''

  const dotted = DOTTED.exec(text)
  if (dotted) {
    part = dotted[2]
    text = dotted[3]
  } else {
    text = text.replace(LEAD_NUMBER, '')
    const legacy = LEGACY_PART.exec(text)
    if (legacy) {
      part = legacy[1]
      text = legacy[2]
    }
  }

  const suffixed = PART_SUFFIX.exec(text)
  if (suffixed) {
    text = suffixed[1]
    part = suffixed[2]
  }

  text = text.trim()
  return part && text ? `${text} · часть ${part}` : text
}

/**
 * Название без сквозного номера и БЕЗ разбора порции — как написано.
 *
 * Для уроков, которых сид не клал: цифра в начале там может быть частью
 * названия, и трогать её нельзя.
 */
export function plainTitle(raw: string): string {
  return (raw ?? '').trim().replace(LEAD_NUMBER, '').trim()
}

/** Название с номером: то, что видит ученик в списке уроков. */
export function numberedTitle(raw: string, index: number): string {
  const body = lessonBody(raw)
  return body ? `${index}. ${body}` : `${index}.`
}

/** То же, но тело задаётся отдельно (сверка сама решает, чьё это название). */
export function withNumber(body: string, index: number): string {
  return body ? `${index}. ${body}` : `${index}.`
}
