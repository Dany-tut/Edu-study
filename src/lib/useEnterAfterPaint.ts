import { useEffect, useState } from 'react'

// ─────────────────────────────────────────────────────────────────────────────
// ВХОД НАЧИНАЕТСЯ С ПЕРВОГО НАРИСОВАННОГО КАДРА, А НЕ С МОНТИРОВАНИЯ.
//
// Замер на симуляторе (запись экрана, 60 к/с): от касания по вкладке до первого
// кадра нового экрана проходит 130–580 мс — столько стоит сборка экрана. Часы
// анимации у framer идут всё это время, поэтому к первому же кадру пружина уже
// отработала: на записи вход виден одним полупрозрачным кадром, а то и вовсе не
// виден. Экраны потяжелее теряли его целиком — «вход одинаковый» держался в
// коде, но не на экране.
//
// Двойной rAF — это «после первой отрисовки»: первый кадр отдаём под саму
// отрисовку, на втором отпускаем анимацию, и она играет целиком у всех вкладок
// одинаково, независимо от того, сколько собирался экран.
//
// Таймер — страховка: в неактивной вкладке (и в headless-браузере превью) rAF
// не тикает вовсе, и без него шапка осталась бы прозрачной навсегда.
// ─────────────────────────────────────────────────────────────────────────────

export function useEnterAfterPaint(): boolean {
  const [ready, setReady] = useState(false)
  useEffect(() => {
    let inner = 0
    const outer = requestAnimationFrame(() => {
      inner = requestAnimationFrame(() => setReady(true))
    })
    const fallback = window.setTimeout(() => setReady(true), 400)
    return () => {
      cancelAnimationFrame(outer)
      cancelAnimationFrame(inner)
      window.clearTimeout(fallback)
    }
  }, [])
  return ready
}
