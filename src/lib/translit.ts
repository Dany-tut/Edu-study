/** Катакана → хирагана: ряды идут параллельно, разница ровно 0x60. */
function toHiragana(ch: string): string {
  const c = ch.charCodeAt(0)
  return c >= 0x30a1 && c <= 0x30f6 ? String.fromCharCode(c - 0x60) : ch
}

function jaTranslit(text: string): string {
  const src = [...text].map(toHiragana).join('')
  let out = ''
  let i = 0
  while (i < src.length) {
    const pair = src.slice(i, i + 2)
    if (JA_DIGRAPH[pair]) { out += JA_DIGRAPH[pair]; i += 2; continue }
    const ch = src[i]
    // っ удваивает следующий согласный: きって → «китте».
    if (ch === 'っ') {
      const next = JA_DIGRAPH[src.slice(i + 1, i + 3)] ?? JA_KANA[src[i + 1]] ?? ''
      if (next) out += next[0]
      i += 1
      continue
    }
    // ー тянет предыдущий гласный: ラーメン → «раамэн».
    if (ch === 'ー') {
      if (out) out += out[out.length - 1]
      i += 1
      continue
    }
    out += JA_KANA[ch] ?? ch
    i += 1
  }
  return out
}

/**
 * Транскрипция слова русскими буквами. Пустая строка означает «для этого языка
 * (или этого текста) транскрипции нет» — например, латиница или голые цифры.
 */
export function transcribe(text: string, lang: string): string {
  if (lang === 'ko') {
    let has = false
    let out = ''
    // Слоги копятся в слово и разбираются вместе: и озвончение, и переезд
    // патчхима смотрят на соседа, поэтому посимвольно их не посчитать. Пробел и
    // знак препинания слово закрывают — через них ничего не переносится.
    let word: number[] = []
    const flush = () => { if (word.length) { out += koWord(word); word = [] } }
    for (const ch of text) {
      const c = ch.charCodeAt(0)
      if (c >= KO_START && c <= KO_END) { word.push(c); has = true; continue }
      flush()
      out += ch
    }
    flush()
    return has ? out : ''
  }
  if (lang === 'ja') {
    const out = jaTranslit(text)
    // Если ничего не поменялось, значит это были не кана и не катакана —
    // транскрибировать нечего (иероглифы без чтения мы не угадываем).
    return out !== text ? out : ''
  }
  return ''
}
