// ─────────────────────────────────────────────────────────────────────────────
// Транскрипция: как звучит слово, записанное чужим письмом
//
// ЗАЧЕМ. Перевод отвечает «что это значит», но не отвечает «как это сказать».
// Ученик первой недели видит 신어야 해요 и не может даже проговорить это про
// себя — а непроговариваемое слово не запоминается. Поэтому в подсказке под
// словом идёт русская запись звучания.
//
// ПОЧЕМУ КИРИЛЛИЦА, А НЕ ЛАТИНИЦА. Латинская романизация (sineoya haeyo) сама
// требует объяснения: eo — это «о», ae — «э». Русскому читателю она добавляет
// ещё один шаг расшифровки вместо того, чтобы его убрать.
//
// ПОЧЕМУ СЧИТАЕМ, А НЕ ПИШЕМ РУКАМИ. Хангыль и кана — слоговые письменности с
// однозначным разбором: слог хангыля раскладывается арифметикой по коду
// символа, кана переводится таблицей. Руками это писать значило бы завести
// шестьсот мест, где можно опечататься.
//
// ЧЕГО ЭТА ТРАНСКРИПЦИЯ НЕ ДЕЛАЕТ. Она послоговая и не учитывает ассимиляций на
// стыках (신라 звучит «силла», а здесь получится «синра»). Это осознанный
// размен: точная запись живой речи требует полного разбора фонетики, а
// эталоном произношения всё равно служит озвучка рядом — кнопка динамика в той
// же подсказке. Транскрипция здесь нужна, чтобы слово можно было проговорить и
// удержать в памяти, а не чтобы заменить слух.
//
// Английский и португальский сюда не входят: латиница читается сама, а честная
// транскрипция для них выводится не из букв, а из словаря — её при
// необходимости пишут руками в поле `reading` (см. data/wordGloss.ts).
// ─────────────────────────────────────────────────────────────────────────────

// ─── Корейский ───────────────────────────────────────────────────────────────

const KO_START = 0xac00
const KO_END = 0xd7a3

/**
 * Начальные согласные, в порядке кодировки.
 *
 * ㄱ ㄷ ㅂ ㅈ звучат глухо в начале слова и звонко между гласными: 감사 —
 * «камса», но 아기 — «аги». Поэтому у них два варианта, и выбор делается по
 * предыдущему слогу (см. koVoiced).
 */
const KO_INITIAL = [
  'к', 'кк', 'н', 'т', 'тт', 'р', 'м', 'п', 'пп', 'с', 'сс', '',
  'ч', 'чч', 'чх', 'кх', 'тх', 'пх', 'х',
]

/** Звонкие пары для позиции между гласными: индекс начального → замена. */
const KO_VOICED: Record<number, string> = { 0: 'г', 3: 'д', 7: 'б', 12: 'дж' }

/** Патчхимы, после которых следующий согласный озвончается (плюс «нет патчхима»). */
const KO_SONORANT = new Set([0, 4, 8, 16, 21])

/**
 * Патчхим, переехавший в следующий слог.
 *
 * Если слог начинается с ㅇ (немой согласный), конечная согласная предыдущего
 * слога произносится уже как начальная следующего: 있어요 — не «ит-о-ё», а
 * «и-ссо-ё», 들어 — «тыро», 음식은 — «ымсигын». Это самое частое явление
 * корейской фонетики, и без него транскрипция расходится со слухом на каждом
 * втором слове.
 */
const KO_LIAISON: Record<number, string> = {
  1: 'г', 2: 'кк', 3: 'кс', 4: 'н', 5: 'ндж', 6: 'н', 7: 'д', 8: 'р',
  9: 'льг', 10: 'льм', 11: 'льб', 12: 'льс', 13: 'льтх', 14: 'льпх', 15: 'р',
  16: 'м', 17: 'б', 18: 'пс', 19: 'с', 20: 'сс', 22: 'дж', 23: 'чх',
  24: 'кх', 25: 'тх', 26: 'пх', 27: '',
}

/** Индекс немого начального ㅇ — с него начинается слог «без согласной». */
const KO_SILENT = 11

/** Гласные (включая дифтонги), в порядке кодировки. */
const KO_VOWEL = [
  'а', 'э', 'я', 'йэ', 'о', 'е', 'ё', 'йе', 'о', 'ва', 'вэ', 'ве', 'ё',
  'у', 'во', 'ве', 'ви', 'ю', 'ы', 'ый', 'и',
]

/** Конечные согласные (патчхим); первый элемент — «нет патчхима». */
const KO_FINAL = [
  '', 'к', 'к', 'к', 'н', 'н', 'н', 'т', 'ль', 'к', 'м', 'ль', 'ль', 'ль',
  'п', 'ль', 'м', 'п', 'п', 'т', 'т', 'н', 'т', 'т', 'к', 'т', 'п', 'т',
]

/** Разбор слога хангыля: начальный, гласный, патчхим. */
function koParts(code: number) {
  const n = code - KO_START
  return {
    initial: Math.floor(n / (21 * 28)),
    vowel: Math.floor((n % (21 * 28)) / 28),
    final: n % 28,
  }
}

/** Переезжает ли патчхим слога `a` в начало слога `b`. */
const linksTo = (a: ReturnType<typeof koParts> | null, b: ReturnType<typeof koParts> | null) =>
  !!a && !!b && b.initial === KO_SILENT && a.final !== 0 && a.final !== 21

/** Индексы начальных ㄴ, ㄹ, ㅁ — согласных, из-за которых стык меняет звук. */
const KO_N = 2
const KO_R = 5
const KO_M = 6

/** Смычный патчхим перед носовым: 습니다 звучит «сымнида», не «сыпнида». */
const KO_NASALIZED: Record<string, string> = { к: 'н', т: 'н', п: 'м' }

/**
 * Стык двух слогов: что на нём слышно вместо написанного.
 *
 * Два правила, без которых транскрипция расходится со слухом на самых частых
 * словах, — и оба живут ровно на границе, поэтому считаются парой, а не внутри
 * слога:
 *
 *  • носовое уподобление: смычный патчхим перед ㄴ/ㅁ сам становится носовым —
 *    합니다 «хамнида», 먹는 «монын». Под это попадает окончание ‑ㅂ니다, то есть
 *    каждая вежливая форма языка;
 *  • ㄹ на стыке: после ㅁ/ㅇ он звучит как ㄴ (음료수 «ымнёсу»), а рядом с ㄴ или
 *    ㄹ даёт долгое «лл» (신라 «силла», 설립 «соллип»). После смычного сначала
 *    работает первое правило, потом второе: 독립 «тонним».
 *
 * Возвращает замену патчхима предыдущего слога и начального согласного
 * текущего; null — «оставить как есть».
 */
function koJoin(prevFinal: number, initial: number): { coda: string | null; onset: string | null } {
  let coda = KO_FINAL[prevFinal]
  if (!coda) return { coda: null, onset: null }
  let changed: string | null = null
  if (initial === KO_N || initial === KO_M || initial === KO_R) {
    const nasal = KO_NASALIZED[coda]
    if (nasal) { coda = nasal; changed = nasal }
  }
  if (initial !== KO_R) return { coda: changed, onset: null }
  // ㄴ (патчхим 4) и ㄹ (патчхим 8) дают долгое «лл» — без мягкого знака внутри
  // пары, иначе выходит «сильла» вместо «силла».
  if (prevFinal === 4 || coda === 'ль') return { coda: 'л', onset: 'л' }
  if (coda === 'м' || coda === 'н') return { coda: changed, onset: 'н' }
  return { coda: changed, onset: null }
}

/** Одно слово хангыля: слоги разбираются с оглядкой на соседей. */
function koWord(codes: number[]): string {
  const parts = codes.map(koParts)
  let out = ''
  for (let i = 0; i < parts.length; i++) {
    const cur = parts[i]
    const prev = i > 0 ? parts[i - 1] : null
    const next = i + 1 < parts.length ? parts[i + 1] : null

    let onset: string
    if (linksTo(prev, cur)) {
      onset = KO_LIAISON[prev!.final] ?? ''
    } else {
      // Озвончение — только внутри слова и только после гласной или сонорного
      // патчхима: 학교 остаётся «хаккё», а 아기 становится «аги».
      const open = prev !== null && KO_SONORANT.has(prev.final)
      onset = (open && KO_VOICED[cur.initial]) || KO_INITIAL[cur.initial]
      if (prev) onset = koJoin(prev.final, cur.initial).onset ?? onset
    }
    // Патчхим не пишем дважды: если он уехал в следующий слог, здесь его нет.
    let coda = ''
    if (!linksTo(cur, next)) {
      coda = KO_FINAL[cur.final]
      if (next) coda = koJoin(cur.final, next.initial).coda ?? coda
    }
    out += onset + KO_VOWEL[cur.vowel] + coda
  }
  return out
}

// ─── Японский ────────────────────────────────────────────────────────────────
//
// Таблица ведётся по хирагане; катакана переводится в хирагану сдвигом кода
// (они лежат в Unicode параллельными рядами), поэтому リナ и りな дают одно и
// то же чтение. Система записи — киридзи (поливановская): し «си», ち «ти»,
// つ «цу», じ «дзи».

