// ─────────────────────────────────────────────────────────────────────────────
// Сверка перевода: одно значение — много формулировок
//
// ЗАЧЕМ. Словарная карточка сверялась строкой в строку: `normAnswer(ответ) ===
// normAnswer(эталон)`. Для перевода это неверная модель. «agency → агентство»
// ученик пишет «в агентстве», «to specialise in → специализироваться на» —
// «специализируюсь на», и машина ставит «Неверно» там, где слово усвоено:
// расходятся падеж, вид глагола и предлог, а не значение.
//
// ЧТО ЗДЕСЬ ДЕЛАЕТСЯ. Обе стороны раскладываются на смысловые слова, служебные
// (предлоги, частицы, английские артикли) отбрасываются, каждое слово режется
// до основы. Совпадение — это одинаковый НАБОР основ, порядок слов не важен.
// Так «в агентстве» = «агентство», «специализируюсь на» = «специализироваться
// на», «UX/UI-дизайнер» = «ux ui дизайнер».
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Мы не принимаем ответ, в котором смысловых слов
// меньше, чем в эталоне: иначе «дизайнер» закрывал бы и «продуктовый
// дизайнер», и «графический дизайнер», и «моушн-дизайнер» — вся тема сдавалась
// бы одним словом. Синонимы («моушн-дизайнер» = «анимационный дизайнер»)
// алгоритмом не выводятся: для них у слова есть список `alt` в сиде, он
// доезжает до задания полем `altAnswers`.
//
// ГДЕ ПРИМЕНЯЕТСЯ. Только там, где ученик переводит смысл: словарная карточка.
// Диктант, подстановка и дрилл сверяются по-прежнему строго — там как раз
// проверяется форма (worked ≠ work), и терпимость к окончаниям убила бы смысл
// задания.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Служебные слова. Выкидываются с ОБЕИХ сторон: разница «в агентстве» против
 * «агентство» — это разница управления, а не значения.
 */
const FUNCTION_WORDS = new Set([
  // предлоги
  'в', 'во', 'на', 'к', 'ко', 'с', 'со', 'у', 'о', 'об', 'обо', 'за', 'из', 'изо',
  'по', 'для', 'от', 'ото', 'до', 'при', 'над', 'под', 'про', 'без', 'через',
  // частицы и связки
  'же', 'бы', 'ли', 'это', 'быть',
  // английская служебка — карточка бывает и в обратную сторону
  'to', 'the', 'a', 'an',
])

/**
 * Окончания, которые срезаются при поиске основы. Порядок важен: список
 * перебирается сверху вниз, длинные раньше коротких.
 *
 * Это намеренно не морфологический анализатор: нам нужно свести формы одного
 * слова к общему началу, а не разобрать язык. Ошибка «срезали лишнее» тут
 * дешёвая — дальше основы всё равно сравниваются с допуском по началу слова.
 */
const ENDINGS = [
  'ившись', 'ыми', 'ими', 'ями', 'ами', 'ешь', 'ишь', 'ует', 'уют', 'ают', 'ять',
  'ать', 'ить', 'еть', 'уть', 'ыть', 'ого', 'его', 'ому', 'ему', 'ых', 'их', 'ов',
  'ев', 'ах', 'ях', 'ей', 'ой', 'ый', 'ий', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие',
  'ым', 'им', 'ом', 'ем', 'ую', 'юю', 'ла', 'ло', 'ли', 'ть', 'ет', 'ит', 'ут',
  'ют', 'ат', 'ят', 'ам', 'ям', 'ся', 'сь', 'ии',
  'а', 'я', 'о', 'е', 'и', 'ы', 'у', 'ю', 'ь', 'й', 'л',
]

/** Минимальная длина основы: короче — это уже не слово, а огрызок («мой» → «м»). */
const MIN_STEM = 3

/**
 * Приведение строки к сравнимому виду: регистр, ё, уточнение в скобках,
 * дефисы и слэши. «UX/UI-дизайнер» и «ux ui дизайнер» — одно и то же.
 */
function normalize(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\([^)]*\)/g, ' ')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
}

/** Смысловые слова строки. Если служебными оказались все — берём как есть. */
function contentWords(s: string): string[] {
  const all = normalize(s).split(' ').filter(Boolean)
  const kept = all.filter(w => !FUNCTION_WORDS.has(w))
  return kept.length > 0 ? kept : all
}

/** Основа слова: снимаем возвратность, затем одно окончание. */
function stem(word: string): string {
  let w = word
  if (w.length - 2 >= MIN_STEM + 1 && (w.endsWith('ся') || w.endsWith('сь'))) {
    w = w.slice(0, -2)
  }
  for (const end of ENDINGS) {
    if (w.length - end.length >= MIN_STEM && w.endsWith(end)) return w.slice(0, -end.length)
  }
  return w
}

/**
 * Одно ли это слово. Точное совпадение основ либо общее начало: формы вроде
 * «специализируюсь» / «специализироваться» после срезки окончания расходятся
 * на хвосте, но совпадают первыми двенадцатью буквами.
 *
 * Порог держит вместе формы одного слова и разводит однокоренные, но разные:
 * «красный» и «красивый» — 4 общие буквы, «дизайн» и «дизайнер» — 6 из 8.
 * Так далеко расходятся уже значения, а не окончания.
 */
function sameWord(a: string, b: string): boolean {
  if (a === b) return true
  let i = 0
  while (i < a.length && i < b.length && a[i] === b[i]) i++
  return i >= 5 && i >= 0.8 * Math.max(a.length, b.length)
}

/** Набор слов ответа совпал с набором слов эталона (порядок не важен). */
function sameWordSet(given: string[], want: string[]): boolean {
  if (given.length === 0 || given.length !== want.length) return false
  const left = want.map(stem)
  return given.map(stem).every(g => {
    const hit = left.findIndex(w => sameWord(g, w))
    if (hit < 0) return false
    left.splice(hit, 1)
    return true
  })
}

/**
 * Варианты эталона. Перевод часто пишется списком — «бэкграунд, предыдущий
 * опыт»: принимаем и строку целиком, и каждую её часть.
 */
function variants(expected: string): string[] {
  return [expected, ...expected.split(/[,;|]|\bили\b/)]
    .map(s => s.trim())
    .filter(Boolean)
}

/**
 * Совпал ли перевод. `alts` — принимаемые формулировки из задания
 * (`altAnswers`): синонимы, которые из эталона не выводятся.
 */
export function matchTranslation(given: string, expected: string | undefined, alts?: string[]): boolean {
  if (!given?.trim() || !expected?.trim()) return false
  const got = contentWords(given)
  if (got.length === 0) return false
  const targets = [...variants(expected), ...(alts ?? []).flatMap(variants)]
  return targets.some(t => sameWordSet(got, contentWords(t)))
}
