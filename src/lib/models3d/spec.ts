// ─────────────────────────────────────────────────────────────────────────────
// Описание 3D-модели для конспекта: что это за объект и из каких частей он
// состоит. Сцена (viewer.ts) не знает ни про атомы, ни про клетки — она
// умеет показать любой набор частей, развести их в стороны, показать одну
// отдельно и подписать. Так один вьюер обслуживает все предметы.
//
// Модуль не тянет three.js напрямую: сборщики частей получают его аргументом,
// чтобы спецификации и сцена попадали в один ленивый чанк, а в основном
// бандле не было ни байта геометрии.
// ─────────────────────────────────────────────────────────────────────────────
import type * as THREE from 'three'

export type ThreeNS = typeof THREE

export interface ModelPartSpec {
  id: string
  /** Подпись-ярлык на модели и в списке частей. */
  name: string
  /** Короткая справка — показывается в карточке при выборе части. */
  info: string
  /** Цвет метки части (CSS hex). Совпадает с цветом материала. */
  color: string
  /** Собрать объект части. Объект стоит в своих «собранных» координатах. */
  build: (T: ThreeNS) => THREE.Object3D
  /** Куда часть уезжает при разборе (мировые единицы при explode = 1). */
  explode?: [number, number, number]
  /** Точка подписи в локальных координатах объекта; по умолчанию — его центр. */
  anchor?: [number, number, number]
  /** Полупрозрачная оболочка: при разборе и изоляции прячется, а не уезжает. */
  shell?: boolean
  /** Не показывать ярлык на самой модели (для мелких рассыпанных частей). */
  hideLabel?: boolean
}

export interface ModelSpec {
  id: string
  title: string
  subtitle?: string
  /** Радиус описанной сферы собранной модели — по нему ставится камера. */
  radius: number
  parts: ModelPartSpec[]
  /** Есть ли смысл в кнопке «Разобрать». */
  canExplode: boolean
  /** Покадровая анимация (вращение электронов и т. п.); t — секунды. */
  animate?: (t: number, objects: Map<string, THREE.Object3D>) => void
  /**
   * Модель со стадиями (митоз, развитие зародыша): прогресс 0…1 непрерывно
   * переводит сцену от первой стадии к последней, стадия i стоит в точке
   * i / (n − 1). Блок показывает стадии кнопками и плеером.
   */
  timeline?: {
    stages: Array<{ name: string; info: string }>
    /** Секунд на полный проход при автопроигрывании. */
    duration: number
    update: (progress: number, objects: Map<string, THREE.Object3D>) => void
  }
}
