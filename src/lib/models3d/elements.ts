export const ELEMENTS: ElementInfo[] = RAW.map(([symbol, name, mass], i) => ({ z: i + 1, symbol, name, mass }))

/** Элемент по номеру или символу (`6`, `C`, `c`). */
export function findElement(key: string | number): ElementInfo | null {
  const s = String(key).trim()
  const z = Number(s)
  if (Number.isInteger(z)) return ELEMENTS[z - 1] ?? null
  const low = s.toLowerCase()
  return ELEMENTS.find(e => e.symbol.toLowerCase() === low) ?? null
}

/** Порядок заполнения подуровней: [n, ёмкость]. */
const AUFBAU: Array<[number, number]> = [
  [1, 2], [2, 2], [2, 6], [3, 2], [3, 6], [4, 2], [3, 10], [4, 6], [5, 2], [4, 10], [5, 6],
  [6, 2], [4, 14], [5, 10], [6, 6], [7, 2], [5, 14], [6, 10], [7, 6],
]

/** Реальные конфигурации там, где правило Клечковского ошибается. */
const SHELL_EXCEPTIONS: Record<number, number[]> = {
  24: [2, 8, 13, 1], 29: [2, 8, 18, 1], 41: [2, 8, 18, 12, 1], 42: [2, 8, 18, 13, 1],
  44: [2, 8, 18, 15, 1], 45: [2, 8, 18, 16, 1], 46: [2, 8, 18, 18], 47: [2, 8, 18, 18, 1],
}

/** Электроны по энергетическим уровням: углерод → [2, 4], железо → [2, 8, 14, 2]. */
export function electronShells(z: number): number[] {
  if (SHELL_EXCEPTIONS[z]) return SHELL_EXCEPTIONS[z]
  const shells: number[] = []
  let left = z
  for (const [n, cap] of AUFBAU) {
    if (left <= 0) break
    const take = Math.min(cap, left)
    shells[n - 1] = (shells[n - 1] ?? 0) + take
    left -= take
  }
  return shells.map(v => v ?? 0)
}

export const SHELL_LETTERS = ['K', 'L', 'M', 'N', 'O', 'P', 'Q']

/** Число нейтронов самого распространённого изотопа. */
export function neutronCount(el: ElementInfo): number {
  return Math.max(0, Math.round(el.mass) - el.z)
}

/** Номер группы (краткая форма) по внешнему уровню — для подписи. */
export function periodAndGroupNote(el: ElementInfo): string {
  const shells = electronShells(el.z)
  const outer = shells[shells.length - 1]
  const period = shells.length
  const noble = [2, 10, 18, 36, 54, 86].includes(el.z)
  if (noble) return `${period}-й период, внешний уровень завершён`
  return `${period}-й период, на внешнем уровне ${outer} ${plural(outer, 'электрон', 'электрона', 'электронов')}`
}

export function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10, m100 = n % 100
  if (m10 === 1 && m100 !== 11) return one
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few
  return many
}
