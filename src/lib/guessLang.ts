// ─────────────────────────────────────────────────────────────────────────────
// Язык пачки карточек — по написанию слов
//
// ЗАЧЕМ. Список слов приезжает в набор одной вставкой, и язык у набора при этом
// остаётся тем, что стоял в форме по умолчанию: корейские карточки лежат под
// подписью «Английский», пока кто-нибудь не заметит. Заметить некому — поле
// стоит в колонке справа и выглядит уже заполненным.
//
// СМОТРИМ НА ЛЕВУЮ СТОРОНУ. Язык набора — это язык ИЗУЧАЕМОГО слова, а не
// перевода: в паре «Систематика — наука о классификации» оба поля русские, а в
// паре «hunter — охотник» русский только правый. Поэтому в расчёт идут термины
// и ничего кроме них.
//
// МОЛЧИМ, КОГДА НЕ УВЕРЕНЫ. Ошибка здесь не видна глазом и всплывает озвучкой,
// которая читает корейское слово по-английски. Поэтому: письменность должна
// набрать больше половины терминов, иначе ответа нет вовсе — пусть человек
// выберет сам, это честнее подстановки наугад.
// ─────────────────────────────────────────────────────────────────────────────

/** Коды из реестра предметов: другие языки тренажёр не ведёт. */
export type GuessedLang = 'ru' | 'en' | 'ko' | 'ja' | 'pt-BR' | 'de'

const HANGUL = /[가-힣ᄀ-ᇿ]/
const KANA = /[぀-ゟ゠-ヿ]/
const HAN = /[一-鿿]/
const CYRILLIC = /[Ѐ-ӿ]/
const LATIN = /[A-Za-zÀ-ÿ]/

/**
 * Немецкий против португальского против английского.
 *
 * Все трое пишутся латиницей, и различают их надстрочные знаки: умляуты и ß —
 * немецкие, тильда и седиль — португальские. Знаков может не быть вовсе
 * (short list из простых слов) — тогда английский как самый частый.
 */
function latinFlavor(terms: string[]): GuessedLang {
  const text = terms.join(' ').toLowerCase()
  const de = (text.match(/[äöüß]/g) ?? []).length
  const pt = (text.match(/[ãõçáâêéíóôú]/g) ?? []).length
  if (de > pt && de > 0) return 'de'
  if (pt > de && pt > 0) return 'pt-BR'
  return 'en'
}

/**
 * Язык пачки или null, если письменности перемешаны.
 *
 * Японский и китайский иероглифы общие, но из двоих тренажёр ведёт только
 * японский, поэтому ханьцзи без каны — всё равно `ja`.
 */
export function guessLang(terms: string[]): GuessedLang | null {
  const words = terms.map(t => t.trim()).filter(Boolean)
  if (words.length === 0) return null

  const hits: Record<string, number> = { ko: 0, ja: 0, ru: 0, latin: 0 }
  for (const w of words) {
    if (HANGUL.test(w)) hits.ko++
    else if (KANA.test(w) || HAN.test(w)) hits.ja++
    else if (CYRILLIC.test(w)) hits.ru++
    else if (LATIN.test(w)) hits.latin++
  }

  const [top, count] = Object.entries(hits).sort((a, b) => b[1] - a[1])[0]
  if (count <= words.length / 2) return null
  return top === 'latin' ? latinFlavor(words) : (top as GuessedLang)
}
