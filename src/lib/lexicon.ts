/** Часть слова в разборе по составу: сам кусок и его перевод, если он есть. */
export interface WordPart {
  text: string
  gloss?: WordGloss
}

/** Кусок разобранного текста. `gloss` есть только у того, что нашлось в словаре. */
export interface Segment {
  text: string
  gloss?: WordGloss
  /** true — по куску можно кликнуть (слово, а не пробел и не запятая). */
  word: boolean
  /**
   * Разбор по составу — для слова, которого нет в словаре целиком, но части
   * которого известны: 문화체육관광부는 это 문화 + 체육 + 관광 + 부 + 는.
   *
   * Части НЕ кликаются по отдельности и живут только внутри карточки перевода.
   * Это и есть разница между «слово тапается целиком» и разбором по буквам:
   * ткнуть можно в слово, а из чего оно состоит — написано в карточке.
   */
  parts?: WordPart[]
}

export interface Lexicon {
  lookup: (term: string) => WordGloss | undefined
  segment: (text: string) => Segment[]
  size: number
}

// Иероглифы, кана и хангыль. Для них единица «не нашлось» — один символ:
// пробелов внутри слова нет, откусывать больше нечего.
const CJK = /[぀-ヿ㐀-䶿一-鿿가-힯々ー]/
// Латиница с цифрами: слово может содержать апостроф (I'd) и дефис (mid-level).
const WORD_CHAR = /[\p{L}\p{N}]/u

/**
 * Своя письменность языка.
 *
 * Формулировки вопросов к сцене нередко написаны по-русски — «Что означает
 * «폭싹 속았수다»?». Разбор не знает русского и не должен: без этой проверки
 * каждое русское слово становилось кликабельным и открывало «этого слова нет
 * в словаре», то есть тупик там, где никакого слова и не спрашивали. Чужая
 * письменность без перевода — просто текст; своя — кликается всегда, даже без
 * перевода (по хангылю и кане важно хотя бы услышать чтение).
 */
const SCRIPT: Record<string, RegExp> = {
  en: /[A-Za-z]/,
  'pt-BR': /[A-Za-zÀ-ÖØ-öø-ÿ]/,
  de: /[A-Za-zÄÖÜäöüß]/,
  ko: /[가-힣ㄱ-ㅎㅏ-ㅣ]/,
  ja: /[぀-ヿ㐀-䶿一-鿿々ー]/,
}
/**
 * Языки, где кликается ТОЛЬКО то, для чего есть толкование.
 *
 * Родной язык (русский, литература) отличается от изучаемого тем, что слово в
 * подсказке не нуждается: «дверь» толковать носителю нечего. Кликабельным
 * должно быть исключительно то, что действительно требует пояснения, —
 * устаревшее и специальное («экзекутор», «ваше-ство»), и оно приезжает из
 * glossary самого текста. Без этого исключения каждое русское слово в отрывке
 * Гоголя открывало бы «этого слова нет в словаре», то есть тупик на ровном
 * месте.
 */
const GLOSS_ONLY = new Set(['ru'])

const DIGIT = /\p{N}/u
const LETTER = /\p{L}/u

/**
 * Класс символа для проверки границ: 'd' — цифра, 'l' — буква (апостроф и дефис
 * считаются частью слова, иначе «I'd» распалось бы на «I» и «d»), 'x' — всё
 * остальное. Совпадение со словарём допускается, только если по краям стоит
 * символ ДРУГОГО класса: так «a» не находится внутри «academia», а «h» из «6h»
 * находится — цифра и буква разные единицы, «6» это число, «h» это «часов».
 */
function cls(c: string | undefined): 'd' | 'l' | 'x' {
  if (!c) return 'x'
  if (DIGIT.test(c)) return 'd'
  if (c === "'" || c === '’' || c === '-') return 'l'
  return LETTER.test(c) && !CJK.test(c) ? 'l' : 'x'
}

/**
 * Класс СОСЕДА совпадения — того символа, что стоит вплотную слева или справа.
 *
 * Отличается от cls() ровно в одном: дефис и апостроф склеивают слово, только
 * когда с другой стороны от них тоже буква (mid-level, I'd). Иначе это тире, а
 * тире слово не продолжает. Без этой оговорки любое слово, набранное вплотную к
 * тире («--eram» у Машаду, «слово--слово» у Диккенса), не находилось в словаре
 * вовсе: проверка границы считала, что совпадение начинается внутри слова.
 */
function edge(text: string, i: number, back: boolean): 'd' | 'l' | 'x' {
  const c = text[i]
  if (!c) return 'x'
  if (c === "'" || c === '’' || c === '-') {
    const beyond = text[back ? i - 1 : i + 1]
    return beyond && LETTER.test(beyond) && !CJK.test(beyond) ? 'l' : 'x'
  }
  return cls(c)
}

/**
 * Ключ словаря: регистр для латиницы не значим, для остального нейтрален.
 *
 * Апостроф приводится к прямому. Тексты набраны по-разному — в одном didn’t с
 * типографским апострофом, в другом didn't с прямым, — и без нормализации одна
 * и та же запись словаря находилась бы в половине текстов.
 */
const key = (s: string) => s.toLowerCase().replace(/[’‘`]/g, "'")

// ─── Английские формы ────────────────────────────────────────────────────────
//
// ПОЧЕМУ ЗДЕСЬ МОРФОЛОГИЯ ЕСТЬ, А ВЫШЕ НАПИСАНО, ЧТО ЕЁ НЕТ. Выше речь о
// корейском и японском: там окончание приклеено к слову без пробела, вариантов
// разреза много, и угадывание границы врёт. Английское словоизменение устроено
// иначе — окончаний ровно четыре (-s, -ed, -ing, -er/-est/-ly), и проверка
// здесь не «угадать», а «отрезать и посмотреть, есть ли ТАКАЯ основа в
// словаре». Нет основы — ничего не показываем, поэтому ложных срабатываний
// почти не бывает: sauntered находит saunter, а bring не находит br.
//
// Зачем вообще: держать в словаре face, faces, facing и faced четырьмя записями
// — это вчетверо больше работы ради одного и того же перевода, и всё равно не
// покрывает текст, которого мы не видели. Форма помечается («форма слова…»),
// чтобы ученик видел, что перевод дан для основы, а не для того, во что он ткнул.

/** Минимальная длина основы: короче — почти всегда мусор (his → hi, as → a). */
const MIN_STEM = 3

/** Двойная согласная на конце: stopped → stop, running → run. */
const undouble = (s: string) =>
  s.length > 3 && s[s.length - 1] === s[s.length - 2] && !'aeiou'.includes(s[s.length - 1])
    ? s.slice(0, -1)
    : null

/**
 * Возможные основы английской словоформы — от самой вероятной к менее.
 *
 * Список кандидатов, а не ответ: какой из них настоящий, решает наличие записи
 * в словаре (см. buildLexicon).
 */
function enStems(k: string): string[] {
  const out: string[] = []
  const add = (s: string | null | undefined) => { if (s && s.length >= MIN_STEM) out.push(s) }
  // Притяжательное и стяжения с апострофом: men's → men.
  const apos = k.match(/^(.+?)['’](s|d|ll|ve|re|m)$/)
  if (apos) add(apos[1])
  if (k.endsWith('ies') && k.length > 4) add(k.slice(0, -3) + 'y')
  if (k.endsWith('es') && k.length > 3) { add(k.slice(0, -2)); add(k.slice(0, -1)) }
  else if (k.endsWith('s') && !k.endsWith('ss') && k.length > 3) add(k.slice(0, -1))
  if (k.endsWith('ied') && k.length > 4) add(k.slice(0, -3) + 'y')
  if (k.endsWith('ed') && k.length > 3) {
    add(k.slice(0, -1))          // liked → like
    add(k.slice(0, -2))          // walked → walk
    add(undouble(k.slice(0, -2))) // stopped → stop
  }
  if (k.endsWith('ing') && k.length > 4) {
    add(k.slice(0, -3))              // walking → walk
    add(k.slice(0, -3) + 'e')        // making → make
    add(undouble(k.slice(0, -3)))    // running → run
  }
  if (k.endsWith('ily') && k.length > 4) add(k.slice(0, -3) + 'y')
  if (k.endsWith('ly') && k.length > 3) { add(k.slice(0, -2)); add(k.slice(0, -2) + 'e') }
  if (k.endsWith('ier') || k.endsWith('iest')) add(k.replace(/i(er|est)$/, 'y'))
  if (k.endsWith('er') && k.length > 4) { add(k.slice(0, -2)); add(k.slice(0, -1)) }
  if (k.endsWith('est') && k.length > 5) { add(k.slice(0, -3)); add(k.slice(0, -2)) }
  return out
}

// ─── Корейский: слово тапается целиком ───────────────────────────────────────
//
// ЧТО СЛОМАЛОСЬ. Пока разбор кормили курсовыми текстами, словаря хватало: слово
// урока в нём есть по определению, и 내일은 честно раскладывалось на «내일» +
// «은». В ленте текст чужой и свежий, словаря на него нет и быть не может —
// новости приходят каждый день. И разбор делал ровно худшее: добирал покрытие
// одиночными слогами. 마포구 «район Мапхо» превращался в 마 + 포 + 구,
// 스타스퀘어 — в пять слогов, каждый со своим «переводом», 인기 «популярность» —
// в 인 + 기. Ученик тыкал в слово и получал разбор по буквам.
//
// ДВА ПРАВИЛА. Оба про одно: единица тапа в корейском — это то, что стоит
// между пробелами (어절), и меньше неё разбор не режет НИКОГДА.
//
//  1. ХВОСТ ОТРЕЗАЕТСЯ, ЕСЛИ ОСНОВА НАШЛАСЬ (koTails ниже). 행사는 → 행사 плюс
//     тематическая частица, 운영한다 → 운영하다, 학생이에요 → 학생 плюс связка.
//     Проверка та же, что у английских форм: отрезали кандидата — смотрим, есть
//     ли ТАКАЯ основа в словаре. Нет — правило молчит.
//  2. ЧЕГО НЕ ЗНАЕМ ЦЕЛИКОМ — ПОКАЗЫВАЕМ РАЗБОРОМ ПО СОСТАВУ, а не пятью
//     кликабельными слогами (см. `parts` у Segment). И односложные куски внутри
//     такого слова идут БЕЗ перевода: односложная запись, подставленная внутрь
//     незнакомого слова, врёт увереннее, чем молчание, — ровно тот случай, ради
//     которого написано правило Р16 в docs/MEMORY_STANDARD.md.

// ── Слог хангыля разбирается на буквы, и без этого не обойтись ───────────────
//
// Корейское окончание приклеивается не только СЛОГОМ, но и БУКВОЙ внутрь
// последнего слога основы: 하 + ㄴ다 = 한다, 하 + ㄹ게요 = 할게요, 가 + ㅂ니다 =
// 갑니다, 오 + 았어요 = 왔어요. Резать такое по слогам бесполезно — граница
// проходит внутри знака. Зато слог хангыля собран арифметикой из трёх номеров
// (начальная, гласная, финальная), и разобрать его обратно — три деления.

const HANGUL_FIRST = 0xac00
const HANGUL_LAST = 0xd7a3

interface Jamo { lead: number; vowel: number; tail: number }

function jamo(ch: string | undefined): Jamo | null {
  if (!ch) return null
  const c = ch.charCodeAt(0)
  if (c < HANGUL_FIRST || c > HANGUL_LAST) return null
  const n = c - HANGUL_FIRST
  return { lead: Math.floor(n / 588), vowel: Math.floor((n % 588) / 28), tail: n % 28 }
}

const syllable = (j: Jamo) =>
  String.fromCharCode(HANGUL_FIRST + j.lead * 588 + j.vowel * 28 + j.tail)

/** Финальные согласные, которые бывают не своими, а пришедшими от окончания. */
const KO_GLUED = new Set([4 /* ㄴ */, 8 /* ㄹ */, 17 /* ㅂ */, 20 /* ㅆ */])

/**
 * Стяжения гласной: во что превращается основа, слившись с 아/어.
 *
 * Слева — что стоит в тексте, справа — что было в словарной форме. 해 ← 하다,
 * 돼 ← 되다, 봐 ← 보다, 줘 ← 주다, 셔 ← 시다, 써 ← 쓰다, 바빠 ← 바쁘다.
 * Список нарочно короткий: это самые частые стяжения, а не полная таблица
 * спряжения — полную писать нельзя (см. data/koreanEndings.ts: движок на все
 * чередования врал бы молча). Здесь вранья не выйдет, потому что кандидат
 * принимается ТОЛЬКО если такая словарная форма реально есть в словаре.
 */
const KO_CONTRACT: Record<number, number[]> = {
  0: [18],   // ㅏ ← ㅡ : 바빠요 → 바쁘다
  1: [0],    // ㅐ ← ㅏ : 해요 → 하다
  4: [18],   // ㅓ ← ㅡ : 써요 → 쓰다
  6: [20],   // ㅕ ← ㅣ : 마셔요 → 마시다
  9: [8],    // ㅘ ← ㅗ : 봐요 → 보다
  10: [11],  // ㅙ ← ㅚ : 돼요 → 되다
  14: [13],  // ㅝ ← ㅜ : 줘요 → 주다
}

/**
 * Кандидаты в основу: что могло стоять до того, как к слову приклеилось
 * окончание. Список, а не ответ — какой из кандидатов настоящий, решает
 * наличие записи в словаре (ровно как у английских enStems).
 */
function koStems(head: string): string[] {
  const out = new Set<string>([head])
  const j = jamo(head[head.length - 1])
  if (!j) return [...out]
  const pre = head.slice(0, -1)
  // Финальная согласная могла быть частью окончания (한 ← 하 + ㄴ), а могла
  // быть своей (먹 в 먹다). Пробуем оба чтения.
  const seeds = j.tail && KO_GLUED.has(j.tail) ? [j, { ...j, tail: 0 }] : [j]
  for (const s of seeds) {
    out.add(pre + syllable(s))
    if (s.tail) continue
    for (const vowel of KO_CONTRACT[s.vowel] ?? []) out.add(pre + syllable({ ...s, vowel }))
    // ㄹ выпадает перед вежливым окончанием: 사세요 ← 살다, 만드세요 ← 만들다.
    out.add(pre + syllable({ ...s, tail: 8 }))
  }
  // НЕПРАВИЛЬНЫЕ ОСНОВЫ. Слияние с 아/어 у них не сводится к гласной: часть
  // основы переписывается целиком. Все четыре ряда — школьная таблица, и
  // каждый кандидат всё равно проверяется по словарю, так что выдумать слово
  // правило не может.
  const last = head[head.length - 1]
  const prev = jamo(head[head.length - 2])
  if (prev) {
    const stem = head.slice(0, -2)
    // ㅂ: 춥다 → 추워, 돕다 → 도와, 덥다 → 더워.
    if ((last === '워' || last === '와') && !prev.tail) out.add(stem + syllable({ ...prev, tail: 17 }))
    // ㅅ: 낫다 → 나아, 짓다 → 지어.
    if ((last === '아' || last === '어') && !prev.tail) out.add(stem + syllable({ ...prev, tail: 19 }))
    // ㄷ: 듣다 → 들어, 걷다 → 걸어.
    if ((last === '아' || last === '어') && prev.tail === 8) out.add(stem + syllable({ ...prev, tail: 7 }))
    // 르: 모르다 → 몰라, 부르다 → 불러, 다르다 → 달라.
    if ((last === '라' || last === '러') && prev.tail === 8) out.add(stem + syllable({ ...prev, tail: 0 }) + '르')
  }
  // ПОЧТИТЕЛЬНОЕ 시 СИДИТ ВНУТРИ ОСНОВЫ, а не в хвосте: 하셨습니다 = 하 + 시 +
  // 었습니다, 도와주실 = 도와주 + 시 + ㄹ. Хвост отрезали — осталось 하시,
  // 도와주시, и словарной формой это не станет никогда: в словаре лежит 하다 и
  // 도와주다. Поэтому у каждого кандидата пробуем ещё и вариант без 시.
  for (const s of [...out]) if (s.length > 1 && s.endsWith('시')) out.add(s.slice(0, -1))
  return [...out]
}

/**
 * Существительное без множественного 들: 어른들은 → 어른, 아이들과 → 아이.
 *
 * 들 не меняет смысла слова и в словаре отдельной записью не нужен — но без
 * этого правила каждое слово во множественном числе выпадало из разбора.
 */
function koHeads(head: string): string[] {
  return head.length > 1 && head.endsWith('들') ? [head, head.slice(0, -1)] : [head]
}

