// ─────────────────────────────────────────────────────────────────────────────
// Почему не дали микрофон — и что с этим делать
//
// ЗАЧЕМ. Все места записи голоса (домашка, тренажёр, шэдоуинг) ловили любую
// ошибку getUserMedia одинаково: «Нет доступа к микрофону». Для ученика это
// тупик — он видит запрет и не знает ни причины, ни куда идти. Особенно на
// телефоне, где приложение стоит на домашнем экране: там разрешение спрашивают
// раз за запуск, и один случайный «Не разрешать» закрывает микрофон до полного
// перезапуска — догадаться об этом невозможно.
//
// ЧТО ЗДЕСЬ. Разбор DOMException по имени и человеческий текст к каждому
// случаю, включая шаг, который надо сделать. Строки — по-русски: их переводит
// t() на месте показа, как и весь остальной интерфейс.
// ─────────────────────────────────────────────────────────────────────────────

export interface MicProblem {
  /** Короткая причина — строкой рядом с кнопкой. */
  text: string
  /** Что сделать, чтобы починить. Пусто — делать нечего. */
  hint: string
}

/** Приложение открыто с домашнего экрана (PWA), а не вкладкой браузера. */
export function isStandalone(): boolean {
  if (typeof window === 'undefined') return false
  const iosStandalone = (window.navigator as Navigator & { standalone?: boolean }).standalone
  return !!iosStandalone || window.matchMedia?.('(display-mode: standalone)').matches === true
}

const isApple = (): boolean =>
  typeof navigator !== 'undefined'
  && /iPad|iPhone|iPod/.test(navigator.userAgent)
  // iPad с iPadOS 13+ представляется маком; отличаем по касаниям.
  || (typeof navigator !== 'undefined' && navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1)

/**
 * Как включить микрофон — для той системы, в которой ученик сейчас сидит.
 *
 * ПОЧЕМУ У ДОМАШНЕГО ЭКРАНА СВОЙ СОВЕТ. У приложения с домашнего экрана на iOS
 * нет ни адресной строки, ни замка: разрешение спрашивается при первой записи в
 * КАЖДЫЙ запуск, а отказ живёт до тех пор, пока приложение не выгружено из
 * переключателя. Совет «нажмите на замок» там бесполезен, а «закройте и
 * откройте заново» — единственное, что работает.
 */
function howToAllow(): string {
  if (isApple()) {
    return isStandalone()
      ? 'Разрешение спрашивают один раз за запуск. Закройте приложение (смахните его в переключателе программ), откройте заново и на вопрос о микрофоне ответьте «Разрешить». Если вопроса нет — проверьте: Настройки → Safari → Микрофон.'
      : 'Нажмите «АА» слева в адресной строке → «Настройки для веб-сайта» → Микрофон → «Разрешить». Если такого пункта нет: Настройки → Safari → Микрофон.'
  }
  return 'Нажмите на значок замка слева в адресной строке и разрешите этому сайту микрофон, потом попробуйте ещё раз.'
}

/** Разбор отказа getUserMedia: причина плюс шаг, который её снимает. */
export function micProblem(error: unknown): MicProblem {
  const name = error instanceof DOMException ? error.name : ''
  switch (name) {
    case 'NotFoundError':
    case 'OverconstrainedError':
      return { text: 'Микрофон не найден', hint: 'Проверьте, что микрофон подключён и не отключён в системе.' }
    case 'NotReadableError':
      return {
        text: 'Микрофон занят другой программой',
        hint: 'Закройте звонок или запись в другом приложении и попробуйте ещё раз.',
      }
    case 'SecurityError':
      return {
        text: 'Запись доступна только по защищённому адресу',
        hint: 'Откройте приложение по адресу с https:// — по http микрофон не работает ни в одном браузере.',
      }
    default:
      return { text: 'Нет доступа к микрофону', hint: howToAllow() }
  }
}
