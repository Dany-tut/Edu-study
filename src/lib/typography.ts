import type { CSSProperties } from 'react'

// ── Типографика учебных текстов ──────────────────────────────────────────────
//
// Всё, что читает ученик — формулировка вопроса, условие, вариант ответа, —
// ломается по строкам там, где решит браузер, а решает он плохо: предлог
// остаётся висеть в конце строки, тире начинает следующую, последняя строка
// заголовка состоит из одного слова, а корейское слово рвётся посреди слога
// (в CJK нет переноса по словам, разрыв допустим между любыми двумя знаками).
// Правила ниже — один набор на все такие места, чтобы не переизобретать их
// в каждой карточке.

const SHORT_WORD = /(^|[\s(«„"'>])([А-яЁё]{1,2}|[aAiI]) /g

/**
 * Короткое слово не остаётся в конце строки: предлоги и союзы («в», «с», «и»,
 * «по», английские «a»/«I») приклеиваются к следующему слову неразрывным
 * пробелом. Тире по-русски тоже не начинает строку — неразрывным делается
 * пробел перед ним.
 *
 * Работает по обычному тексту. Для HTML — bindShortWordsHtml.
 */
export function bindShortWords(text: string): string {
  // Два прохода: подряд идущие коротышки («и в лесу») за один replace не
  // ловятся — пробел после первого слова уже съеден, и у второго не остаётся
  // левой границы.
  const once = (s: string) => s.replace(SHORT_WORD, (_m, pre, word) => `${pre}${word}\u00A0`)
  return once(once(text)).replace(/ ([—–])/g, '\u00A0$1')
}

/** То же по HTML-условию: теги обходим стороной, правим только текст между ними. */
export function bindShortWordsHtml(html: string): string {
  return html
    .split(/(<[^>]*>)/)
    .map(part => (part.startsWith('<') ? part : bindShortWords(part)))
    .join('')
}

/**
 * Перенос по словам, а не по слогам чужого алфавита: `keep-all` держит вместе
 * корейские и китайские слова, `pretty` не даёт последней строке схлопнуться в
 * одно слово, `break-word` спасает от вылезающей за карточку длинной ссылки.
 */
export const proseWrap: CSSProperties = {
  textWrap: 'pretty',
  wordBreak: 'keep-all',
  overflowWrap: 'break-word',
}

/**
 * Письмо без пробелов между словами — японское и китайское.
 *
 * Для него правила переноса ровно обратные корейским: там пробел есть, и
 * `keep-all` бережёт слово от разрыва посреди слога, а здесь пробела нет вовсе
 * — и `keep-all` означает «не переносить никогда». Реплика становится одним
 * бесконечным словом и уезжает за край карточки.
 */
export function isDenseScript(lang: string): boolean {
  return /^(ja|zh)/i.test(lang)
}

/**
 * Перенос текста на конкретном языке. Везде — proseWrap, в плотном письме с
 * него снимается keep-all: разрыв строки между двумя знаками там нормален и
 * единственно возможен.
 */
export function langWrap(lang: string): CSSProperties {
  return isDenseScript(lang) ? { ...proseWrap, wordBreak: 'normal' } : proseWrap
}

/** Для коротких надписей в 2–3 строки (плашки, подписи): строки равной длины. */
export const balancedWrap: CSSProperties = {
  textWrap: 'balance',
  wordBreak: 'keep-all',
  overflowWrap: 'break-word',
}

/**
 * «Прочитайте вслух: 아이, 우유, 나무» — инструкция и сам материал в одной
 * строке набраны одинаково, и глаз не отличает задание от того, что надо
 * прочитать. Разделяем: инструкция уходит в лид-ин, материал остаётся
 * основным текстом.
 *
 * Отделяем только короткую команду без внутренней пунктуации: в «Что не так в
 * предложении, если он идёт: домой» двоеточие — часть фразы, и разрывать её
 * посередине хуже, чем оставить как есть.
 */
export function splitLeadIn(prompt: string): { lead: string; body: string } | null {
  const i = prompt.indexOf(':')
  if (i < 3 || i > 40) return null
  const lead = prompt.slice(0, i)
  if (/[,;.!?—–(]/.test(lead)) return null
  const body = prompt.slice(i + 1).trim()
  if (!body) return null
  return { lead: `${lead}:`, body }
}

// ── Висячие знаки ────────────────────────────────────────────────────────────
//
// В конспекте с корейскими вставками браузер переносит строку в местах, где по
// смыслу шва нет: «…на «ты»» уезжает в конец строки, а следующая начинается
// с точки; «корейское «» повисает открывающей кавычкой, а её содержимое
// начинает новую строку. Читается это как опечатка — глаз спотыкается и
// возвращается перечитывать.
//
// Причина не в тексте (в исходнике всё написано слитно), а в правилах переноса:
// в абзаце со смешанным письмом браузер применяет к кавычкам и скобкам
// CJK-логику, где после закрывающей кавычки разрыв допустим. Спорить с ней
// настройками CSS бесполезно — `word-break` управляет словами, а не знаками.
// Поэтому шов запрещаем прямо в тексте: между знаком и его словом ставим
// word-joiner (U+2060) — невидимый символ нулевой ширины, единственный смысл
// которого «здесь не переносить».
//
// Знак приклеивается к той стороне, к которой он относится: открывающая
// кавычка и скобка — к следующему слову, закрывающая, точка, запятая и прочая
// финальная пунктуация — к предыдущему. Многоточие и «?!» склеиваются между
// собой, потому что стоят подряд одной группой.

const WJ = '⁠'

/** Знаки, которые не имеют права начинать строку (относятся к слову слева). */
const TAIL = '.,;:!?…»”“)\\]%‰°'
/**
 * Из них те, перед которыми пробела не бывает вовсе. Процент и градус сюда не
 * входят: «5–10 %» — не опечатка, а принятая запись, и съедать этот пробел
 * значит править текст, а не вёрстку. Приклеить знак к числу это не мешает.
 */
const TIGHT = '.,;:!?»”)\\]'
/** Знаки, которые не имеют права заканчивать строку (относятся к слову справа). */
const HEAD = '«„“(\\[№'

/**
 * Запрет висячих знаков: пунктуация не остаётся одна на краю строки.
 *
 * Работает по обычному тексту и НЕ меняет его видимую длину: word-joiner
 * невидим и не занимает места. Поиск подстрок по результату ломается — поэтому
 * применяется последним, уже перед показом (как и bindShortWords).
 */
export function glueHangingPunct(text: string): string {
  return text
    // Лишний пробел ПЕРЕД финальным знаком — это уже висячий знак в исходнике:
    // «слово ,» браузер честно перенесёт запятой на новую строку.
    .replace(new RegExp(`[ \\t]+([${TIGHT}])`, 'g'), '$1')
    .replace(new RegExp(`([${HEAD}])[ \\t]+`, 'g'), '$1')
    // Знак приклеивается к соседнему слову — но только если оно есть: точка,
    // начинающая абзац, приклеиваться не к чему.
    .replace(new RegExp(`(\\S)([${TAIL}]+)`, 'g'), `$1${WJ}$2`)
    .replace(new RegExp(`([${HEAD}]+)(\\S)`, 'g'), `$1${WJ}$2`)
}

/**
 * Полная правка учебного текста перед показом: короткие слова не висят в конце
 * строки, знаки препинания не отрываются от своих слов.
 *
 * Один вызов на все места, где ученик читает связный текст (конспект, шторка
 * правила, чек-лист): правила типографики не должны отличаться от экрана
 * к экрану.
 */
export function tidyProse(text: string): string {
  return glueHangingPunct(bindShortWords(text))
}
