import type { CSSProperties } from 'react'

// ── Типографика учебных текстов ──────────────────────────────────────────────
//
// Всё, что читает ученик — формулировка вопроса, условие, вариант ответа, —
// ломается по строкам там, где решит браузер, а решает он плохо: предлог
// остаётся висеть в конце строки, тире начинает следующую, последняя строка
// заголовка состоит из одного слова, а корейское слово рвётся посреди слога
// (в CJK нет переноса по словам, разрыв допустим между любыми двумя знаками).
// Правила ниже — один набор на все такие места, чтобы не переизобретать их
// в каждой карточке.

/** Однобуквенные слова: «в», «с», «к», «я», английские «a» и «I». */
const ONE_LETTER = /^(?:[А-Яа-яЁё]|[aAiI])$/
/**
 * Двухбуквенные слова, которые читаются вместе со СЛЕДУЮЩИМ: предлоги, союзы,
 * отрицание. Список, а не «любые две буквы»: «то», «он», «мы», «их» к себе
 * ничего не притягивают, и связка с ними только отнимает место в строке.
 */
const GLUE_NEXT = /^(?:во|со|ко|об|из|от|до|на|за|по|не|ни|но|да|уж)$/i
/** Частицы, относящиеся к слову СЛЕВА: «то же», «если бы», «так ли». */
const GLUE_BACK = /^(?:же|ли|ль|бы|б)$/i

/**
 * Слово слева от стыка. Открывающая кавычка не мешает, а знак в конце — мешает:
 * «в лесу» связка, «в, лесу» нет, запятая связь и разрывает.
 */
const leftWord = (t: string) => /^["'«„“([]*(\p{L}+)$/u.exec(t)?.[1] ?? ''
/** Слово справа: конечный знак связи не отменяет — «то же,» остаётся вместе. */
const rightWord = (t: string) => /^["'«„“([]*(\p{L}+)[)\].,;:!?»”'"…]*$/u.exec(t)?.[1] ?? ''

/**
 * Короткое слово не остаётся в конце строки: предлоги, союзы и отрицание («в»,
 * «с», «и», «по», «не», английские «a»/«I») приклеиваются к следующему слову
 * неразрывным пробелом, частицы «же», «бы», «ли» — к предыдущему. Тире
 * по-русски тоже не начинает строку — неразрывным делается пробел перед ним.
 *
 * СВЯЗКА — ЭТО ДВА СЛОВА, А НЕ ПОЛПРЕДЛОЖЕНИЯ. Прошлая версия склеивала
 * коротышки цепью, и «но не то же самое» становилось одним неразрывным куском
 * в восемнадцать знаков: в остаток строки он не влезал и уезжал вниз целиком,
 * оставляя дыру в треть строки — ровно то, от чего склейка должна спасать.
 * Поэтому связка занимает ОДИН стык: склеили «но» со следующим словом — стык
 * после него обычный. Исключения два, и оба про одинокий знак на краю строки:
 * однобуквенное слово не имеет права закончить строку никогда, а частица «же»
 * — начать её.
 *
 * Работает по обычному тексту. Для HTML — bindShortWordsHtml.
 */
export function bindShortWords(text: string): string {
  return keepQuotesAttached(text
    .split('\n')
    .map(bindLine)
    .join('\n')
    .replace(/ ([—–])/g, '\u00A0$1'))
}

/**
 * Кавычка не остаётся одна на краю строки.
 *
 * ЗАЧЕМ. Строка «Наберите по буквам слово «огурец» — 오이» на телефоне ломалась
 * ПОСЛЕ открывающей кавычки: первая строка кончалась одиноким «, слово уезжало
 * на вторую. Неразрывный пробел тут не помогает — разрыв не на пробеле, а на
 * стыке знака и буквы, и запретить его можно только словесным соединителем
 * U+2060 (WORD JOINER). Он невидим, ширины не имеет и на сверку ответов не
 * влияет: сюда приходит только показ, а не данные задания.
 *
 * Симметрично держим закрывающую: строка, начинающаяся с », читается так же
 * сиротски, как и кончающаяся на «.
 *
 * ОДНОГО СОЕДИНИТЕЛЯ МАЛО: WebKit (iOS) его в этом месте игнорирует и рвёт
 * строку после кавычки всё равно — проверено обходом ширин на iOS 26. Там
 * работает только запрет разметкой, см. «Связки в разметке» ниже.
 */
function keepQuotesAttached(text: string): string {
  return text
    .replace(/([«„“(\[])(\S)/g, '$1\u2060$2')
    .replace(/(\S)([»”)\]])/g, '$1\u2060$2')
}

/** Стыки одной строки: решение принимается по паре слов вокруг пробела. */
function bindLine(line: string): string {
  // Чередование «слово, пробелы, слово»: правим только сами пробелы, буквы
  // остаются как были.
  const parts = line.split(/( +)/)
  // Связка предыдущего стыка: пока она есть, следующий стык остаётся обычным.
  let bound = false
  for (let i = 1; i < parts.length; i += 2) {
    // Двойной пробел — не стык, а опечатка; её ловит check:prose, не показ.
    if (parts[i] !== ' ') { bound = false; continue }
    const left = leftWord(parts[i - 1])
    const right = rightWord(parts[i + 1] ?? '')
    const must = ONE_LETTER.test(left) || GLUE_BACK.test(right)
    const want = must || GLUE_NEXT.test(left)
    if (want && (must || !bound)) { parts[i] = '\u00A0'; bound = true }
    else bound = false
  }
  return parts.join('')
}

/** То же по HTML-условию: теги обходим стороной, правим только текст между ними. */
export function bindShortWordsHtml(html: string): string {
  return html
    .split(/(<[^>]*>)/)
    .map(part => (part.startsWith('<') ? part : bindShortWords(part)))
    .join('')
}

/**
 * Перенос по словам, а не по слогам чужого алфавита: `keep-all` держит вместе
 * корейские и китайские слова, `pretty` не даёт последней строке схлопнуться в
 * одно слово, `break-word` спасает от вылезающей за карточку длинной ссылки.
 */
export const proseWrap: CSSProperties = {
  textWrap: 'pretty',
  wordBreak: 'keep-all',
  overflowWrap: 'break-word',
}

/**
 * Письмо без пробелов между словами — японское и китайское.
 *
 * Для него правила переноса ровно обратные корейским: там пробел есть, и
 * `keep-all` бережёт слово от разрыва посреди слога, а здесь пробела нет вовсе
 * — и `keep-all` означает «не переносить никогда». Реплика становится одним
 * бесконечным словом и уезжает за край карточки.
 */
export function isDenseScript(lang: string): boolean {
  return /^(ja|zh)/i.test(lang)
}

/**
 * Перенос текста на конкретном языке. Везде — proseWrap, в плотном письме с
 * него снимается keep-all: разрыв строки между двумя знаками там нормален и
 * единственно возможен.
 */
export function langWrap(lang: string): CSSProperties {
  return isDenseScript(lang) ? { ...proseWrap, wordBreak: 'normal' } : proseWrap
}

/** Для коротких надписей в 2–3 строки (плашки, подписи): строки равной длины. */
export const balancedWrap: CSSProperties = {
  textWrap: 'balance',
  wordBreak: 'keep-all',
  overflowWrap: 'break-word',
}

/**
 * «Прочитайте вслух: 아이, 우유, 나무» — инструкция и сам материал в одной
 * строке набраны одинаково, и глаз не отличает задание от того, что надо
 * прочитать. Разделяем: инструкция уходит в лид-ин, материал остаётся
 * основным текстом.
 *
 * Отделяем только короткую команду без внутренней пунктуации: в «Что не так в
 * предложении, если он идёт: домой» двоеточие — часть фразы, и разрывать её
 * посередине хуже, чем оставить как есть.
 */
export function splitLeadIn(prompt: string): { lead: string; body: string } | null {
  const i = prompt.indexOf(':')
  if (i < 3 || i > 40) return null
  const lead = prompt.slice(0, i)
  if (/[,;.!?—–(]/.test(lead)) return null
  const body = prompt.slice(i + 1).trim()
  if (!body) return null
  return { lead: `${lead}:`, body }
}

// ── Висячие знаки ────────────────────────────────────────────────────────────
//
// В конспекте с корейскими вставками браузер переносит строку в местах, где по
// смыслу шва нет: «…на «ты»» уезжает в конец строки, а следующая начинается
// с точки; «корейское «» повисает открывающей кавычкой, а её содержимое
// начинает новую строку. Читается это как опечатка — глаз спотыкается и
// возвращается перечитывать.
//
// Причина не в тексте (в исходнике всё написано слитно), а в правилах переноса:
// в абзаце со смешанным письмом браузер применяет к кавычкам и скобкам
// CJK-логику, где после закрывающей кавычки разрыв допустим. Спорить с ней
// настройками CSS бесполезно — `word-break` управляет словами, а не знаками.
// Поэтому шов запрещаем прямо в тексте: между знаком и его словом ставим
// word-joiner (U+2060) — невидимый символ нулевой ширины, единственный смысл
// которого «здесь не переносить».
//
// Знак приклеивается к той стороне, к которой он относится: открывающая
// кавычка и скобка — к следующему слову, закрывающая, точка, запятая и прочая
// финальная пунктуация — к предыдущему. Многоточие и «?!» склеиваются между
// собой, потому что стоят подряд одной группой.

const WJ = '⁠'

/** Знаки, которые не имеют права начинать строку (относятся к слову слева). */
const TAIL = '.,;:!?…»”“)\\]%‰°'
/**
 * Из них те, перед которыми пробела не бывает вовсе. Процент и градус сюда не
 * входят: «5–10 %» — не опечатка, а принятая запись, и съедать этот пробел
 * значит править текст, а не вёрстку. Приклеить знак к числу это не мешает.
 */
const TIGHT = '.,;:!?»”)\\]'
/** Знаки, которые не имеют права заканчивать строку (относятся к слову справа). */
const HEAD = '«„“(\\[№'

/**
 * Запрет висячих знаков: пунктуация не остаётся одна на краю строки.
 *
 * Работает по обычному тексту и НЕ меняет его видимую длину: word-joiner
 * невидим и не занимает места. Поиск подстрок по результату ломается — поэтому
 * применяется последним, уже перед показом (как и bindShortWords).
 */
export function glueHangingPunct(text: string): string {
  return text
    // Лишний пробел ПЕРЕД финальным знаком — это уже висячий знак в исходнике:
    // «слово ,» браузер честно перенесёт запятой на новую строку.
    .replace(new RegExp(`[ \\t]+([${TIGHT}])`, 'g'), '$1')
    .replace(new RegExp(`([${HEAD}])[ \\t]+`, 'g'), '$1')
    // Знак приклеивается к соседнему слову — но только если оно есть: точка,
    // начинающая абзац, приклеиваться не к чему.
    .replace(new RegExp(`(\\S)([${TAIL}]+)`, 'g'), `$1${WJ}$2`)
    .replace(new RegExp(`([${HEAD}]+)(\\S)`, 'g'), `$1${WJ}$2`)
}

// ── Связки в разметке ────────────────────────────────────────────────────────
//
// ПОЧЕМУ word-joiner'а МАЛО. Всё, что написано выше про висячие знаки, Chrome
// выполняет честно, а WebKit (iOS) — нет: он рвёт строку ПОСЛЕ открывающей
// кавычки, и никакой невидимый знак его не останавливает. Проверено обходом
// ширин 240–360 px на iOS 26 — «висит» одинаково и с word-joiner'ом, и без,
// и с `text-wrap: pretty`, и без него, и в чисто русском абзаце (то есть дело
// не в корейских вставках). Отсюда в конспекте и берётся строка, кончающаяся
// на «, со следующей, начинающейся с «о».».
//
// Единственное, что WebKit исполняет без оговорок, — `white-space: nowrap` на
// куске разметки. Поэтому связку приходится показывать не символом, а тегом:
// текст режется по ОБЫЧНЫМ пробелам, и каждый кусок между ними едет по строкам
// целиком. Неразрывный пробел внутри куска при этом остаётся неразрывным сам
// по себе — резать по нему нечего.

/**
 * Пробел, по которому переносить МОЖНО. Неразрывный ( ) сюда не входит
 * намеренно: это и есть склейка, поставленная bindShortWords.
 */
export const BREAK_SPACE = /([ \t\n\r\f\v]+)/

/** Знаки двойной ширины: хангыль, кана, иероглифы. */
const WIDE = /[\u1100-\u11FF\u2E80-\u9FFF\uAC00-\uD7AF\uFF00-\uFF60]/

/**
 * Можно ли запрещать перенос внутри куска.
 *
 * У запрета есть потолок: кусок шире строки не переносится вовсе и уезжает за
 * край карточки — это хуже любой висячей кавычки. Двадцать два знака — около
 * двух третей строки на телефоне, длиннее бывают только ссылки и составные
 * слова, там перенос нужнее красоты.
 */
export function keepsTogether(chunk: string): boolean {
  let w = 0
  for (const ch of chunk) w += WIDE.test(ch) ? 2 : 1
  return w > 0 && w <= 22
}

/**
 * Полная правка учебного текста перед показом: короткие слова не висят в конце
 * строки, знаки препинания не отрываются от своих слов.
 *
 * Один вызов на все места, где ученик читает связный текст (конспект, шторка
 * правила): правила типографики не должны отличаться от экрана к экрану.
 */
export function tidyProse(text: string): string {
  return glueHangingPunct(bindShortWords(text))
}

/**
 * Строки абзаца конспекта с ВИСЯЧИМ отступом.
 *
 * Список слов приходит из генератора одной строкой на слово, а пример к слову —
 * следующей строкой с ведущими пробелами (`languageCourse.ts`, portionTheory).
 * Пока абзац рисовался одним блоком с `pre-wrap`, отступ держала только ПЕРВАЯ
 * строка: перенос возвращал текст к левому полю, и хвост примера («course.»)
 * оказывался левее самого примера и вровень с маркером соседнего слова —
 * список читался как рваный. Отступ обязан быть свойством СТРОКИ, а не
 * пробелами в её начале.
 *
 * Каждая строка становится своим блоком: ведущие пробелы снимаются и
 * возвращаются полем слева (шаг PROSE_STEP), а строка с маркером получает
 * вдобавок отрицательный `text-indent` — маркер стоит на своём поле, перенос
 * выравнивается по тексту за ним. Пустых строк внутри абзаца не бывает:
 * `theoryToParagraphs` режет конспект как раз по ним.
 */
const PROSE_STEP = 1.15

export type ProseLine = { key: string; text: string; style: CSSProperties }

/** Маркер списка в начале строки — за ним перенос и выравнивается. */
const PROSE_BULLET = /^[•▪‣·—–-]\s/

export function proseLines(text: string): ProseLine[] {
  const out: ProseLine[] = []
  text.split('\n').forEach((raw, i) => {
    const lead = /^[ \t]*/.exec(raw)![0].length
    const body = raw.slice(lead).trimEnd()
    if (!body) return
    // Уровень, а не число пробелов: в исходнике их то два, то три, то четыре, а
    // на экране отступ должен быть один и тот же.
    const level = Math.min(3, Math.ceil(lead / 3))
    const hang = PROSE_BULLET.test(body) ? PROSE_STEP : 0
    const pad = level * PROSE_STEP + hang
    out.push({
      key: `l${i}`,
      text: body,
      style: pad
        ? { paddingLeft: `${pad}em`, textIndent: `${-hang}em` }
        : {},
    })
  })
  return out
}
