// ─────────────────────────────────────────────────────────────────────────────
// Р17 — долг колоды первым в занятии.
//
// ЗАЧЕМ. Колода интервального повторения (review_cards + lib/fsrs.ts) до сих пор
// была приёмником: домашка сдавалась и высыпала в неё слова (captureBasicToDeck),
// а обратного провода не существовало ни одного — генератор занятия и словом не
// спрашивал, что у ученика просрочено. Повторение жило отдельным экраном, куда
// заходят по желанию, то есть не заходят: долг растёт, слово, «выученное» месяц
// назад, не возвращается никогда, и вся часть 1 стандарта про кривую забывания
// остаётся теорией.
//
// ЧТО ЗДЕСЬ. Правило и раскладка, без запросов и без React: сколько карточек
// долга берёт занятие и во что превращается карточка, чтобы её можно было
// показать по канону урока (вердикт сразу, обманки из освоенного), а не
// самооценкой «помню / не помню».
//
// ПОЧЕМУ ВЫБОР, А НЕ САМООЦЕНКА. Экран колоды (ReviewSession, CardDeck) просит
// оценить себя самому — это модель Anki, и для отдельного сеанса повторения она
// нормальна. Внутри занятия она ломает Р10: вердикт по каждому ответу обязан
// быть немедленным и однозначным, а «я вроде вспомнил» — ни то ни другое.
// Поэтому карточка долга внутри урока становится выбором из вариантов, а
// обманки берутся из ДРУГИХ карточек той же колоды — то есть из слов, которые
// ученик уже проходил (ровно требование Р9: обманка — только освоенное).
//
// ПОЧЕМУ ЕСТЬ ЗАПАСНОЙ РЕЖИМ. У ученика на втором занятии в колоде две карточки,
// и обманку взять неоткуда. Выбрасывать долг из-за этого нельзя, поэтому такая
// карточка показывается как припоминание с открытием ответа и честным «вспомнил
// / не вспомнил». Это единственное место, где самооценка остаётся, и она уходит
// сама, как только колода набрала четыре слова.
// ─────────────────────────────────────────────────────────────────────────────

import type { ReviewCard } from '../data/reviewDeck'
import type { ReviewGrade } from './srs'

/**
 * Сколько карточек долга берёт обычное занятие.
 *
 * Медиана занятия — 20 экранов (docs/MEMORY_STANDARD.md, блок H), и весь блок H
 * был про то, чтобы вечер не превращался в марафон. Карточка долга дешевле
 * экрана лестницы — это один тап по знакомому слову, — но четыре штуки это
 * потолок, за которым повторение начинает читаться как вторая домашка.
 */
export const DEBT_SLOTS = 4

/** Сколько берёт занятие, когда долг уже большой (см. DEBT_THRESHOLD). */
export const DEBT_SLOTS_WIDE = 8

/**
 * Долг, выше которого занятие открывается расширенным повторением.
 *
 * Порог, а не пропорция: пятнадцать просроченных слов — это уже пропущенная
 * неделя, и разгребать её по четыре штуки значит не разгрести никогда. Выше
 * порога занятие честно отдаёт повторению вдвое больше места.
 */
export const DEBT_THRESHOLD = 15

/**
 * Сколько карточек долга ставится в начало занятия.
 *
 * Потолок обязателен в обе стороны: без верхней границы ученик, вернувшийся
 * после отпуска, получил бы вместо занятия сто карточек и не получил бы ни
 * одного нового слова — то есть наказание за паузу. Долг разгребается по
 * куску за вечер, остальное продолжает ждать своего срока в колоде.
 */
export function reviewSlots(dueTotal: number): number {
  if (dueTotal <= 0) return 0
  return Math.min(dueTotal, dueTotal >= DEBT_THRESHOLD ? DEBT_SLOTS_WIDE : DEBT_SLOTS)
}

/** Задание из карточки долга: выбор из вариантов либо припоминание с открытием. */
export type ReviewTask =
  | { kind: 'choice'; card: ReviewCard; choices: string[]; correct: number }
  | { kind: 'recall'; card: ReviewCard }

/** Балл в колоду по итогу ответа (шкала lib/srs.ts: 1 — не помню, 4 — хорошо). */
export function gradeFor(ok: boolean): ReviewGrade {
  return ok ? 4 : 1
}

/**
 * Лицо ответа — то, что стоит в вариантах выбора.
 *
 * Оборот карточки собирается в двух разных формах, и обе надо срезать, но с
 * разных концов:
 *
 *   • словарная карточка урока — «перевод — чтение» (lib/reviewCapture.ts:
 *     vocabBack). Чтение в варианте лишнее: оно длинное и ничего не различает,
 *     потому что есть у всех четырёх;
 *   • карточка тренажёра — «слово — перевод», и слово в ней ТО ЖЕ, что стоит в
 *     вопросе: «대학교 — что значит?» → «대학교 — университет». Оставить его
 *     значит напечатать ответ прямо в задании: из четырёх вариантов верный тот,
 *     чьё начало совпало с вопросом, и знать язык для этого не нужно.
 *
 * Отличаются они не источником, а тем, повторяет ли голова оборота вопрос.
 * Проверять по `source` было бы хрупко: одну и ту же форму пишут и ручные
 * карточки, и разговорник.
 *
 * Полный оборот со всем, что здесь срезано, показывается после ответа.
 */
export function answerFace(card: ReviewCard): string {
  const answer = (card.answer ?? '').trim()
  const prompt = (card.prompt ?? '').trim()
  const cut = answer.indexOf(' — ')
  if (cut <= 0) return answer

  const head = answer.slice(0, cut).trim()
  const tail = answer.slice(cut + 3).trim()
  // Голова повторяет вопрос — берём хвост (перевод).
  if (tail && head && prompt.includes(head)) return tail
  // Иначе хвост — это чтение, и в варианте выбора ему делать нечего.
  const last = answer.lastIndexOf(' — ')
  return last > 0 ? answer.slice(0, last).trim() : answer
}

/** Ключ сравнения вариантов: регистр и пробелы не различают ответы. */
const key = (s: string) => s.trim().toLowerCase().replace(/\s+/g, ' ')

/**
 * Детерминированный хеш строки.
 *
 * Без `Math.random`: варианты обязаны лечь одинаково при каждом рендере, иначе
 * они прыгают на перерисовке, а после F5 ученик видит другой набор обманок к
 * тому же слову и читает это как поломку.
 */
function hash(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0
  return Math.abs(h)
}

/** Сколько вариантов в задании долга. Четыре — ступень 4 по Р2. */
const CHOICES = 4

/**
 * Порода ответа — что это за строка вообще.
 *
 * ЗАЧЕМ. Колода одна на предмет, а кладут в неё карточки трёх разных жанров, и
 * ответы у них несопоставимы:
 *
 *   «Как звучит 옷을?»              → «[오슬] — одежду (винительный)»  чтение
 *   «Что происходит с 받침 …?»       → «Он переходит в начало слога»   правило
 *   «ㄹ»                            → «р»                             буква
 *   «평일»                          → «будни»                         значение
 *
 * Каждая из них — правильный ответ на СВОЙ вопрос. Но подставленная обманкой к
 * чужому, она отсекается не глядя: к «매운 — что значит?» вариант «[오슬]» не
 * читают, его видят. Замер на живой колоде: у восьми карточек долга такие
 * посторонние варианты стояли в трёх.
 *
 * Породу выводим из самой строки — отдельного поля в review_cards нет и заводить
 * его ради этого значило бы мигрировать таблицу под эвристику.
 */
type FaceKind = 'reading' | 'letter' | 'phrase' | 'meaning'

function faceKind(face: string): FaceKind {
  const s = face.trim()
  // Чтение в квадратных скобках — [오슬], [한구거]. Пишет тренажёр правил чтения.
  if (/^\[.*\]$/.test(s)) return 'reading'
  // Буква алфавита: «р», «п», «ㄹ». Обманкой годится только другой букве.
  if (s.length <= 2) return 'letter'
  // Формулировка правила: длинная фраза от четырёх слов. Значения слов такими
  // не бывают даже у многословных («ничего страшного; нормально» — три).
  if (s.split(/\s+/).length >= 4) return 'phrase'
  return 'meaning'
}

/**
 * Годится ли строка в обманку к этому ответу — по ФОРМЕ, а не по смыслу.
 *
 * Порода обязана совпасть (см. faceKind), плюс отношение длин: внутри одной
 * породы «будни» (5) и «не работает, выходной» (21) — это 4.2, и такая пара
 * тоже решается длиной.
 *
 * Порог 2.5 выставлен по замеру, а не на глаз. Обязаны пройти: «нога, мост»
 * (10) против «не работает, выходной» (21) — это 2.1. Обязаны отсеяться: «р»
 * (1) против того же — 21; «Он переходит в начало следующего слога» (38)
 * против «будни» (5) — 7.6. На тройке в сито проползала пара «автобус» (7) /
 * «не работает, выходной» (21) — ровно 3.0.
 */
const SHAPE_RATIO = 2.5

/**
 * Два варианта об одном и том же — уточнение в скобках у того же слова.
 *
 * «спасибо» и «спасибо (мягче)» в одном задании это не четыре варианта, а три:
 * ученик, знающий ответ, всё равно видит две строки об одном, а не знающий
 * справедливо считает задание кривым. Тот же случай, что Р5 ловит в порциях
 * («нет» / «нет (не имеется)»), только здесь — среди обманок.
 *
 * Сравниваем по границе слова, а не подстрокой: «р» лежит внутри «острый», и
 * подстрочная проверка выбросила бы честную обманку.
 */
function nearDuplicate(a: string, b: string): boolean {
  const x = key(a)
  const y = key(b)
  return x === y || x.startsWith(y + ' ') || y.startsWith(x + ' ')
}

function shapeFits(candidate: string, right: string): boolean {
  const a = candidate.trim().length
  const b = right.trim().length
  if (!a || !b) return false
  if (faceKind(candidate) !== faceKind(right)) return false
  return Math.max(a, b) / Math.min(a, b) <= SHAPE_RATIO
}

/**
 * Карточки долга → задания занятия.
 *
 * `pool` — колода того же предмета целиком (для обманок). Сами карточки долга
 * тоже годятся в обманки друг другу и входят в пул у вызывающего.
 *
 * Место верного ответа считается от карточки, а не пишется нулём (Р15): у
 * долга это особенно важно, потому что одно и то же слово возвращается
 * десятки раз, и постоянное место превратило бы повторение в тренировку
 * пальца.
 */
export function buildReviewTasks(due: ReviewCard[], pool: ReviewCard[]): ReviewTask[] {
  // Пул обманок: по одной записи на смысл. Дубли (одно слово, попавшее в колоду
  // и словом урока, и ошибкой) дали бы два одинаковых варианта в одном задании —
  // задание без верного ответа с точки зрения ученика.
  const faces = new Map<string, string>()
  for (const c of pool) {
    const face = answerFace(c)
    if (face && !faces.has(key(face))) faces.set(key(face), face)
  }

  return due.map((card): ReviewTask => {
    const right = answerFace(card)
    if (!right) return { kind: 'recall', card }

    // У карточки из ошибки домашки варианты свои — те же, что были в задании.
    const own = (card.options ?? []).map(o => o.trim()).filter(Boolean)
    if (own.length >= 2 && own.some(o => key(o) === key(right))) {
      return placed(card, own.filter((o, i) => own.findIndex(x => key(x) === key(o)) === i), right)
    }

    const others = [...faces.entries()].filter(([k]) => k !== key(right)).map(([, v]) => v)
    if (others.length < 1) return { kind: 'recall', card }

    // Обманка должна быть ПОХОЖА ПО ФОРМЕ на верный ответ, иначе задание
    // решается видом строки. В одной колоде лежат ответы четырёх пород: буква
    // («р»), значение («будни»), чтение в скобках («[오슬]») и формулировка
    // правила («Он переходит в начало следующего слога»). Вопрос «쉽니다 — что
    // значит?» с вариантами «р», «п», «нога, мост», «не работает, выходной»
    // формально имеет четыре варианта, а на деле два: однобуквенные строки
    // отсекаются не глядя. Замер на живой колоде — этот экран и был.
    const kind = faceKind(right)
    const fit = others.filter(o => shapeFits(o, right))
    // Запас на случай, когда подходящих меньше трёх. Порода важнее длины:
    // слишком короткое слово своей породы ученик хотя бы прочитает, а чужая
    // порода отсекается видом, сколько бы букв в ней ни было.
    const rest = others
      .filter(o => !shapeFits(o, right))
      .sort((a, b) =>
        Number(faceKind(b) === kind) - Number(faceKind(a) === kind)
        || Math.abs(a.length - right.length) - Math.abs(b.length - right.length))

    // Внутри подходящих — детерминированное смещение по кругу, а не с начала:
    // иначе у всех карточек занятия обманки были бы одни и те же три слова, и
    // выбор решался бы «какое из четырёх сегодня ещё не мелькало».
    const start = hash(card.id) % fit.length || 0
    const picked: string[] = []
    const take = (o: string) => {
      if (nearDuplicate(o, right)) return
      if (picked.some(p => nearDuplicate(p, o))) return
      picked.push(o)
    }
    for (let i = 0; i < fit.length && picked.length < CHOICES - 1; i++) {
      take(fit[(start + i) % fit.length])
    }
    // Подходящих не хватило — добираем ближайшими по длине. Слабая обманка
    // хуже хорошей, но лучше выбора из двух.
    for (const o of rest) {
      if (picked.length >= CHOICES - 1) break
      take(o)
    }
    return placed(card, [right, ...picked], right)
  })
}

/** Собрать вариант выбора, поставив верный ответ на место, зависящее от карточки. */
function placed(card: ReviewCard, choices: string[], right: string): ReviewTask {
  const rest = choices.filter(c => key(c) !== key(right))
  const at = hash(card.id + '|' + right) % (rest.length + 1)
  const out = [...rest]
  out.splice(at, 0, right)
  return { kind: 'choice', card, choices: out, correct: at }
}
