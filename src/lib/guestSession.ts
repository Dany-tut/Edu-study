// ─────────────────────────────────────────────────────────────────────────────
// Гость — человек без аккаунта, пришедший по присланной ссылке
//
// ЗАЧЕМ. Аккаунт ученика заводит учитель (см. JoinPage), и до сих пор это
// означало, что присланная ссылка работает только между теми, у кого кабинет
// уже есть. Знакомому, которому «скинули классный урок», доставался лендинг —
// то есть ничего. Тренажёр при этом ничего от аккаунта не хочет: тексты, сцены,
// разговорник и созвучия общие, они не выдаются курсом. Значит материал можно
// показать сразу, а вход и заявку поставить рядом как следующий шаг.
//
// ЧТО ТАКОЕ ID ГОСТЯ. Непрозрачная метка браузера, а не имя и не контакт: под
// ней в review_cards ложатся карточки, взятые в колоду (колонка anon_name,
// политика для роли anon уже есть — см. миграцию 0068). Ничего личного в ней
// нет и быть не должно: строки анонимной колоды по нынешним политикам видит
// любой anon, и метка не должна ни на кого указывать.
//
// ID НЕ СТИРАЕТСЯ ПРИ ВХОДЕ. Гость, который завёл аккаунт, оставляет за собой
// колоду под старой меткой — перенос её на ученика будет отдельной работой, и
// стереть метку сейчас значит потерять то, что переносить.
// ─────────────────────────────────────────────────────────────────────────────

const KEY = 'guest_id'

/** Метка гостя, если этот браузер уже был гостем. */
export function guestId(): string | null {
  try { return localStorage.getItem(KEY) || null } catch { return null }
}

/**
 * Начать гостевой визит: вернуть метку, заведя её при первом приходе.
 *
 * Зовётся ровно там, где гостя пускают на экран (GuestTrainerPage), а не при
 * загрузке приложения: метка в браузере ученика или учителя не нужна никому.
 */
export function startGuest(): string {
  const have = guestId()
  if (have) return have
  const id = `guest-${Math.random().toString(36).slice(2, 10)}${Date.now().toString(36)}`
  try { localStorage.setItem(KEY, id) } catch { /* приватный режим — метка живёт до перезагрузки */ }
  return id
}
