// ─────────────────────────────────────────────────────────────────────────────
// Ступени урока: какое задание легче и про какое слово оно вообще
// (docs/MEMORY_STANDARD.md — Р2 «лестница из шести касаний», Р8 «мастери-цикл»)
//
// ЗАЧЕМ. Очередь урока (lib/lessonQueue.ts) умела возвращать промах, но
// возвращала ТО ЖЕ САМОЕ задание. Ученик, который не смог набрать 아이 на
// экранной клавиатуре, через два экрана получал ту же клавиатуру и то же слово,
// которого по-прежнему не помнит, — и промахивался второй раз. Повтор без
// снижения ступени проверяет ту же неудачу, а не учит.
//
// Правильный ход — тот, который описан в стандарте и который просил ученик
// словами «подсунуть задание попроще, из предложенных хангылей»: промах на
// ступени 3 возвращает слово на ступени 2 (собрать из плиток), и только потом —
// снова на 3. Это и есть «ступень −1» из Р8.
//
// ЧТО ЗДЕСЬ. Две чистые функции без React и без данных курса:
//
//   • taskStage   — на какой ступени стоит задание (1 узнавание → 4 продукция);
//   • taskElement — про КАКОЕ слово (букву, слог) оно спрашивает.
//
// Обе смотрят только на само задание: связи «задание → слово» в данных нет и
// заводить её нельзя — тогда её пришлось бы проставить в девяти сидах и во всех
// уже сохранённых курсах, а сохранённые курсы как раз и расходятся с сидом.
//
// ПОЧЕМУ ЭЛЕМЕНТ ОПОЗНАЁТСЯ ПО ПИСЬМУ. У языкового задания две стороны: смысл
// по-русски и форма на изучаемом письме. Одинаковое слово — это одинаковая
// ФОРМА (아이), а не одинаковый перевод: «ребёнок» и «дитя» могут стоять в
// разных заданиях, а 아이 в них одно. Поэтому элемент — это первая непустая
// строка на НЕ-кириллице; у курсов родного языка (обе стороны кириллица) его
// нет, и лестница там просто не включается — очередь работает как раньше.
// ─────────────────────────────────────────────────────────────────────────────

import { normalizeTaskType } from '../data/taskTypes'
import type { HomeworkQuizQuestion } from '../data/lessonContent'

/** Ступень задания: 1 — узнавание, 2 — сборка с опорой, 3 — ввод, 4 — продукция. */
export type LadderStage = 1 | 2 | 3 | 4

/**
 * Ступени по типам заданий (Р2).
 *
 * 1. УЗНАВАНИЕ — ответ есть на экране, надо его выбрать или соединить.
 * 2. СБОРКА С ОПОРОЙ — форма собирается из готовых кусков: плитки, слоги, буквы.
 * 3. ВВОД — форма набирается целиком, опора остаётся только подсказкой.
 * 4. ПРОДУКЦИЯ — форма достаётся из памяти без опор вовсе.
 */
const STAGE_BY_TYPE: Record<string, LadderStage> = {
  flashcard: 1,
  single: 1,
  multi: 1,
  matching: 1,
  minimalPair: 1,
  videoWatch: 1,

  charBank: 2,
  wordBank: 2,
  listenBank: 2,
  buildSyllable: 2,
  unscramble: 2,
  blockOrder: 2,
  sequence: 2,
  wordDrop: 2,
  dialogGap: 2,
  trace: 2,
  pattern: 2,

  jamoType: 3,
  listenType: 3,
  crossword: 3,

  extended: 4,
  speaking: 4,
  imageDescribe: 4,
  imageCompare: 4,
}

/**
 * Ступень задания.
 *
 * `fill` стоит особняком: со скелетом ответа (сколько знаков, с чего начинается)
 * это ступень 3 — ввод с опорой; без скелета опор нет вовсе, и это уже 4.
 */
export function taskStage(q: HomeworkQuizQuestion): LadderStage {
  const tp = normalizeTaskType(q.type ?? 'single')
  if (tp === 'fill') return q.answerSkeleton?.trim() ? 3 : 4
  return STAGE_BY_TYPE[tp] ?? 3
}

/** Кириллица — язык интерфейса, а не изучаемый: форма слова не в ней. */
const CYRILLIC = /[Ѐ-ӿ]/
/** Знаки, которые формой не являются: разметка, скобки, кавычки, латинские пометки. */
const NOISE = /[«»„“”"'()\[\]{}<>.,!?;:—–\-_/\\|~*+=]/g

/**
 * Форма на изучаемом письме, вынутая из строки, — или пусто.
 *
 * Берём самый длинный кусок без кириллицы: у «Соберите слово „огурец“ (ои)» это
 * ничего (там всё по-русски), у «Прочитайте вслух: 오이 — огурец» — 오이.
 */
function scriptForm(text: string | undefined): string {
  if (!text) return ''
  const cleaned = text.replace(NOISE, ' ')
  let best = ''
  for (const chunk of cleaned.split(/\s+/)) {
    const token = chunk.trim()
    if (!token || CYRILLIC.test(token)) continue
    // Цифры и одинокая латиница — это номера и пометки вроде «o (eo)»,
    // а не слово: у формы должен быть хотя бы один незападный знак либо
    // два и больше латинских (английское слово).
    const latinOnly = /^[A-Za-z]+$/.test(token)
    if (/^\d+$/.test(token)) continue
    if (latinOnly && token.length < 2) continue
    if (token.length > best.length) best = token
  }
  return best
}

/**
 * Слово (буква, слог), про которое это задание.
 *
 * Порядок источников — от самого надёжного к догадке. Сначала то, что ученик
 * должен ПРОИЗВЕСТИ: эталон ответа, слог сборки, буква обводки. Потом лицо
 * карточки и озвучка. И только в конце — сама формулировка: в ней форма стоит у
 * заданий вида «Что значит 오이 (ои)?», где ответом служит русский перевод.
 */
export function taskElement(q: HomeworkQuizQuestion): string {
  const direct = [q.syllable, q.chamo, q.front, q.referenceAnswer, q.ttsText]
    .map(v => (v ?? '').trim())
    .find(v => v && !CYRILLIC.test(v))
  if (direct) return direct
  // Верный вариант выбора: «Как будет „о (o)“?» → ㅗ.
  const correct = (q.options ?? []).find((o: { id: string; text: string }) => o.id === q.correctOptionId)?.text
  const fromOption = scriptForm(correct)
  const fromPrompt = scriptForm(q.prompt)
  // Латиница берётся ПОСЛЕДНЕЙ. У русских пометок вроде «о (eo)» она выглядит
  // как форма, но формой не является: у «Что значит ㅓ (어)?» ответ подписан
  // «о (eo)», и по нему заданиe оказывалось про несуществующее слово «eo»
  // вместо буквы ㅓ. Настоящая форма — та, что не в западном алфавите.
  const foreign = (s: string) => !!s && !/^[A-Za-z]+$/.test(s)
  if (foreign(fromOption)) return fromOption
  if (foreign(fromPrompt)) return fromPrompt
  return fromOption || fromPrompt || ''
}

/**
 * Задание попроще про то же слово — куда откатить промах (Р8).
 *
 * Ищем по ВСЕМУ уроку, а не только позади: лестница слова разложена по занятию
 * кругами (Р2), и лёгкая ступень может стоять как до промаха, так и после. Из
 * подходящих берём САМУЮ ВЫСОКУЮ из тех, что ниже промаха: откат должен быть на
 * ступень, а не в самое начало — иначе после промаха на клавиатуре ученик
 * получал бы карточку со словом, то есть показ вместо припоминания.
 *
 * Возвращает индекс в списке заданий или -1.
 */
export function easierSameElement(
  questions: HomeworkQuizQuestion[],
  index: number,
): number {
  const missed = questions[index]
  if (!missed) return -1
  const element = taskElement(missed)
  if (!element) return -1
  const stage = taskStage(missed)
  if (stage <= 1) return -1

  let best = -1
  let bestStage = 0
  questions.forEach((q, i) => {
    if (i === index) return
    if (taskElement(q) !== element) return
    const s = taskStage(q)
    if (s >= stage) return
    if (s > bestStage) { bestStage = s; best = i }
  })
  return best
}
