// ─────────────────────────────────────────────────────────────────────────────
// Глубина по курсу: докуда ученик реально дошёл
//
// ЗАЧЕМ. Тренажёр до сих пор показывал весь материал языка сразу: тридцать
// восемь тем разговорника, десяток гнёзд созвучий, вся библиотека. Человеку,
// который на втором уроке, это читается не как «много», а как «мне сюда
// нельзя»: он не может отличить то, что ему сейчас по силам, от того, что будет
// через полгода, и закрывает вкладку. Дозировать материал должен курс — он
// единственный знает порядок.
//
// ЧТО СЧИТАЕМ ГЛУБИНОЙ. Номер последнего ОТКРЫТОГО урока, а не пройденного.
// Открытие — это решение учителя (или расписание при доступе by_date), то есть
// ровно тот рубеж, до которого ученику разрешено. Считать по «завершённым»
// значило бы наказывать за несданную домашку: урок прошли на занятии, слова
// звучали, а тренажёр их прячет.
//
// ПОЧЕМУ НЕ ХРАНИМ. Глубина выводится из уже загруженных курсов
// (studentDataStore): отдельное поле пришлось бы синхронизировать с каждым
// открытием урока и оно бы разъезжалось. Расчёт дешёвый — проход по урокам
// одного курса.
//
// НОЛЬ — ЭТО «ПОКАЗАТЬ ВСЁ». Тренажёром пользуются и без курса: ученик может
// зайти в языковой предмет, у которого курс ещё не назначен, и материал ему всё
// равно полезен. Прятать его тогда не за что и не по чему.
// ─────────────────────────────────────────────────────────────────────────────

import type { Subject } from '../data/mockData'

/**
 * Докуда открыт курс предмета: номер последнего доступного урока.
 *
 * `aliases` — написания предмета, по которым курс узнаётся среди остальных
 * (тот же список, что фильтрует колоду повторений, см. subjectAliases).
 * Курса нет или все уроки закрыты — ноль.
 */
export function courseReach(subjects: Subject[], aliases: string[]): number {
  const want = new Set(aliases.map(a => a.toLowerCase()))
  let reach = 0
  for (const s of subjects) {
    const tag = (s.subject ?? s.name ?? '').toLowerCase()
    if (want.size > 0 && !want.has(tag)) continue
    for (const m of s.modules) {
      for (const l of m.lessons) {
        // Закрытый урок глубину не двигает: он ученику ещё не показан.
        if (l.status === 'locked') continue
        if (l.number > reach) reach = l.number
      }
    }
  }
  return reach
}

/**
 * Подпись глубины для рейла: «открыто 7 уроков» или честное «курс не назначен».
 *
 * Отдельной строкой, потому что цифра без объяснения читается как ограничение
 * («почему мне показывают только это?»), а с объяснением — как ориентир.
 */
export function reachNote(reach: number): string {
  return reach > 0
    ? `Открыто уроков курса: ${reach}. Новое доливается по мере прохождения.`
    : 'Курс не назначен — показан весь материал языка.'
}
