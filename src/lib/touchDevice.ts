/**
 * Есть ли у этого устройства палец.
 *
 * Жесты по посту (свайп, долгое нажатие, двойной тап) существуют только там,
 * где есть касание: мышью их не сделать, и прятать ради них кнопки под постом
 * на десктопе значило бы отобрать действия совсем.
 *
 * Считается ОДИН РАЗ при загрузке модуля: гибрид (ноутбук с сенсорным экраном)
 * тут честно считается сенсорным — кнопки при этом никуда не деваются, потому
 * что строку действий гасит отдельная настройка, а не сам факт касания.
 */
export const touchDevice: boolean = typeof window !== 'undefined'
  && (navigator.maxTouchPoints > 0 || 'ontouchstart' in window)
