/**
 * Названия таксонов после слова ранга — с заглавной: «класс Ракообразные»,
 * «к типу Членистоногих», «тип Кольчатые черви». Слово ранга не трогаем.
 *
 * Распознавание речи и OCR пишут их строчными. Правим только явный случай:
 * слово ранга, сразу за ним название во множественном числе с типичной для
 * таксонов основой. «Этот класс животных», «тип химической связи», «класс
 * неорганических веществ», «отдел мозга» остаются как есть.
 */

const RANK = '(?:(?:над|под|инфра)?(?:царств|домен|тип|отдел|класс|отряд|порядк|семейств|триб)(?:о|а|у|ом|е|ы|ов|ам|ами|ах)?|порядок)'
// Множественное число прилагательного/причастия: Ракообразные, Членистоногих, Хищным…
const PLURAL = '(?:ые|ие|ых|их|ым|им|ыми|ими)'
// Основы, по которым прилагательное узнаётся как название таксона.
const TAXON_STEM = '(?:образн|ног|крыл|цветн|семенн|дольн|питающ|полостн|кож|хордов|позвоночн|черепн|челюстн|земноводн|пресмыкающ|хищн|оядн|копытн|простейш|жаберн|лучепер|хрящев|костист|ресничн|кольчат|сумчат|плацентарн|паукообразн|насеком|споров|жгутиков|саркодов|инфузор|мохообразн|папоротниковидн|хвощевидн|плауновидн|злаков|бобов|паслёнов|пасленов|лилейн|розоцветн|сложноцветн|крестоцветн|зонтичн|псов|кошач|осетров|лососев|карпов|окунев|воробьин|бесхвост|хвостат|безног|членистоног|иглокож|головоног|брюхоног|двустворчат|моллюск)'
// Существительные-таксоны (во всех формах множественного числа).
const NOUN = '(?:птиц|рыб|моллюск|черв|губк|хвощ|плаун|папоротник|примат|грызун|рептили|амфиби|насеком|трилобит|ракоскорпион|мхи|мхов|мхам)(?:ы|и|ей|ов|ам|ами|ах)?'
// Только после «царство»: общие слова, которые иначе писать с заглавной нельзя.
const KINGDOM = '(?:животн|растени|гриб|бактери|архе|протист)(?:ые|ых|ым|ыми|я|й|ям|ями|ях|ы|ов|ам|ами|ах|и|ей)?'
// «этот класс животных», «каждый тип», «данного отряда» — не название.
const DETERMINER = new Set(('этот этого этому этим этом эта этой эту эти этих этими тот того тому тем том та той ту те тех такой такого таком такая такие таких ' +
  'каждый каждого каждом каждая данный данного данном данная наш нашего ваш вашего другой другого другом любой любого какой какого каком ' +
  'который которого котором один одного одном сам самого весь всего целый целого').split(' '))

const LETTER = '[а-яёА-ЯЁ]'
const pattern = new RegExp(
  `(^|[^а-яёА-ЯЁ-])(${RANK})(\\s+)([а-яё]${LETTER}*)(?=$|[^а-яёА-ЯЁ-])`,
  'giu',
)
// Распознавание часто даёт единственное число («класс ракообразный») — тоже название.
const taxonAdjective = new RegExp(`^(?:${LETTER}*${TAXON_STEM})(?:${PLURAL}|ый|ий|ая|яя|ое)$`, 'u')
const anyPluralAdjective = new RegExp(`^${LETTER}+${PLURAL}$`, 'u')
const taxonNoun = new RegExp(`^${NOUN}$`, 'u')
const kingdomWord = new RegExp(`^${KINGDOM}$`, 'u')
const worms = new RegExp(`^\\s+черв(?:и|ей|ям|ями|ях)(?=$|[^а-яё])`, 'u')

function isTaxon(rank: string, word: string, after: string): boolean {
  if (taxonAdjective.test(word) || taxonNoun.test(word)) return true
  if (/^(?:над|под)?царств/.test(rank) || /^домен/.test(rank)) return kingdomWord.test(word)
  // «тип Кольчатые черви», «класс Плоских червей»
  return anyPluralAdjective.test(word) && worms.test(after)
}

export function taxonCase(text: string): string {
  if (!text) return text
  return text.replace(pattern, (whole, lead: string, rankWord: string, gap: string, word: string, offset: number, source: string) => {
    const rank = rankWord.toLocaleLowerCase('ru')
    const before = source.slice(0, offset + lead.length).match(/([а-яёА-ЯЁ]+)\s*$/u)?.[1]?.toLocaleLowerCase('ru')
    if (before && DETERMINER.has(before)) return whole
    const after = source.slice(offset + whole.length)
    if (!isTaxon(rank, word, after)) return whole
    return lead + rankWord + gap + word[0].toLocaleUpperCase('ru') + word.slice(1)
  })
}
