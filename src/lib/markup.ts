// ─────────────────────────────────────────────────────────────────────────────
// Выделение в учебном тексте: **важное** становится жирным, а не звёздочками.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ РАЗБОР, А НЕ MARKDOWN-БИБЛИОТЕКА. Абзац конспекта доезжает до
// экрана не строкой, а разметкой: слова разбирает словарь (GlossedText), стыки
// склеивает типографика (lib/typography). Готовый парсер вернул бы свой HTML —
// и слова в нём перестали бы тапаться. Поэтому из текста мы достаём ровно одно:
// ГДЕ выделение, в координатах уже очищенной строки. Само оформление остаётся
// за тем, кто рисует текст.
//
// ПОЧЕМУ ГРАНИЦЫ, А НЕ КУСКИ. Позиции переживают любую последующую нарезку:
// на слова, на связки, на колонки транскрипции. Куски пришлось бы резать ещё
// раз в каждом из этих мест.
// ─────────────────────────────────────────────────────────────────────────────

/** Отрезок выделенного текста в очищенной строке: [start, end). */
export type BoldRun = { start: number; end: number }

// Пара звёздочек вокруг непустого куска. Ленивый квантификатор — чтобы два
// выделения в абзаце не слиплись в одно вместе с текстом между ними.
const BOLD = /\*\*([^*]+?)\*\*/g

/**
 * Убрать маркеры и запомнить, что было выделено.
 *
 * Одиночная звёздочка остаётся в тексте как есть: это либо опечатка автора,
 * либо настоящая звёздочка (сноска, умножение), и молча съедать её нельзя.
 */
export function parseBold(text: string): { text: string; bold: BoldRun[] } {
  if (!text.includes('**')) return { text, bold: [] }
  const bold: BoldRun[] = []
  let out = ''
  let at = 0
  for (const m of text.matchAll(BOLD)) {
    out += text.slice(at, m.index)
    const start = out.length
    out += m[1]
    bold.push({ start, end: out.length })
    at = m.index + m[0].length
  }
  return { text: out + text.slice(at), bold }
}

/** Попадает ли знак под номером `at` в выделение. */
export function isBoldAt(bold: BoldRun[], at: number): boolean {
  return bold.some(r => at >= r.start && at < r.end)
}

/** Насыщенность выделенного текста. Одно число на все места показа. */
export const BOLD_WEIGHT = 750
