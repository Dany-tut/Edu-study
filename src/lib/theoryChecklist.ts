// ─────────────────────────────────────────────────────────────────────────────
// Легаси-чек-листы в конспекте
//
// Раньше конспект юнита заканчивался списком «Чек-лист: что должно остаться в
// руке» — пунктами с галочками (разметка `- [ ]`). Блок убран: галочка была
// самозаявлением, ничего не проверяла, никуда не шла (ни в прогресс, ни
// учителю) и прожималась насквозь за три секунды, а на телефоне занимала
// половину экрана между конспектом и материалами. То, что он спрашивал («узнаю
// ㅏ на слух»), проверяет тренажёр, а не отметка о себе.
//
// Из сидов курсов блок удалён, но у курсов, СОХРАНЁННЫХ В БАЗУ раньше, он
// остался абзацем внутри lessons.content. Поэтому распознавание живёт дальше:
// такой абзац при показе урока выбрасывается (см. data/lessonContent), иначе
// ученик увидел бы сырую разметку «- [ ] …» вместо чек-листа.
// ─────────────────────────────────────────────────────────────────────────────

const ITEM = /^[-*]\s*\[\s*\]\s+.+$/

/**
 * Абзац конспекта — это старый чек-лист?
 *
 * Заголовок допустим только один и только первой строкой, всё остальное обязано
 * быть пунктами: абзац, где после пунктов идёт обычная строка, чек-листом не
 * считается — иначе из конспекта пропал бы текст, который разметку не имел в
 * виду.
 */
export function isChecklistParagraph(chunk: string): boolean {
  const lines = chunk.split('\n').map(l => l.trim()).filter(Boolean)
  if (lines.length < 2) return false
  const body = ITEM.test(lines[0]) ? lines : lines.slice(1)
  return body.length > 0 && body.every(l => ITEM.test(l))
}
