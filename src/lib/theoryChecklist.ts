// ─────────────────────────────────────────────────────────────────────────────
// Чек-лист внутри конспекта
//
// ЗАЧЕМ. Конспект отвечает на вопрос «как это устроено», но не отвечает на
// вопрос «а я это уже умею». Между «прочитал про 은/는» и «ставлю 은/는, не
// задумываясь» проходит несколько недель, и всё это время ученик не знает, где
// он находится: юнит пройден, форма — нет. Чек-лист даёт ему ту самую отметку,
// которую он иначе ставит в голове и забывает.
//
// ПОЧЕМУ РАЗМЕТКОЙ В ТЕКСТЕ, А НЕ ПОЛЕМ УРОКА. Конспект едет к ученику одной
// строкой (lessons.content → LessonParagraph), и любое новое поле пришлось бы
// протаскивать через редактор курса, jsonb и сверку сида — ради списка из шести
// строк. Разметка `- [ ]` этого не требует: чек-лист остаётся частью текста,
// его правит тот же редактор, а не поддержавший её экран покажет обычный
// список — не сломается ничего.
//
// ОТМЕТКИ ЛОКАЛЬНЫЕ. Галочка — заметка ученика себе, а не оценка: она не идёт
// ни в прогресс, ни учителю. Поэтому localStorage, а не БД: цена синхронизации
// здесь выше пользы, а потерянная при смене устройства галочка ничего не портит.
// ─────────────────────────────────────────────────────────────────────────────

/** Разобранный чек-лист: заголовок (если он был) и пункты. */
export interface TheoryChecklist {
  /** Строка перед списком — «Чек-лист: …». Пусто, если список начинается сразу. */
  title: string
  /** Пункты без маркера `- [ ]`. */
  items: string[]
}

const ITEM = /^[-*]\s*\[\s*\]\s+(.+)$/

/**
 * Разобрать абзац конспекта как чек-лист.
 *
 * Возвращает null, если это обычный текст: заголовок допустим только один и
 * только первой строкой, всё остальное обязано быть пунктами. Абзац, где после
 * пунктов идёт обычная строка, чек-листом не считается — иначе разметка начнёт
 * срабатывать на текстах, которые её не имели в виду.
 */
export function parseChecklist(chunk: string): TheoryChecklist | null {
  const lines = chunk.split('\n').map(l => l.trim()).filter(Boolean)
  if (lines.length < 2) return null

  const first = lines[0]
  const head = ITEM.test(first) ? '' : first
  const body = head ? lines.slice(1) : lines
  if (!body.length) return null

  const items: string[] = []
  for (const line of body) {
    const hit = line.match(ITEM)
    if (!hit) return null
    items.push(hit[1].trim())
  }
  return { title: head, items }
}

/** Собрать чек-лист обратно в абзац конспекта. */
export function checklistBlock(title: string, items: string[]): string {
  return [title, ...items.map(i => `- [ ] ${i}`)].join('\n')
}
