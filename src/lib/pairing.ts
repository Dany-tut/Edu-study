// ─────────────────────────────────────────────────────────────────────────────
// Пара «слово оригинала ↔ слово перевода»
//
// ЗАЧЕМ. В партитуре (см. components/trainer/ScoreReader) перевод стоит целой
// строкой напротив оригинала, и это правильная единица для чтения: пословный
// перевод корейского или японского нечитаем. Но когда ученик уже ткнул в
// незнакомое слово, ему сразу нужно второе — ГДЕ ЭТО В ПЕРЕВОДЕ. Карточка
// говорит «отзывать», а в русской строке стоит «отзывается», и глаз ищет его
// вручную; на длинной строке договора этот поиск занимает больше времени, чем
// сам перевод.
//
// Обратный ход нужен ровно так же и даже чаще: в переводе видно понятие
// («средневзвешенный балл»), и вопрос — каким английским словом оно сказано.
//
// КАК СВОДИМ. Морфологии у нас нет и не будет (см. lib/lexicon.ts), поэтому
// сводим по огрублённой основе: у русского слова отрезаем окончание, у перевода
// из словаря — тоже, и сверяем. Это догадка, и она ошибается в обе стороны:
// «поездки» и «поезд» дают одну основу, а «день» и «дня» — разные (беглая
// гласная). Поэтому цена ошибки держится низкой: пара — это подсветка, а не
// утверждение. Лишняя подсветка стоит одного взгляда, пропущенная — ровно того
// же, что и сегодня.
//
// ЧЕГО ЗДЕСЬ НЕТ. Служебных слов: пара «of ↔ из» ничего не объясняет, а
// подчёркнутых предлогов в строке перевода становится больше, чем слов.
// ─────────────────────────────────────────────────────────────────────────────

import { buildLexicon } from './lexicon'
import type { WordGloss } from '../data/wordGloss'

/** Кусок перевода. `pair` есть только у слова, нашедшего себе пару в оригинале. */
export interface PairToken {
  text: string
  /** Слово оригинала в нижнем регистре — ключ подсветки на обеих сторонах. */
  pair?: string
}

// Служебные слова: их пары не несут смысла (см. шапку). Всё короче трёх букв
// отсеивается само — по длине.
const RU_STOP = new Set([
  'или', 'что', 'как', 'это', 'этот', 'эта', 'эти', 'тот', 'там', 'тут', 'вот',
  'все', 'весь', 'вся', 'уже', 'ещё', 'еще', 'так', 'кто', 'чем', 'чтобы',
  'если', 'при', 'под', 'над', 'про', 'без', 'для', 'между', 'только', 'быть',
  'был', 'была', 'были', 'есть', 'его', 'её', 'ее', 'их', 'ему', 'ней', 'они',
  'она', 'оно', 'мне', 'вам', 'нам', 'тебе', 'себя', 'свой', 'своя', 'свои',
  'своих', 'который', 'которая', 'которое', 'которые', 'которых',
])

// Окончания — от длинных к коротким. Регулярка привязана к концу строки, то
// есть совпасть может только хвост; из нескольких хвостов берётся самый длинный.
const RU_END = /(?:иями|ениях|ениям|ями|ами|иях|иям|ыми|ими|ого|его|ому|ему|ешь|ете|ишь|ите|ают|яют|уют|ать|ять|еть|ить|уть|ыть|ия|ию|ии|ах|ях|ов|ев|ей|ой|ый|ий|ая|яя|ое|ее|ые|ие|ым|им|ом|ем|ую|юю|ит|ят|ет|ут|ют|ал|ял|ил|ла|ло|ли|ть|а|я|о|е|ы|и|у|ю|ь|й)$/

/**
 * Огрублённая основа русского слова. Не лингвистическая: задача не «получить
 * лемму», а «получить одно и то же для двух форм одного слова».
 *
 * Короче трёх букв основу не режем: «дом» после отрезания «о» превратился бы в
 * «д» и сцепился бы с половиной словаря.
 */
export function ruStem(word: string): string {
  const base = word.toLowerCase().replace(/ё/g, 'е').replace(/(?:ся|сь)$/, '')
  const cut = base.replace(RU_END, '')
  return cut.length >= 3 ? cut : base
}

/**
 * Считаем ли две основы одним словом.
 *
 * Точное совпадение — от трёх букв: короче начинается ловля чужого. Совпадение
 * по началу — от четырёх и с разницей не больше двух букв: этим добираются
 * случаи, где стеммер отрезал по-разному («стипенди» из «стипендия» против
 * «стипенд» из «стипендии»).
 */
function stemsMatch(a: string, b: string): boolean {
  if (!a || !b) return false
  if (a === b) return a.length >= 3
  const [short, long] = a.length < b.length ? [a, b] : [b, a]
  return short.length >= 4 && long.startsWith(short) && long.length - short.length <= 2
}

/**
 * Русские слова, которыми словарь объясняет одну запись.
 *
 * Пояснения в скобках выбрасываем: «(о человеке) строгий» — это не перевод, а
 * условие, и «человек» из него в паре со strict выглядел бы ошибкой. Варианты
 * через запятую берём все: словарь пишет «отзывать, забирать», а в строке
 * перевода может стоять любое из двух.
 */
function glossWords(ru: string): string[] {
  const out: string[] = []
  for (const part of ru.replace(/\([^)]*\)/g, ' ').split(/[,;/|]|\bили\b/)) {
    for (const w of part.split(/[^\p{L}\p{N}-]+/u)) {
      const word = w.trim()
      if (word.length >= 3 && !RU_STOP.has(word.toLowerCase())) out.push(word)
    }
  }
  return out
}

/**
 * Разложить перевод на куски и подписать те, что нашли себе слово в оригинале.
 *
 * Ключ пары — слово оригинала в нижнем регистре: по нему подсвечиваются ОБЕ
 * стороны разом (в оригинале — через highlight у GlossedText, который сверяет
 * так же). Поэтому все вхождения одного слова загораются вместе — это и надо:
 * «вот же оно, тремя строками выше» здесь такая же польза, как и сама пара.
 */
export function pairTranslation(
  source: string,
  translation: string,
  lang: string,
  extra: WordGloss[] = [],
): PairToken[] {
  const tokens: PairToken[] = (translation.match(/[\p{L}\p{N}]+(?:[-’'][\p{L}\p{N}]+)*|[^\p{L}\p{N}]+/gu) ?? [])
    .map(text => ({ text }))
  if (!translation.trim() || !source.trim()) return tokens

  // Основа перевода → слово оригинала. Первое вхождение выигрывает: если слово
  // повторяется, ученику важнее то, что стоит раньше в тексте.
  const lex = buildLexicon(lang, extra)
  const index: { stem: string; term: string }[] = []
  const seen = new Set<string>()
  for (const seg of lex.segment(source)) {
    if (!seg.word || !seg.gloss) continue
    const term = seg.text.trim().toLowerCase()
    for (const w of glossWords(seg.gloss.ru)) {
      const stem = ruStem(w)
      if (stem.length < 3 || seen.has(stem)) continue
      seen.add(stem)
      index.push({ stem, term })
    }
  }

  for (const token of tokens) {
    if (!/^[\p{L}\p{N}]/u.test(token.text)) continue
    const word = token.text.toLowerCase()
    if (word.length < 3 || RU_STOP.has(word)) continue
    const stem = ruStem(word)
    const hit = index.find(e => stemsMatch(e.stem, stem))
    if (hit) token.pair = hit.term
  }

  return tokens
}
