// ─────────────────────────────────────────────────────────────────────────────
// Подписи курсов в узких местах
//
// ЗАЧЕМ. Переключатель курсов в мобильном доке зажат в 340 пикселей, а подписью
// служит полное название курса. У человека, который учит один язык двумя
// курсами, названия начинаются одинаково — «Корейский к TOPIK I» и «Корейский:
// язык выживания», — и на общее слово уходит треть строки. До различающейся
// части место не доезжает: обе чипсы показывают ровно тот кусок, который у них
// одинаковый, и выбрать глазами нельзя, хотя ряд листается.
//
// ПОЧЕМУ НЕ ОБРЕЗАТЬ МНОГОТОЧИЕМ. Обрезка убирает конец, а различие живёт
// именно в конце. «Корейский к TO…» и «Корейский: яз…» отличаются не лучше
// полных названий — просто короче.
//
// ГДЕ ЭТО НЕ ПРИМЕНЯТЬ. Там, где подпись стоит одна: в шапке экрана, в списке
// курсов, в письме. Срезанный префикс читается только в ряду, где остальные
// подписи рядом и общее слово восстанавливается из соседей.
// ─────────────────────────────────────────────────────────────────────────────

/** Слово без хвостовой пунктуации и регистра — для сравнения, а не для показа. */
const norm = (w: string) => w.replace(/[:,.;—–-]+$/, '').toLowerCase()

/**
 * Срезать у подписей общее начало — по словам, а не по символам.
 *
 * Посимвольное сравнение дало бы «Корейский» и «Корейский:» с общим началом в
 * девять букв и остатком «: язык выживания» — то есть строку, начинающуюся с
 * двоеточия. Общее слово — единица, которую видит глаз.
 *
 * Возвращает столько же строк, сколько получил, в том же порядке. Если резать
 * нечего или остаток вышел бы пустым, возвращаются исходные подписи: пустая
 * чипса хуже длинной.
 */
export function stripCommonPrefix(names: string[]): string[] {
  if (names.length < 2) return names

  const words = names.map(n => n.trim().split(/\s+/).filter(Boolean))
  if (words.some(ws => ws.length === 0)) return names

  let k = 0
  for (;;) {
    const head = words[0][k]
    if (head === undefined) break
    if (!words.every(ws => ws[k] !== undefined && norm(ws[k]) === norm(head))) break
    // Последнее слово не срезаем никогда: подпись, совпавшая с соседкой
    // целиком, осталась бы пустой строкой.
    if (!words.every(ws => ws.length > k + 1)) break
    k++
  }
  if (k === 0) return names

  const cut = words.map(ws => ws.slice(k).join(' ').replace(/^[\s:,.;—–-]+/, ''))
  // Огрызок в один символ ничего не говорит — в таком случае честнее длинное
  // название и горизонтальный скролл.
  if (cut.some(x => x.length < 2)) return names

  // Остаток становится самостоятельной подписью, поэтому пишется с большой:
  // «к TOPIK I» отдельной чипсой выглядит обрывком, «К TOPIK I» — названием.
  return cut.map(x => x.charAt(0).toUpperCase() + x.slice(1))
}
