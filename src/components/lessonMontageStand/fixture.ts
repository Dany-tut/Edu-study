/** Длительность реплики ≈ по словам, как у живой речи. */
const say = (text: string) => Math.max(1.6, text.split(/\s+/).length * 0.43)

// «Много пауз»: после каждой третьей реплики — ещё отрезок тишины или тихой
// работы разной длины. Так видно, как листается длинный список вырезок.
function build(many = false) {
  const lines: MontageLine[] = []
  const quiet: QuietSpan[] = []
  let t = 4
  const pause = (length: number, level: number) => {
    quiet.push({ id: 'q' + quiet.length, start: +t.toFixed(2), end: +(t + length).toFixed(2), level })
    t += length + 0.4
  }
  for (const step of script) {
    if (Array.isArray(step)) {
      const [voice, text] = step
      const d = say(text)
      lines.push({ id: 'l' + lines.length, start: +t.toFixed(2), end: +(t + d).toFixed(2), text, speaker: voice })
      t += d + 0.7
      if (many && lines.length % 3 === 0) pause(25 + (lines.length * 37) % 160, lines.length % 2 ? -44 : -56)
    } else pause(step.quiet, step.level)
  }
  return { lines, quiet, duration: Math.ceil(t + 6) }
}

export type Fixture = ReturnType<typeof build> & { chapters: LessonTimecode[]; levelAt: (t: number) => number }
export const voices = ['v1', 'v2', 'v3', 'v4', 'v5']

function make(many: boolean): Fixture {
  const f = build(many)
  const at = (prefix: string) => f.lines.find(l => l.text.startsWith(prefix))!.start
  const chapters: LessonTimecode[] = [
    { seconds: 0, time: '0:00', label: 'Степень окисления' },
    { seconds: at('Теперь метод'), time: '', label: 'Электронный баланс' },
    { seconds: at('Извините, звонок'), time: '', label: 'Перманганат в разных средах' },
    { seconds: at('Последнее на сегодня'), time: '', label: 'Диспропорционирование' },
  ]
  /** Громкость в момент t, дБ: речь громкая, тихая работа шуршит, тишина пустая. */
  const levelAt = (t: number) => {
    const n = Math.sin(t * 12.9898) * 43758.5453, noise = n - Math.floor(n)
    const line = f.lines.find(l => t >= l.start && t < l.end)
    if (line) return -26 + noise * 16 * (0.55 + 0.45 * Math.sin(t * 2.3))
    const q = f.quiet.find(s => t >= s.start && t < s.end)
    if (q) return q.level - 3 + noise * (q.level > -50 ? 5 : 2) + (q.level > -50 && noise > 0.97 ? 9 : 0)
    return -50 + noise * 6
  }
  return { ...f, chapters, levelAt }
}

