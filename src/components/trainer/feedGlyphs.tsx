// ЗНАЧКИ ПОСТА — СВОИ, А НЕ ИЗ НАБОРА
//
// Библиотечные значки нарисованы под интерфейс вообще: одинаковая жёсткая
// сетка, острые сочленения, одна и та же толщина у сердца и у буквы. В ленте
// они стоят вплотную друг к другу и на просвет читаются как забор из палочек.
//
// Здесь одно семейство: общий кегль, скруглённые концы, одна толщина линии и —
// главное — ЗАЛИВКА КАК СОСТОЯНИЕ. Нажатое сердце и открытый тред залиты
// акцентом целиком, а не подкрашены контуром: тонкий цветной контур на тёмной
// теме почти неотличим от серого (см. память про «невидимое в тёмной теме»),
// заливка видна с первого взгляда.
//
// `vectorEffect` держит толщину линии постоянной: значок иногда едет вместе с
// кнопкой (нажатие ужимает её), и без него штрих ужимался бы вместе с ним.
//
// ЖИВУТ ОТДЕЛЬНО ОТ ПОСТА: те же знаки рисует слой жеста (lib/feedGestures.ts)
// и макет в настройках ленты — сердце под пальцем при свайпе обязано быть тем
// же сердцем, что стояло в строке действий.
// ─────────────────────────────────────────────────────────────────────────────

const SIZE = 19

export function Glyph({ children, filled, accent, size = SIZE }: {
  children: React.ReactNode
  filled?: boolean
  accent?: string
  size?: number
}) {
  return (
    <svg
      width={size} height={size} viewBox="0 0 24 24"
      fill={filled && accent ? accent : 'none'}
      stroke="currentColor" strokeWidth={1.7}
      strokeLinecap="round" strokeLinejoin="round"
      aria-hidden
      style={{ display: 'block', overflow: 'visible' }}
    >
      {children}
    </svg>
  )
}

/** Сердце: одна замкнутая кривая — потому и заливается ровно. */
export function HeartGlyph({ filled, accent, size }: { filled: boolean; accent: string; size?: number }) {
  return (
    <Glyph filled={filled} accent={accent} size={size}>
      <path d="M12 20.1c-.42 0-.82-.15-1.13-.42C6.28 15.85 3.6 13.28 3.6 10.15A4.55 4.55 0 0 1 8.1 5.55c1.6 0 2.95.83 3.9 2.15.95-1.32 2.3-2.15 3.9-2.15a4.55 4.55 0 0 1 4.5 4.6c0 3.13-2.68 5.7-7.27 9.53-.31.27-.71.42-1.13.42Z" />
    </Glyph>
  )
}

/** Облако реплики с хвостом влево-вниз — как в мессенджере, а не кружок. */
export function ReplyGlyph({ filled, accent, size }: { filled: boolean; accent: string; size?: number }) {
  return (
    <Glyph filled={filled} accent={accent} size={size}>
      <path d="M12 4.9c4.42 0 8 2.94 8 6.57s-3.58 6.57-8 6.57c-.87 0-1.71-.11-2.5-.32l-3.83 1.6a.4.4 0 0 1-.54-.48l.83-2.83C4.68 14.85 4 13.28 4 11.47 4 7.84 7.58 4.9 12 4.9Z" />
    </Glyph>
  )
}

/**
 * Перевод: латинская «A» и китайский знак 文 — два письма рядом.
 *
 * Готовый значок «Languages» рисует стопку палочек, в которой на 17 пикселях
 * не разобрать ни буквы, ни иероглифа. Здесь оба знака нарисованы штрихами
 * той же толщины, что сердце: на просвет видно ровно то, что значок обещает, —
 * перевод с одного письма на другое.
 */
export function TranslateGlyph({ size }: { size?: number } = {}) {
  return (
    <Glyph size={size}>
      {/* A */}
      <path d="M3.4 14.6 6.6 6.4l3.2 8.2" />
      <path d="M4.5 12.1h4.2" />
      {/* 文 */}
      <path d="M16.4 5.6v1" />
      <path d="M13.2 8.8h6.6" />
      <path d="M18 8.8c-.5 3.4-2 5.9-4.6 8" />
      <path d="M15.7 12.3c1.1 2.4 2.6 4.3 4.6 5.6" />
    </Glyph>
  )
}

/**
 * Озвучка: рупор с двумя волнами. Волны — дуги той же толщины, что штрих
 * сердца: значок стоит в одном ряду с ним и обязан весить столько же.
 */
export function SpeakGlyph({ size }: { size?: number } = {}) {
  return (
    <Glyph size={size}>
      <path d="M4 9.6h3.1L11.4 6v12l-4.3-3.6H4a.9.9 0 0 1-.9-.9v-3a.9.9 0 0 1 .9-.9Z" />
      <path d="M15.1 9.4a3.6 3.6 0 0 1 0 5.2" />
      <path d="M17.9 6.9a7.2 7.2 0 0 1 0 10.2" />
    </Glyph>
  )
}
