// ─────────────────────────────────────────────────────────────────────────────
// Справочник грамматики: форма как отдельная единица, а не абзац внутри урока
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ КУРСА. Курс отвечает на вопрос «что учить дальше»: юниты
// идут по порядку, грамматика вплетена в конспект и живёт там же, где словарь и
// задания. Но у грамматики есть второй способ употребления, которого у курса
// нет вовсе: человек на пятнадцатом уроке забыл, чем 은/는 отличается от 이/가,
// и ему нужна ЭТА форма — сейчас, отдельно, без прохождения урока заново.
//
// Пока такого экрана нет, ученик уходит искать ответ наружу, и там его встречает
// чужой платный сборник. Поэтому справочник — не витрина курса, а свой раздел с
// плоским списком форм, поиском и уровнем.
//
// ЧТО В КАРТОЧКЕ ФОРМЫ И ПОЧЕМУ ИМЕННО ЭТО
//
//   rule      — объяснение, а не название. «~고 싶어요 (желание)» ничего не даёт:
//               нужно знать, к чему клеится и где ломается.
//   examples  — ДЕСЯТЬ И БОЛЬШЕ, и у каждого подписан контекст. Одна форма с
//               одним примером не даёт понять, КОГДА так говорят, — а именно
//               этот вопрос и приводит человека в справочник. Поле `when` —
//               обязательная часть примера, а не украшение.
//   pitfall   — ошибка, которую делает именно русскоязычный.
//   contrast  — против соседней формы. Половина вопросов к грамматике — это
//               вопросы «а чем это отличается от…», и отвечать на них внутри
//               двух разных карточек порознь бессмысленно.
//   quiz      — самопроверка на месте. Без неё чтение справочника заканчивается
//               ощущением «понятно», которое не проверено ничем.
//
// ЛЕНИВО, КАК РАЗГОВОРНИКИ. Справочник одного языка — сотни примеров; человек,
// открывший тренажёр на «Чтении», не должен возить с собой все языки сразу.
// hasGrammarRef при этом синхронный: раздел, который сначала появляется пустым,
// хуже раздела, которого нет.
// ─────────────────────────────────────────────────────────────────────────────

/** Пример употребления формы. */
export interface GrammarExample {
  /** Фраза на изучаемом языке. */
  text: string
  /** Перевод. */
  ru: string
  /**
   * Когда так говорят — ситуация в одну строку.
   *
   * Это главное поле примера. Десять фраз с одной и той же формой без подписи
   * читаются как десять раз одно и то же; с подписью они показывают ДИАПАЗОН:
   * где форма нейтральна, где звучит резко, где так сказать нельзя.
   */
  when: string
}

/** Вопрос самопроверки. */
export interface GrammarQuiz {
  q: string
  options: string[]
  /** Индекс верного варианта в options. */
  answer: number
  /** Почему верный — верный. Показывается после ответа, а не вместо него. */
  why: string
}

/** Сравнение с соседней формой. */
export interface GrammarContrast {
  /** id формы, с которой сравниваем. */
  with: string
  /** Чем отличается — одна-две фразы. */
  note: string
}

/** Таблица форм — заголовок и строки, без разметки. */
export interface GrammarTable {
  head: string[]
  rows: string[][]
}

export interface GrammarForm {
  /** Стабильный ключ: `${lang}-${короткое имя формы}`. */
  id: string
  /** Раздел справочника — см. GRAMMAR_CHAPTERS языка. */
  chapter: string
  /** Уровень, на котором форма нужна впервые: '0급', '1급', '2급'. */
  level: string
  /** Сама форма так, как её пишут: «~아/어요», «은/는». */
  form: string
  /** Название по-русски: «Вежливое настоящее». */
  title: string
  /** Одна строка: что форма делает. Видна на плитке. */
  short: string
  /** К чему клеится: «к основе глагола», «к существительному». */
  attach: string
  /** Объяснение. Абзацы разделяются пустой строкой. */
  rule: string
  table?: GrammarTable
  examples: GrammarExample[]
  /** Типичная ошибка русскоязычного. */
  pitfall?: string
  contrast?: GrammarContrast[]
  /** shortId юнита курса, где форму проходят. Связь справочника с курсом. */
  unit?: string
  quiz: GrammarQuiz[]
}

export interface GrammarRef {
  lang: string
  /** Порядок разделов — им же группируется витрина. */
  chapters: string[]
  forms: GrammarForm[]
}

/**
 * Сколько форм в справочнике каждого языка — СИНХРОННО.
 *
 * Той же логикой, что и SCENE_COUNTS у сцен: бейдж на пункте меню нужен до
 * того, как чанк поехал, иначе цифра появляется через секунду после самого
 * пункта и прыгает. Расхождение с настоящим списком ловится при первой же
 * загрузке — см. проверку в loadGrammarRef.
 */
export const GRAMMAR_COUNTS: Record<string, number> = {
  ko: 85,
  de: 20,
}

type Loader = () => Promise<GrammarRef>

const LOADERS: Record<string, Loader> = {
  ko: () => import('./grammarKo').then(m => m.KOREAN_GRAMMAR),
  de: () => import('../grammarDe').then(m => m.GERMAN_GRAMMAR),
}

/** Базовый код языка: pt-BR → pt. */
const base = (lang: string) => lang.split('-')[0].toLowerCase()

/** Есть ли для языка справочник. Синхронно — по нему решается, рисовать ли раздел. */
export const hasGrammarRef = (lang: string | undefined): boolean =>
  !!lang && (lang in LOADERS || base(lang) in LOADERS)

/** Подгрузить справочник языка. undefined — его для этого языка пока нет. */
export async function loadGrammarRef(lang: string | undefined): Promise<GrammarRef | undefined> {
  if (!lang) return undefined
  const load = LOADERS[lang] ?? LOADERS[base(lang)]
  if (!load) return undefined
  try {
    const ref = await load()
    const claimed = GRAMMAR_COUNTS[lang] ?? GRAMMAR_COUNTS[base(lang)]
    if (claimed !== undefined && claimed !== ref.forms.length) {
      console.warn(`GRAMMAR_COUNTS[${lang}] разошёлся со справочником: подпись ${claimed}, форм ${ref.forms.length}`)
    }
    return ref
  } catch (e) {
    // Чанк мог не догрузиться на плохой сети: пустой раздел лучше белой страницы.
    console.error('loadGrammarRef:', e)
    return undefined
  }
}

/** Форма по id — для ссылок «сравните с…» внутри карточек. */
export const formById = (ref: GrammarRef, id: string): GrammarForm | undefined =>
  ref.forms.find(f => f.id === id)
