// ─────────────────────────────────────────────────────────────────────────────
// Наборы английских слов
//
// ПОЧЕМУ НЕ «ГЛАГОЛЫ ДВИЖЕНИЯ». У корейского и японского набор слов начинается
// с базовой лексики: человек не знает вообще ничего. С английским так почти ни
// у кого не бывает — go, eat и big знают все, кто дошёл до тренажёра. Набор
// «сто первых глаголов» здесь был бы полкой, мимо которой проходят.
//
// Проблема у изучающего английский другая и всегда одна и та же: он знает слова
// и не знает, КАК ИХ СОЕДИНЯЮТ. Говорит «do a mistake» вместо «make», «very
// tired» там, где носитель скажет «exhausted», и не понимает «let's circle back
// on this» из письма. Поэтому наборы здесь — ровно те четыре оси, на которых
// это чинится: фразовые глаголы, устойчивые сочетания, академическая лексика и
// то, чем речь выдаёт неносителя (ложные друзья, оттенки, реакции).
//
// ЧТЕНИЯ НЕТ. Латиница читается сама; поле reading в модели необязательное
// именно для таких языков.
//
// ПЕРЕВОД — ЭТО РУССКОЕ ВЫРАЖЕНИЕ, А НЕ ПОДСТРОЧНИК. «Get the hang of it» — не
// «получить свисание этого», а «наловчиться». Подстрочник в карточке учит
// разбирать выражение по частям, то есть ровно тому, чего с идиомой делать
// нельзя.
// ─────────────────────────────────────────────────────────────────────────────

