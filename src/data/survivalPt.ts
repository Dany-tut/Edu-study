// Бразильский португальский: разговорник выживания
//
// КАКОЙ ИМЕННО ПОРТУГАЛЬСКИЙ. Бразильский, а не европейский. Это принципиально:
// в Бразилии «ты» — você (а не tu), «автобус» — ônibus (а не autocarro),
// «завтрак» — café da manhã (а не pequeno-almoço), и герундий (estou falando)
// вытеснил инфинитивную конструкцию. Человек, выучивший лиссабонский вариант,
