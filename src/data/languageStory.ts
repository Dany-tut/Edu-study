// ─────────────────────────────────────────────────────────────────────────────
// Тема о языке: рассказ, который читают до и вместо правил
//
// ЗАЧЕМ. Конспект урока отвечает на вопрос «как делать». Он не отвечает на
// вопрос «почему язык такой» — а именно этот вопрос решает, останется человек
// в языке или бросит его на третьей неделе. Хангыль, объяснённый как замысел
// («буква рисует то, что делает рот»), учится за вечер; он же, выданный
// таблицей из сорока знаков, учится неделю и забывается за две.
//
// ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Не конспектом: здесь нет упражнений, нет заданий и не
// проверяется ничего. И не статьёй: статью в тренажёре не читают. Единица
// рассказа — КАРТОЧКА: одна мысль, при ней схема, и кнопка «Дальше». Ровно так
// устроены объяснения в приложениях, которые люди действительно дочитывают, —
// и причина не в моде, а в том, что шаг мысли виден целиком и не тонет в
// абзаце.
//
// ПОЧЕМУ ГЛАВЫ, А НЕ ОДНА ЛЕНТА. Рассказ читают кусками и возвращаются к нему:
// «а как там было про 받침». Глава — то, что помещается в один заход (три-пять
// карточек) и имеет название, по которому её найдут снова.
//
// КАРТИНКИ — ВЕКТОР НАШ (см. languageStoryFigures.ts). Схема лежит в карточке
// готовой строкой data-URI: ей не нужны ни сеть, ни лицензия.
// ─────────────────────────────────────────────────────────────────────────────

/** Одна мысль рассказа. */
export interface StoryCard {
  /** Схема над текстом — data-URI из languageStoryFigures.ts. Не обязательна. */
  figure?: string
  /**
   * Заголовок карточки.
   *
   * Не обязателен, и это важно: половина карточек — продолжение предыдущей
   * мысли, и заголовок над ними превращал бы рассказ в список тезисов.
   */
  title?: string
  /** Текст карточки. Один шаг, а не абзац конспекта. */
  text: string
  /**
   * Строки-выноски под текстом: «Небо (·)», «Земля (─)».
   *
   * Нужны там, где перечисление — и есть содержание карточки. Внутри текста
   * тот же список читается как поток и не запоминается.
   */
  bullets?: string[]
  /**
   * Что стоит унести из карточки одной строкой.
   *
   * Пишется не к каждой: пометка на каждой карточке перестаёт читаться уже к
   * третьей и превращается в фон.
   */
  keep?: string
}

/** Глава рассказа — то, что читают за один заход. */
export interface StoryChapter {
  /** Стабильный ключ — по нему запоминается, докуда дочитано. */
  id: string
  title: string
  /** О чём глава одной строкой — подпись на витрине. */
  about: string
  cards: StoryCard[]
}

/** Рассказ о языке. */
export interface LanguageStory {
  /** Ключ книги — префикс ключей прогресса. */
  key: string
  /** BCP-47 языка. */
  lang: string
  chapters: StoryChapter[]
}

/** Глава по id. */
export const chapterById = (story: LanguageStory | undefined, id: string): StoryChapter | undefined =>
  story?.chapters.find(c => c.id === id)

/** Сколько всего карточек в рассказе — подпись на витрине. */
export const storyCardCount = (story: LanguageStory | undefined): number =>
  story ? story.chapters.reduce((n, c) => n + c.cards.length, 0) : 0
