// ─────────────────────────────────────────────────────────────────────────────
// Пословный словарь к текстам тренажёра
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ GLOSSARY ТЕКСТА
// У каждого текста в readingLibrary есть `glossary` — пять-шесть ключевых слов,
// которые учитель считает главными. Это подсказка «на что смотреть», а не
// словарь: остальные восемьдесят слов текста остаются без перевода, и ученик
// уровня TOPIK 1 упирается в них на второй строке. Здесь лежит то, что делает
// осмысленным клик по ЛЮБОМУ слову: служебные частицы, формы глаголов, числа,
// бытовая лексика — всё, что реально встречается в текстах библиотеки.
//
// ПОЧЕМУ НЕ БЕРЁМ СЛОВАРИ КУРСОВ-СИДОВ
// В сидах (koreanTopik.ts и семь других) лежат тысячи слов, но: во-первых, это
// словари ЮНИТОВ — там словосочетания и учебные формы, а не то, что стоит в
// тексте; во-вторых, каждый файл сида тянет за собой схемы конспекта в data-URI,
// и импорт ради словаря утащил бы в бандл ученика мегабайты картинок. Поэтому
// словарь ведётся здесь и руками.
//
// ПОВЕРХНОСТНЫЕ ФОРМЫ, А НЕ ЛЕММЫ
// Корейский и японский агглютинативны: 내일은 = 내일 + 은, しごとが = しごと + が.
// Автоматически резать окончания — гарантированно врать (곧/고, ます/ま), поэтому
// словарь хранит и основу, и частицу отдельными записями, а разборщик
// (lib/lexicon.ts) берёт самое длинное совпадение и продолжает со следующей
// позиции. 내일은 разбирается на «завтра» + «частица темы» без морфологии.
//
// ЧЕГО ЗДЕСЬ НЕТ
// Это не общий словарь языка и не претендует им быть: он покрывает библиотеку
// текстов и частотную бытовую лексику вокруг неё. Слово, которого нет, не
// ломает чтение — по клику ученик всё равно услышит произношение, просто без
// перевода.
// ─────────────────────────────────────────────────────────────────────────────

/** Слово или устойчивое сочетание с переводом. */
export interface WordGloss {
  /** Форма ровно в том виде, в каком она встречается в тексте. */
  term: string
  ru: string
  /** Чтение — там, где письменность его не даёт (иероглифы, редкие чтения). */
  reading?: string
  /** Грамматическая пометка: «частица», «вежливая форма», «разг.». */
  note?: string
}

const w = (term: string, ru: string, note?: string): WordGloss => ({ term, ru, note })

/**
 * Формула с записанным руками чтением.
 *
 * Обычным словам чтение считает lib/translit.ts, и для них этого хватает. Но
 * счётчик слогов не знает ассимиляций на стыках, а именно на них стоят самые
 * частые вежливые формы: 감사합니다 послогово читается «камсахапнида», хотя
 * произносится «камсамнида», 잘 먹었습니다 — «могоссымнида», а не
 * «моготсыпнида». Ученик слышит одно, читает другое и решает, что ослышался.
 * Поэтому у бытовых формул чтение записано вручную: оно бьёт вычисленное
 * (см. GlossedText).
 */
const f = (term: string, ru: string, reading: string, note?: string): WordGloss =>
  ({ term, ru, reading, note })

