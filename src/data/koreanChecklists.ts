// ─────────────────────────────────────────────────────────────────────────────
// Чек-листы грамматики корейских курсов
//
// ЗАЧЕМ. Курс отвечает на вопрос «что учить дальше», конспект — «как это
// устроено». Вопрос «а я это уже умею» до сих пор не задавался нигде, и ученик
// отвечал на него ощущением «вроде проходили»: юнит закрыт, форма — нет. Чек-лист
// разбирает грамматику юнита на пункты, каждый из которых либо в активе, либо нет.
//
// ПУНКТ — ФОРМА, А НЕ ТЕМА. «~지 않다 — книжное отрицание» проверяемо; «понимать
// отрицание» — нет. Поэтому в пункте стоит сама форма и подпись в несколько слов,
// по которой её узнают в тексте.
//
// ПОЧЕМУ РОВНО ЭТИ ФОРМЫ. Список сверен с тем, что реально спрашивают у
// начинающих: частицы, времена и стили речи, вопросы, связки, модальность.
// Каждая форма стоит в том юните, где её ПРОХОДЯТ, а не там, где она впервые
// мелькнула: 기 때문에 живёт в юните причин второго курса, а не рядом с ~아/어서,
// хотя переводятся они похоже.
//
// ЧЕГО ЗДЕСЬ НЕТ. Юниты повторения чек-листа не получают: отмечать в них нечего,
// а список ради списка обесценивает остальные. Курс алфавита сюда тоже не
// попадает, но по другой причине — его чек-лист СОБИРАЕТСЯ ИЗ САМИХ БУКВ урока
// (см. koreanHangul.ts) и потому не пишется руками: дописали букве пример —
// пункт появился сам.
//
// ЭКЗАМЕНАЦИОННЫЕ ЮНИТЫ — ИСКЛЮЧЕНИЕ, И ОНО ОСОЗНАННОЕ. Сначала их тоже
// оставили без списка по правилу «пункт — форма». Но в 쓰기 и 읽기 балл теряется
// не на незнании форм: человек пишет работу в 해요체 вместо 문어체, не заявляет
// мнение в 서론, отвечает на вопрос, которого не задавали. Это ровно такие же
// проверяемые пункты, просто единица в них — требование формата, а не
// грамматическая форма. Отмечаться по ним есть чему, и без списка ученик узнаёт
// об этих требованиях один раз в конспекте и забывает к экзамену.
//
// Отметки ученика локальные и никуда не идут — см. lib/theoryChecklist.
// ─────────────────────────────────────────────────────────────────────────────

