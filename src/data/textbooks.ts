// Полка учебников
//
// ЗАЧЕМ ЭТО В ТРЕНАЖЁРЕ. Вопрос «а по какому учебнику заниматься» человек задаёт
// на первой неделе и получает на него худший из возможных ответов — список из
// подборки в соцсетях, где двадцать обложек без единого слова о том, кому это
// подходит. В итоге берут первое попавшееся, упираются в него на третьем уроке
// и решают, что дело в них.
//
// ЧТО ЗДЕСЬ ЕСТЬ. Немного книг, но про каждую сказано главное: чему учит, что
// внутри и — обязательно — КОГДА ЗА НЕЁ БРАТЬСЯ. Последнее и есть содержание
// полки: «Korean Grammar in Use» прекрасна и бесполезна человеку, который ещё
// не читает хангыль.
//
// ССЫЛКИ ТОЛЬКО ОФИЦИАЛЬНЫЕ — на издательство, на институт, на сайт экзамена.
// Раздавать чужие учебники файлами мы не будем: это ровно то, чем занимаются
// «подборки», и ровно то, из-за чего у них потом мёртвые ссылки.
//
// ОБЛОЖКИ РИСУЮТСЯ, А НЕ БЕРУТСЯ. Настоящая обложка — чужая картинка с чужой
// лицензией. Полке достаточно цвета, знака и названия: книга узнаётся по ним, а
// не по фотографии (как это нарисовано — см. trainer/BookShelf.tsx).
//
// ССЫЛКА ОБЕЩАЕТ РОВНО ТО, ЧТО БУДЕТ. Одна кнопка «Официальная страница» на всех
// книгах — это одно обещание на всю полку, за которым стоит совершенно разное:
// у Сечжона там бесплатный учебник целиком, у Дараквона — витрина магазина, у
// Naver — рабочий словарь. Поэтому у книги есть ТИП ДОСТУПА, и подпись кнопки
// берётся из него.
//
// ПОЧЕМУ НЕ ССЫЛКА НА САМ ФАЙЛ. У корейских порталов адреса страниц с файлами
// сессионные (nuri.iksi.or.kr отдаёт csCmsMastrSeq, topik.go.kr — номера
// раздач): такая ссылка умирает быстрее, чем мы про неё вспомним. Ведём на
// устойчивый раздел и ПОДПИСЫВАЕМ, что там искать (`urlNote`) — это честнее
// мёртвой ссылки и полезнее корпоративной главной.
// ─────────────────────────────────────────────────────────────────────────────

/** Чем книга является — по этому её и выбирают. */
export type TextbookKind = 'курс' | 'грамматика' | 'экзамен' | 'самоучитель' | 'словарь'

/**
 * Что с книгой можно сделать — от этого зависит подпись кнопки.
 *
 * `free` — официально выложена бесплатно, `shop` — продаётся у издателя,
 * `service` — это не книга, а веб-сервис (словарь), `page` — страница
 * издателя, где книгу не продают, но она описана.
 */
export type TextbookAccess = 'free' | 'shop' | 'service' | 'page'

export interface Textbook {
  id: string
  title: string
  /**
   * Название НА ОБЛОЖКЕ — коротко, в одну-две строки.
   *
   * Полное название с переводом и уточнениями («세종한국어 (Sejong Korean)»)
   * на обложке 108 пикселей не помещается и рвётся посреди слова. Обложке
   * нужно ровно то, по чему книгу узнают в разговоре.
   */
  short?: string
  /** Автор или составитель. Пусто — у институтских изданий автора нет. */
  authors?: string
  /** Издательство, институт или проект. */
  publisher: string
  kind: TextbookKind
  /** Уровень строкой, как его заявляет сама книга. */
  level: string
  /** Язык объяснений: на чём написаны пояснения, а не чему учит. */
  explainedIn: string
  /** Бесплатна ли официально. */
  free?: boolean
  /**
   * Цвет обложки: фон и текст. Обложка рисуется, а не берётся.
   *
   * `mark` — крупный знак на обложке. Задаётся книге только тогда, когда знак
   * по типу (см. bookMark) для неё не годится; обычно его и не задают.
   */
  cover: { bg: string; fg: string; mark?: string }
  /** Чему учит и чем отличается от соседей по полке. */
  about: string
  /** Что внутри. */
  parts: string[]
  /** Когда за неё браться — и когда рано. */
  when: string
  /** Официальная страница. */
  url?: string
  /** Что за ссылкой. По умолчанию `page`. */
  access?: TextbookAccess
  /** Что искать на той странице — когда устойчивой ссылки на файл нет. */
  urlNote?: string
}

/**
 * Знак на обложке — по ТИПУ книги, а не по её названию.
 *
 * Один слог из корейского слова: 한(국어) курс, 문(법) грамматика, 급 ступень
 * экзамена, 말 разговорный самоучитель, 사(전) словарь. Так знак читается как
 * эмблема раздела, а не как случайный иероглиф: три курса на полке помечены
 * одинаково, и это правильно — они и есть одно и то же по назначению.
 *
 * Языки без иероглифики сюда не попадают намеренно: знак у английского
 * учебника был бы натянутым, и обложка вместо него получает иконку (см.
 * trainer/BookShelf.tsx).
 */
const MARKS: Record<string, Partial<Record<TextbookKind, string>>> = {
  ko: { 'курс': '한', 'грамматика': '문', 'экзамен': '급', 'самоучитель': '말', 'словарь': '사' },
  ja: { 'курс': '日', 'грамматика': '文', 'экзамен': '級', 'самоучитель': '話', 'словарь': '辞' },
}

/** Знак обложки: свой у книги, иначе по типу, иначе ничего. */
export function bookMark(book: Textbook, lang: string | undefined): string | null {
  if (book.cover.mark) return book.cover.mark
  return (lang && MARKS[base(lang)]?.[book.kind]) || null
}

/** Название на обложке: короткое, если задано, иначе — до первого уточнения. */
export function bookShort(book: Textbook): string {
  return book.short ?? book.title.split(/\s+[(—]/)[0]
}

