// и решают, что дело в них.
//
// ЧТО ЗДЕСЬ ЕСТЬ. Немного книг, но про каждую сказано главное: чему учит, что
// внутри и — обязательно — КОГДА ЗА НЕЁ БРАТЬСЯ. Последнее и есть содержание
// полки: «Korean Grammar in Use» прекрасна и бесполезна человеку, который ещё
// не читает хангыль.
//
// ССЫЛКИ ТОЛЬКО ОФИЦИАЛЬНЫЕ — на издательство, на институт, на сайт экзамена.
// Раздавать чужие учебники файлами мы не будем: это ровно то, чем занимаются
// «подборки», и ровно то, из-за чего у них потом мёртвые ссылки.
//
// ОБЛОЖКИ РИСУЮТСЯ, А НЕ БЕРУТСЯ. Настоящая обложка — чужая картинка с чужой
// лицензией. Полке достаточно корешка: цвет, название, автор. Узнаётся книга по
// цвету и названию, а не по фотографии.
// ─────────────────────────────────────────────────────────────────────────────

/** Чем книга является — по этому её и выбирают. */
export type TextbookKind = 'курс' | 'грамматика' | 'экзамен' | 'самоучитель' | 'словарь'

export interface Textbook {
  id: string
  title: string
  /** Автор или составитель. Пусто — у институтских изданий автора нет. */
  authors?: string
  /** Издательство, институт или проект. */
  publisher: string
  kind: TextbookKind
  /** Уровень строкой, как его заявляет сама книга. */
  level: string
  /** Язык объяснений: на чём написаны пояснения, а не чему учит. */
  explainedIn: string
  /** Бесплатна ли официально. */
  free?: boolean
  /** Цвет корешка: фон и текст. Обложка рисуется, а не берётся. */
  cover: { bg: string; fg: string }
  /** Чему учит и чем отличается от соседей по полке. */
  about: string
  /** Что внутри. */
  parts: string[]
  /** Когда за неё браться — и когда рано. */
  when: string
  /** Официальная страница. */
  url?: string
}

