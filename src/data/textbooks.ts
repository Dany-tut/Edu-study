/** Базовый код языка: pt-BR → pt. */
const base = (lang: string) => lang.split('-')[0].toLowerCase()

/** Есть ли для языка полка учебников. */
export const hasTextbooks = (lang: string | undefined): boolean =>
  !!lang && (base(lang) in BOOKS)

/** Учебники языка. Пусто — полки для него ещё нет. */
export const textbooksForLang = (lang: string | undefined): Textbook[] =>
  (lang && BOOKS[base(lang)]) || []
