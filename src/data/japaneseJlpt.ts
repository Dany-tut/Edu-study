// ─────────────────────────────────────────────────────────────────────────────
// Японский с нуля (подготовка к JLPT N5 с выходом на N4)
//
// От нуля (не знает кану) до уровня N5 с выходом на N4: бытовое общение,
// чтение простых текстов с базовыми кандзи, рассказ о себе и своём дне.
//
// МЕТОДИЧЕСКАЯ ОСНОВА
// 1. Хирагана и катакана — первые четыре юнита, до любой грамматики. Ромадзи в
//    курсе используется только как подпись к слову в карточке, никогда как
//    основной текст задания: чтение ромадзи закрепляет неправильную фонетику.
// 2. Отдельный юнит на долготу и удвоение (юнит 4). Для русскоязычного おばさん
//    (тётя) и おばあさん (бабушка) — одно слово, а разница смыслоразличительная.
//    Это не «тонкость на потом», а причина, по которой ученика не понимают.
// 3. Три частицы-ловушки (は читается «ва», を — «о», へ — «э») даются в юните 2,
//    сразу после хираганы: иначе привычка читать их «как написано» закрепляется.
// 4. Глагольные группы (годан / итидан / нерегулярные) вводятся вместе с ます-
//    формой, а не позже: без деления на группы любое спряжение — угадывание.
// 5. Кандзи даются порциями по 8–10 знаков с юнита 12 и только те, что реально
//    встречаются в N5: 日 本 人 大 小 上 下 中 山 川 学 生 先 私 時 分 年 月.
//
// ПРО ЭКЗАМЕН
// JLPT — только распознавание: 言語知識 (лексика и грамматика), 読解 (чтение) и
// 聴解 (аудирование). Продуктивных частей (говорение, письмо) в JLPT нет вообще.
// Поэтому курс тренирует речь отдельно и специально: сертификат N5 без умения
// говорить — обычная и бесполезная ситуация, которую мы не воспроизводим.
//
// ПРО ЗАДАНИЯ «СОБЕРИ ПРЕДЛОЖЕНИЕ»
// Плитки нарезаются по пробелам, а в японском пробелов нет. Поэтому эталонные
// предложения записаны с пробелами между смысловыми группами (бунсэцу):
// «わたしは まいあさ コーヒーを のみます。» Ученик собирает группы, а не знаки —
// это и есть нужный навык: порядок членов предложения с глаголом в конце.
//
// ПРО АУДИО
// Аудио-задания заполнены текстом для синтеза. Долготу гласных синтез передаёт
// приемлемо, а вот тональное ударение (はし «палочки» и はし «мост») — нет, и
// заданий на него здесь сознательно нет: их нужно записывать голосом носителя.
//
// ЮРИДИЧЕСКОЕ
// Все примеры написаны с нуля. Порядок черт кандзи при добавлении заданий на
// обводку брать из KanjiVG (CC BY-SA) с указанием источника.
// ─────────────────────────────────────────────────────────────────────────────

