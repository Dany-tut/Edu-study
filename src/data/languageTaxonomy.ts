/** Уровни по умолчанию, если язык не описан отдельно. */
const DEFAULT_LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1']

// ─── Публичный API ───────────────────────────────────────────────────────────

/**
 * Разметка для языкового предмета. Принимает и слаг, и русское название.
 * Для неязыкового предмета возвращает undefined — у него разметка ЕГЭ.
 */
export function languageTaxonomy(idOrName: string | undefined): LanguageTaxonomy | undefined {
  const def = getSubject(idOrName)
  if (!def?.isLanguage) return undefined
  const extra = PER_LANGUAGE[def.id] ?? {}
  return {
    kind: 'language',
    levels: extra.levels ?? DEFAULT_LEVELS,
    skills: [...CORE_SKILLS, ...(extra.skills ?? [])],
    topics: [...CORE_TOPICS, ...(extra.topics ?? [])],
    examTasks: extra.examTasks ?? [],
  }
}

/** Разметка конкретного задания — лежит в task_bank.payload. */
export interface TaskLanguageTags {
  /** Минимальный уровень, с которого задание имеет смысл давать. */
  level?: string
  skill?: string
  topic?: string
  /** Формат экзаменационного задания, если это подготовка к экзамену. */
  examTask?: string
}

/** Подпись разметки одной строкой — для карточки задания в списке. */
export function tagsLabel(tags: TaskLanguageTags): string {
  return [tags.level, tags.skill, tags.topic, tags.examTask].filter(Boolean).join(' · ')
}
