// ─────────────────────────────────────────────────────────────────────────────
// Разметка языковых заданий
//
// ЗАЧЕМ ОТДЕЛЬНАЯ ФОРМА. Разметка ЕГЭ устроена как «раздел → тема → линия», где
// тема ПРИНАДЛЕЖИТ разделу. Для языка это ломается сразу: тема «еда» бывает и в
// чтении, и в аудировании, и в говорении. Вложив темы в навыки, пришлось бы
// держать шесть копий каждой темы, и через месяц они разъедутся.
//
// Поэтому оси НЕЗАВИСИМЫЕ: уровень, навык, тема. Плюс необязательный
// экзаменационный формат — им собирается пробник одним фильтром.
//
// ХРАНЕНИЕ. Ничего нового заводить не нужно: разметка самого задания уходит в
// task_bank.payload (jsonb, миграция 0051), а списки значений — в ту же таблицу
// curriculum, где лежит таксономия ЕГЭ; она хранит по одной JSON-записи на
// предмет, поэтому форма может отличаться. Различаются по полю kind.
//
// УРОВЕНЬ У ЗАДАНИЯ ОДИН, не диапазон: это минимальный уровень, с которого
// задание имеет смысл давать. Диапазон удобнее звучит, но при заведении каждого
// задания заставляет думать «а до какого уровня», и на сотне заданий это
// превращается в разнобой.
// ─────────────────────────────────────────────────────────────────────────────

import { getSubject } from '../lib/subjects'

export interface LanguageTaxonomy {
  kind: 'language'
  /** Шкала уровней СВОЕГО языка: CEFR, TOPIK или JLPT. */
  levels: string[]
  /** Навыки: общий костяк плюс добавки языка. */
  skills: string[]
  /** Темы — плоский список, не привязаны к навыку. */
  topics: string[]
  /** Форматы экзаменационных заданий. Пусто у неэкзаменационных языков. */
  examTasks: string[]
}

