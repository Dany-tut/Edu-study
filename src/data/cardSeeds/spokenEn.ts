// придумана — то же правило, что в соседнем файле.
//
// ПОЧЕМУ ЭТО ВАЖНЕЕ РЕДКИХ СЛОВ. Разбор тех же 104 серий показал: на уровне B1
// ученик уже знает около 95% слов любой серии, и выше B1 регулярно возвращаются
// всего восемь лемм. Понимание упирается не в словарь, а вот в это: «how did
// you» произносится одним слогом, и пока форма не узнаётся, знание слов how, did
// и you не помогает совершенно.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Форм dunno, lemme, coupla, cuz, outta здесь нет,
// хотя они первыми приходят в голову: в субтитрах 104 серий они не встречаются
// НИ РАЗУ. Актёр их глотает, но строка пишется нормативно («I don't know»).
// Такие формы существуют и в письме встречаются — но подписать их частотностью
// сериала значило бы соврать, а карточка без честной подписи здесь не нужна.
//
// ПРИМЕРЫ НАШИ. Реплики сериала — чужой текст (см. корзину 'inspired' на полке
// «Сцены»), поэтому предложения под карточками написаны с нуля: у сериала взяты
// только регистр и обстановка.
// ─────────────────────────────────────────────────────────────────────────────

