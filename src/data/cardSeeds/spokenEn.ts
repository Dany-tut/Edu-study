//
// ЗАЧЕМ ОТДЕЛЬНАЯ ГРУППА, ЕСЛИ РЯДОМ УЖЕ ЕСТЬ «Сверхъестественное»
// Та группа даёт ЛЕКСИКУ сериала: охота, нечисть, мифология сезонов. Здесь —
// другое и единственное: формы, в которых обычные, давно известные слова
// склеиваются в речи. Это не словарь, это распознавание на слух.
//
// ОТКУДА ЦИФРЫ. Посчитано по субтитрам 104 серий (сезоны 1–5): в подписи каждой
