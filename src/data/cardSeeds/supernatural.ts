// картинке, через день его нет. Набор закрывает ровно этот разрыв: те же слова,
// но с переводом, пояснением и расписанием повторений. Мотивация здесь уже
// готовая — её не надо создавать, надо не мешать.
//
// ПОЧЕМУ СЕЗОН — ЭТО НАБОР. Сезон — естественная единица: у него своя завязка,
// свой словарь (ангелы в четвёртом, Левиафаны в седьмом) и понятная человеку
// граница «докуда я досмотрел». Серия набором быть не может: 8–10 слов на
// стопку — это полминуты работы, а 327 плиток в витрине не выбираются вовсе.
// Серия осталась МЕТКОЙ карточки (`ep`) — чипсом в списке и фильтром внутри
// набора.
//
// ЧТО ЗДЕСЬ ЗА СЛОВА И ЧЕГО ЗДЕСЬ НЕТ. Это не расшифровка серий: реплики
// сериала — чужой текст, и переносить их сюда нельзя (то же правило, что на
// полке «Сцены»: подлинный текст только из общественного достояния). Здесь
// лексика, на которой сериал ДЕРЖИТСЯ: слова охоты и нечисти, которые
// повторяются из сезона в сезон, плюс живая разговорная речь братьев —
// фразовые глаголы и идиомы, которых нет в учебнике, но которые звучат в
// каждой второй сцене. Перевод — то, что сказал бы русский, а не подстрочник.
//
// МЕТКА СЕРИИ СТОИТ ТОЛЬКО ТАМ, ГДЕ Я В НЕЙ УВЕРЕН. Где слово вошло в сериал
// одной конкретной, всем известной серией — стоит её код и название. Где слово
// просто живёт в сезоне — стоит код сезона. Придумывать номер серии ради
// красивого чипса нельзя: ученик поверит, полезет проверять и найдёт враньё.
//
// УРОВЕНЬ. B1 у ранних сезонов (быт, дорога, страшилки) и B2 у поздних (мифо-
