// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СОСЕДНЕГО ФАЙЛА. В cardSeeds/supernatural.ts лексика
// отобрана редакторски — по памяти о сериале и по тому, что в нём важно. Это
// правильный способ, но у него есть слепое пятно: запоминается яркое, а не
// частое. Здесь добор с другой стороны — по счёту.
//
// КАК СЧИТАЛОСЬ. Субтитры 104 серий (сезоны 1–5) разобраны на леммы и сверены с
// частотным списком по субтитровому корпусу OpenSubtitles. Отобрано то, что
// (а) стоит выше уровня B1, (б) встречается не меньше чем в восьми сериях из
