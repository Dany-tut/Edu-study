// это и есть число серий; ни одна не придумана.
//
// ЧЕГО ЗДЕСЬ НЕТ. Имён и топонимов (Winchester, Castiel, Impala, Roadhouse) —
// они частотны, но карточками быть не должны: имя не переводят, его узнают.
// Их место — справка по лору, а не колода. Стяжений (how'd, ain't, 'em) — под
// них есть отдельная группа cardSeeds/spokenEn.ts. И одноразовых слов: две
// трети редкой лексики сериала встречается ровно в одной серии из 104, и
// тратить на них карточку — худшее вложение времени, какое тут возможно.
//
// ПРИМЕРЫ НАШИ. Реплики сериала — чужой текст; предложения написаны с нуля, у
// сериала взяты только регистр и обстановка (то же правило, что на полке
// «Сцены» в корзине 'inspired').
// ─────────────────────────────────────────────────────────────────────────────

