// «Сверхъестественное» по сериям — колода перед просмотром
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ ДВУХ СОСЕДНИХ НАБОРОВ. cardSeeds/supernatural.ts даёт
// лексику сезона (12 слов на сезон — обзор, а не подготовка), spnMeasured.ts —
// ядро всего сериала (36 слов, которые возвращаются десятки раз). Здесь третья,
// и единственная практическая задача: ПРОЙТИ КОЛОДУ И ВКЛЮЧИТЬ СЕРИЮ. Двадцать
// слов, десять минут, дальше смотришь и понимаешь.
//
// ОТКУДА СЛОВА. Отбор считает scripts/buildSpnDecks.mjs по субтитрам 104 серий
// (сезоны 1–5): слово идёт в колоду, если стоит выше B1, вернётся ещё хотя бы в
// одной серии, не разобрано в других наборах и встречается в ЭТОЙ серии
// впервые. Потолок — двадцать карточек. Замерено: в среднем 19,4 на серию.
//
// НО СПИСОК СКРИПТА — ЭТО СЫРЬЁ, А НЕ КОЛОДА. Частотный ранг плохо заменяет
// уровень: roads, dozens, decades, tapes формально стоят выше B1, а по существу
// известны любому. Выбрасывать их нельзя — они реально звучат и реально
// цепляют, — но учить надо не слово, а СОЧЕТАНИЕ, в котором оно стоит:
// missing persons, back roads, swan dive, cassette tapes. Поэтому карточки
// пишутся руками, а не переносятся из отбора как есть.
//
// ПРИМЕРЫ НАШИ. Реплики сериала — чужой текст (корзина 'inspired' на полке
// «Сцены»); строка из субтитров нужна только для того, чтобы выбрать верное
// значение, а в карточку идёт своё предложение в том же регистре.
// ─────────────────────────────────────────────────────────────────────────────

