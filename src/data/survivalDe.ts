// Немецкий: разговорник выживания
//
// КАКОЙ НЕМЕЦКИЙ. Стандартный (Hochdeutsch) — тот, на котором говорят в
// ведомствах, магазинах и на вокзале от Гамбурга до Вены. Диалекты не даются:
// баварское Servus и швейцарское Grüezi упомянуты там, где без них человека
// сочтут глухим, но учить с них нельзя — понимать вас будут везде, а вы их нет.
//
// РЕГИСТР — ГЛАВНОЕ, ЧТО ЗДЕСЬ МОЖНО СЛОМАТЬ. Немецкий делит мир на Sie и du
// жёстче, чем русский на «вы» и «ты». С продавцом, врачом, соседом, водителем,
// чиновником — Sie, всегда, независимо от возраста. Du говорят детям, друзьям,
// студентам между собой и (внезапно) коллегам во многих фирмах — но первым его
// предлагает старший или начальник, а не вы. Ошибка в эту сторону не «мило», а
// невежливо, поэтому весь разговорник написан на Sie, а du показано отдельно.
//
// АРТИКЛЬ ЗАПИСАН ВМЕСТЕ СО СЛОВОМ. Не из аккуратности: слово без der/die/das
// выучено наполовину — без рода не собирается ни падеж, ни прилагательное.
// Поэтому в списках стоит «der Termin», а не «Termin», и в карточке ответ с
// артиклем считается полным ответом.
//
// ТРАНСКРИПЦИЯ НЕ ДАЁТСЯ. Латиница читается сама, а честная запись немецкого
// произношения (ö, ü, ch после разных гласных, оглушение на конце) требует
// разбора фонетики, а не строки в скобках. Вместо неё рядом с фразой стоит
// озвучка, а трудные пары вынесены в гнёзда созвучий (soundNests.ts).
//
// БЫТ, КОТОРОГО НЕТ В УЧЕБНИКАХ. Немецкая жизнь держится на словах, которых нет
// ни в одном разговорнике для туриста: Anmeldung, Termin, Pfand, Kaution,
// Nebenkosten, Krankmeldung, Ruhezeit, Trennung des Mülls. Человек, приехавший
// жить, упирается в них на первой неделе — поэтому они здесь, и с объяснением,
// а не только с переводом.
//
// ЮРИДИЧЕСКОЕ. Все фразы написаны с нуля, чужие учебники не копировались.
// ─────────────────────────────────────────────────────────────────────────────

