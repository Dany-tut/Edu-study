// ─────────────────────────────────────────────────────────────────────────────
// Схемы конспектов курса «Корейский с нуля: хангыль»
//
// ЗАЧЕМ. Аудит: девять уроков из девяти без единой схемы. Для курса про алфавит
// это самый заметный пробел из возможных: буква — это форма, и таблица букв с
// чтением здесь не украшение конспекта, а его главная часть. Ученик всё равно
// рисует её себе в тетрадь — вопрос только в том, спишет он её с урока или
// придумает сам.
//
// ПОЧЕМУ ГЕНЕРАЦИЯ, А НЕ ДЕВЯТЬ РУЧНЫХ КАРТИНОК. Буквы урока уже перечислены в
// самом уроке (HangulLesson.chamo), а чтение и название каждой лежат в CHAMO.
// Схема, собранная из этих же данных, не может разойтись с уроком: добавят
// букву в урок — она сама появится в таблице.
// ─────────────────────────────────────────────────────────────────────────────

import { charGrid, hangulSyllableFigure, formTable } from './lessonFigures'
import { CHAMO, HANGUL_LESSONS } from './hangul'
import type { CourseFigures, UnitFigure } from './languageCourse'

/** Строка чтения под клеткой: звук и корейское название буквы. */
function cellRead(ch: string): string {
  const c = CHAMO[ch]
  if (!c) return ''
  // Название даём только там, где оно короткое: в клетке 66 px длинное
  // ужимается до нечитаемого, а звук важнее названия.
  return c.name.length <= 3 ? `${c.sound} · ${c.name}` : c.sound
}

/** Буквы урока рядами по пять — больше в строку не помещается читаемо. */
function letterGrid(title: string, chamo: string[], note?: string): string {
  const rows: Array<Array<{ sym: string; read?: string }>> = []
  for (let i = 0; i < chamo.length; i += 5) {
    rows.push(chamo.slice(i, i + 5).map(ch => ({ sym: ch, read: cellRead(ch) })))
  }
  return charGrid(title, rows, { note })
}

/**
 * Схемы уроков хангыля.
 *
 * У каждого урока — таблица его букв. Там, где урок вводит не буквы, а правило
 * (строение слога, патчхим), рядом встаёт вторая схема: одной таблицей букв
 * такое правило не показать.
 */
export const KOREAN_HANGUL_FIGURES: CourseFigures = {}

HANGUL_LESSONS.forEach((lesson, i) => {
  // Ключ берём из самого урока: shortId юнита — это и есть lesson.id
  // (см. koreanHangul.ts). Собирать его из номера значило бы завести
  // вторую схему именования, которая разъедется при первой же вставке урока.
  const shortId = lesson.id
  const figures: UnitFigure[] = []

  if (lesson.chamo.length) {
    figures.push({
      after: 2,
      caption: `Буквы урока: ${lesson.chamo.join(' ')}`,
      src: letterGrid(
        lesson.title,
        lesson.chamo,
        'Под буквой — её звук и корейское название. Название пригодится, когда букву диктуют вслух',
      ),
    })
  }

  // Первый урок вводит саму идею слогового блока: буквы в корейском не идут
  // строкой, они складываются в квадрат. Без этой схемы дальше непонятно ничего.
  if (i === 0) {
    figures.push({
      after: 4,
      caption: 'Как из букв собирается слог',
      src: hangulSyllableFigure(),
    })
  }

  // Патчхим — не новые буквы, а новая позиция для уже известных: та же ㄱ
  // читается по-разному сверху и снизу. Это таблицей букв не показывается.
  if (/патчхим/i.test(lesson.title)) {
    figures.push({
      after: 3,
      caption: 'Одна буква, две позиции',
      src: formTable('Согласная сверху и снизу', ['Слог', 'Разбор', 'Читается'], [
        ['가', 'ㄱ + ㅏ', 'ка — согласная в начале'],
        ['각', 'ㄱ + ㅏ + ㄱ', 'как — та же ㄱ внизу'],
        ['간', 'ㄱ + ㅏ + ㄴ', 'кан'],
        ['갈', 'ㄱ + ㅏ + ㄹ', 'каль'],
      ], {
        note: 'Внизу слога согласная теряет придыхание и часто меняет звук: 있 читается [ит], а не [исс]. Таких конечных звуков всего семь',
        highlight: [1],
      }),
    })
  }

  if (figures.length) KOREAN_HANGUL_FIGURES[shortId] = figures
})
