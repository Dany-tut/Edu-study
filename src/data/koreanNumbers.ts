// ─────────────────────────────────────────────────────────────────────────────
// Числа: две системы счёта и счётные слова
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ
// В корейском два полных ряда числительных: исконный (하나, 둘, 셋…) и китайский
// (일, 이, 삼…). Учебник даёт их таблицей и оставляет ученика с вопросом, на
// который таблица не отвечает: КАКИМ считать сейчас. Ответ не в числе, а в том,
// что считают: людей и предметы — исконным, деньги, даты, минуты и телефон —
// китайским, а часы с минутами требуют обоих в одной фразе (세 시 삼십 분).
//
// Поэтому материал разложен не по числам, а по ситуациям: «сколько штук»,
// «который час», «сколько стоит», «какое число». Таблица 1–10 при этом никуда
// не девается — она первый набор, потому что без неё остальные не читаются.
//
// ПОЧЕМУ ФОРМЫ ЗАПИСАНЫ ЦЕЛИКОМ
// Числительное перед счётным словом меняется: 하나 → 한 개, 둘 → 두 명, 셋 → 세
// 시, 넷 → 네 권, 스물 → 스무 살. У китайского ряда свои неправильности в
// месяцах: шестой месяц — 유월, а не 육월, десятый — 시월, а не 십월. Генератор
// на такие вещи врёт молча, поэтому здесь всё выписано руками.
//
// ЧЕГО ЗДЕСЬ НЕТ
// Полного списка счётных слов (их больше сотни) и порядковых числительных
// (첫째, 둘째). Взяты те, без которых нельзя купить кофе, назначить встречу и
// сказать свой возраст, — остальное набирается уже по ходу чтения.
//
// ЧТО НЕ ПРОВЕРЕНО НОСИТЕЛЕМ
// Романизация дана по пересмотренной системе и не отражает ассимиляций на стыке
// слов. Возраст в вежливой речи считают и китайским рядом со счётным словом 세
// (스물세 살 против 이십삼 세) — здесь взят разговорный вариант.
// ─────────────────────────────────────────────────────────────────────────────

/** Строка набора: готовая форма и то, из чего она собрана. */
export interface NumberRow {
  /** Форма целиком: «세 시». */
  form: string
  /** Романизация. */
  reading: string
  /** Перевод. */
  ru: string
  /**
   * Число и счётное слово по отдельности, если форма собирается из двух плиток.
   * Без них строка показывается одной плиткой — так стоят сами числительные.
   */
  num?: string
  counter?: string
  /** Пояснение к неправильной форме: почему 열둘 стало 열두, а 육월 — 유월. */
  note?: string
}

/** Каким рядом считают в этой ситуации. */
export type NumberSystem = 'native' | 'sino' | 'mixed'

/** Набор — это ситуация, а не десяток чисел. */
export interface NumberSet {
  id: string
  title: string
  system: NumberSystem
  /** Когда этим считают — одна строка, ради которой набор и существует. */
  when: string
  /** Развёрнутое объяснение на страницу набора. */
  note: string
  rows: NumberRow[]
  /**
   * Рисовать таблицей двух рядов, а не списком.
   *
   * Ровно один набор — счёт 1–10. Две системы рядом читаются только колонками:
   * списком из двадцати строк они выглядят как двадцать разных слов.
   */
  table?: boolean
}

/** Строка таблицы 1–10: цифра и обе её формы. */
export interface CoreNumber {
  digit: number
  native: string
  nativeReading: string
  sino: string
  sinoReading: string
  /** Форма перед счётным словом, если она короче словарной. */
  attr?: string
}

