/** Есть ли числа для языка. Пока написан только корейский. */
export const hasNumbers = (lang: string): boolean => lang === 'ko'

export const numberSetById = (id: string): NumberSet | undefined =>
  KO_NUMBER_SETS.find(s => s.id === id)

/** Подпись ряда — общая на плитку, страницу и справочник в рейле. */
export const systemLabel = (system: NumberSystem): string =>
  system === 'native' ? 'исконный ряд' : system === 'sino' ? 'китайский ряд' : 'оба ряда'

/** Сколько форм в наборах — цифра для подписи половины. */
export const numberRowCount = (): number =>
  KO_NUMBER_SETS.reduce((n, s) => n + s.rows.length, 0)
