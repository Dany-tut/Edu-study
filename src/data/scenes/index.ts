// ─── Модель ──────────────────────────────────────────────────────────────────

/** Правовой режим произведения. Определяет, что именно можно показать. */
export type Bucket = 'pd' | 'licensed' | 'inspired'

/**
 * Что это за вещь. Фильм заведён отдельно от сериала не ради точности подписи:
 * у сериала спрашивают «на чём смотреть», у книги — «какого года», а у фильма
 * важно и то и другое, и подпись под названием собирается по-разному.
 */
export type Medium = 'book' | 'series' | 'film'

/**
 * Возрастная метка. Нужна не для галочки: платформа работает с детьми, и полка
 * с «Эйфорией» не должна открываться у пятиклассника. Учитель скрывает
 * категорию для группы тем же deny-списком, что и виджеты.
 */
export type Age = '12+' | '16+' | '18+'

export type ShelfId =
  | 'ru-classics'
  | 'west-classics'
  | 'kr'
  | 'jp'
  | 'series'
