export interface Work {
  id: string
  /** Русское название — по нему ищут. */
  title: string
  /** Оригинальное название: The Idiot, 蜘蛛の糸, 운수 좋은 날. */
  origTitle: string
  author: string
  year: number
  medium: Medium
  /** Netflix / HBO / Apple TV+ — только у сериалов. */
  platform?: string
  shelf: ShelfId
  /** Язык, на котором даём сцены этого произведения. */
  lang: string
  bucket: Bucket
  age: Age
  /** 'антиутопия', 'детектив', 'young-adult', 'лгбт' — для фильтра и подписи. */
  tags: string[]
  /** О чём это, два-три предложения. Показывается на карточке до сцен. */
  blurb: string
  /**
   * Откуда взят текст. ОБЯЗАТЕЛЕН при bucket === 'pd' — без переводчика и
   * ссылки проверить право на публикацию невозможно, а «кажется, свободно» не
   * является проверкой.
   */
  source?: {
    /** Издание или корпус: Project Gutenberg, 青空文庫, 위키문헌. */
    corpus: string
    url: string
    /** Переводчик и год перевода — если текст не на языке оригинала. */
    translator?: string
    translatedIn?: number
    /**
     * Предупреждение о самом тексте: устаревшая орфография, диалект, архаика.
     * Показывается перед чтением, иначе ученик заучит то, чего писать нельзя.
     */
    caveat?: string
  }
  /** Короткая цитата с атрибуцией — законна и для современных вещей. */
  quote?: { text: string; attribution: string }
  /**
   * СМОТРЕТЬ И ЧИТАТЬ ЦЕЛИКОМ — то, ради чего язык и начинают.
   *
   * ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ ОТДЕЛЬНОЙ ПОЛКОЙ. Человек посмотрел рейтинг дорам,
   * захотел смотреть — и застрял на единственном вопросе: потяну ли. Отдельная
   * витрина «что посмотреть» отвечала бы на него теми же двадцатью карточками,
   * которые уже лежат здесь; вместо второго списка тех же вещей страница
   * произведения становится одним местом про одну вещь: вот отрывки под твой
   * уровень, а вот что будет, если включить целиком.
   *
   * ЧЕСТНО ПРО УРОВЕНЬ. `from` — не «с какого уровня разрешено», а с какого
   * это перестаёт быть мучением. Слух отстаёт от чтения на ступень, и сериал,
   * чьи сцены читаются на 3급, на слух идёт с 4급; занижать здесь — то же
   * самое, что занижать метку у классики.
   *
   * ЧЕГО ЗДЕСЬ НЕТ. Ссылок на просмотр: где что идёт, меняется по странам и
   * месяцам, и такая ссылка умирает быстрее, чем мы про неё вспомним.
   * Платформа названа в `platform`, дальше человек ищет сам.
   */
  inOriginal?: {
    /** С какого уровня это перестаёт быть мучением. */
    from: string
    /** Субтитры на языке оригинала — или где лежит подлинный текст. */
    subs: string
    /** Чем труден на слух или в чтении. Одна конкретная вещь, а не «сложный». */
    hard: string
    /** Как смотреть или читать, чтобы это работало. */
    how?: string
  }

  /** Официальный трейлер: встраивание плеером законно, скачивание — нет. */
  trailerUrl?: string
  /** id парного произведения: книга ↔ экранизация. */
  screenPair?: string
}

