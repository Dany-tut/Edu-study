// ─────────────────────────────────────────────────────────────────────────────
// Сцены: отрывки из книг и сериалов для языкового тренажёра
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ readingLibrary
//
// Учебный текст выбирают фильтром: «A2, работа, три минуты». Отрывок из книги
// так не выбирают — его выбирают по обложке и по тому, читал ли ты это раньше.
// Поэтому у сцены поверх обычного текста есть ПРОИЗВЕДЕНИЕ (Work), а у витрины —
// полки, а не плоский список.
//
// Главная ставка блока: ЗНАКОМЫЙ СЮЖЕТ СНИМАЕТ ПОЛОВИНУ НАГРУЗКИ. Кто читал
// «Идиота» по-русски, читает ту же сцену по-английски почти без словаря: он не
// разгадывает, что происходит, — он видит, как это сказано. Поэтому первая
// полка — русская классика на изучаемом языке, а не английская.
//
// ЧТО МОЖНО ПОКАЗЫВАТЬ, А ЧТО НЕТ
//
// Правило то же, что в readingLibrary и listeningLibrary, и оно не смягчается
// от того, что проект некоммерческий: некоммерческое использование чужого
// текста — всё равно использование. Отсюда три корзины (поле `bucket`):
//
//   'pd'       — общественное достояние. Настоящий текст автора, любой длины.
//                Это основа блока и то, ради чего он вообще работает.
//   'licensed' — есть письменное разрешение правообладателя. Пока пусто; поле
//                заведено сразу, чтобы не переделывать модель, когда появится.
//   'inspired' — современное произведение. Показываем карточку, пересказ
//                сюжета своими словами и КОРОТКУЮ цитату с атрибуцией, а сам
//                учебный текст пишем сами: берём у книги тему, регистр и
//                лексику, но не сюжет и не персонажей. Пересказ сцены с теми же
//                героями — производное произведение, оно охраняется так же,
//                как оригинал, поэтому так делать нельзя.
//
// ПРОВЕРКА ОБЩЕСТВЕННОГО ДОСТОЯНИЯ — ПО ДВУМ ЮРИСДИКЦИЯМ СРАЗУ
//
// Хостинг в США, ученики в РФ, значит применяем более строгую из двух: автор
// умер до 1955 (70 лет, РФ и ЕС) И произведение опубликовано до 1930 (США).
// Оруэлл под это не проходит: свободен в РФ с 2021, в США под охраной до 2045.
//
// И отдельно — У ПЕРЕВОДА СВОЙ СРОК. Достоевский свободен, но по-английски его
// написал переводчик, и это отдельное охраняемое произведение. Поэтому в
// `source` обязательны переводчик и год: Констанс Гарнетт (ум. 1946, переводы
// 1910-х) — можно, Пивер и Волохонская — нельзя.
//
// ЛЕНИВАЯ ЗАГРУЗКА. Одна сцена с переводом, словарём и вопросами — около двух
// килобайт. Полка на четыре языка — сотни килобайт в бандле, который открывается
// на вкладке «Чтение». Поэтому здесь реестр произведений (лёгкий, синхронный —
// по нему рисуются полки и обложки) и функции-загрузчики, а сами тексты лежат
// по файлам на язык. Та же схема, что у разговорников в survivalBooks.ts.
// ─────────────────────────────────────────────────────────────────────────────

