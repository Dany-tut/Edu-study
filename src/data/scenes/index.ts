// ─── Загрузка сцен ───────────────────────────────────────────────────────────

type Loader = () => Promise<Scene[]>

const LOADERS: Record<string, Loader> = {
  en: () => import('./scenesEn').then(m => m.EN_SCENES),
  ja: () => import('./scenesJa').then(m => m.JA_SCENES),
  ko: () => import('./scenesKo').then(m => m.KO_SCENES),
  pt: () => import('./scenesPt').then(m => m.PT_SCENES),
}

/**
 * Сколько сцен в каждом чанке. Знать это НАДО СИНХРОННО: «Чтение» в меню
 * режимов считает тексты вместе со сценами, а сам чанк приезжает только когда
 * откроют половину «Сцены». Без этой таблицы у корейского в меню стояло 3
 * (учебные тексты) при 3 текстах и 15 сценах на экране.
 *
 * Числа продублированы и потому могут разойтись с файлами. Расхождение не
 * тихое, и держится оно на трёх подпорках: `npm run check:scenes` сверяет
 * таблицу с файлами (`--fix` переписывает), loadScenes ругается в консоль,
 * когда приехавший список другой длины, а на экране счётчик после загрузки
 * берётся уже из самого списка (см. LanguageTrainer).
 */
export const SCENE_COUNTS: Record<string, number> = {
  en: 116,
  ja: 9,
  ko: 25,
  pt: 4,
}

/** Базовый код языка: pt-BR → pt. */
const base = (lang: string) => lang.split('-')[0].toLowerCase()

/** Есть ли для языка сцены. Синхронно — по этому решается, рисовать ли раздел. */
export const hasScenes = (lang: string | undefined): boolean =>
  !!lang && (lang in LOADERS || base(lang) in LOADERS)

/** Сколько сцен у языка — синхронно, ещё до загрузки чанка. */
export function sceneCount(lang: string | undefined): number {
  if (!lang) return 0
  return SCENE_COUNTS[lang] ?? SCENE_COUNTS[base(lang)] ?? 0
}

/** Произведения языка — из синхронного реестра, без загрузки текстов. */
export function worksForLang(lang: string | undefined): Work[] {
  if (!lang) return []
  const b = base(lang)
  return WORKS.filter(w => base(w.lang) === b)
}

export const workById = (id: string): Work | undefined => WORKS.find(w => w.id === id)

/** Полки, в которых у языка есть хоть одно произведение, — в порядке SHELVES. */
export function shelvesForLang(lang: string | undefined): Shelf[] {
  const works = worksForLang(lang)
  return SHELVES.filter(s => works.some(w => w.shelf === s.id))
}

/**
 * Подгрузить сцены языка. Пустой массив — либо языка нет, либо чанк не доехал.
 * Уронить тренажёр из-за библиотеки отрывков нельзя: чтение должно остаться.
 */
export async function loadScenes(lang: string | undefined): Promise<Scene[]> {
  if (!lang) return []
  const load = LOADERS[lang] ?? LOADERS[base(lang)]
  if (!load) return []
  try {
    const list = await load()
    const declared = sceneCount(lang)
    if (declared !== list.length) {
      console.warn(`scenes: у «${lang}» в SCENE_COUNTS ${declared}, а в файле ${list.length} — поправь таблицу в data/scenes/index.ts`)
    }
    return list
  } catch (e) {
    console.error('loadScenes:', e)
    return []
  }
}

// ─── Хелперы витрины ─────────────────────────────────────────────────────────

/**
 * «1 сцена», «2 сцены», «5 сцен».
 *
 * Общего склонятора в проекте нет, а «1 сцен» на карточке видно сразу и читается
 * как недоделка. Здесь он нужен ровно для одного слова, поэтому и живёт рядом с
 * ним, а не в отдельном модуле на весь проект.
 */
export function scenesWord(n: number): string {
  const tens = n % 100
  if (tens > 10 && tens < 20) return 'сцен'
  switch (n % 10) {
    case 1: return 'сцена'
    case 2: case 3: case 4: return 'сцены'
    default: return 'сцен'
  }
}

/** Подпись под названием произведения: «Достоевский · 1869 · книга». */
export function workLine(w: Work): string {
  // У книги в подписи стоит год, у сериала — платформа: книгу ищут по эпохе, а
  // сериал по тому, где его включить. Фильму нужно и то и другое: «Прайм, 2023»
  // отвечает сразу на оба вопроса, а год без платформы у фильма бесполезен.
  const kind = w.medium === 'book'
    ? String(w.year)
    : w.medium === 'film'
      ? [w.platform, w.year].filter(Boolean).join(', ')
      : (w.platform ?? 'сериал')
  return `${w.author} · ${kind}`
}

/**
 * Пометка происхождения текста для карточки сцены.
 *
 * Показывается всегда, а не только в спорных случаях: ученик имеет право знать,
 * читает он Акутагаву или написанный нами текст на тему Акутагавы.
 */
export function originLabel(s: Scene): string {
  return s.textOrigin === 'verbatim' ? 'подлинный текст' : 'наш текст по мотивам'
}
