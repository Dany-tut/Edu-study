export interface Work {
  id: string
  /** Русское название — по нему ищут. */
  title: string
  /** Оригинальное название: The Idiot, 蜘蛛の糸, 운수 좋은 날. */
  origTitle: string
  author: string
  year: number
  medium: Medium
  /** Netflix / HBO / Apple TV+ — только у сериалов. */
  platform?: string
  shelf: ShelfId
  /** Язык, на котором даём сцены этого произведения. */
  lang: string
  bucket: Bucket
  age: Age
  /** 'антиутопия', 'детектив', 'young-adult', 'лгбт' — для фильтра и подписи. */
  tags: string[]
  /** О чём это, два-три предложения. Показывается на карточке до сцен. */
  blurb: string
  /**
   * Откуда взят текст. ОБЯЗАТЕЛЕН при bucket === 'pd' — без переводчика и
   * ссылки проверить право на публикацию невозможно, а «кажется, свободно» не
   * является проверкой.
   */
  source?: {
    /** Издание или корпус: Project Gutenberg, 青空文庫, 위키문헌. */
    corpus: string
    url: string
    /** Переводчик и год перевода — если текст не на языке оригинала. */
    translator?: string
    translatedIn?: number
    /**
     * Предупреждение о самом тексте: устаревшая орфография, диалект, архаика.
     * Показывается перед чтением, иначе ученик заучит то, чего писать нельзя.
     */
    caveat?: string
  }
  /** Короткая цитата с атрибуцией — законна и для современных вещей. */
  quote?: { text: string; attribution: string }
  /** Официальный трейлер: встраивание плеером законно, скачивание — нет. */
  trailerUrl?: string
  /** id парного произведения: книга ↔ экранизация. */
  screenPair?: string
}

/** Насколько длинный отрезок. Определяет и подачу, и место в списке. */
export type SceneSize = 'flash' | 'short' | 'long'

