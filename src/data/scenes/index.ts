/**
 * Сцена — это ReadingText плюс то, что делает его отрывком, а не текстом.
 *
 * Наследование здесь не ради экономии типов: сцена проходит через ТУ ЖЕ
 * читалку, тот же словарь по клику и ту же запись результата. Второй читалки
 * для книг быть не должно — она разойдётся с первой на первой же правке.
 */
export interface Scene extends ReadingText {
  workId: string
  /** Место в произведении — по нему сортируется список сцен книги. */
  order: number
  /** «Часть 1, глава 3» или «S1E4, 12:30» — где мы находимся. */
  where: string
  size: SceneSize
  /**
   * ЧТО ВОКРУГ. Два-четыре предложения по-русски: кто эти люди, что было до,
   * почему сцена важна. БЕЗ спойлеров вперёд.
   *
   * Это главное поле блока. Без него отрывок из середины книги — просто
   * случайный абзац; с ним — момент, ради которого стоит прочитать.
   */
  setup: string
  /** Чем кончилось. Открывается ПОСЛЕ ответов: награда и крючок к следующей. */
  after?: string
  /** 1 — безопасно, 2 — раскрывает середину, 3 — раскрывает финал. */
  spoiler: 1 | 2 | 3
  /**
   * Происхождение самого body.
   * 'verbatim' — подлинный текст автора (только для bucket 'pd' и 'licensed').
   * 'ours' — текст написан нами по теме произведения. Это честная пометка, а не
   * формальность: ученик должен знать, читает он Достоевского или нас.
   */
  textOrigin: 'verbatim' | 'ours'
}

