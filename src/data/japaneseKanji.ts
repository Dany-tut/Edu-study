// ─────────────────────────────────────────────────────────────────────────────
// Кандзи: корни, из которых собран японский словарь
//
// ЗАЧЕМ. Та же логика, что у корейской ханчи (data/koreanHanja): японская
// книжная лексика собрана из односложных кирпичей, и знак 学 даёт 学校, 学生,
// 大学, 学期, 見学, 入学 — шесть слов из одного знания. Учить их списком значит
// выучить шесть раз то, что учится один.
//
// ПОЧЕМУ ЭТО НУЖНО ИМЕННО ЯПОНСКОМУ. У корейского ханча — вспомогательный
// слой: современный текст пишется хангылем, и корень виден только через
// значение. В японском кирпич виден ГЛАЗОМ, прямо в строке: увидев 学 в
// незнакомом слове, вы уже знаете половину смысла. Поэтому разбор по корням
// здесь работает сильнее, чем в корейском, а не слабее.
//
// ФОРМАТ. Тот же интерфейс HanjaRoot, что у корейского, — экраны «Конструктора»
// (trainer/RootBuilder) общие. Поля читаются так:
//   ko  — то, чем корень стоит В САМОМ СЛОВЕ. У корейского это слог хангылем,
//         у японского — сам иероглиф: слова здесь пишутся кандзи, и склейка
//         кирпичей должна давать ровно термин (проверка в wordBricks).
//   cn  — подпись под корнем. У корейского там иероглиф, у японского — онъёми
//         каной: сам знак уже стоит в ko, а вот его чтение нужно подсказать.
//
// ОНЪЁМИ, А НЕ КУНЪЁМИ. В составных словах работает китайское чтение (学校 —
// гакко:), и именно оно делает корень узнаваемым на слух. Кунъёми даётся только
// там, где корень частотен и в одиночку (見る, 人).
//
// ЧТО НЕ ПРОВЕРЕНО НОСИТЕЛЕМ. Значения корней и разборы сверялись со
// стандартной этимологией канго, но живость отдельных книжных слов стоит
// уточнять у преподавателя: часть из них вытесняется катаканой.
// ─────────────────────────────────────────────────────────────────────────────

