/**
 * Реестр разговорников по коду языка. Заполняется в survivalBooks.ts, а не
 * здесь: этот файл не должен зависеть от контента, иначе импорт модели тянул бы
 * за собой четыре тысячи фраз в любой экран, который её коснулся.
 */
export type SurvivalRegistry = Record<string, SurvivalBook>

/** Тема разговорника с фразами — то, что показывает тренажёр. */
export interface SurvivalThemeCards {
  theme: SurvivalTheme
  phrases: Phrase[]
}

/** Темы языка с фразами, в порядке сетки. Пусто — разговорника для языка нет. */
export function themesWithPhrases(book: SurvivalBook | undefined): SurvivalThemeCards[] {
  if (!book) return []
  return SURVIVAL_THEMES
    .map(theme => ({ theme, phrases: book.phrases[theme.id] ?? [] }))
    .filter(x => x.phrases.length > 0)
}

/** Полка тренажёра: модуль и его темы, у которых есть фразы. */
export interface SurvivalShelf {
  title: string
  subtitle: string
  themes: SurvivalThemeCards[]
  /** Сколько всего фраз на полке — подпись на выборе слева. */
  count: number
}

/**
 * Темы языка, разложенные по модулям.
 *
 * Пустые полки выбрасываются: язык может быть заполнен не целиком, и раздел
 * «Тело и медицина» без единой темы выглядит как поломка, а не как «пока не
 * написали». Тема, не попавшая ни в один модуль (появилась в сетке, но её
 * номер забыли добавить в SURVIVAL_MODULES), уходит в последнюю полку — так
 * пропажа видна на экране, а не молча теряется.
 */
export function survivalShelves(book: SurvivalBook | undefined): SurvivalShelf[] {
  const cards = themesWithPhrases(book)
  if (cards.length === 0) return []
  const byN = new Map(cards.map(c => [c.theme.n, c]))

  const shelves = SURVIVAL_MODULES.map(m => {
    const themes = m.units.map(n => byN.get(n)).filter((x): x is SurvivalThemeCards => !!x)
    themes.forEach(x => byN.delete(x.theme.n))
    return {
      title: m.title,
      subtitle: m.subtitle,
      themes,
      count: themes.reduce((s, x) => s + x.phrases.length, 0),
    }
  }).filter(s => s.themes.length > 0)

  const orphans = [...byN.values()]
  if (orphans.length > 0) {
    shelves.push({
      title: 'Остальное',
      subtitle: 'Темы вне модулей',
      themes: orphans,
      count: orphans.reduce((s, x) => s + x.phrases.length, 0),
    })
  }
  return shelves
}
