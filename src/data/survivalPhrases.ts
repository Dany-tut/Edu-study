// ─── Генерация заданий ───────────────────────────────────────────────────────

/**
 * Фразы темы, начиная с позиции `from`, по кругу.
 *
 * По кругу — чтобы срез не упирался в конец списка: темы разной длины (в
 * «Еде» фраз вдвое больше, чем в «Не понимаю»), и жёсткие индексы дали бы
 * пустые задания в коротких темах.
 */
const slice = (list: Phrase[], from: number, count: number): Phrase[] =>
  Array.from({ length: Math.min(count, list.length) }, (_, k) => list[(from + k) % list.length])

/**
 * Обманки, ни одна из которых не повторяет верный ответ.
 *
 * ЗАЧЕМ. Обманки берутся из той же темы, и в теме легко встречаются две фразы с
 * одним переводом: «obrigado» и «obrigada» обе значат «спасибо», «Valeu» — тоже.
 * Срез из четырёх подряд давал варианты «спасибо / пожалуйста / спасибо / …»,
 * где верных внешне два, а засчитывается один. Аудит поймал такое в
 * португальском разговорнике; генератор общий, значит могло вылезти в любом.
 *
 * Добираем по кругу дальше по списку, пока не наберём нужное число непохожих.
 * Если в теме столько разных значений вообще нет, отдаём сколько нашлось —
 * лучше вопрос с тремя вариантами, чем с двумя одинаковыми.
 */
function distractors(list: Phrase[], from: number, count: number, answer: string, of: (p: Phrase) => string): string[] {
  const out: string[] = []
  const taken = new Set([answer.trim()])
  for (let k = 0; k < list.length && out.length < count; k++) {
    const text = of(list[(from + k) % list.length])
    if (taken.has(text.trim())) continue
    taken.add(text.trim())
    out.push(text)
  }
  return out
}

/**
 * Задания юнита из его же фраз.
 *
 * Позиции срезов сдвинуты на номер темы, поэтому в каждой теме отрабатываются
 * разные фразы, а не первые четыре по списку. Индекс верного варианта тоже
 * выводится из номера — иначе ответ всегда стоял бы первым, и ученик научился
 * бы нажимать первую кнопку вместо того, чтобы читать.
 */
function unitTasks(theme: SurvivalTheme, list: Phrase[], book: SurvivalBook): SeedTask[] {
  const n = theme.n
  const tasks: SeedTask[] = []

  // Пары «фраза — перевод»: узнавание, самый дешёвый вход в тему.
  tasks.push(pairsOf('Соедините фразу и перевод.',
    slice(list, n, 4).map(x => [x.term, x.ru] as [string, string])))
  tasks.push(pairsOf('Соедините фразу и перевод.',
    slice(list, n + 7, 4).map(x => [x.term, x.ru] as [string, string])))

  // Выбор из четырёх: русский смысл → фраза. Обманки берутся из этой же темы —
  // выбирать между фразами одной ситуации сложнее и полезнее, чем между
  // фразами из разных уроков.
  for (let k = 0; k < 3; k++) {
    const from = n * 3 + k * 5
    const target = slice(list, from, 1)[0]
    const choices = distractors(list, from + 1, 3, target.term, x => x.term)
    const correct = Math.min((n + k) % 4, choices.length)
    choices.splice(correct, 0, target.term)
    tasks.push(one(`Как сказать: «${target.ru}»?`, choices, correct))
  }

  // Обратное направление: фраза → смысл. Проверяет понимание услышанного, а
  // не умение вспомнить нужное — в жизни это разные навыки.
  for (let k = 0; k < 2; k++) {
    const from = n * 5 + k * 4
    const target = slice(list, from, 1)[0]
    const choices = distractors(list, from + 1, 3, target.ru, x => x.ru)
    const correct = Math.min((n + k + 2) % 4, choices.length)
    choices.splice(correct, 0, target.ru)
    tasks.push(one(`Что означает «${target.term}»?`, choices, correct))
  }

  // Вписать фразу целиком: единственный тип, где нет подсказки-варианта.
  for (let k = 0; k < 3; k++) {
    const target = slice(list, n * 2 + k * 6, 1)[0]
    tasks.push(fill(`Напишите на ${book.langName}: «${target.ru}»`, target.term))
  }

  // Аудио. Синтез годится как стимул для диктанта, но эталоном произношения не
  // является — см. шапку languageCourse.ts.
  const heard = slice(list, n + 3, 2)
  heard.forEach(x => tasks.push(dictation('Напечатайте услышанное.', x.term)))

  // Сборка из плиток — только для языков с пробелами: нарезка идёт по ним, и
  // японская фраза стала бы одной плиткой (см. SurvivalBook.spaced).
  if (book.spaced) {
    const bankable = slice(list, n * 4, 8).find(x => x.term.trim().split(/\s+/).length >= 3)
    if (bankable) {
      tasks.push(dictationBank('Соберите услышанное из плиток.', bankable.term.replace(/[?!.]+$/, '')))
    }
  }

  // Чтение вслух: пять фраз подряд — заодно проверка, что ученик вообще может
  // произнести тему, а не только узнать её глазами.
  const aloud = slice(list, n * 6, 5)
  tasks.push(readAloud(
    'Прочитайте вслух пять фраз темы.',
    aloud.map(x => x.term).join(' '),
    45,
  ))

  // Ролевое и письменное — единственные два задания, написанные руками: их
  // нельзя вывести из списка фраз, потому что это ситуация, а не лексика.
  tasks.push(say(theme.roleplay, 90))
  tasks.push(write(theme.written))

  return tasks
}

