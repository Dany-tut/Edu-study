/**
 * Пример употребления фразы — живое предложение, а не словарная статья.
 *
 * ЗАЧЕМ. Фраза в списке стоит голой: «다녀오겠습니다 — я пошёл и вернусь».
 * Понятно, что значит, и непонятно, как это звучит во рту: кому говорят, что
 * стоит рядом, куда девается частица. Пример показывает фразу внутри
 * предложения того же уровня и той же ситуации — и тем самым отвечает на
 * вопрос «а сказать-то это как», ради которого фразу и учат.
 *
 * УРОВЕНЬ. Пример не имеет права быть сложнее самой фразы: вокруг неё
 * ставится только то, что уже встречалось в этой теме или в предыдущих.
 */
export interface PhraseExample {
  /** Предложение на изучаемом языке. */
  term: string
  /** Романизация или транскрипция — по тем же правилам, что и у фразы. */
  reading?: string
  /** Перевод примера — тоже живой, а не подстрочник. */
  ru: string
}

/** Фраза разговорника. Совместима с VocabItem — уходит в карточки как есть. */
export interface Phrase {
  /** Фраза на изучаемом языке — ровно в том виде, в каком её произносят. */
  term: string
  /** Перевод. Не подстрочник, а то, что сказал бы русский в этой ситуации. */
  ru: string
  /** Чтение: романизация или транскрипция. У латиницы не нужно. */
  reading?: string
  /** Когда так говорить нельзя, что ответят, чем отличается от соседней фразы. */
  note?: string
  /** Фраза в живом предложении. */
  ex?: PhraseExample
}

/**
 * Ступень темы по общеевропейской шкале.
 *
 * ЧТО ЭТО ЗНАЧИТ. Не «когда тема наступает в жизни», а насколько сложна речь
 * внутри неё: «Числа и счёт» — это A1 даже для того, кто прилетел впервые, а
 * «Счета и коммуналка» останется B2, хотя платить за квартиру приходится с
 * первого месяца. Порядок тем отвечает на вопрос «что понадобится раньше»,
 * уровень — на вопрос «потяну ли я это сейчас», и это разные вопросы.
 *
 * ЗАЧЕМ. Разговорник открывают не только с нуля. Человеку на B2 витрина из
 * сорока стопок, которая начинается с «Здравствуйте» и «Числа», честно говорит
 * «это не для тебя» — и он закрывает вкладку, не дойдя до «Визы» и «Больницы»,
 * которые ему как раз нужны. Ступень — ось, по которой такую витрину можно
 * отфильтровать до своего.
 *
 * ПОЧЕМУ ТОЛЬКО ДО B2. Разговорник кончается там, где кончается выживание:
 * C1 — это уже не «объясниться в миграционной службе», а язык ради языка, и
 * такой ступени в сетке ситуаций просто нет.
 */
export type SurvivalLevel = 'A1' | 'A2' | 'B1' | 'B2'

/** Ступени по возрастанию — порядок фильтра и сортировки. */
export const SURVIVAL_LEVELS: SurvivalLevel[] = ['A1', 'A2', 'B1', 'B2']

/**
 * Ступень в шкале самого языка.
 *
 * У корейского и японского CEFR официально нет — там TOPIK и JLPT (см.
 * languageTaxonomy). Показывать корейцу «B2» значит показывать шкалу, которой
 * он в своих учебниках не встретит, поэтому ступень переводится в родную шкалу
 * предмета по позиции: A1 — первая ступень снизу, B2 — четвёртая.
 *
 * Соответствие приблизительное — точного пересчёта CEFR↔TOPIK не существует, и
 * здесь он и не нужен: это подпись «насколько это сложно», а не сертификат.
 */
export function survivalLevelLabel(level: SurvivalLevel, subject?: string): string {
  const scale = languageTaxonomy(subject)?.levels
  return scale?.[SURVIVAL_LEVELS.indexOf(level)] ?? level
}

/**
 * Ситуация — единица разговорника и будущий урок курса.
 *
 * Поля повторяют LangUnit не случайно: тема должна собираться в юнит без
 * переходников. Разница в том, что здесь всё пишется по-русски и один раз на
 * все языки — это описание жизненной ситуации, а не языкового материала.
 */
export interface SurvivalTheme {
  /** Стабильный ключ: и id урока, и ключ в phrases/notes книги языка. */
  id: string
  /** Порядковый номер, 1-based. */
  n: number
  /** Насколько сложна речь темы — ось фильтра в тренажёре. */
  level: SurvivalLevel
  title: string
  /** Что человек сможет сделать после темы. */
  goal: string
  /** Почему тема стоит именно здесь и что будет без неё. */
  why: string
  /** Как ситуация устроена: что происходит, чего ждут от вас. */
  situation: string
  /** Лексическая тема — подпись в описании урока. */
  vocabTheme: string
  /** Что ученик делает своими руками. */
  artifact: string
  /** Сценарий устного задания — ролевая ситуация. */
  roleplay: string
  /** Сценарий письменного задания. */
  written: string
  /** Тема из общей разметки языков (languageTaxonomy). */
  topic: string
}

/** Формула и заметка по теме для конкретного языка. */
export interface ThemeNote {
  /** Ключевая конструкция темы — то, что переставляется под себя. */
  formula: string
  /** Регистр, ловушки, что вам ответят. */
  note: string
}

/** Разговорник одного языка. */
export interface SurvivalBook {
  /** Ключ курса-сида — должен быть уникален среди всех сидов. */
  key: string
  title: string
  /** Русское название предмета (см. lib/subjects.ts). */
  subject: string
  /** BCP-47 изучаемого языка — уходит в задания для синтеза речи. */
  lang: string
  level: string
  /** Название языка в родительном/винительном для формулировок заданий. */
  langName: string
  /**
   * Пишется ли язык с пробелами между словами.
   *
   * От этого зависит, можно ли давать задания-плитки: нарезка идёт по пробелам,
   * и японская фраза без них превратилась бы в одну плитку — то есть в задание
   * «нажмите единственную кнопку». Для таких языков сборка из плиток
   * пропускается, а не выдаётся сломанной.
   */
  spaced: boolean
  /** Вводный абзац курса: как в этом языке устроена вежливость к чужому. */
  intro: string
  /** Заметки по темам: ключ — id темы. */
  notes: Record<string, ThemeNote>
  /** Фразы по темам: ключ — id темы. */
  phrases: Record<string, Phrase[]>
  /**
   * Ядро темы — то, что реально учат на уроке. Ключ темы → термы фраз.
   *
   * ЗАЧЕМ. Список темы пишется как справочник: в «Спасибо, извините» лежат все
   * пять способов поблагодарить, потому что человек их услышит. Урок — не
   * справочник. Сорок карточек во втором уроке, из которых десять переводятся
   * словом «спасибо», не выучиваются: ученик видит пять почти одинаковых
   * ответов, не понимает, какой из них его, и не запоминает ни одного. На
   * первом заходе нужна одна форма на смысл, а варианты — потом, когда основная
   * держится сама.
   *
   * Поэтому тема живёт в двух видах. Ядро (десяток фраз, по одной на смысл)
   * уходит в карточки и задания урока. Остальное остаётся в разговорнике
   * тренажёра — оно никуда не девается, но не выдаётся к сроку и не считается
   * за долг.
   *
   * ПОЧЕМУ СПИСКОМ ТЕРМОВ, А НЕ ФЛАЖКОМ У ФРАЗЫ. Ядро — это ещё и порядок: в
   * каком виде тема встаёт в голову с нуля. Отдельный список показывает этот
   * порядок целиком, одним экраном, и его видно при правке. Флажки, размазанные
   * по сорока строкам, такого не дают.
   *
   * Не задано — темой становится весь список. Так и должно быть у языков, где
   * фраз в теме и так десяток (см. английский, японский, португальский).
   */
  core?: Record<string, string[]>
}

/**
 * Короткая запись фразы — иначе тысяча строк контента превращается в простыню.
 *
 * Четвёртым аргументом идёт либо заметка строкой, либо сразу пример: заметка
 * есть у трети фраз, пример — почти у всех, и заставлять писать `undefined`
 * между ними значило бы поставить его в тысяче строк.
 */
export const p = (
  term: string,
  ru: string,
  reading?: string,
  noteOrEx?: string | PhraseExample,
  ex?: PhraseExample,
): Phrase => ({
  term,
  ru,
  reading,
  note: typeof noteOrEx === 'string' ? noteOrEx : undefined,
  ex: typeof noteOrEx === 'object' ? noteOrEx : ex,
})

/**
 * Пример к фразе: предложение — чтение — перевод, в порядке показа.
 *
 * У латиницы чтения нет (см. Phrase.reading), поэтому второй аргумент можно
 * опустить: `e('I am lost.', 'Я заблудился.')` — иначе в английском файле
 * пришлось бы поставить пустую строку тысячу раз.
 */
export function e(term: string, reading: string, ru: string): PhraseExample
export function e(term: string, ru: string): PhraseExample
export function e(term: string, second: string, third?: string): PhraseExample {
  return third === undefined ? { term, ru: second } : { term, reading: second, ru: third }
}

/** Примеры одного языка: тема → фраза → пример. */
export type ThemeExamples = Record<string, Record<string, PhraseExample>>

/**
 * Приклеить примеры к фразам книги.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ПЯТЫМ АРГУМЕНТОМ p(). Пример есть у каждой
 * фразы, то есть их полторы тысячи на язык. Написанные прямо в списке, они
 * растят файл втрое и хоронят под собой сам список: чтобы увидеть, какие фразы
 * есть в теме, пришлось бы пролистывать примеры. Поэтому фразы остаются
 * плотным списком, а примеры лежат рядом в survival<Lang>Examples.ts и
 * привязываются по тексту фразы.
 *
 * Ключ — сам term, а не индекс: список фраз правят (вставляют, меняют местами),
 * и привязка по номеру разъехалась бы молча, приписав примеру чужую фразу.
 * Пример, написанный прямо в p(), сильнее: его не перебьёт файл примеров.
 */
export function withExamples(
  phrases: Record<string, Phrase[]>,
  examples: ThemeExamples,
): Record<string, Phrase[]> {
  const out: Record<string, Phrase[]> = {}
  for (const [themeId, list] of Object.entries(phrases)) {
    const byTerm = examples[themeId]
    out[themeId] = byTerm
      ? list.map(ph => (ph.ex || !byTerm[ph.term] ? ph : { ...ph, ex: byTerm[ph.term] }))
      : list
  }
  return out
}

