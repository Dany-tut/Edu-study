// ─────────────────────────────────────────────────────────────────────────────
// Разговорник выживания: общая модель
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ КУРСОВ-СИДОВ
// Восемь готовых курсов (TOPIK, JLPT, IELTS, CELPE-Bras, карьерный английский)
// экзаменационные: они ведут к баллу. Бытовая речь в них есть, но размазана по
// грамматическим юнитам — «где туалет» лежит в юните про частицы места, «счёт,
// пожалуйста» в юните про просьбы. Человеку, который завтра выходит из
// аэропорта, это бесполезно: ему нужен не порядок изучения грамматики, а
// порядок жизненных ситуаций.
//
// Поэтому разговорник — своя ось. Единица здесь не правило, а СИТУАЦИЯ:
// кофейня, метро, аптека, «у меня украли телефон». Внутри ситуации — готовые
// формулы, которые произносятся целиком, и минимум разбора: ровно столько,
// чтобы фразу можно было переставить под себя, а не заучить как заклинание.
//
// ЧТО ОБЩЕЕ, А ЧТО ПО ЯЗЫКАМ
// Сетка тем (SURVIVAL_THEMES) одна на все языки: ситуации у путешественника
// одинаковые независимо от того, куда он летит. По языкам различаются только
// фразы и заметки о регистре (SurvivalBook) — это единственное, что реально
// зависит от языка. Держать четыре копии списка тем значило бы гарантированно
// получить четыре разных списка через месяц.
//
// КАК ЭТО ПОПАДАЕТ К УЧЕНИКУ
// Три двери, один источник:
//   1. Курс-сид «Язык выживания» в Конструкторе — тема становится уроком,
//      фразы становятся карточками, задания генерируются (см. unitTasks).
//   2. Карточки: словарь юнита автоматически превращается в flashcard-задания
//      сборщиком buildLanguageCourse — отдельного кода для этого не нужно.
//   3. Тренажёр ученика — режим «Карточки» умеет набрать колоду фразами по
//      выбранным темам (phrasesForLang).
//
// ЗАДАНИЯ ГЕНЕРИРУЮТСЯ, А НЕ ПИШУТСЯ РУКАМИ
// 25 тем × 4 языка = 100 наборов заданий. Написанные руками, они бы разъехались
// по качеству на второй же теме, а на правку одной формулировки уходило бы сто
// правок. Поэтому задания выводятся из самих фраз детерминированно (никакого
// Math.random: сид обязан собираться одинаково каждый раз), а руками пишется
// то, что вывести нельзя — сценарии ролевых заданий и заметки о вежливости.
// ─────────────────────────────────────────────────────────────────────────────

