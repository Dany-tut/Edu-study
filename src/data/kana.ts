const KATA_SHIFT = 0x60
export const toKatakana = (s: string): string =>
  Array.from(s).map(c => {
    const code = c.codePointAt(0)!
    return code >= 0x3041 && code <= 0x3096 ? String.fromCodePoint(code + KATA_SHIFT) : c
  }).join('')

function make(cell: Exclude<Cell, null>, row: string, script: KanaScript): Kana {
  const [hira, ru, latin, alt = []] = cell
  const ch = script === 'hira' ? hira : toKatakana(hira)
  return {
    ch, script, ru, latin, row, say: ch,
    alt: [latin, ...alt],
    hint: HINTS[hira] && script === 'hira' ? HINTS[hira] : undefined,
  }
}

