// ЗАЧЕМ ЭТОТ ФАЙЛ. Японский в проекте жил словами и фразами, а знак был куском
// текста внутри слова — ровно как корейский до data/hangul.ts. Из-за этого
// японский курс давал всю хирагану одним уроком и не мог ни спросить «как
// читается さ», ни дать написать знак пальцем. Здесь знак становится сущностью
// со звуком, рядом таблицы, похожими знаками и порядком черт.
//
