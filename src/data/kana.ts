/**
 * Ответ на «как читается знак»: главный вариант и что ещё принимаем.
 * Подпись малых знаков («я (малая)») для поля ответа не годится — принимаем
 * голое «я».
 */
export function kanaAnswer(ch: string): { main: string; alt: string[] } {
  const k = KANA[ch]
  if (!k) return { main: '', alt: [] }
  const main = k.ru.replace(/\s*\(.*\)$/, '')
  return { main, alt: [...new Set([k.ru, ...k.alt])].filter(s => s && s !== main) }
}

