/**
 * Похожие на `ch` знаки той же азбуки, не больше `n`.
 *
 * Для звонких (が, パ) — сам «голый» знак и соседи по ряду: が путают не с
 * かかか по форме, а с か и ぎ — точка-две решают всё.
 */
export function lookalikes(ch: string, n = 3): string[] {
  const k = KANA[ch]
  if (!k) return []
  const out: string[] = []
  const push = (c: string) => { if (c !== ch && KANA[c]?.script === k.script && !out.includes(c)) out.push(c) }
  for (const g of LOOKALIKE_GROUPS) if (g[0] === ch) g.slice(1).forEach(push)
  for (const g of LOOKALIKE_GROUPS) if (g.includes(ch)) g.forEach(push)
  const base = plainOf(ch)
  if (base !== ch) {
    push(base)
    for (const g of LOOKALIKE_GROUPS) if (g[0] === base) g.slice(1).forEach(c => push(voicedLike(c, ch)))
  }
  // Добираем соседями по ряду: у них то же начало, и это тоже ловушка.
  for (const other of Object.values(KANA)) {
    if (out.length >= n) break
    if (other.row === k.row && other.script === k.script) push(other.ch)
  }
  return out.slice(0, n)
}

/** Голый знак без ゛/゜: が → か, ぱ → は. */
export function plainOf(ch: string): string {
  const d = ch.normalize('NFD')
  return d.length > 1 ? d[0] : ch
}

/** Знак `c` с той же меткой, что у `like` (если такой есть), иначе сам `c`. */
function voicedLike(c: string, like: string): string {
  const mark = like.normalize('NFD').slice(1)
  if (!mark) return c
  const v = (c + mark).normalize('NFC')
  return v.length === 1 && KANA[v] ? v : c
}

/**
 * Пары, которые русское ухо путает: из них — задания «что вы услышали».
 * Только то, что реально различается: じ/ぢ звучат одинаково, и такой пары
 * здесь нет.
 */
const SOUND_PARTNERS: Array<[string, string]> = [
  ['つ', 'す'], ['し', 'ち'], ['ぬ', 'む'], ['れ', 'ね'], ['ら', 'な'], ['ろ', 'よ'], ['ふ', 'ほ'],
  ['か', 'が'], ['た', 'だ'], ['さ', 'ざ'], ['は', 'ば'], ['ば', 'ぱ'], ['こ', 'ご'], ['と', 'ど'],
  ['き', 'ぎ'], ['く', 'ぐ'], ['ひ', 'び'], ['ほ', 'ぼ'], ['ぶ', 'ぷ'], ['じ', 'ち'],
  ['お', 'を'],
]

/** Знак, с которым `ch` путают на слух; null — такого нет. */
export function soundPartner(ch: string, known: Set<string>): string | null {
  const hira = KANA[ch]?.script === 'kata' ? String.fromCodePoint(ch.codePointAt(0)! - KATA_SHIFT) : ch
  for (const [a, b] of SOUND_PARTNERS) {
    const other = a === hira ? b : b === hira ? a : null
    if (!other || other === 'を' || hira === 'を') continue
    const out = KANA[ch]?.script === 'kata' ? toKatakana(other) : other
    if (known.has(out)) return out
  }
  return null
}

