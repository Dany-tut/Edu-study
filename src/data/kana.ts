// которые нужны только на экране обводки. Здесь — лёгкая часть, которую
// курс-сид и проверки читают синхронно.
//
// ЧТЕНИЕ — ПО ПОЛИВАНОВУ (し «си», ち «ти», つ «цу», じ «дзи»): так пишут
// русские словари и так знак выглядит в остальных японских курсах проекта.
// Латиница (shi, chi, tsu, ji) принимается в ответе наравне — её знает любой,
// кто видел аниме, и требовать от него «си» вместо «shi» — проверка привычки,
// а не знания знака.
// ─────────────────────────────────────────────────────────────────────────────

export type KanaScript = 'hira' | 'kata'

export interface Kana {
  ch: string
  script: KanaScript
  /** Чтение кириллицей, по Поливанову. */
  ru: string
  /** Латиница (Хэпбёрн). */
  latin: string
  /** Что ещё принимается в ответе. */
  alt: string[]
  /** Строка таблицы годзюон: «а», «ка», … — для таблиц и подписи. */
  row: string
  /** Что озвучивать. У малых ゃ/っ своего звука нет — читается полный знак или ничего. */
  say: string
  /** Одна строка о том, чего по записи не видно. */
  hint?: string
}

