// семи тем B2 — две. Человек выше A2 открывал витрину и видел, что курс
// кончился, хотя ровно его темы — виза, документы, аренда, больница — в сетке
// были и ждали текста. Корейский пока глубже по числу фраз (40 тем по 40), но
