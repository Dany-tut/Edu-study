// ─────────────────────────────────────────────────────────────────────────────
// Английский разговорник выживания
//
// ЗАЧЕМ ОН НУЖЕН, ЕСЛИ АНГЛИЙСКИЙ «ВСЕ ЗНАЮТ». Школьный английский даёт слова,
// но не даёт формул. Человек, который знает и «can» и «I have», в кафе всё равно
// говорит «I want coffee» — грамматически верно и звучит грубо. Разница между
// «I want» и «Could I have» не в уровне языка, а в том, что первую фразу никто
// не произносит вслух. Здесь собраны именно те обороты, которые говорят.
//
// КАКОЙ ВАРИАНТ. Смешанный, с пометками. Английский — язык, на котором говорят
// в разных странах по-разному, и приезжему важнее знать обе стороны пары
// (restroom / toilet, check / bill, to go / takeaway), чем выбрать одну.
// Различия помечены в самих фразах.
//
// ТРАНСКРИПЦИЯ. Не даётся: латиница читается сама, а честная запись английского
// произношения требует не строки в скобках, а фонетического разбора. Эталон —
// озвучка рядом с фразой.
//
// ГЛУБИНА. Первая редакция: 26 ситуаций по 14–16 фраз. Корейский разговорник
// глубже (39 тем по 40 фраз) — он писался дольше. Незаполненные темы второго
// блока на экран не выводятся.
//
// ЮРИДИЧЕСКОЕ. Все фразы написаны с нуля, чужие учебники не копировались.
// ─────────────────────────────────────────────────────────────────────────────

