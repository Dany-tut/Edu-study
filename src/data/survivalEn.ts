// (restroom / toilet, check / bill, to go / takeaway), чем выбрать одну.
// Различия помечены в самих фразах.
//
// ТРАНСКРИПЦИЯ. Не даётся: латиница читается сама, а честная запись английского
// произношения требует не строки в скобках, а фонетического разбора. Эталон —
// озвучка рядом с фразой.
//
