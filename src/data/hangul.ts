/**
 * Ответ карточки буквы: главный звук и что ещё принимаем.
 *
 * ЗАЧЕМ ЭТО НЕ ПОЛЕ `sound` НАПРЯМУЮ. `sound` написан для чтения глазами: «к / г»
 * и «— / нъ» объясняют человеку позиционные варианты. Печатать такую строку в
 * поле ответа никто не будет, и карточка, требующая «к / г» с пробелами вокруг
 * косой черты, — это не проверка знания, а проверка терпения.
 *
 * ПРАВИЛО. Варианты режутся по косой черте; прочерк (у немой ㅇ в начале слога)
 * из кандидатов на главный ответ выбрасывается, но принимается — «не читается»
 * тоже верный ответ про ㅇ, просто не тот, который стоит требовать печатать.
 */
export function chamoAnswer(ch: string): { main: string; alt: string[] } {
  const parts = (CHAMO[ch]?.sound ?? '').split('/').map(s => s.trim()).filter(Boolean)
  const real = parts.filter(s => s !== '—')
  const main = real[0] ?? parts[0] ?? ''
  const alt = [...new Set([...parts, CHAMO[ch]?.sound ?? ''])].filter(s => s && s !== main)
  return { main, alt }
}

