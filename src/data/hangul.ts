export type ChamoKind = 'consonant' | 'vowel'

export interface Chamo {
  /** Сама буква в совместимом блоке (ㄱ, U+3131…), как её печатает клавиатура. */
  ch: string
  kind: ChamoKind
  /** Корейское название буквы: 기역, 니은, 아. */
  name: string
  /**
   * Звук отдельной буквы кириллицей. Через косую — позиционные варианты, в том
   * порядке, в каком их встречают: 김 «ким», но 아기 «аги».
   */
  sound: string
  /** Латинская пометка — она стоит в словарях и в чужих курсах. */
  latin: string
  /** Одна строка о том, чего по записи не видно. Показывается на карточке. */
  hint?: string
  /** Из чего состоит: ㄲ → [ㄱ, ㄱ], ㅘ → [ㅗ, ㅏ]. Пусто у простых букв. */
  parts?: string[]
  /** Черты в порядке письма. */
  strokes: Stroke[]
  /** Слова, где буква видна и слышна. Берутся из уроков алфавита ниже. */
  examples: string[]
}

