export interface SyllableParts {
  /** Начальная согласная; у слога без согласной это ㅇ. */
  initial: string
  vowel: string
  /** Патчхим или пустая строка. */
  final: string
}

/** Слог ли это хангыля (а не буква, латиница или знак). */
export const isSyllable = (ch: string): boolean => {
  const c = ch.codePointAt(0)
  return c !== undefined && c >= BASE && c <= LAST
}

/** Буква ли это хангыля в отдельностоящем виде. */
export const isChamo = (ch: string): boolean => ch in CHAMO

/** Разбор слога на три позиции. Не слог — null. */
export function splitSyllable(ch: string): SyllableParts | null {
  if (!isSyllable(ch)) return null
  const n = (ch.codePointAt(0) as number) - BASE
  return {
    initial: INITIALS[Math.floor(n / (21 * 28))],
    vowel: VOWELS[Math.floor((n % (21 * 28)) / 28)],
    final: FINALS[n % 28],
  }
}

/** Сборка слога из трёх позиций. Неизвестная буква — null. */
export function joinSyllable(initial: string, vowel: string, final = ''): string | null {
  const i = INITIALS.indexOf(initial)
  const v = VOWELS.indexOf(vowel)
  const f = FINALS.indexOf(final)
  if (i < 0 || v < 0 || f < 0) return null
  return String.fromCodePoint(BASE + (i * 21 + v) * 28 + f)
}

/**
 * Буквы слога так, как их называют: 김 → ㄱ ㅣ ㅁ, 과 → ㄱ ㅘ.
 *
 * Составные гласные и патчхимы остаются целыми — это отдельные буквы алфавита,
 * и на карточке ㅘ показывают как ㅘ, а не как ㅗ+ㅏ.
 */
export function chamoOf(ch: string): string[] {
  const p = splitSyllable(ch)
  if (!p) return isChamo(ch) ? [ch] : []
  return [p.initial, p.vowel, ...(p.final ? [p.final] : [])]
}

/**
 * Буквы слога так, как их НАБИРАЮТ: 꽈 → ㄱ ㄱ ㅗ ㅏ.
 *
 * Это разбор для заданий «собери слог» и для клавиатуры: составные разложены до
 * тех знаков, которые есть на клавишах.
 */
export function keysOf(ch: string): string[] {
  return chamoOf(ch).flatMap(c => COMPOUND[c] ?? [c])
}

// ─── Клавиатурный автомат ────────────────────────────────────────────────────

/** Пары «две буквы → составная»: обратный COMPOUND плюс трёхклавишные гласные
 *  (ㅘ+ㅣ → ㅙ): ученик мог набрать ㅙ и как ㅗ+ㅐ, и как ㅗ+ㅏ+ㅣ. */
const COMBINE: Record<string, string> = (() => {
  const m: Record<string, string> = {}
  for (const [whole, [a, b]] of Object.entries(COMPOUND)) m[a + b] = whole
  m['ㅘㅣ'] = 'ㅙ'
  m['ㅝㅣ'] = 'ㅞ'
  return m
})()

/**
 * Сборка текста из потока нажатий-букв — то, что делает корейская клавиатура.
 *
 * Нужна типу задания jamoType: ученик тапает буквы, а слоги складываются на
 * глазах (ㅇ+ㅏ+ㄴ → 안, следующая ㄴ начинает 녀…). Правила ровно клавиатурные:
 * две одинаковые согласные сливаются в напряжённую, патчхим при следующей
 * гласной уезжает в новый слог (안 + ㅛ → 아뇨), составной патчхим при этом
 * делится (닭 + ㅏ → 달가). Обратна keysOf: composeKeys(keysOf-поток слова)
 * возвращает само слово.
 */
export function composeKeys(keys: string[]): string {
  let out = ''
  let ini = ''
  let vow = ''
  let fin = ''
  const flush = () => {
    if (ini && vow) out += joinSyllable(ini, vow, fin) ?? ini + vow + fin
    else out += ini + vow + fin
    ini = vow = fin = ''
  }
  for (const k of keys) {
    if (!VOWELS.includes(k)) {
      // Согласная.
      if (!ini && !vow) { ini = k; continue }
      if (ini && !vow) {
        const two = COMBINE[ini + k]
        if (two && INITIALS.includes(two)) { ini = two; continue }
        flush(); ini = k; continue
      }
      if (!fin) {
        if (FINALS.includes(k)) { fin = k; continue }
        flush(); ini = k; continue
      }
      const two = COMBINE[fin + k]
      if (two && FINALS.includes(two)) { fin = two; continue }
      flush(); ini = k; continue
    }
    // Гласная.
    if (fin) {
      // Патчхим уезжает начальной следующего слога; составной — делится.
      const parts = COMPOUND[fin]
      let carry = fin
      if (parts && FINALS.includes(parts[0]) && INITIALS.includes(parts[1])) {
        fin = parts[0]
        carry = parts[1]
      } else {
        fin = ''
      }
      flush()
      if (INITIALS.includes(carry)) ini = carry
      else out += carry
      vow = k
      continue
    }
    if (vow) {
      const two = COMBINE[vow + k]
      if (two && VOWELS.includes(two)) { vow = two; continue }
      flush(); vow = k; continue
    }
    vow = k
  }
  flush()
  return out
}

/** Слоги слова: 김치 → [김, 치]. Не-хангыль отбрасывается. */
export const syllablesOf = (word: string): string[] => [...word].filter(isSyllable)

/** Все буквы слова подряд: 김치 → ㄱ ㅣ ㅁ ㅊ ㅣ. */
export const chamoOfWord = (word: string): string[] => syllablesOf(word).flatMap(chamoOf)

/** Состав слова для карточки знакомства: по слогу, у каждого свои буквы. */
export function partsOfWord(word: string): { syllable: string; chamo: string[] }[] {
  return syllablesOf(word).map(s => ({ syllable: s, chamo: chamoOf(s) }))
}

/** Есть ли в слоге патчхим — от этого зависит форма связки 이에요/예요. */
export function hasFinal(ch: string): boolean {
  const p = splitSyllable(ch)
  return !!p && p.final !== ''
}

/** Оканчивается ли слово на патчхим. Правило 이에요/예요 спрашивает именно это. */
export function endsWithFinal(word: string): boolean {
  const s = syllablesOf(word)
  return s.length > 0 && hasFinal(s[s.length - 1])
}

