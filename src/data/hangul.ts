// ─── Черты ───────────────────────────────────────────────────────────────────

/** Точка в квадрате буквы: 0..100 по обеим осям, начало — левый верхний угол. */
export type Point = readonly [number, number]

export interface Stroke {
  /** Опорные точки в порядке письма: первая — откуда ведём. */
  pts: Point[]
  /** Гнуть линию через точки (ㅅ, ㅇ), а не вести углами (ㄱ, ㄷ). */
  round?: boolean
  /** Замкнутая линия. Нужна ровно одной букве — ㅇ — и её производным. */
  closed?: boolean
}

/** Середина отрезка — опора сглаживания. */
const mid = (a: Point, b: Point): Point => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2]

const n2 = (v: number) => Math.round(v * 100) / 100

/**
 * SVG-путь одной черты.
 *
 * Сглаживание сделано квадратичными сегментами через середины отрезков: опорная
 * точка становится управляющей, а линия проходит через середины. Способ
 * старый и невзыскательный к данным — для трёх-восьми точек он даёт ровно ту
 * плавность, которая нужна кругу ㅇ и наклонным чертам ㅅ.
 */
export function strokePath(s: Stroke): string {
  const p = s.pts
  if (p.length === 0) return ''
  if (p.length === 1) return `M ${n2(p[0][0])} ${n2(p[0][1])}`

  if (!s.round && !s.closed) {
    return `M ${p.map(([x, y]) => `${n2(x)} ${n2(y)}`).join(' L ')}`
  }

  if (s.closed) {
    const start = mid(p[p.length - 1], p[0])
    let d = `M ${n2(start[0])} ${n2(start[1])}`
    for (let i = 0; i < p.length; i++) {
      const c = p[i]
      const m = mid(c, p[(i + 1) % p.length])
      d += ` Q ${n2(c[0])} ${n2(c[1])} ${n2(m[0])} ${n2(m[1])}`
    }
    return `${d} Z`
  }

  let d = `M ${n2(p[0][0])} ${n2(p[0][1])}`
  for (let i = 1; i < p.length - 1; i++) {
    const m = mid(p[i], p[i + 1])
    d += ` Q ${n2(p[i][0])} ${n2(p[i][1])} ${n2(m[0])} ${n2(m[1])}`
  }
  const last = p[p.length - 1]
  return `${d} L ${n2(last[0])} ${n2(last[1])}`
}

/** Длина черты по опорным точкам — «сколько вести пальцем». */
export function strokeLength(s: Stroke): number {
  let sum = 0
  const p = s.pts
  for (let i = 1; i < p.length; i++) sum += Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1])
  if (s.closed && p.length > 1) sum += Math.hypot(p[0][0] - p[p.length - 1][0], p[0][1] - p[p.length - 1][1])
  return sum
}

/**
 * Ужать черты в прямоугольник исходного квадрата.
 *
 * Так собираются составные буквы: ㅐ — это ㅏ, ужатая в левые две трети, и ㅣ в
 * правой трети. Координаты остаются в том же квадрате 0..100, поэтому
 * получившаяся буква ничем не отличается от написанной руками.
 */
function box(strokes: Stroke[], x0: number, y0: number, x1: number, y1: number): Stroke[] {
  const sx = (x1 - x0) / 100
  const sy = (y1 - y0) / 100
  return strokes.map(s => ({
    ...s,
    pts: s.pts.map(([x, y]) => [x0 + x * sx, y0 + y * sy] as Point),
  }))
}

/** Точки круга: ㅇ ведут против часовой стрелки от верхней точки. */
function circle(cx: number, cy: number, r: number): Stroke {
  const pts: Point[] = []
  for (let i = 0; i < 8; i++) {
    const a = -Math.PI / 2 - (i * Math.PI) / 4
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)])
  }
  return { pts, round: true, closed: true }
}

