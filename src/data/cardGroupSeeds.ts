// Сиды групп карточек — готовые подборки, приезжающие с кодом
//
// ЗАЧЕМ ОНИ РЯДОМ С БАЗОЙ. Группы и наборы придуманы для учителя: он собирает
// их в Конструкторе, и они лежат в card_groups. Но витрина, у которой контент
// появляется только после того, как кто-то его завёл, у нового ученика пуста —
// ровно та же беда, из-за которой в своё время появился разговорник (см.
// шапку PhraseDecks). Поэтому пара подборок едет с кодом и видна всем.
//
// СИД НЕЛЬЗЯ ПРАВИТЬ, ЕГО МОЖНО ЗАБРАТЬ СЕБЕ. У сидовой группы `seed: true`, и
// редактор Конструктора не даёт менять её на месте: изменения жили бы до
// следующего деплоя. Кнопка «Забрать себе» копирует группу в card_groups под
// учителя — дальше это его группа, и правится она как любая другая.
//
// ЗАГРУЗКА ЛЕНИВАЯ. Одна подборка — это сотни карточек с примерами и
// пояснениями; тащить их в главный чанк ради тех, кто открыл «Чтение», нельзя
// (см. reference про вес бандла).
// ─────────────────────────────────────────────────────────────────────────────

import type { CardGroup } from '../lib/cardGroups'

/** Какие языки вообще имеют сидовые группы — синхронно, по этому рисуется вкладка. */
const SEED_LANGS: Record<string, () => Promise<CardGroup[]>> = {
  // Порядок здесь — порядок на витрине. Стянутая речь стоит первой намеренно:
  // она пятнадцать карточек длиной, учится один раз и делает понятнее ВСЁ
  // остальное, включая соседнюю подборку по сериалу.
  en: () => Promise.all([
    import('./cardSeeds/spokenEn').then(m => m.SPOKEN_EN),
    import('./cardSeeds/supernatural').then(m => m.SUPERNATURAL),
    import('./cardSeeds/spnMeasured').then(m => m.SPN_MEASURED),
  ]),
}

export function hasCardSeeds(lang: string): boolean {
  return lang in SEED_LANGS
}

export async function loadCardSeeds(lang: string): Promise<CardGroup[]> {
  const load = SEED_LANGS[lang]
  if (!load) return []
  try {
    return await load()
  } catch (e) {
    console.error('loadCardSeeds:', e)
    return []
  }
}
