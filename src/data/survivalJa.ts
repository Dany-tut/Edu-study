// РЕГИСТР. Всё написано на です/ます — нейтрально-вежливой форме. Это ровно тот
// регистр, в котором иностранец разговаривает со всеми, кого встречает:
// продавец, таксист, стойка отеля, коллега. Простую форму (だ/する) курс не даёт
// вовсе: услышать её вы услышите, а сказать её незнакомому человеку нельзя.
// Кэйго — сверхвежливые формы вроде いらっしゃいませ и かしこまりました — дано
// только на узнавание: их говорят ВАМ в магазине и кафе, отвечать ими не нужно.
//
// РОМАНИЗАЦИЯ. По Хэпбёрну, с оглядкой на звучание: долгота отмечена чертой
// (ō, ū), частица は записана как «wa», へ как «e» — так, как произносится, а не
// как пишется. Конечное «u» в -masu и -desu в речи почти не слышно; в записи оно
// оставлено, потому что убрать его — значит сломать поиск по форме.
//
// ПИСЬМЕННОСТЬ. Фразы даны так, как они выглядят в жизни: кандзи там, где их
// пишут, кана там, где кана. Учебная запись «всё каной» здесь была бы вредна —
// на вывеске у станции ученик увидит 出口, а не でぐち.
//
// ГЛУБИНА. Это первая редакция: 26 ситуаций, по 14–16 фраз в каждой. Корейский
// разговорник глубже (39 тем по 40 фраз) — он писался дольше. Темы второго
// блока (быт, бумаги, медицина) здесь пока не заполнены; пустая тема на экран не
// выводится, а не показывается заглушкой.
