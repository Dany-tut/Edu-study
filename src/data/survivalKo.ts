// РЕГИСТР. Всё написано на 해요체 — вежливой разговорной форме. Это
// сознательный выбор: 해요체 уместно везде, где иностранец вообще открывает рот
// (магазин, такси, кафе, стойка), и не звучит ни грубо, ни неуместно-официально.
// Формы на -ㅂ니다 даются точечно там, где они реально звучат в жизни
// (감사합니다, 죄송합니다, 알겠습니다) — их произносят все и всегда.
// Панмаль (반말) в курсе нет вообще: язык, на котором приезжий обращается к
// незнакомому человеку на «ты», — это не экономия слогов, а хамство.
//
// РОМАНИЗАЦИЯ. Дана по пересмотренной романизации, но с оглядкой на реальное
// звучание: 감사합니다 записано как «gamsahamnida», хотя по буквам там
// «gamsahabnida» — озвончение и ассимиляция происходят обязательно, и
// побуквенная запись научила бы неправильному. Романизация в карточках
// прячется тумблером: она нужна первые две недели и мешает потом.
//
// ЧТО ЗДЕСЬ НЕ ПРОВЕРЕНО. Фразы бытовые и стандартные, но живой язык меняется
// быстрее курса: молодёжные сокращения и то, как сейчас говорят в кофейнях
// Сеула, лучше уточнять у носителя. Учителю имеет смысл записать свой голос на
// темы 1–3: синтез не передаёт корейскую интонацию вопроса.
//
// ЮРИДИЧЕСКОЕ. Все фразы написаны с нуля. Чужие учебники (в том числе TTMIK) не
// копировались: заимствован только принцип «ситуация вперёд грамматики», а он
// не объект авторского права.
// ─────────────────────────────────────────────────────────────────────────────

