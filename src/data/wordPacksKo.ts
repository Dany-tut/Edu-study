//
// ОТКУДА СПИСКИ. Это ядро бытового корейского: глаголы и глаголы-прилагательные,
// которые встречаются в первых же диалогах, сериалах и вывесках. Порядок внутри
// набора не алфавитный, а смысловой — противоположности стоят рядом (크다 и
// 작다, 덥다 и 춥다), потому что пара запоминается лучше, чем два слова порознь.
//
// ФОРМА СЛОВАРНАЯ. Все глаголы даны на -다: это то, что стоит в словаре и что
// нужно знать, чтобы образовать любую другую форму. Спряжение — дело урока и
// правил, а не карточки: карточка, где 먹어요 и 먹었어요 идут двумя разными
// словами, учит формы вместо слова.
//
// ЧТЕНИЕ — ПРОИЗНОШЕНИЕ, А НЕ БУКВЫ. Романизация записана по официальной
// системе (Revised Romanization) и от ЗВУЧАНИЯ, а не от написания: 좋다 читается
// jota, а не johda, 착하다 — chakada. Иначе транскрипция учит ошибке, ради
// исправления которой её и показывают.
//
// СГЕНЕРИРОВАНО ИЗ СПИСКА ПАР «слово — перевод»: чтения посчитаны правилами
// стыка (озвончение, придыхание с ㅎ, назализация, ассимиляция ㄹ), а не набраны
// руками — двести романизаций, набранных вручную, содержат опечатки гарантированно.
// ─────────────────────────────────────────────────────────────────────────────

