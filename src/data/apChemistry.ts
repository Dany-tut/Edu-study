// Two courses ("AP Chemistry — Полный курс" RU / "AP Chemistry — Full Course" EN),
// each with 12 lessons: 0 — intro, 1–9 — College Board units, E1 — lab/experiment,
// E2 — exam prep. Every lesson is "Full": it links a Trainer (MCQ practice) and a
// facts Widget (formula / key-fact card), which is what the constructor persists.
//
// Wired into TeacherConstructorPage via mergeById() so the entities seed into
// existing localStorage without wiping the teacher's other work.
// ─────────────────────────────────────────────────────────────────────────────
import type {
  Course, Lesson, Trainer, TrainerQ, Widget, Difficulty,
} from '../pages/teacher/TeacherConstructorPage'

const EDITED = '14.06'
const PURPLE = { color: 'var(--color-purple)', bg: 'var(--color-purple-soft)' }
const GREEN = { color: '#1E9E63', bg: 'var(--color-green-soft)' }

/** Merge seed entities into an existing array, skipping any whose id already
 *  exists (so teacher edits are never overwritten). New seeds go to the front. */
export function mergeById<T extends { id: string }>(base: T[], seed: T[]): T[] {
  const ids = new Set(base.map(b => b.id))
  const missing = seed.filter(s => !ids.has(s.id))
  return [...missing, ...base]
}

// ── builders ────────────────────────────────────────────────────────────────
function q(
  id: string, text: string, opts: string[], correct: number,
  explanation: string, difficulty: Difficulty = 'medium',
): TrainerQ {
  return {
    id,
    text,
    answer: opts[correct],
    answers: opts.map((t, i) => ({ id: `${id}a${i}`, text: t, correct: i === correct })),
    explanation,
    difficulty,
    source: 'manual',
    questionType: 'choice',
  }
}

function trainer(id: string, title: string, topic: string, difficulty: Difficulty, questions: TrainerQ[]): Trainer {
  return { id, title, topic, difficulty, timePerQuestion: 60, questions, subject: 'Химия', ...PURPLE, lastEdited: EDITED }
}

function facts(id: string, title: string, items: [string, string][]): Widget {
  return {
    id, title, type: 'facts', linkedTrainerId: null,
    items: items.map(([factTitle, factText], i) => ({ id: `${id}i${i}`, factTitle, factText })),
    ...GREEN, lastEdited: EDITED,
  }
}

function lesson(id: string, title: string, trainerId: string, widgetId: string): Lesson {
  return { id, title, trainerId, widgetId }
}

