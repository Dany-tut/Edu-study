// ─────────────────────────────────────────────────────────────────────────────
// Примеры к словам: модель и ключ поиска
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. Карточка повторений приходит из БД (review_cards), где
// лежат только prompt и answer: слово и перевод, больше ничего. Пример к слову
// в базу не пишется и писать его туда нельзя — он не про ученика, а про язык,
// и меняется вместе с контентом, а не вместе с прогрессом. Поэтому пример
// подбирается на чтении, по самому слову, как это уже сделано с картинкой
// (см. data/vocabImages.ts).
//
// КЛЮЧ — слово, приведённое к общему виду. Одно и то же слово приходит с
// разным оформлением: «to apply» из глоссария текста, «apply» из словаря
// юнита, «Apply.» из ошибки тренажёра. Без нормализации три записи считались
// бы разными словами, и примера не получила бы ни одна.
// ─────────────────────────────────────────────────────────────────────────────

/** Пример: предложение, чтение (если письмо чужое) и перевод. */
export interface VocabExample {
  term: string
  reading?: string
  /**
   * Перевод предложения.
   *
   * НЕОБЯЗАТЕЛЕН намеренно. У примеров, написанных руками, он есть всегда. Но
   * часть примеров добывается из самого урока — из теории и из отработки
   * конструкции, — и там перевод есть не у каждой строки. Пример без перевода
   * всё равно лучше пустого места: предложение из своего же урока узнаётся, а
   * непонятное слово в нём разбирается тапом (GlossedText) и слушается кнопкой.
   */
  ru?: string
}

/** Словарь примеров одного языка: ключ слова → пример. */
export type ExampleMap = Record<string, VocabExample>

/**
 * Короткая запись примера — как `e()` в разговорнике: у латиницы чтения нет,
 * и заставлять писать пустую строку в тысяче строк не нужно.
 */
export function x(term: string, ru: string): VocabExample
export function x(term: string, reading: string, ru: string): VocabExample
export function x(term: string, second: string, third?: string): VocabExample {
  return third === undefined ? { term, ru: second } : { term, reading: second, ru: third }
}

/**
 * Ключ слова: регистр, обрамляющая пунктуация и служебные хвосты убираются.
 *
 * ЧТО ИМЕННО СНИМАЕМ. Английское «to» перед инфинитивом и артикль — потому что
 * словарь урока пишет «to apply», а глоссарий текста «apply», и это одно
 * слово. Португальское «o/a/um/uma» — по той же причине. Хвост в скобках
 * («сумка (ручная кладь)») — это пояснение к слову, а не часть слова.
 * Корейское и японское словарное слово не трогаем: там огласовки нет, а резать
 * окончания у агглютинативного языка значит склеить разные слова.
 */
export function exampleKey(term: string): string {
  return term
    .toLowerCase()
    .replace(/\([^)]*\)/g, ' ')
    .replace(/[.!?,;:«»"'`´]/g, ' ')
    .replace(/^(to|the|a|an|o|as|os|um|uma)\s+/, '')
    .replace(/\s+/g, ' ')
    .trim()
}
