// ─────────────────────────────────────────────────────────────────────────────
// Английский B1 → B2 — IELTS Academic
//
// Курс для тех, у кого английский уже работает на бытовом уровне, а нужен балл.
// Цель — не «выучить английский», а закрыть разрыв между тем, что человек умеет,
// и тем, что оценивают по критериям: 6.0 → 7.0.
//
// МЕТОДИЧЕСКАЯ ОСНОВА
// 1. Критерии даются первым юнитом. Пока ученик не знает, за что именно
//    начисляют баллы, он тренирует не то: пишет длиннее вместо связнее,
//    заучивает «умные слова» вместо точных. Разбор band descriptors — самая
//    рентабельная пара часов всего курса.
// 2. Перефразирование (юнит 2) идёт до любой техники по секциям, потому что оно
//    лежит в основе всех четырёх: в Listening и Reading вопрос почти всегда
//    перефразирует запись или текст, в Writing и Speaking повтор формулировки
//    задания прямо снижает балл за Lexical Resource.
// 3. Reading отрабатывается через типы вопросов, а не через «чтение текстов»:
//    полоса потерь у B1–B2 — не понимание, а True/False/Not Given и Matching
//    Headings, где проверяется работа с формулировкой, а не язык.
// 4. Writing Task 2 стоит вдвое дороже Task 1 и разбирается на трёх юнитах
//    против двух — распределение времени в курсе повторяет вес в экзамене.
// 5. Speaking тренируется записью голоса с разбором учителя. Это то, чего нет у
//    приложений: у них обратная связь исчезает вместе с диалогом.
//
// ФАКТЫ О ФОРМАТЕ, НА КОТОРЫХ ПОСТРОЕН КУРС
// Listening — 4 части, 40 вопросов, запись звучит один раз. Reading Academic —
// 3 текста, 40 вопросов, 60 минут без дополнительного времени на перенос
// ответов. Writing — Task 1 (от 150 слов) и Task 2 (от 250 слов), Task 2 весит
// вдвое больше. Speaking — 11–14 минут, три части, во второй минута на
// подготовку и 1–2 минуты монолога. Итоговый балл — среднее четырёх,
// округлённое до половины.
//
// ЮРИДИЧЕСКОЕ
// IELTS — торговая марка British Council, IDP и Cambridge; курс их не
// представляет. Все тексты, вопросы и примеры написаны с нуля; официальные
// материалы и реальные задания прошлых экзаменов в курс не копируются.
// ─────────────────────────────────────────────────────────────────────────────

