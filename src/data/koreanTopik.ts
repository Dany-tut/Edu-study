// ─────────────────────────────────────────────────────────────────────────────
// Корейский A1 → A2 (подготовка к TOPIK I)
//
// Курс ведёт от нуля (не знает хангыль) до уровня, на котором сдаётся TOPIK I:
// понимает бытовую речь, читает простые тексты, рассказывает о себе, покупает,
// заказывает, договаривается о встрече.
//
// МЕТОДИЧЕСКАЯ ОСНОВА
// 1. Хангыль даётся первым и целиком (юниты 1–4), потому что дальше без него
//    невозможно ничего: романизация, оставленная «на подольше», превращается в
//    костыль, который потом отламывают месяцами.
// 2. Отдельный юнит на правила чтения (4). Корейское письмо морфонологическое:
//    한국어 пишется «хан-гук-о», читается [한구거]. Это детерминированные
//    преобразования — их можно и нужно выучить правилом, а не наслушиванием.
// 3. Порядок слов SOV и падежные частицы идут до расширения лексики: у
//    русскоязычных ошибка №1 не в словах, а в том, что 을/를 и 이/가 ставятся
//    «на слух» либо не ставятся вовсе.
// 4. Две системы числительных (юниты 14–15) разведены по разным юнитам и сразу
//    привязаны к счётным словам: 두 개 / 두 시 / 이십 분 — иначе смешиваются.
// 5. Вежливые уровни (юнит 27) даются в конце, но 해요체 используется с юнита 5:
//    ученик всё время говорит вежливо, а в конце узнаёт, что бывает иначе.
//
// ПРО ЭКЗАМЕН
// TOPIK I состоит из 듣기 (аудирование) и 읽기 (чтение), 200 баллов; уровень 1급
// или 2급 присваивается по набранной сумме. Говорение в TOPIK I не входит —
// оно сдаётся отдельным тестом TOPIK 말하기. Курс всё равно тренирует речь: без
// неё язык не живёт, а половина заданий здесь — устные.
//
// ПРО АУДИО
// Аудио-задания заполнены текстом для синтеза речи. Синтез годится как стимул
// для диктанта, но НЕ как эталон произношения: напряжённые (ㄲ ㄸ ㅃ ㅆ ㅉ) и
// придыхательные (ㅋ ㅌ ㅍ ㅊ) синтез передаёт неровно, а на машине без
// корейского голосового пакета хангыль может быть прочитан английским голосом.
// В юнитах 2 и 4 учителю имеет смысл записать свой голос или голос носителя.
//
// ЮРИДИЧЕСКОЕ
// Все примеры и задания написаны с нуля. Записи Национального института
// корейского языка к распространению запрещены — их здесь нет и быть не должно.
// Корпусные примеры при расширении курса брать из Tatoeba (CC BY) с указанием
// источника, аудио — заказывать у носителей.
// ─────────────────────────────────────────────────────────────────────────────

