  lang: 'ko',
  guidedHours: '250–300',
  scopeNote: 'Охват — с нуля до TOPIK I (уровни 1급–2급). Продолжение до TOPIK II (3급–4급) — следующий курс.',
  modules: KOREAN_MODULES,
  // Конспекты живут отдельным файлом: здесь — последовательность и задания,
