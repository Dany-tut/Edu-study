export const hasEndings = (lang: string): boolean => lang === 'ko'

/** Хвост по id — форма и подпись берутся по нему в обе стороны. */
export const endingById = (id: string): Ending | undefined => KO_ENDINGS.find(e => e.id === id)

/** Основа по словарной форме. */
export const verbByDict = (dict: string): EndingVerb | undefined => KO_VERBS.find(v => v.dict === dict)

/**
 * Слилась ли основа с хвостом.
 *
 * 보 + 아요 даёт не «보아요», а 봐요; 하 + 았어요 даёт 했어요. Гласная основы и
 * гласная хвоста стягиваются в один слог, и границы между кирпичами в такой
 * форме физически нет. Экран обязан это показывать честно: рисовать «보 + 봐요»
 * значит учить границе, которой не существует.
 */
export function isMerged(verb: EndingVerb, endingId: string): boolean {
  const form = verb.forms[endingId]
  return !!form && !form.form.startsWith(verb.stem)
}

/**
 * Хвост, каким он выглядит именно у этой основы, — или пустая строка, если
 * основа с хвостом слились (см. isMerged).
 *
 * Блок в справочнике общий («았/었어요»), а в строке основы он конкретный
 * («었어요»): это и есть то место, где ученик видит гармонию гласных не правилом,
 * а разницей двух соседних строк. Считается вычитанием основы из готовой формы —
 * склейки здесь по-прежнему нет, есть срез уже написанного.
 */
export function tailOf(verb: EndingVerb, endingId: string): string {
  const form = verb.forms[endingId]
  if (!form || isMerged(verb, endingId)) return ''
  return form.form.slice(verb.stem.length)
}

/** Сколько форм даёт матрица — цифра для подписи режима. */
export const endingFormCount = (): number => KO_VERBS.length * KO_ENDINGS.length
