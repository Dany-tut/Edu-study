// ─────────────────────────────────────────────────────────────────────────────
// Конструктор форм: основа глагола + окончание
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ
// Корейский глагол не спрягается по лицам — он собирается из блоков: основа
// остаётся одна и та же, а смысл задаёт хвост. 가 + 요 «иду», 가 + 고 싶어요
// «хочу пойти», 가 + 기 싫어요 «неохота идти», 가 + 겠어요 «пойду», 가 + 고 있어요
// «иду прямо сейчас». Восемь хвостов на восьми основах — это 64 формы, которые
// учатся не как 64 слова, а как 8 + 8.
//
// Учебник даёт это таблицей спряжений и теряет ровно то, ради чего таблица и
// существует: что основа НЕ МЕНЯЕТСЯ. Поэтому здесь материал лежит матрицей —
// строка это основа, столбец это хвост, — а экран показывает её блоками.
//
// ПОЧЕМУ ФОРМЫ ЗАПИСАНЫ ЦЕЛИКОМ, А НЕ СКЛЕИВАЮТСЯ КОДОМ
// Склейка требует морфологии: гармонии гласных (먹 + 어요, но 가 + 요), стяжений
// (보 + 아요 = 봐요, 마시 + 어요 = 마셔요), вставного 으 после согласной
// (먹 + 을 거예요) и неправильных основ (듣 → 들어요). Движок на всё это — это
// отдельная библиотека, которая будет врать на каждом десятом глаголе и врать
// молча. Таблица врать не может: что написано, то и показано.
//
// ЧЕГО ЗДЕСЬ НЕТ
// Неправильных глаголов (ㄷ, ㅂ, ㅅ, ㄹ-основы) — они ломают саму идею «основа не
// меняется» и должны идти отдельным материалом, после того как конструктор
// усвоен. Панмаля (반말) тоже нет: восемь хвостов даны в вежливой форме на 요,
// одной и той же — иначе ученик учит два регистра сразу и путает оба.
//
// ЧТО НЕ ПРОВЕРЕНО НОСИТЕЛЕМ
// Русские переводы форм даны по смыслу, а не пословно: «가고 싶어요» это «хочу
// пойти», а не «хочу идти». Оттенок 겠어요 (намерение против предположения)
// зависит от лица и контекста — в подписи взято намерение как более частое в
// речи ученика.
// ─────────────────────────────────────────────────────────────────────────────

/** Готовая форма: основа + хвост, склеенные заранее. */
export interface EndingForm {
  /** Форма целиком. */
  form: string
  /** Романизация формы. */
  reading: string
  /** Перевод формы. */
  ru: string
}

/** Хвост — то, что задаёт смысл. */
export interface Ending {
  id: string
  /** Как хвост выглядит блоком: «고 싶어요». */
  block: string
  /** Название смысла: «хочу». */
  label: string
  /** Развёрнутое объяснение — одна строка под блоком. */
  note: string
  /** Цветовая пара блока (см. TONE в компоненте). */
  tone: EndingTone
}

export type EndingTone = 'yellow' | 'blue' | 'rose' | 'peach' | 'green' | 'teal' | 'purple' | 'red'

/** Основа — то, что не меняется. */
export interface EndingVerb {
  /** Словарная форма: 가다. */
  dict: string
  /** Основа, к которой всё цепляется: 가. */
  stem: string
  /** Романизация словарной формы. */
  reading: string
  /** Перевод словарной формы. */
  ru: string
  /** Формы по id хвоста. */
  forms: Record<string, EndingForm>
}

