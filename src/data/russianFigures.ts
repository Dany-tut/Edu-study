// Схемы конспектов курсов русского языка
//
// ПОЧЕМУ РУКАМИ, А НЕ ГЕНЕРАТОРОМ. Остальным курсам схему считает
// unitFigures.ts: там у юнита есть либо грамматика-развилка, либо шаблон
// конструкции со знаком «…». Здесь нет ни того, ни другого — грамматика
// описана прозой, а «шаблон» это инструкция («Замените затычку точным
// словом»). Табличка «термин → толкование» из словаря тоже отпадает: карточка
// в курсе родного языка ПЕРЕВЁРНУТА (на лице толкование, ответом служит
// термин), и такая схема напечатала бы в конспекте ответы к своим же
// карточкам.
//
// ЧТО ТОГДА ПОКАЗЫВАТЬ. То, чего в тексте не видно: противопоставление там,
// где весь юнит про выбор (одеть/надеть, канцелярит/живой глагол), шкалу там,
// где важно «что выше чего» (регистр, сила чувства), и порядок шагов там, где
// юнит про процедуру (правка, строение рассказа). Это три разные картинки, и
// они выбраны по смыслу юнита, а не по одному шаблону на всех.
// ─────────────────────────────────────────────────────────────────────────────

