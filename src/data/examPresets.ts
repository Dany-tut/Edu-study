import type { TaskTypeId } from './taskTypes'

export type ExamCode = 'ege' | 'oge'

export interface ExamSubtype {
  /** Короткое имя подтипа линии (у линии бывает «ИЛИ»-вариант). */
  title: string
  /** Тип задания Искры, которым собрать линию. */
  type: TaskTypeId
  /** Готовая формулировка ФИПИ — ложится в вопрос задания. */
  prompt: string
  /** Подсказка о форме ответа. */
  hint?: string
  /** matching — число позиций слева. */
  entries?: number
  /** fill — число клеток бланка (короткий ответ фиксированной длины). */
  cells?: number
  /** long — критерии оценивания (К1, К2…). */
  criteria?: string[]
}

export interface ExamLine {
  /** Номер линии КИМ. */
  number: number
  title: string
  /** Первичные баллы за линию. */
  points: number
  subtypes: ExamSubtype[]
}

