// ─────────────────────────────────────────────────────────────────────────────
// Ханча: корни, из которых собран корейский словарь
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ
// Примерно 60% корейской лексики — слова китайского происхождения (한자어), и
// собраны они из односложных кирпичей. Кирпич 학 («учёба») даёт 학교, 학생,
// 학원, 대학, 학기, 방학, 유학 — семь слов из одного знания. Учить их списком
// значит выучить семь раз то, что можно выучить один.
//
// Отсюда формат: не «список иероглифов», а корень + гнездо слов, которые из
// него выводятся. Сам иероглиф даётся для опоры и для тех, кто знает китайский
// или японский, но учить его начертание не требуется: современный кореец пишет
// хангылем, а ханчу узнаёт в лучшем случае в именах и заголовках газет.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
// Написания знака по чертам нет: она не нужна для чтения по-корейски. Полного
// списка «обязательных 1800 иероглифов» школьной программы тоже нет — это
// материал для корейского школьника, а не для иностранца, которому нужна
// словообразовательная логика.
//
// ЧТО НЕ ПРОВЕРЕНО НОСИТЕЛЕМ
// Значения корней и разборы слов сверялись со стандартной этимологией 한자어,
// но частотность и «живость» отдельных слов лучше уточнять у преподавателя:
// часть книжных слов вытесняется заимствованиями из английского.
// ─────────────────────────────────────────────────────────────────────────────

/** Слово, собранное из корней. */
export interface HanjaWord {
  /** Слово хангылем. */
  term: string
  /** Романизация. */
  reading: string
  /** Перевод. */
  ru: string
  /** Разбор по кирпичам — то, ради чего слово здесь стоит. */
  parts: string
  /**
   * Слог, которым корень звучит именно в этом слове, если он звучит не так,
   * как в заголовке гнезда.
   *
   * ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ. Корень 年 в 작년 звучит «년», а в 연세 — «연»: в начале
   * слова ㄴ перед и/й отпадает (두음법칙). 不 звучит «불», но перед ㄷ и ㅈ —
   * «부». Без пометки такие слова выглядят как ошибка раскладки, и проверка «в
   * слове есть корень» их справедливо ловит. С пометкой они становятся тем, чем
   * и являются, — отдельным правилом, которое ученику всё равно предстоит
   * узнать.
   */
  alt?: string
}

/** Корень ханча и его словарное гнездо. */
export interface HanjaRoot {
  /** Чтение корня хангылем — то, как он звучит внутри слов. */
  ko: string
  /** Сам иероглиф — опора, а не предмет заучивания. */
  cn: string
  /** Значение корня по-русски. */
  ru: string
  /** Тематическая группа — по ней корни раскладываются на полки. */
  group: HanjaGroup
  /** Слова, которые из корня выводятся. */
  words: HanjaWord[]
}

