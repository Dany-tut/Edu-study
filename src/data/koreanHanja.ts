/** Корни одной полки. */
export const hanjaByGroup = (group: HanjaGroup): HanjaRoot[] =>
  HANJA_ROOTS.filter(r => r.group === group)

/** Сколько слов открывает разбор — цифра для мотивации в конспекте. */
export const hanjaWordCount = (): number =>
  HANJA_ROOTS.reduce((n, r) => n + r.words.length, 0)

/**
 * Слова, в которых встречается корень, — включая те, что записаны в гнёздах
 * других корней. Одно слово почти всегда собрано из двух знакомых кирпичей, и
 * увидеть его дважды полезнее, чем один раз: 학원 стоит и под 학, и под 원.
 */
export const wordsWithRoot = (ko: string): HanjaWord[] =>
  HANJA_ROOTS.flatMap(r => r.words).filter(word => word.parts.includes(ko))
