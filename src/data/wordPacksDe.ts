// ─────────────────────────────────────────────────────────────────────────────
// Наборы немецких слов
//
// СЛОВО ЗАПИСАНО С АРТИКЛЕМ. Не для красоты: без рода в немецком не собирается
// ни падеж, ни прилагательное, ни местоимение. «Tisch» выучен наполовину —
// через месяц человек знает пятьсот слов и не может сказать «на столе».
// Поэтому в наборе стоит «der Tisch», и артикль учится вместе со словом, а не
// когда-нибудь потом.
//
// МНОЖЕСТВЕННОЕ ЧИСЛО — ТАМ, ГДЕ ОНО НЕОЧЕВИДНО. Немецкое множественное не
// выводится по правилу (das Buch → die Bücher, der Tisch → die Tische, das
// Auto → die Autos), поэтому у бытовых существительных форма подписана в
// переводе. У абстрактных, которые во множественном не употребляются, — нет.
//
// ГЛАГОЛЫ В ИНФИНИТИВЕ, СИЛЬНЫЕ — С ТРЕМЯ ФОРМАМИ. Из «fahren» не выводится
// «fuhr/gefahren», это надо знать наизусть, и учить три формы легче пачкой в
// одном наборе, чем поодиночке из тридцати уроков.
//
// ОТДЕЛЯЕМЫЕ ПРИСТАВКИ ПОМЕЧЕНЫ. «aufstehen» в предложении разваливается —
// ich stehe um sieben auf. Без пометки это выглядит как ошибка, а не как
// правило, поэтому в переводе стоит «(отделяемая)».
//
// ЧТЕНИЯ НЕТ. Латиница читается по правилам, а трудные пары (schon/schön,
// Kirche/Kirsche) вынесены в гнёзда созвучий — там их и надо слушать.
// ─────────────────────────────────────────────────────────────────────────────

