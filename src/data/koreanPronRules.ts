// ─────────────────────────────────────────────────────────────────────────────
// Правила чтения корейского: почему слово звучит не так, как написано
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. До него правила произношения жили россыпью по курсам:
// связывание и назализация — в юните 4 TOPIK I, 유음화/경음화/구개음화 — одним
// уроком в TOPIK II, 두음법칙 — там же среди ханчи, а придыхание на стыке и
// выпадение ㅎ — двумя абзацами теории хангыля. Каждое правило прозвучало по
// разу и больше не возвращалось — а расхождение письма и звука не лечится
// одним уроком (тот же довод, что у гнёзд созвучий в soundNests.ts). Здесь
// правило — МАТЕРИАЛ: со своим разбором, своими примерами и своим прогоном,
// к которому можно возвращаться; промахи уходят в колоду повторений.
//
// ПОЧЕМУ ДЕСЯТЬ, А НЕ ДВЕНАДЦАТЬ. Классические плакаты насчитывают дюжину
// пунктов, но «받침» и «правило конца слога» — это одно правило, названное
// дважды, а «ассимиляция согласных» — общая шапка над назализацией и 유음화.
// Считаем явления, а не заголовки: семь конечных звуков, связывание, пять
// преобразований на стыке, правило начала слова и цепочки правил.
//
// ПОЧЕМУ ПРИМЕРЫ, А НЕ ГЕНЕРАТОР. Транскрипция в lib/translit.ts считает часть
// этих правил (связывание, назализацию, ㄹ на стыке), но не все: напряжение,
// придыхание через ㅎ и палатализация зависят от морфологии, которой у нас нет
// (учебное [효과/효꽈] против словарного). Сгенерированный «неправильный»
// вариант мог бы случайно оказаться правильным — поэтому и верный ответ, и
// обманки написаны руками и проверяемы глазами.
//
// ЧТО ЗДЕСЬ НЕ ЛЕЖИТ. Озвончение ㄱ/ㄷ/ㅂ/ㅈ между гласными — это не правило
// стыка, а свойство самих букв; оно разбирается в уроках алфавита (юниты 2–4
// курса хангыля) и в подсказках транскрипции живёт само. Гнёзда похожих слов —
// в soundNests.ts: там тренируется слух, здесь — чтение.
// ─────────────────────────────────────────────────────────────────────────────

/** Пример работы правила: написано одно — звучит другое. */
export interface PronExample {
  /** Как написано: 꽃이. */
  written: string
  /** Как звучит, хангылем без скобок: 꼬치. Скобки рисует экран. */
  spoken: string
  /** Перевод. */
  ru: string
  /**
   * Чем именно правило здесь сработало. Читается в момент ошибки, поэтому
   * пишется действием («ㅊ уехал к гласной»), а не термином.
   */
  note?: string
  /**
   * Неверные «прочтения» для прогона. Первая обманка — почти всегда наивное
   * чтение по буквам: именно так ошибается человек, не знающий правила.
   */
  distractors: string[]
}

export interface PronRule {
  id: string
  /** Корейское название — как в учебниках и на плакатах: 연음, 비음화… */
  ko: string
  /** Русское название правила. */
  title: string
  /** Формула одной строкой: что во что переходит. */
  tagline: string
  /** Разбор: почему так и на что смотреть. Два-четыре предложения. */
  why: string
  /**
   * `sound` — правило звучания: написано 꽃이, звучит [꼬치].
   * `spelling` — правило письма (두음법칙): корень звучит и пишется иначе в
   * начале слова. Прогон там спрашивает не «как звучит», а «как пишется».
   */
  kind: 'sound' | 'spelling'
  /** Ловушка или граница правила — когда оно НЕ работает. */
  trap?: string
  examples: PronExample[]
}

