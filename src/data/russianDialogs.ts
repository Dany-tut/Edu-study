// ─────────────────────────────────────────────────────────────────────────────
// Диалоги курсов русского языка
//
// ЗАЧЕМ ДИАЛОГ В КУРСЕ РОДНОГО ЯЗЫКА. У иностранного курса диалог проверяет,
// понял ли ученик собеседника. Здесь понимание не проблема — проблема ВЫБОР:
// носитель знает все слова из списка и всё равно говорит «одеть пальто» и
// «в целях недопущения». Ответная реплика ставит его в положение, где выбрать
// придётся: собеседник уже сказал своё, пауза за тобой, и мимо точного слова
// не пройти, как проходят мимо него в упражнении «подчеркните верное».
//
// ПОЧЕМУ НЕ ВО ВСЕХ ЮНИТАХ. Диалог уместен там, где содержание юнита — это
// РЕПЛИКА. Дыхание, артикуляция и стечения согласных проверяются только своим
// голосом (в «Голосе и речи» для этого и стоит запись); деталь у Чехова и
// пейзаж у Бунина — это разбор прозы, и обмен репликами там был бы викториной
// на цитату. Поэтому в «Живой речи» диалоги почти везде, в «Голосе» — только в
// разговорных юнитах, в «Литературе» — в двух, которые сами про речь.
// ─────────────────────────────────────────────────────────────────────────────

