/**
 * Перевод вопроса целиком — или ничего. Половинчатый перевод (формулировка на
 * русском, половина вариантов на языке оригинала) читается как сбой вёрстки и
 * мешает сильнее, чем отсутствие перевода: поэтому кнопки у такого вопроса нет.
 */
export function questionRu(lang: string, q: ReadingQuestion): { q: string; options: string[] } | undefined {
  const d = dict[lang]
  if (!d) return undefined
  const head = d[q.q]
  if (!head) return undefined
  const options: string[] = []
  for (const o of q.options) {
    const ru = d[o]
    if (!ru) return undefined
    options.push(ru)
  }
  return { q: head, options }
}
