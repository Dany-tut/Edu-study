// ─────────────────────────────────────────────────────────────────────────────
// Правила корейской грамматики
//
// ЧТО ВОШЛО. То, без чего нельзя составить предложение, и то, на чём стабильно
// ошибаются: вежливые формы, времена, частицы, соединение действий, причина и
// условие. Порядок полок — порядок появления в речи, а не в учебнике: сначала
// «сказать что-то», потом «про кого», потом «связать два действия».
//
// ЧЕГО НЕ ВОШЛО. Всё, что относится к уровню, до которого этот набор не ведёт:
// косвенная речь, отглагольные существительные, книжные окончания. Правило,
// которым ученик не воспользуется в ближайшие полгода, не помогает ему, а
// удлиняет список, в котором он ищет нужное.
//
// ПАРЫ, А НЕ ОДИНОЧКИ. Половина правил здесь идёт со сравнением (versus), и это
// не украшение: 은/는 без 이/가, -아/어서 без -(으)니까 и -는 동안 без -(으)면서
// объяснить нельзя — их не путают с чем попало, их путают друг с другом.
//
// ЧТЕНИЕ СЧИТАЕТСЯ, А НЕ НАБИРАЕТСЯ. Романизация примеров идёт через
// lib/romanize.ts — от звучания, со всеми стыками. Набранная руками, она в
// половине примеров разошлась бы с тем, что ученик слышит в озвучке.
// ─────────────────────────────────────────────────────────────────────────────

