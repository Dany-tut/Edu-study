/** Название раздела по коду темы («2.4» → «2 · Основы неорганической химии»). */
export function kesSectionLabel(setKey: string, code: string): string {
  const sec = code.split('.')[0]
  const name = FIPI_KES[setKey]?.sections[sec]
  return name ? `${sec} · ${name}` : sec
}

/** Подпись темы: «2.4 Генетическая связь…». */
export function kesTopicLabel(setKey: string, code: string): string {
  const name = FIPI_KES[setKey]?.topics[code]
  return name ? `${code} ${name}` : code
}
