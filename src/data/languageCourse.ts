/**
 * Задание сида → задание редактора. Дефолты типа кладутся первыми, поля сида
 * их перекрывают: так задание не приезжает в редактор с пустыми обязательными
 * полями (например, `allowSlow` у аудио-типов), но и не теряет своё содержимое.
 *
 * ЗДЕСЬ ЖЕ РАСКЛАДЫВАЕТСЯ ВЫБОР (Р15). Через editorTask проходит каждое задание
 * курса, и здесь у него впервые есть АДРЕС — id вида `<урок>-t7`, то есть урок
 * плюс номер задания в уроке. Именно адрес и служит солью: от него зависит и
 * место верного варианта, и порядок обманок. Считать это раньше (в хелперах
 * `one`, в лестнице) было нельзя — там известен только текст вопроса, а он у
 * генерируемых заданий повторяется дословно.
 *
 * Заодно правило перестало зависеть от автора: раскладывается ЛЮБОЙ одиночный
 * выбор, включая написанные руками прямо в юните, а не только собранные через
 * `one()`.
 */
function editorTask(seed: SeedTask, id: string, lang: string) {
  const def = TASK_TYPES[seed.type]
  const task = { isHard: false, label: def.label, lang, ...def.makeDefault(), ...seed, id }
  const choices = task.choices ?? []
  const correct = task.correctChoices ?? []
  // Только одиночный выбор: у множественного верных несколько, и «место
  // верного» там не определено.
  if (task.type === 'single' && choices.length > 1 && correct.length === 1) {
    const spread = placeCorrect(task.question ?? '', choices, correct[0], id)
    task.choices = spread.choices
    task.correctChoices = [spread.correct]
  }
  return task
}

/**
 * Слово словаря → карточка «лицо/оборот». Чтение идёт отдельным полем.
 *
 * ЧТЕНИЕ. Раньше оно вклеивалось в лицо карточки строкой «우유 (uyu)». Так
 * романизация оказывалась несъёмной: ученик, уже разобравший хангыль, всё равно
 * читал подсказку — а она ровно на этом шаге и мешает. Теперь `front` — само
 * слово, `reading` — отдельно, и решатель показывает его по тумблеру.
 *
 * `question` заполняется обязательно и уже СО чтением: и редактор, и списки
 * заданий показывают именно его. Без него десятки словарных карточек выглядели
 * в редакторе одинаковыми пустыми блоками «без текста», и понять, какое слово в
 * какой, было нельзя.
 */
function vocabCard(word: VocabItem, id: string, lang: string, native = false) {
  const label = word.reading ? `${word.term} (${word.reading})` : word.term
  // Картинка ищется по русскому значению, поэтому один рисунок обслуживает все
  // языки курса-сида (см. vocabImages.ts). У абстрактных слов её нет — и это
  // норма, карточка остаётся текстовой.
  const image = vocabImage(word.ru)
  // У родного языка карточка перевёрнута: на лице толкование, в ответе — само
  // слово (см. LanguageCourseSpec.native). Чтение при этом становится
  // подсказкой ударения и уходит на оборот, к слову, а не к описанию.
  return editorTask(
    native
      // Сочетания: сперва записанные в самом юните, иначе — из общего словаря
      // (collocations.ts). Одно и то же слово стоит в словарях нескольких
      // курсов, и держать его сочетания в каждом значило бы их разводить.
      ? { type: 'flashcard', question: label, front: word.ru, back: word.term, reading: word.reading, image, altAnswers: word.alt, related: word.related ?? collocationsFor(word.term) }
      : { type: 'flashcard', question: label, front: word.term, reading: word.reading, back: word.ru, image, altAnswers: word.alt, related: word.related ?? collocationsFor(word.term) },
    id, lang,
  )
}

/**
 * Узнавание слова перед вводом перевода.
 *
 * ЗАЧЕМ. Словарь юнита превращался в карточки один к одному: десять слов —
 * десять одинаковых вопросов «впиши перевод». На них приходилось 47% всех
 * заданий курса, и это была не только скука. Ввод перевода — это ПРИПОМИНАНИЕ,
 * самый тяжёлый вид проверки, а до него слово встречалось ровно один раз, на
 * показе словаря. Человек честно смотрел карточки, доходил до шестнадцатого
 * вопроса и не мог вспомнить слово, которое видел десять минут назад один раз.
 *
 * ЧТО ЗДЕСЬ. Из того же словаря собирается ступенька между показом и вводом:
 * сопоставление (узнать пару среди пяти) и выбор в обе стороны — «что значит
 * это слово» и «как сказать это». Узнавание легче припоминания, и к карточке
 * ученик приходит, увидев слово третий раз, а не первый.
 *
 * ПОЧЕМУ СОПОСТАВЛЕНИЕ, А НЕ ЧЕТЫРЕ ОТДЕЛЬНЫХ ВОПРОСА. Оно закрывает всю порцию
 * одним заданием: разнообразие растёт, а домашка не удлиняется.
 *
 * ОБМАНКИ БЕРУТСЯ ИЗ ЭТОГО ЖЕ ЮНИТА — выбирать между словом урока и словом из
 * другой темы не тренирует ничего: там разводит контекст, а не значение. Что
 * именно считать «этим же юнитом», решает параметр `seen`: у порции это все
 * слова юнита, которые ученик к этому занятию уже видел.
 */
// Возвращаемый тип НЕ аннотируем SeedTask[]: наружу уходит уже готовое задание
// редактора (editorTask проставляет id, label и язык), а SeedTask — это сид без
// id, и с ним весь список hwTasks переставал собираться.
function vocabRecognition(
  unit: LangUnit,
  idBase: string,
  lang: string,
  native = false,
  /**
   * Откуда брать обманки. По умолчанию — свой же словарь; у порции (Р1) сюда
   * приходят ВСЕ слова юнита, введённые к этому занятию, включая слова прошлых
   * порций. Иначе выбор из трёх слов одной порции решается вычёркиванием, а не
   * узнаванием, — и обманка при этом остаётся знакомой (Р9).
   */
  seen: VocabItem[] = unit.vocab,
) {
  const clean = (list: VocabItem[]) => list.filter(w => w.term?.trim() && w.ru?.trim())
  const words = clean(unit.vocab)
  const pool = clean(seen).filter((w, i, all) => all.findIndex(x => x.term === w.term) === i)
  // Меньше четырёх слов в запасе — обманок не набрать, и узнавание
  // вырождается в подсказку.
  //
  // ПОРОГ НА САМУ ПОРЦИЮ СНЯТ. Раньше здесь стояло ещё и «меньше трёх слов в
  // порции — выходим», и это отсекало не сопоставление (у него свой порог
  // ниже), а ВЕСЬ экзамен порции. Порция из одного-двух слов — обычное дело
  // там, где словарь спутываемый (Р5), и такие занятия оставались без выбора
  // из четырёх, то есть без ступени 4 — целевой ступени урока (Р2). До неё
  // доходило 23% слов курса хангыля и 33% слов TOPIK I.
  //
  // Выбор из четырёх на одном новом слове законен: обманки берутся из `seen`,
  // то есть из уже пройденного (Р9), — а это и есть то, чего правило требует.
  if (words.length < 1 || pool.length < 4) return []

  const label = (w: VocabItem) => (w.reading ? `${w.term} (${w.reading})` : w.term)
  const out: SeedTask[] = []

  // ── сопоставление: не больше двух блоков ──
  //
  // Соблазн покрыть сопоставлением весь словарь есть, но домашка и так идёт
  // около часа. Два блока — это до десяти слов, узнанных четырьмя минутами;
  // остальные закрывают карточки и интервальные повторения.
  //
  // Слово, чей перевод уже есть в блоке, пропускается: obrigado и obrigada оба
  // «спасибо», и пара становится неугадываемой — не потому, что ученик не знает
  // языка, а потому, что верных ответов два. Такие слова остаются карточкам,
  // где сравнение идёт по значению и обе формы засчитываются.
  const usedRu = new Set<string>()
  const pairPool = words.filter(w => {
    const ru = w.ru.trim().toLowerCase()
    if (usedRu.has(ru)) return false
    usedRu.add(ru)
    return true
  })
  // Пар не больше четырёх (Р4): пять и больше — это уже не одно задание, а
  // таблица, которую решают перебором.
  if (pairPool.length >= 3) {
    out.push(pairsOf(
      native ? 'Соедините слово и толкование.' : 'Соедините слово и перевод.',
      pairPool.slice(0, 4).map(w => [label(w), w.ru] as [string, string]),
    ))
  }

  /**
   * Три обманки, взятые вокруг самого слова.
   *
   * Брать первые три слова списка нельзя: они оказывались обманками в каждом
   * вопросе юнита, и к третьему ученик отвечал, вычёркивая знакомые варианты,
   * а не узнавая нужный. Смещение от позиции слова даёт каждому вопросу свой
   * набор.
   */
  const wrongFor = (idx: number, of: (w: VocabItem) => string): string[] => {
    const right = of(words[idx])
    const picked: string[] = []
    for (let k = 1; k < pool.length && picked.length < 3; k++) {
      const cand = of(pool[(idx + k * 2) % pool.length])
      if (cand !== right && !picked.includes(cand)) picked.push(cand)
    }
    return picked
  }

  // Выбор из четырёх — ступень 4, ЦЕЛЕВАЯ ступень урока (Р2).
  //
  // ПОЧЕМУ ПО КАЖДОМУ СЛОВУ, А НЕ ДВА ВОПРОСА НА ПОРЦИЮ. Раньше здесь стояло
  // ровно два вызова — по слову из середины списка и по последнему. Порция из
  // четырёх слов получала ступень 4 у двух из них, а из двух — у ОДНОГО:
  // Math.floor(2/2) и 2-1 дают один и тот же индекс, и оба вопроса уходили на
  // одно слово. По всем корейским курсам целевой ступени достигало 27–38%
  // словаря: не потому, что слова трудные, а потому, что их не спрашивали.
  //
  // Теперь спрашивается каждое слово порции, кроме тех, что уже закрыты
  // сопоставлением выше (оно и есть проверка значения, только тяжелее). Плюс
  // один вопрос НА ГЛУБИНУ по слову из сопоставления — в обратную сторону,
  // «как будет …»: узнать среди четырёх легче, чем достать форму по смыслу.
  //
  // Направление чередуется по номеру слова: иначе вся порция спрашивается в
  // одну сторону, и ученик тренирует только узнавание.
  const ask = (idx: number, reverse: boolean) => {
    const w = words[idx]
    const wrong = wrongFor(idx, x => (reverse ? x.term : x.ru))
    if (wrong.length < 2) return
    // Формулировки родного языка спрашивают не о переводе, а о точности слова:
    // «какое слово это описывает» и «что именно значит это слово».
    out.push(reverse
      ? one(native ? `Какое слово это описывает: «${w.ru}»?` : `Как будет «${w.ru}»?`, [w.term, ...wrong], 0)
      : one(native ? `Что точно значит «${label(w)}»?` : `Что значит ${label(w)}?`, [w.ru, ...wrong], 0))
  }
  const inPairs = new Set(pairPool.slice(0, 4).map(w => w.term))
  words.forEach((w, i) => { if (!inPairs.has(w.term)) ask(i, i % 2 === 1) })
  const deep = words.findIndex(w => inPairs.has(w.term))
  if (deep >= 0) ask(deep, true)

  return out.map((task, i) => editorTask(task, `${idBase}${i + 1}`, lang))
}

/**
 * Сопоставление длиннее четырёх пар — на несколько заданий (Р4).
 *
 * ЗАЧЕМ. Авторские задания писались до стандарта, и сопоставлений на пять-шесть
 * пар в курсах больше трёхсот. Шесть пар — это двенадцать связей, которые надо
 * держать в голове одновременно: рабочая память столько не держит (Cowan 2001),
 * и решается такое перебором, а не знанием.
 *
 * ПОЧЕМУ РЕЖЕМ, А НЕ ОБРЕЗАЕМ. Выкинуть лишние пары — значит выкинуть материал,
 * который автор поставил осознанно. Здесь ничего не пропадает: шесть пар
 * становятся двумя заданиями по три, семь — четыре и три. Куски ровные:
 * задание из одной пары выглядит сбоем.
 */
export function splitMatching(tasks: SeedTask[]): SeedTask[] {
  const MAX = 4
  return tasks.flatMap(task => {
    const pairs = task.pairs ?? []
    if (task.type !== 'matching' || pairs.length <= MAX) return [task]
    const chunks = Math.ceil(pairs.length / MAX)
    const out: SeedTask[] = []
    let at = 0
    for (let k = 0; k < chunks; k++) {
      const end = Math.round((pairs.length * (k + 1)) / chunks)
      out.push({ ...task, pairs: pairs.slice(at, end) })
      at = end
    }
    return out
  })
}

/**
 * Пример употребления, разобранный на предложение и перевод.
 *
 * Поле `example` пишется в трёх видах, и все три встречаются в курсах:
 *   • «I specialise in mobile interfaces.» — просто предложение (латиница);
 *   • «제 이름은 다냐예요. — Меня зовут Даня.» — предложение и перевод;
 *   • «저는 다냐예요 (чонын Danya-eyo) — Я Даня.» — ещё и с чтением (разговорник).
 *
 * Плюс четвёртый вид, который предложением НЕ является: «Читается [감사함니다] —
 * ㅂ перед ㄴ становится ㅁ». Это заметка о произношении, и в задание с
 * пропуском её ставить нельзя. Отдельного признака у неё нет, но есть верный
 * косвенный: сама фраза в такой заметке не написана — и вызывающий отбрасывает
 * её проверкой «предложение содержит слово».
 */
function parseExample(example?: string): { sentence: string; ru?: string } | null {
  const raw = (example ?? '').trim()
  if (!raw) return null
  // Тире с пробелами по бокам — граница перевода. Внутри предложения оно тоже
  // бывает («Я — Даня»), поэтому режем по ПЕРВОМУ, а не по последнему: слева
  // всегда изучаемый язык.
  const cut = raw.indexOf(' — ')
  const left = cut >= 0 ? raw.slice(0, cut) : raw
  const ru = cut >= 0 ? raw.slice(cut + 3).trim() : undefined
  // Чтение в скобках — подпись для человека, а не часть предложения.
  const sentence = left.replace(/\s*\([^)]*\)\s*/g, ' ').replace(/\s+/g, ' ').trim()
  return sentence ? { sentence, ru } : null
}

/**
 * Пропуски по общему банку слов из примеров словаря (тип `wordDrop`).
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНОЕ ЗАДАНИЕ, А НЕ ПЯТЬ «ВПИСАТЬ ОТВЕТ». Банк один на всю
 * пачку строк, и слово из него уходит навсегда: поставил 물 в строку про
 * автобус — отнял его у строки про воду. Пять отдельных «впиши ответ» проверяют
 * пять слов поодиночке; здесь проверяется, что ученик различает их МЕЖДУ СОБОЙ,
 * а это ровно то, что ломается у похожих слов (Р5).
 *
 * ОТКУДА СТРОКИ. Из поля `example` самих слов порции — то есть из предложений,
 * написанных автором под это слово. Синтетических рамок («Это ___») здесь нет
 * намеренно: рамка проверяет не язык, а умение читать шаблон.
 *
 * ГДЕ НЕ ПОЯВИТСЯ. Там, где примеров нет или они не содержат самого слова
 * (экзаменационные курсы, где пример — это заметка о чтении). Задание не
 * подделывается: нет данных — нет задания.
 */
function dropInSeed(words: VocabItem[], seen: VocabItem[]): SeedTask[] {
  const rows: Array<[text: string, answer: string] | [text: string, answer: string, gloss: string]> = []
  const used = new Set<string>()
  for (const w of words) {
    const term = (w.term ?? '').trim()
    const parsed = parseExample(w.example)
    if (!term || !parsed || used.has(term)) continue
    if (!parsed.sentence.includes(term)) continue
    // Слово встречается в примере дважды — закрываем только первое вхождение:
    // два одинаковых пропуска в строке ученик закрыть не сможет, банк даёт одну
    // плитку на слово.
    const text = parsed.sentence.replace(term, GAP_MARK)
    if (!text.includes(GAP_MARK)) continue
    used.add(term)
    rows.push(parsed.ru ? [text, term, parsed.ru] : [text, term])
  }
  // Меньше трёх строк — это уже не «разложить пачку», а «впиши ответ» в
  // непривычной обёртке: банк из двух плиток решается вычёркиванием.
  if (rows.length < 3) return []

  // Одна обманка сверх числа дыр: без неё последнее слово встаёт само, и
  // последняя строка перестаёт быть заданием.
  const extra = seen
    .map(w => (w.term ?? '').trim())
    .filter(t => t && !used.has(t))
    .slice(0, 1)

  return [dropIn('Разложите слова по строкам: каждое слово встаёт ровно в одну.', rows, extra)]
}

/**
 * Кроссворд по пройденному (тип `crossword`) — ступень 6.
 *
 * ПОЧЕМУ ТОЛЬКО ПО ПРОЙДЕННОМУ. Кроссворд — единственное задание без единой
 * опоры формы: ни плиток, ни вариантов, ни первой буквы, только значение. По
 * Р2 это ступень 6, а целевая ступень внутри урока — четвёртая; слова СЕГОДНЯШНЕЙ
 * порции здесь дали бы свободную продукцию через полчаса после знакомства.
 * Поэтому клетки заполняются словами прошлых юнитов — теми, что уже прошли
 * ступень 4 и лежат в колоде.
 *
 * ПОЧЕМУ НЕ ВСЕГДА. Слово в один знак загадать клеткой нельзя (подсказка и
 * ответ совпадут), а из двух слов сетки не выходит. Не набралось трёх —
 * задания просто нет.
 */
function crosswordSeed(words: VocabItem[], native = false): SeedTask[] {
  const seenRu = new Set<string>()
  const items = words
    .filter(w => w.term?.trim() && w.ru?.trim())
    .filter(w => Array.from(w.term.replace(/\s+/g, '')).length >= 2)
    // Одинаковый перевод — две подсказки с одним ответом: клетки заполнить
    // можно, но какая из них чья, ученик не узнает (та же причина, что и в
    // vocabRecognition).
    .filter(w => {
      const ru = w.ru.trim().toLowerCase()
      if (seenRu.has(ru)) return false
      seenRu.add(ru)
      return true
    })
    // Пробел в клетках не живёт: сетка считает знаки, и фраза из двух слов
    // легла бы в неё слитно, а ученик написал бы с пробелом.
    .filter(w => !/\s/.test(w.term.trim()))
    .slice(0, 5)
  if (items.length < 3) return []
  return [crossword(
    native
      ? 'Кроссворд по пройденному: вспомните слово по толкованию.'
      : 'Кроссворд по пройденному: вспомните слово по значению.',
    items.map(w => [w.term.trim(), w.ru.trim()] as [string, string]),
  )]
}

/**
 * Дрилл юнита как задание домашки — ноль или одно.
 *
 * Возвращает массив, а не «задание либо undefined», чтобы в списке заданий он
 * раскрывался спредом наравне с остальными группами и в юнитах без конструкции
 * не оставлял дырки.
 */
function patternTask(unit: LangUnit, id: string, lang: string) {
  const p = unit.pattern
  if (!p || p.items.length === 0) return []
  return [editorTask(
    {
      type: 'pattern',
      question: p.question ?? 'Отработайте конструкцию: подставьте слово и запишите предложение целиком.',
      pattern: p.template,
      patternGloss: p.gloss,
      patternItems: p.items,
    },
    id, lang,
  )]
}

/**
 * Задания «что на картинке» из словаря юнита.
 *
 * Единственный тип задания, который проверяет знание слова без русского
 * посредника: ученик видит предмет и выбирает слово на изучаемом языке.
 * Собирается автоматически там, где в юните набирается хотя бы четыре
 * нарисованных слова (см. vocabImages.ts) — в юнитах с абстрактной лексикой
 * задания просто не будет.
 *
 * Всё детерминировано: и слово-ответ, и позиция верного варианта выводятся из
 * номера юнита. Случайность сломала бы стабильность сида — при каждой сборке
 * курс получался бы другим.
 */
function pictureTasks(unit: LangUnit, idBase: string, lang: string) {
  const drawn = unit.vocab.filter(w => vocabImage(w.ru))
  // Обманки берутся из того же юнита: выбирать между словами одного урока —
  // это проверка слова, а между словами разных уроков — проверка памяти о том,
  // какой урок вообще шёл.
  if (!drawn.length || unit.vocab.length < 4) return []

  // Два задания там, где нарисованного хватает; иначе одно. Больше двух —
  // это уже не отработка, а перебор картинок.
  const count = drawn.length >= 5 ? 2 : 1
  const tasks = []
  for (let k = 0; k < count; k++) {
    const target = drawn[(unit.n + k) % drawn.length]
    // Обманка не должна иметь ту же картинку, что и ответ: «кот» и «кошка»
    // рисуются одинаково, и такое задание нерешаемо.
    const targetImage = vocabImage(target.ru)
    const others = unit.vocab
      .filter(w => w.term !== target.term && vocabImage(w.ru) !== targetImage)
      .slice(k, k + 3)
    if (others.length < 3) break
    // Задание собирается объектом, а не через `one()` (у него картинка и свой
    // размер), поэтому место верного ответа зовётся руками (Р15). Ключ — id
    // задания, а не текст вопроса: вопрос у всех картинок дословно один, и по
    // нему все они уехали бы в одно и то же место.
    const spread = placeCorrect(`${idBase}${k + 1}`, [target.term, ...others.map(w => w.term)], 0)
    const choices = spread.choices
    const correct = spread.correct
    tasks.push(editorTask(
      {
        type: 'single',
        question: 'Что на картинке? Выберите слово.',
        image: vocabImage(target.ru),
        // Размер S (25%): при 40% картинка съедала экран и четыре варианта
        // уходили под сгиб — задание переставало быть «одним экраном».
        // Рисунки простые (силуэт предмета), в четверть колонки они читаются.
        imageSize: 25,
        choices,
        correctChoices: [correct],
      },
      `${idBase}${k + 1}`, lang,
    ))
  }
  return tasks
}

/**
 * Возврат к пройденному — блок повторения в начале домашки.
 *
 * ЗАЧЕМ. Курс был лестницей без перил: юнит вводил десять слов, проверял их в
 * тот же вечер и больше не возвращался к ним никогда. Замер по корейским
 * курсам показал, во что это выливается: в «Разговорнике» слово всплывало в
 * заданиях другого юнита в 13% случаев, в курсе TOPIK II — в 15%. То есть
 * сорок восемь уроков подряд — это сорок восемь непересекающихся островов, и
 * забывание между ними ничем не прервано.
 *
 * Интервальные повторения у нас есть (lib/srs.ts + колода), но они живут
 * СНАРУЖИ курса: ученик должен сам открыть виджет. Тот, кто честно делает
 * домашку и не открывает, не повторяет ничего. Здесь повторение возвращается
 * в саму домашку — туда, куда ученик и так пришёл.
 *
 * ПОЧЕМУ ИМЕННО ЭТИ ИНТЕРВАЛЫ. Юниты 1, 2, 4, 7 и 12 шагов назад — это
 * расширяющаяся лестница: вчерашнее, позавчерашнее, недельной давности.
 * Ровный шаг («три прошлых юнита») даёт частое повторение свежего и полный
 * провал старого, а именно старое и забывается.
 *
 * ПОЧЕМУ ТРИ РАЗНЫХ ЗАДАНИЯ, А НЕ ТРИ КАРТОЧКИ. Повторение одним типом — это
 * повторение одного навыка. Здесь три ступени сразу: узнать пару среди
 * пяти (самое лёгкое), вспомнить слово по смыслу (тяжелее) и заново решить
 * упражнение прошлого юнита (перенос в работу).
 *
 * Блок стоит ПЕРВЫМ — до дрилла нового юнита. Разминка на знакомом материале
 * дешевле в начале, чем хвостом после часа работы, до которого не доходят.
 */
const REVIEW_OFFSETS = [1, 2, 4, 7, 12]

/** Типы, которые можно перенести в другой юнит, не потеряв смысла. */
const CARRYABLE_TYPES = new Set<TaskTypeId>([
  'single', 'multi', 'fill', 'wordBank', 'sequence', 'matching', 'tableFill',
  'listenType', 'listenBank',
])

function reviewTasks(
  unit: LangUnit,
  byN: Map<number, LangUnit>,
  idBase: string,
  lang: string,
  native = false,
): ReviewBlock {
  const prev = REVIEW_OFFSETS
    .map(o => byN.get(unit.n - o))
    .filter((u): u is LangUnit => !!u)
  if (prev.length === 0) return { head: [], late: [] }

  const label = (w: VocabItem) => (w.reading ? `${w.term} (${w.reading})` : w.term)
  const wordOf = (u: LangUnit, shift: number): VocabItem | null => {
    const words = u.vocab.filter(w => w.term?.trim() && w.ru?.trim())
    return words.length ? words[(unit.n + shift) % words.length] : null
  }
  /**
   * Слово, чей перевод в своём юните единственный.
   *
   * ЗАЧЕМ. Задание «как будет …» даёт русский смысл и ждёт ровно одну форму.
   * В юните отрицания рядом стоят 아니요 и 없어요, и оба честно переводятся
   * «нет»: вопрос «как будет „нет“?» не имеет единственного верного ответа, и
   * ученик получает ошибку за корректное слово. Та же защита, что у
   * разговорника (см. askable в survivalPhrases.ts), — только там она нужна
   * внутри темы, а здесь внутри юнита-источника.
   */
  const unambiguousOf = (u: LangUnit, shift: number): VocabItem | null => {
    const words = u.vocab.filter(w => w.term?.trim() && w.ru?.trim())
    const times = new Map<string, number>()
    for (const w of words) {
      const ru = w.ru.trim().toLowerCase()
      times.set(ru, (times.get(ru) ?? 0) + 1)
    }
    const pool = words.filter(w => times.get(w.ru.trim().toLowerCase()) === 1)
    const from = pool.length ? pool : words
    return from.length ? from[(unit.n + shift) % from.length] : null
  }
  const out: SeedTask[] = []
  /** Отложенные касания — их сборщик разложит по занятию (placeLate). */
  const late: SeedTask[] = []

  // ── 1. Узнавание: по слову из каждого прошлого юнита ──
  //
  // Слова с одинаковым переводом в один блок не ставятся: пара становится
  // неугадываемой не потому, что ученик не знает языка, а потому что верных
  // ответов два (та же причина, что и в vocabRecognition).
  const seenRu = new Set<string>()
  const pool = prev
    .map((u, i) => wordOf(u, i))
    .filter((w): w is VocabItem => !!w)
    .filter(w => {
      const ru = w.ru.trim().toLowerCase()
      if (seenRu.has(ru)) return false
      seenRu.add(ru)
      return true
    })
  if (pool.length >= 3) {
    out.push(pairsOf(
      native
        ? 'Повторение: соедините слово и толкование — из прошлых уроков.'
        : 'Повторение: соедините слово и перевод — из прошлых уроков.',
      pool.map(w => (native ? [w.ru, w.term] : [label(w), w.ru]) as [string, string]),
    ))
  }

  // ── 2. Припоминание: вписать слово без вариантов ──
  //
  // Берётся из юнита позапрошлого, а не вчерашнего: вчерашнее ученик помнит
  // ещё «эхом», и такая проверка ничего не показывает.
  const recallFrom = prev[1] ?? prev[0]
  const target = unambiguousOf(recallFrom, 3)
  if (target) {
    const ask = native
      ? `Повторение: какое слово это описывает — «${target.ru}»?`
      : `Повторение: как будет «${target.ru}»?`
    // ХАНГЫЛЬ НАБИРАЕТСЯ ЭКРАННОЙ КЛАВИАТУРОЙ, А НЕ ПОЛЕМ ВВОДА.
    //
    // Поле «впиши слово» предполагает, что у ученика есть корейская раскладка в
    // системе. У начинающего её нет — и ступень 5 для него оказывалась не
    // трудной, а физически невыполнимой: он видит вопрос, знает ответ и не
    // может его ввести. Экранная клавиатура из букв слова закрывает ровно эту
    // дыру и остаётся ступенью 5 по сути: опора здесь — суженный алфавит
    // (нужные буквы плюс пара похожих), как у скелета ответа опора — длина.
    //
    // Другим письменностям это не нужно: кана и латиница набираются с обычной
    // клавиатуры, а иероглифы экранной раскладкой не набрать в принципе.
    //
    // И не одним касанием, а лестницей (см. reviewLadder): узнавание здесь,
    // сборка и ввод — дальше по занятию. Одна попытка в начале урока ничего не
    // измеряет: ошибся — слово ушло невыученным, ответил — ушло непроверенным.
    const ladder = reviewLadder(target, prev.flatMap(u => u.vocab), ask)
    out.push(...ladder.head)
    late.push(...ladder.late)
  }

  // ── 3. Припоминание без опоры: кроссворд по прошлым юнитам (ступень 6) ──
  //
  // Стоит ПОСЛЕ припоминания со скелетом и до переноса: лестница повторения
  // идёт от узнавания пар (ступень 4) через опору (5) к чистому припоминанию
  // (6). Слова берутся из всех прошлых юнитов сразу — по одному на юнит, как и
  // у первого блока, — поэтому пересечения в сетке проверяют разные темы друг
  // другом.
  //
  // Один кроссворд на весь блок, а не по юниту: сетка из пятнадцати слов — это
  // не разминка, а вечер.
  //
  // Из каждого прошлого юнита берётся слово, КОТОРОЕ В СЕТКУ ВСТАЁТ: у
  // английского и разговорника половина словаря — фразы из нескольких слов, а
  // фраза с пробелом клеткам не поддаётся. Брать слово по фиксированному
  // номеру, как в первом блоке, здесь нельзя: попадалась фраза — и кроссворда
  // у курса не было вовсе.
  const griddable = (w: VocabItem) =>
    !!w.term?.trim() && !!w.ru?.trim()
    && !/\s/.test(w.term.trim())
    && Array.from(w.term.trim()).length >= 2
  const crosswordPool = prev
    .flatMap((u, i) => {
      const words = u.vocab.filter(griddable)
      return words.length ? [words[(unit.n + i * 2) % words.length]] : []
    })
  out.push(...crosswordSeed(crosswordPool, native))

  // ── 4. Перенос: задание прошлого юнита целиком ──
  //
  // Задание с отрывком не переносится: отрывок в блоке повторения — это
  // страница текста перед разминкой, а группа вопросов к нему всё равно
  // осталась бы в своём юните.
  const carryFrom = prev[2] ?? prev[1] ?? prev[0]
  const carryable = carryFrom.tasks.filter(t => CARRYABLE_TYPES.has(t.type) && !t.passage)
  if (carryable.length > 0) {
    const src = carryable[unit.n % carryable.length]
    out.push({
      ...src,
      question: src.question ? `Повторение. ${src.question}` : 'Повторение.',
    })
  }

  return numberReview({ head: splitMatching(out), late }, idBase, lang)
}

/**
 * Припоминание, которое можно ВВЕСТИ, — с корейской раскладкой или без неё.
 *
 * ЗАЧЕМ. Поле «впиши слово» предполагает, что у ученика есть корейская
 * раскладка в системе. У начинающего её нет, и ступень 5 для него не трудная, а
 * физически невыполнимая: он видит вопрос, знает ответ и не может его набрать.
 * Экранная клавиатура (`jamoType`) закрывает ровно эту дыру.
 *
 * НО НЕ ЛЮБОЕ СЛОВО НА НЕЁ ЛОЖИТСЯ. Клавиатура требует минимум двух ЧИСТЫХ
 * слогов: на одном слоге это неотличимо от сборки слога, а тильда и пробел
 * («~는데», «어떻게 지내세요?») клавишами не набираются вовсе. Задание при этом
 * не падало — оно просто переставало проверяться: двадцать восемь повторений
 * по четырём корейским курсам ученик не мог сдать никак.
 *
 * Поэтому форма задания выбирается по самому слову:
 *
 *   • два и больше чистых слога — набор по буквам (ступень 5);
 *   • ровно один слог — сборка слога из букв (ступень 3): та же клавиатура по
 *     сути, но без требования, которого слово не выполняет;
 *   • фраза, тильда, пробел — ряд слогов с обманками (ступень 3): собирается
 *     тапами и тоже не требует раскладки;
 *   • не хангыль — обычное поле со скелетом (ступень 5).
 */
function keyboardFreeRecall(ask: string, target: VocabItem): SeedTask[] {
  const term = (target.term ?? '').trim()
  if (!isHangul(term)) return [recall(ask, term, target.alt)]
  const units = Array.from(term)
  if (units.every(isSyllable)) {
    if (units.length >= 2) return [typeWord(ask, term)]
    if (units.length === 1) return [buildSyl(ask, term)]
  }
  return units.length >= 2 ? [sylBank(ask, term)] : [recall(ask, term, target.alt)]
}

/**
 * То же припоминание СТУПЕНЬЮ НИЖЕ — форма собирается из плиток, а не вводится.
 *
 * Нужна как средняя ступень лестницы повторения (Р2) и как то, куда очередь
 * откатывает промах (Р8, lib/lessonLadder.ts): не набралось с клавиатуры —
 * собери из готовых кусков, а набирать будешь через несколько экранов.
 *
 * Пусто, когда собирать не из чего: у слова из одного знака плиток нет.
 */
function tilesRecall(ask: string, target: VocabItem): SeedTask[] {
  const term = (target.term ?? '').trim()
  if (isHangul(term) && Array.from(term).length === 1 && isSyllable(term)) return [buildSyl(ask, term)]
  return Array.from(term.replace(/\s+/g, '')).length >= 2 ? [sylBank(ask, term)] : []
}

/**
 * Лестница повторения по ОДНОМУ слову: узнавание → сборка → ввод.
 *
 * ЗАЧЕМ. Повторение прошлого занятия было одним заданием: «как будет
 * „ребёнок“?» — и всё. Ошибся — слово ушло невыученным (очередь возвращала тот
 * же вопрос, то есть ту же неудачу); ответил верно — тоже ушло, потому что
 * один правильный ответ в начале урока не значит, что слово помнят через
 * сорок минут. Проверка памяти, состоящая из одной попытки, ничего не измеряет
 * (Roediger & Karpicke 2006: помнится то, что извлекали НЕСКОЛЬКО раз, с
 * растущими промежутками).
 *
 * ЧТО СТАЛО. Три касания разной формы, разложенные по занятию: узнавание среди
 * вариантов в разминке, сборка из плиток в середине, набор без опор ближе к
 * концу. Ошибка на любой ступени возвращает слово через очередь (Р8), причём
 * на ступень ниже — этим занимается уже не сид, а lib/lessonLadder.ts.
 *
 * ПОЧЕМУ ВЕРНЫЙ ВАРИАНТ НЕ ВСЕГДА ПЕРВЫЙ. Позиция считается от длины слова:
 * иначе ответ у всех разминок курса стоит на одном месте, и его выбирают, не
 * читая. Случайности тут нельзя — сид обязан собираться одинаково.
 */
function reviewLadder(
  target: VocabItem,
  others: VocabItem[],
  ask: string,
): { head: SeedTask[]; late: SeedTask[] } {
  const head: SeedTask[] = []
  const wrong = others
    .filter(w => w.term?.trim() && w.term.trim() !== target.term.trim())
    .map(w => w.term.trim())
    .filter((t, i, all) => all.indexOf(t) === i)
    .slice(0, 3)
  if (wrong.length >= 1) {
    const at = Array.from(target.term).length % (wrong.length + 1)
    const choices = [...wrong]
    choices.splice(at, 0, target.term)
    head.push(one(ask, choices, at))
  }
  // Средняя ступень идёт ПЕРВОЙ из отложенных: собрать легче, чем набрать.
  const late = [...tilesRecall(ask, target), ...keyboardFreeRecall(ask, target)]
  // Узнавания не вышло (обманок нет) — первое касание берёт на себя сборка,
  // иначе занятие открылось бы сразу вводом.
  if (head.length === 0 && late.length > 1) head.push(late.shift()!)
  return { head, late }
}

/**
 * Есть ли в занятии свободная продукция — задание, где форма достаётся из
 * памяти БЕЗ ОПОР: ни вариантов, ни плиток, ни скелета.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. «Линия продукции» по Р13 засчитывается речью и
 * свободным письмом, но их пишет автор, и в грамматических занятиях их нет.
 * Между тем ступень 6 — это не обязательно микрофон: вписать слово без
 * подсказки, решить кроссворд, набрать его на клавиатуре — та же продукция и
 * так же проверяется машиной. Без неё занятие целиком состоит из узнавания:
 * ученик весь вечер ВЫБИРАЕТ и ни разу ничего не ПОРОЖДАЕТ.
 */
const isFreeProduction = (t: { type: TaskTypeId; answerSkeleton?: string }): boolean =>
  (t.type === 'fill' && !t.answerSkeleton)
  || t.type === 'crossword' || t.type === 'jamoType' || t.type === 'listenType'
  || t.type === 'speaking' || t.type === 'extended' || t.type === 'pattern'

/**
 * Добор продукции, если в занятии её не оказалось: вписать слово по смыслу,
 * без скелета и без вариантов.
 *
 * СЛОВО БЕРЁТСЯ ИЗ ПРОЙДЕННОГО, А НЕ ИЗ СЕГОДНЯШНЕЙ ПОРЦИИ. Целевая ступень
 * для новых слов — четвёртая (Р2); требовать свободного воспроизведения через
 * полчаса после знакомства — это ровно тот дефект, ради которого писался
 * стандарт. Освоенному слову ступень 6 в самый раз.
 *
 * Перевод должен быть единственным в запасе: «как будет „нет“?» при двух
 * словах с этим переводом не имеет одного верного ответа (та же защита, что в
 * reviewTasks).
 */
function productionTask(earlier: VocabItem[], idBase: string, lang: string, native = false) {
  const times = new Map<string, number>()
  for (const w of earlier) {
    const ru = (w.ru ?? '').trim().toLowerCase()
    if (ru) times.set(ru, (times.get(ru) ?? 0) + 1)
  }
  const pick = [...earlier].reverse().find(w =>
    w.term?.trim() && w.ru?.trim() && times.get(w.ru.trim().toLowerCase()) === 1)
  if (!pick) return []
  return [editorTask(
    fill(
      native
        ? `Напишите слово по толкованию: «${pick.ru}»`
        : `Напишите по памяти: как будет «${pick.ru}»?`,
      pick.term,
      pick.alt,
    ),
    `${idBase}1`, lang,
  )]
}

/**
 * Запас обманок для экзамена порции (Р9).
 *
 * Своё — слова юнита, введённые к этому занятию: обманка из той же темы честно
 * проверяет слово, а не тему. Их набирается меньше четырёх у первых, коротких
 * порций — тогда добираем недавно пройденным из прошлых юнитов, от свежего к
 * старому. Ровно четыре и хватит: дальше растёт не сложность, а расстояние
 * между обманкой и ответом, и вопрос решается вычёркиванием.
 */
function examPool(unitSeen: VocabItem[], introduced: VocabItem[]): VocabItem[] {
  if (unitSeen.length >= 6) return unitSeen
  const have = new Set(unitSeen.map(w => w.term))
  const spare: VocabItem[] = []
  for (let i = introduced.length - 1; i >= 0 && unitSeen.length + spare.length < 6; i--) {
    const w = introduced[i]
    if (!w.term?.trim() || have.has(w.term)) continue
    have.add(w.term)
    spare.push(w)
  }
  return [...unitSeen, ...spare]
}

/**
 * Карточки слов — вперемешку с работой, а не хвостом в конце.
 *
 * ЗАЧЕМ. Словарь юнита превращался в карточки один к одному и ложился в конец
 * сплошным блоком: десять слов — десять подряд идущих «впиши перевод». В
 * корейских курсах это 39–41% всех заданий домашки, и последняя её треть
 * состояла из них одних. Ученик доходил до этого места и делал десять
 * одинаковых экранов подряд — ровно то, ради чего люди бросают Duolingo.
 *
 * Само количество карточек при этом уменьшать нельзя: из них строится
 * «Слова урока» (VocabIntro) и из них же наполняется колода интервальных
 * повторений (lib/reviewCapture.ts). Выкинутое из домашки слово исчезло бы
 * из обоих мест. Поэтому меняется не число, а РАСПОЛОЖЕНИЕ: карточки
 * распределяются по всей домашке, и подряд их идёт одна-две, а не десять.
 *
 * ГРУППА ВОПРОСОВ К ОТРЫВКУ НЕДЕЛИМА. Решатель показывает текст один раз на
 * всю группу подряд идущих заданий с одинаковым passage; карточка, вставшая
 * в середину, разорвала бы группу и заставила показать отрывок дважды.
 * Поэтому такие серии склеиваются в один неделимый блок.
 */
/**
 * Порции юнита: урок вводит не больше четырёх новых слов (Р1).
 *
 * ЗАЧЕМ. Юнит давал десять слов за один вечер, и это не порция, а три урока,
 * слепленных в один. Рабочая память держит три-пять несвязанных единиц
 * (Cowan 2001), а незнакомое слово незнакомого письма — это ещё и не одна
 * единица: пока слоги не читаются, 안녕히 계세요 распадается на шесть значков и
 * съедает ёмкость целиком. Десять слов подряд не учатся — они просматриваются.
 *
 * ЧТО ЗДЕСЬ. Словарь юнита режется на порции по ≤ PORTION слов, и КАЖДАЯ
 * ПОРЦИЯ СТАНОВИТСЯ ОТДЕЛЬНЫМ УРОКОМ курса (см. buildLanguageCourse). Юнит из
 * десяти слов — это три урока на одной теме, а не один урок с десятью
 * карточками. Ни одно слово при этом не выброшено, курс не стал короче: то же
 * содержание разложено по числу занятий, которое оно на самом деле занимает.
 *
 * ПОРЦИИ РОВНЫЕ, А НЕ «ПО ЧЕТЫРЕ И ХВОСТ». Десять при капе 4 — это 4+3+3, а не
 * 4+4+2: урок из двух слов выглядит как оборванный, и ученик читает это как
 * сбой, а не как замысел.
 */
const PORTION = 3
/** Курс с незнакомым письмом: буква и слово из неё — уже два новых элемента. */
const PORTION_SCRATCH = 2

const portionSize = (spec: LanguageCourseSpec): number =>
  spec.scratch ? PORTION_SCRATCH : PORTION

/**
 * Стадия письма урока (Р6): знак с транскрипцией или знак сам по себе.
 *
 * Курс не «с нуля» — письмо известно по условию (TOPIK сдают уже читающие).
 * Курс «с нуля» держит транскрипцию до юнита `scriptReadyFrom`, а без этого
 * поля — весь курс: лишняя подсказка стоит меньше, чем вопрос про чтение,
 * заданный раньше, чем чтению научили.
 */
const writingStage = (spec: LanguageCourseSpec, unit: LangUnit): WritingStage =>
  spec.scratch && (spec.scriptReadyFrom == null || unit.n < spec.scriptReadyFrom) ? 'B' : 'C'

export function vocabPortions(vocab: VocabItem[], size: number): VocabItem[][] {
  // Резать подряд идущими кусками нельзя: автор ставит рядом однокоренные и
  // одинаково переводимые слова (안녕히 가세요 / 안녕히 계세요), и такой кусок даёт
  // занятие из двух неразличимых слов. Раскладку делает spreadConfusable (Р5):
  // порции остаются ровными, но спутываемое разъезжается по разным занятиям.
  return spreadConfusable(vocab, size)
}

/**
 * Задания юнита — по порциям, группа вопросов к отрывку неделима.
 *
 * Работа юнита (грамматика, отрывки, аудирование) относится ко всему юниту, а
 * не к четвёрке его слов, поэтому она раскладывается по урокам порций поровну.
 * Блок с одним и тем же отрывком не разрезается между уроками: текст и вопросы
 * к нему в разных днях — это уже не задание с отрывком.
 *
 * ЗАДАНИЕ ЕДЕТ В ПОРЦИЮ СВОЕГО СЛОВА. Если блок называет слово («Обведите
 * букву ㅡ», «Соберите слово 바다»), он обязан попасть в то занятие, где это
 * слово вводится, — иначе ученик обводит букву, которую ещё ни разу не видел
 * (Р3). Это первое правило, и оно сильнее остальных.
 *
 * ОСТАЛЬНОЕ РАЗДАЁМ ЧЕРЕЗ ОДНОГО, А НЕ КУСКАМИ ПОДРЯД. Задания «вообще про
 * тему» слова не называют, и раньше порция получала их сплошным отрезком — со
 * всем однообразием этого отрезка: в юните патчхима шесть заданий «что
 * прозвучало?» стоят рядом, и все шесть уезжали в одно занятие. Ученик видел
 * пять одинаковых экранов подряд (Р13), а соседнее занятие оставалось вовсе
 * без звука. Раздача по кругу разводит такую серию сама собой.
 *
 * Порядок внутри порции остаётся авторским: блоки приходят по возрастанию
 * номера, каким бы правилом ни попали.
 */
function spreadTasks(tasks: SeedTask[], parts: VocabItem[][], firstExtra = 0): SeedTask[][] {
  const count = parts.length
  const blocks: SeedTask[][] = []
  for (const task of tasks) {
    const last = blocks[blocks.length - 1]
    const samePassage = !!task.passage && last?.[0]?.passage === task.passage
    if (samePassage) last.push(task)
    else blocks.push([task])
  }
  const out: SeedTask[][] = Array.from({ length: count }, () => [])

  /** Весь текст блока — в нём и ищется слово порции. */
  const textOf = (block: SeedTask[]) => block
    .map(t => [t.question, t.answer, t.sentence, t.syllable, t.chamo, t.ttsText,
      ...(t.choices ?? []), ...(t.sequenceItems ?? []),
      ...(t.pairs ?? []).flatMap(p => [p.left, p.right])].filter(Boolean).join(' '))
    .join(' ')

  // Длинные слова ищем раньше коротких: «이» входит в «이거», и короткое слово
  // притянуло бы к себе всё подряд.
  const owners = parts
    .flatMap((part, i) => part.map(w => ({ i, term: (w.term ?? '').trim() })))
    .filter(x => x.term.length > 0)
    .sort((a, b) => b.term.length - a.term.length)

  // Бюджет занятия: сколько авторских блоков оно ещё вынесет.
  //
  // ПОЧЕМУ У КАЖДОГО СВОЙ, А НЕ ОБЩАЯ ДОЛЯ. Занятия юнита неравны по весу
  // ЕЩЁ ДО авторских заданий: порция из четырёх слов несёт четыре карточки,
  // лестницу и экзамен — под два десятка экранов, — а занятие-отработка (пустая
  // порция, см. workPortions) не несёт ничего, кроме повторения. Ровная доля
  // «блоков поровну» грузила их одинаково, и разгрузить длинное занятие было
  // нечем: перелив упирался в такое же занятое.
  //
  // Считаем свободное место каждого от общего потолка и раздаём по нему. Тогда
  // добавленное занятие-отработка действительно СНИМАЕТ нагрузку с соседних, а
  // не просто стоит рядом.
  // Первое занятие юнита несёт то, чего нет у продолжений: видео живой речи,
  // диалог темы, дрилл конструкции и возврат к прошлым юнитам. Раньше бюджет
  // этого не знал, и первые занятия разговорника выходили ровно на экран-два
  // сверх потолка — те самые девятнадцать длинных уроков в kosv.
  const budget = parts.map((part, i) =>
    Math.max(2, LESSON_CAP - lessonWeight(part.length) - (i === 0 ? firstExtra : 0)))
  const sizes = new Array(count).fill(0)
  let loose = 0

  /**
   * Куда положить блок, не назвавший ни одного слова порции.
   *
   * Самое свободное занятие — но НЕ то, у которого хвост уже из двух таких же
   * заданий. Иначе авторская серия («как звучит X?» семь раз подряд — разбор
   * правил чтения) целиком уезжает в одно занятие: оно свободнее всех, и после
   * каждого блока остаётся свободнее всех, — а развести серию на месте уже
   * нечем (Р13). Не нашлось занятия с другим хвостом — берём самое свободное:
   * потерять задание хуже, чем поставить третье подряд.
   */
  const placeLoose = (type: TaskTypeId) => {
    const free = (i: number) => budget[i] - sizes[i]
    const sameType = (i: number) => out[i].filter(t => t.type === type).length
    const tailRun = (i: number) => {
      const b = out[i]
      return b.length >= 2 && b[b.length - 1]?.type === type && b[b.length - 2]?.type === type
    }
    // Сначала туда, где заданий ЭТОГО типа меньше, и лишь при равенстве — где
    // просторнее. Одна свободность разводит серию плохо: занятие-отработка
    // свободнее всех и остаётся свободнее всех, так что вся авторская пачка
    // «впишите форму» оседала в нём, и три подряд уже нечем было развести.
    const order = Array.from({ length: count }, (_, i) => i)
      .sort((a, b) => sameType(a) - sameType(b) || free(b) - free(a))
    return order.find(i => !tailRun(i)) ?? order[0]
  }

  blocks.forEach(block => {
    const text = textOf(block)
    const owner = owners.find(o => text.includes(o.term))
    if (!owner) { const at = placeLoose(block[0].type); out[at].push(...block); sizes[at]++; loose++; return }
    // Перелив только ВПЕРЁД: в занятии позже слово уже введено и Р3 цело, а
    // раньше — это задание о слове, которого ученик ещё не видел. Некуда
    // перелить — оставляем у своего слова: правило важнее ровной длины.
    let at = owner.i
    while (at < count - 1 && sizes[at] >= budget[at]) at++
    out[at].push(...block)
    sizes[at]++
  })
  return out
}

/**
 * Развести подряд идущие однотипные задания (Р13).
 *
 * ЗАЧЕМ, ЕСЛИ ЕСТЬ РАЗДАЧА ПО КРУГУ. Она разводит однотипное МЕЖДУ занятиями, а
 * это — ВНУТРИ одного: в юните бывает три «выберите верную форму» на три разных
 * правила, и все три законно попадают в одну порцию.
 *
 * КАК. Жадно: следующим берётся самый ранний блок, чьего типа не было в двух
 * последних; не нашлось такого — берётся самый ранний вообще (значит, разводить
 * уже нечем, и лишний перебор только сломал бы авторский порядок).
 *
 * ЧТО НЕ ТРОГАЕМ. Группу вопросов к отрывку — она едет одним блоком; и вообще
 * ничего, кроме порядка: ни одно задание здесь не пропадает и не появляется.
 */
function breakSameTypeRuns<T extends { type: TaskTypeId; passage?: string }>(tasks: T[]): T[] {
  const blocks: T[][] = []
  for (const task of tasks) {
    const last = blocks[blocks.length - 1]
    const samePassage = !!task.passage && last?.[0]?.passage === task.passage
    if (samePassage) last.push(task)
    else blocks.push([task])
  }
  if (blocks.length < 3) return tasks

  const rest = [...blocks]
  const out: T[][] = []
  /** Тип двух последних выданных блоков — по нему и считается серия. */
  const tail = () => out.slice(-2).map(b => b[0].type)
  while (rest.length > 0) {
    const last2 = tail()
    const run = last2.length === 2 && last2[0] === last2[1] ? last2[0] : null
    const at = run ? rest.findIndex(b => b[0].type !== run) : 0
    out.push(...rest.splice(at >= 0 ? at : 0, 1))
  }
  return out.flat()
}

/**
 * Разминка урока-продолжения: слова предыдущей порции.
 *
 * У первой порции в начале домашки стоит возврат к прошлым юнитам
 * (reviewTasks); у второй и третьей возвращать надо в первую очередь то, что
 * было введено вчера в этом же юните, — иначе порция уходит из вида ровно
 * тогда, когда забывание идёт круче всего.
 */
function portionReview(prev: VocabItem[], idBase: string, lang: string, native = false): ReviewBlock {
  const words = prev.filter(w => w.term?.trim() && w.ru?.trim())
  if (words.length < 2) return { head: [], late: [] }
  const label = (w: VocabItem) => (w.reading ? `${w.term} (${w.reading})` : w.term)
  const out: SeedTask[] = []
  if (words.length >= 3) {
    out.push(pairsOf(
      native
        ? 'Повторение прошлого занятия: соедините слово и толкование.'
        : 'Повторение прошлого занятия: соедините слово и перевод.',
      words.slice(0, 4).map(w => (native ? [w.ru, w.term] : [label(w), w.ru]) as [string, string]),
    ))
  }
  // Припоминание — на слове, которого не было в сопоставлении выше: иначе это
  // проверка последних десяти секунд, а не памяти.
  const target = words[words.length - 1]
  const ladder = reviewLadder(
    target,
    words,
    native ? `Повторение: какое слово это описывает — «${target.ru}»?` : `Повторение: как будет «${target.ru}»?`,
  )
  out.push(...ladder.head)
  return numberReview({ head: out, late: ladder.late }, idBase, lang)
}

/** Разминка занятия: что идёт в начало и что откладывается на потом. */
type StampedTask = ReturnType<typeof editorTask>
type ReviewBlock = { head: StampedTask[]; late: StampedTask[] }

/**
 * Сквозная нумерация разминки — по обеим частям сразу.
 *
 * Отложенные касания получают id из того же ряда (`…-rv4`, `…-rv5`), а не свой:
 * сверка с сидом (lib/seedSync.ts) сопоставляет задания по хвосту id, и два
 * ряда с одинаковыми номерами склеили бы разные задания в одно. По этому же
 * хвосту сторож урока узнаёт блок повторения и не требует от него карточки
 * знакомства (Р3): слова разминки — из ПРОШЛОГО занятия, показывать их заново
 * незачем.
 */
function numberReview(
  block: { head: SeedTask[]; late: SeedTask[] },
  idBase: string,
  lang: string,
): ReviewBlock {
  let n = 0
  const stamp = (task: SeedTask) => editorTask(task, `${idBase}${++n}`, lang)
  return { head: block.head.map(stamp), late: block.late.map(stamp) }
}

/**
 * Разложить отложенные касания по рабочей части занятия.
 *
 * ЗАЧЕМ ИМЕННО ТАК. Смысл повторения — извлечь слово ЧЕРЕЗ ВРЕМЯ. Три вопроса
 * про одно слово подряд проверяют не память, а последние двадцать секунд
 * (Landauer & Bjork 1978: расширяющиеся промежутки дают больше равномерных).
 * Поэтому касания встают примерно на половине и на четырёх пятых занятия.
 *
 * Место подгоняется на пару шагов, если рядом стоит задание того же типа: два
 * одинаковых подряд запрещены (Р13), и вставка не имеет права их создать.
 */
function placeLate<T extends { type: TaskTypeId }>(work: T[], late: T[], room: number): T[] {
  if (late.length === 0) return work
  // Сколько касаний занятие вынесет, не перевалив за потолок (LESSON_CAP).
  //
  // ОДНО ОСТАЁТСЯ ВСЕГДА. Ноль касаний — это ровно то состояние, из-за
  // которого всё это писалось: слово спрашивают один раз, и ошибка уходит
  // невыученной. Экран сверх потолка на самом длинном занятии — цена меньшая,
  // чем невыученное слово; занятия покороче укладываются и так.
  const fit = late.slice(0, Math.max(1, Math.min(late.length, room)))
  const out = [...work]
  const spots = fit.length === 1 ? [0.6] : [0.5, 0.82]
  fit.forEach((task, i) => {
    const want = Math.round(out.length * (spots[i] ?? 0.9))
    let at = Math.min(Math.max(want, 1), out.length)
    for (let shift = 0; shift <= 3; shift++) {
      const cand = Math.min(want + shift, out.length)
      if (out[cand - 1]?.type !== task.type && out[cand]?.type !== task.type) { at = cand; break }
    }
    out.splice(at, 0, task)
  })
  return out
}

/**
 * Конспект урока-продолжения.
 *
 * Полный конспект юнита стоит в первой порции; повторять его в каждой — значит
 * трижды показать одно и то же и обесценить его. Здесь только адрес («это
 * продолжение такого-то юнита»), правило одной строкой и слова самой порции.
 */
function portionTheory(unit: LangUnit, vocab: VocabItem[], k: number, total: number): string {
  const words = vocab
    .map(w => `• ${w.reading ? `${w.term} (${w.reading})` : w.term} — ${w.ru}${w.example ? `\n   ${w.example}` : ''}`)
    .join('\n')
  return [
    `Продолжение юнита ${unit.n} «${unit.title}» — занятие ${k} из ${total}.`,
    `Правило юнита: ${unit.grammar}`,
    // Занятие-отработка (новых слов нет, см. workPortions) — вместо списка
    // слов честно сказано, что тут происходит: иначе пустой заголовок
    // «Слова занятия» читается как потерянный кусок урока.
    vocab.length
      ? `Слова занятия (${unit.vocabTheme}):\n${words}`
      : 'Новых слов сегодня нет: занятие целиком уходит на отработку уже введённых.',
  ].join('\n\n')
}

/**
 * Занятия юнита с учётом РАБОТЫ, а не только словаря.
 *
 * ЗАЧЕМ. Порция = урок (Р1) считает новые слова и ничего не знает про
 * упражнения. У юнита патчхима пять слов и тридцать пять авторских заданий:
 * порции получались две, и в каждую падало по семнадцать упражнений — плюс
 * карточки, лестница, повторение и экзамен. Сорок один экран за вечер,
 * поставленный в получасовой слот. Это не «трудный урок», это невыполненный.
 *
 * ЧТО ДЕЛАЕМ. Считаем, сколько экранов выйдет в занятии — авторские задания
 * ПЛЮС генерируемое, — и если больше LESSON_CAP, добавляем занятия БЕЗ НОВЫХ
 * СЛОВ: карточек и лестницы там нет, есть работа юнита, разминка по прошлой
 * порции и повторение. Такое занятие законно и полезно само по себе — это день
 * отработки, а не день знакомства.
 *
 * ПОЧЕМУ ГЕНЕРИРУЕМОЕ ТОЖЕ СЧИТАЕМ. На порцию из четырёх слов приходится
 * четыре карточки, до двенадцати ступеней лестницы, блок повторения и экзамен —
 * два с половиной десятка экранов ДО единой авторской строки. Считая одну
 * авторскую часть, потолок промахивался мимо самых длинных занятий: они длинные
 * не от автора.
 *
 * ПОЧЕМУ НЕ РЕЗАТЬ СЛОВА МЕЛЬЧЕ. Порция и так на потолке (Р1): дробить её
 * дальше — значит плодить занятия с одним словом, а не разгружать работу.
 */
const LESSON_CAP = 22

/**
 * Прикидка генерируемого веса занятия — сколько экранов выйдет ДО единой
 * авторской строки: карточка на каждое слово, три круга лестницы, блок
 * повторения, экзамен порции, пропуски по банку и добор продукции.
 *
 * ЧИСЛА СНЯТЫ С СОБРАННЫХ КУРСОВ, а не выведены из формулы: по девятистам
 * занятиям восьми курсов генерируемого выходит 6 экранов на одно слово порции,
 * 11 на два, 16 на три, 21 на четыре (медиана) — и на четверть больше в
 * тяжёлом хвосте. Занятие без новых слов несёт 2.
 *
 * ОЦЕНОК ДВЕ, И ЭТО НЕ ДУБЛЬ. Они отвечают на разные вопросы:
 *
 *   • `lessonWeight` — «сколько в занятии УЖЕ занято»: по ней считается,
 *     сколько авторских заданий оно ещё вынесет. Здесь нужна оценка СВЕРХУ
 *     (хвост, а не медиана): промах в эту сторону стоит пустого места, в
 *     обратную — занятия на тридцать пять экранов;
 *   • `splitWeight` — «нужно ли юниту ещё одно занятие»: здесь нужна
 *     ТИПИЧНАЯ оценка. С хвостовой юнит дробился до занятий по шесть заданий:
 *     каждая порция считалась предельно тяжёлой, хотя такой бывает одна.
 *
 * ПОЧЕМУ ОЦЕНКА, А НЕ ТОЧНЫЙ СЧЁТ. Решать, сколько будет занятий и что куда
 * положить, надо ДО сборки: сборка уже зависит от этого решения.
 */
const lessonWeight = (words: number) => (words === 0 ? 2 : words * 6 + 2)
const splitWeight = (words: number) => (words === 0 ? 2 : words * 5 + 1)

function workPortions(parts: VocabItem[][], taskCount: number, firstExtra = 0): VocabItem[][] {
  // Влезает ли ВСЯ работа юнита в столько занятий. Считаем суммой, а не по
  // самому тяжёлому занятию: тяжёлое в юните обычно одно, а делили мы так, как
  // будто все такие, — и юнит из двадцати заданий разлетался на семь вечеров.
  const load = (list: VocabItem[][]) =>
    list.reduce((n, p) => n + splitWeight(p.length), 0) + firstExtra + taskCount
  const out = [...parts]
  // Потолок на число добавленных занятий: юнит из трёх слов и сотни заданий не
  // должен превращаться в двадцать вечеров подряд по одной теме.
  while (out.length < parts.length + 6 && load(out) > out.length * LESSON_CAP) out.push([])
  return out
}

function interleaveCards<T extends { passage?: string }>(work: T[], cards: T[]): T[] {
  if (cards.length === 0) return work
  if (work.length === 0) return cards

  // Неделимые блоки: подряд идущие задания с одним и тем же отрывком.
  const blocks: T[][] = []
  for (const task of work) {
    const last = blocks[blocks.length - 1]
    const samePassage = !!task.passage && last?.[0]?.passage === task.passage
    if (samePassage) last.push(task)
    else blocks.push([task])
  }

  const out: T[] = []
  let ci = 0
  blocks.forEach((block, bi) => {
    out.push(...block)
    // Сколько карточек должно быть выдано к этому месту, чтобы к концу
    // работы кончились и они. Round, а не floor: при равном числе карточек и
    // блоков получается ровное чередование «работа — карточка».
    const want = Math.round((cards.length * (bi + 1)) / blocks.length)
    while (ci < want && ci < cards.length) out.push(cards[ci++])
  })
  while (ci < cards.length) out.push(cards[ci++])
  return out
}

/**
 * Запасной конспект для юнитов, где текст ещё не написан руками.
 *
 * Собирается из уже заданных полей, чтобы урок не был пустым. Это заглушка:
 * настоящий конспект пишется в unit.theory и объясняет правило, а не
 * перечисляет его название.
 */
function composeTheory(unit: LangUnit): string {
  const words = unit.vocab
    .map(w => `• ${w.reading ? `${w.term} (${w.reading})` : w.term} — ${w.ru}${w.example ? `\n   ${w.example}` : ''}`)
    .join('\n')
  return [
    `Что вы сможете после урока: ${unit.goal}.`,
    `Правило: ${unit.grammar}`,
    unit.grammarWhy,
    `Слова урока (${unit.vocabTheme}):\n${words}`,
    `К концу урока вы сделаете: ${unit.artifact}.`,
  ].join('\n\n')
}

/**
 * Конспект юнита для редактора: текст плюс иллюстрации.
 *
 * Картинки встают строкой-маркером после первого абзаца — то есть сразу за
 * правилом, которое они показывают. Сам data-URI уезжает в theoryImages: в
 * поле «Конспект» учитель должен видеть свой текст, а не километр base64
 * (разбор маркеров — в lib/theoryImages.ts).
 */
function theoryOf(unit: LangUnit, figures: UnitFigure[] = []): { theory: string; theoryImages: TheoryImage[] } {
  const text = unit.theory?.trim() || composeTheory(unit)
  if (!figures.length) return { theory: text, theoryImages: [] }

  const paras = text.split(/\n\s*\n/)
  // Якорь по умолчанию: в собранном конспекте (composeTheory) второй абзац —
  // правило, третий объясняет, зачем оно здесь, поэтому картинка идёт за ними и
  // до списка слов. В написанном руками конспекте такого якоря нет — там
  // картинка встаёт после первого абзаца, а точное место задаёт figure.after.
  const ruleAt = paras.findIndex(p => p.startsWith('Правило:'))
  const fallback = ruleAt >= 0 ? ruleAt + 2 : 1

  const out: string[] = []
  paras.forEach((para, i) => {
    out.push(para)
    const here = figures.filter(f => Math.min(f.after ?? fallback, paras.length) === i + 1)
    here.forEach(f => out.push(figureMarker(f.caption, f.src)))
  })
  const packed = packTheoryImages(out.join('\n\n'))
  return { theory: packed.theory, theoryImages: packed.images }
}

/** Сводка курса — для карточки курса, кнопки сида и страницы описания. */
export interface CourseSummary {
  title: string
  level: string
  units: number
  vocabCount: number
  /**
   * Заданий В КУРСЕ — столько их получит ученик, со всеми сгенерированными.
   * Считается по собранному курсу (`countTasks`), а не по спеке: в спеке лежат
   * только авторские задания юнитов, и их в десять раз меньше.
   *
   * В `courseSummary` это поле заполняется авторским числом — там курса ещё
   * нет. Настоящее число живёт в карточке сида (courseSeedCards.ts) и
   * сверяется с собранным курсом при первом же открытии (courseSeeds.ts).
   */
  taskCount: number
  guidedHours: string
  /** Длительность занятия в минутах — из неё считаются часы курса в списке. */
  lessonMinutes: number
  scopeNote?: string
}

/**
 * Сколько заданий ученик получит на самом деле.
 *
 * Считается по СОБРАННОМУ курсу: `courseSummary` знает только про авторские
 * задания юнитов, а генератор добавляет к ним лестницу, экзамен порции, блок
 * повторения и разбор сочетаемости — вдесятеро больше.
 */
export function countTasks(lessons: CELesson[]): number {
  return lessons.reduce((n, l) => n + (l.hwTasks?.length ?? 0), 0)
}

export function courseSummary(spec: LanguageCourseSpec): CourseSummary {
  return {
    title: spec.title,
    level: spec.level,
    units: spec.units.length,
    vocabCount: spec.units.reduce((sum, u) => sum + u.vocab.length, 0),
    taskCount: spec.units.reduce((sum, u) => sum + u.tasks.length, 0),
    guidedHours: spec.guidedHours,
    lessonMinutes: spec.lessonMinutes ?? DEFAULT_LESSON_MINUTES,
    scopeNote: spec.scopeNote,
  }
}

/** Все слова курса — основа словарной колоды и интервальных повторений. */
export function allVocab(spec: LanguageCourseSpec): VocabItem[] {
  return spec.units.flatMap(u => u.vocab)
}

/** Юнит по короткому id. */
export function unitByShortId(spec: LanguageCourseSpec, shortId: string): LangUnit | undefined {
  return spec.units.find(u => u.shortId === shortId)
}

/** Модуль, которому принадлежит юнит. */
export function moduleOfUnit(spec: LanguageCourseSpec, n: number): LangModule | undefined {
  return spec.modules.find(m => m.units.includes(n))
}

/**
 * Собрать курс для редактора. `courseId` приходит снаружи (конструктор выдаёт
 * свежий), поэтому два добавления сида дают два независимых курса, а не
 * перезапись первого. Идентификаторы уроков внутри курса стабильны — short_id
 * в БД всё равно выводится от id курса (см. lessonShortIdMap).
 */
export function buildLanguageCourse(spec: LanguageCourseSpec, courseId: string): CourseEdData {
  const palette = getSubject(spec.subject)?.light
  const accent = palette?.accent ?? '#6354CF'
  const accentSoft = palette?.soft ?? 'rgba(99,84,207,0.14)'

  const byN = new Map(spec.units.map(u => [u.n, u]))

  /**
   * Уроки курса: ПОРЦИЯ, А НЕ ЮНИТ (Р1).
   *
   * Юнит — это тема с её грамматикой и словарём; урок — это один вечер работы.
   * Пока они совпадали, вечер получал десять новых слов, из которых наутро
   * оставалось два. Теперь словарь юнита режется на порции по ≤ 4 слова
   * (vocabPortions), и каждая порция — отдельный урок: та же тема, тот же
   * конспект, но новое даётся ровно столько, сколько человек уносит.
   *
   * ЧТО ОСТАЁТСЯ У ПЕРВОЙ ПОРЦИИ. Конспект со схемами, видео юнита, дрилл
   * конструкции и возврат к прошлым юнитам: это вход в тему, и он бывает один
   * раз. Продолжения получают короткий конспект (portionTheory), разминку по
   * словам предыдущего занятия (portionReview) и свою часть работы юнита.
   *
   * ID ПЕРВОЙ ПОРЦИИ РАВЕН ID ЮНИТА. Курсы, уже разложенные по расписанию и
   * пройденные учениками, не теряют первый урок каждой темы: он остаётся тем
   * же уроком с тем же адресом, а продолжения приходят новыми (`-p2`, `-p3`).
   */
  const size = portionSize(spec)
  const lessons: CELesson[] = []
  const lessonIdsOfUnit = new Map<number, string[]>()
  /** Слова, пройденные к очередному занятию, — запас обманок лестницы (Р9). */
  const introduced: VocabItem[] = []

  spec.units.forEach(unit => {
    // Постоянный груз ПЕРВОГО занятия юнита: ролик живой речи, диалог темы и
    // дрилл конструкции. Продолжениям он не достаётся, и считать его надо
    // отдельно — иначе потолок занятия промахивается ровно на его размер.
    const firstExtra = (spec.homeworkVideos?.[unit.shortId]?.length ?? 0)
      + (spec.dialogs?.[unit.shortId]?.length ?? 0)
      + (unit.pattern?.items?.length ? 1 : 0)
    const parts = workPortions(vocabPortions(unit.vocab, size), unit.tasks.length, firstExtra)
    const taskParts = spreadTasks(unit.tasks, parts, firstExtra)
    const split = parts.length > 1
    const ids: string[] = []

    parts.forEach((vocab, k) => {
      const first = k === 0
      const id = first ? unit.shortId : `${unit.shortId}-p${k + 1}`
      ids.push(id)
      // Юнит с урезанным словарём: генераторы заданий (узнавание, картинки,
      // карточки) работают ровно по словам порции и ничего не знают о делении.
      const part: LangUnit = { ...unit, vocab }
      // Всё, что ученик к этому занятию уже видел в юните: запас обманок (Р9).
      const seen = parts.slice(0, k + 1).flat()
      // Запас обманок лестницы (Р9): всё, что ученик прошёл РАНЬШЕ этого
      // занятия — прошлые юниты и прошлые порции этого юнита. Нужен там, где
      // порция схлопнулась до одного слова: своей обманки в ней нет, и без
      // этого запаса урок оставался одной карточкой.
      const earlier = [...introduced, ...parts.slice(0, k).flat()]

      // Разминка по пройденному: первое касание идёт в начало занятия,
      // остальные раскладываются по рабочей части (см. reviewLadder/placeLate).
      const review = first
        ? reviewTasks(unit, byN, `${id}-rv`, spec.lang, spec.native)
        : portionReview(parts[k - 1], `${id}-rv`, spec.lang, spec.native)

      // Рабочая часть занятия — до того, как в неё лягут отложенные касания
      // повторения: чтобы разложить их, надо знать длину занятия целиком.
      // Лестница (ступени 1–3) вперемешку с работой юнита: узнавание из
      // двух, на слух, сборка написания — кругами по всем словам порции,
      // чтобы между двумя касаниями одного слова стояли чужие (Р2).
      // Разводим однотипное по ВСЕЙ рабочей части, а не только по авторской:
      // круг лестницы и авторская серия того же типа складывались в одну
      // длинную полосу («что прозвучало?» четырежды подряд), хотя порознь
      // каждая укладывалась в потолок Р13.
      const work = breakSameTypeRuns(interleaveCards(
            [
              // Дрилл идёт первым: конструкция сначала ставится в руку
              // подстановкой, и только потом проверяется вразбивку остальными
              // заданиями. В обратном порядке первые упражнения проверяли бы то,
              // что ещё не отработано.
              ...(first ? patternTask(unit, `${id}-p`, spec.lang) : []),
              // Сопоставления длиннее четырёх пар режутся на несколько
              // заданий (Р4) — материал сохраняется целиком. Порядок внутри
              // порции разводится по типам (Р13): id остаются авторскими, то
              // есть присвоенными ДО перестановки, — иначе они бы прыгали от
              // одной сборки курса к другой и ломали прогресс учеников.
              ...breakSameTypeRuns(
                splitMatching(taskParts[k]).map((task, i) => editorTask(task, `${id}-t${i + 1}`, spec.lang)),
              ),
              ...pictureTasks(part, `${id}-pic`, spec.lang),
              // Диалог с пропуском — только в первой порции юнита: он про тему
              // целиком, а не про четвёрку её слов (см. dialogs в спеке).
              ...(first ? (spec.dialogs?.[unit.shortId] ?? []) : [])
                .map((task, i) => editorTask(task, `${id}-dg${i + 1}`, spec.lang)),
              // Сочетаемость: с чем ходит слово порции. Данные лежат в самом
              // словаре (`related`) либо в общем словаре сочетаний
              // (collocations.ts) — и до сих пор доезжали ТОЛЬКО до оборота
              // карточки: генератор заданий по ним был написан и не вызывался
              // ни разу. Слово, увиденное в одиночку, в речь не встаёт: ученик
              // знает, что 약속 — «договорённость», и не может сказать
              // «у меня назначено».
              ...splitMatching(relatedTasks(vocab))
                .map((task, i) => editorTask(task, `${id}-rel${i + 1}`, spec.lang)),
              // Пропуски по общему банку: слова порции в своих же авторских
              // примерах. Появляется там, где примеры написаны (разговорники,
              // курсы с примером у каждого слова) — см. dropInSeed.
              ...dropInSeed(vocab, seen).map((task, i) => editorTask(task, `${id}-wd${i + 1}`, spec.lang)),
            ],
            ladderTasks(vocab, { native: spec.native, stage: writingStage(spec, unit), seen: earlier })
              .map((task, i) => editorTask(task, `${id}-l${i + 1}`, spec.lang)),
      ))

      // Экзамен порции — в конце (Р4): сопоставление пар и припоминание из
      // четырёх. Раньше сопоставление стояло вторым заданием урока, сразу
      // после показа словаря.
      // Обманки экзамена (Р9) — слова юнита, введённые к этому занятию. Их
      // меньше четырёх (порция первая и короткая) — добираем недавно
      // пройденным из прошлых юнитов: без запаса весь экзамен порции
      // пропадал целиком, и ступени 4 у занятия не было вовсе.
      const exam = vocabRecognition(part, `${id}-r`, spec.lang, spec.native, examPool(seen, introduced))

      lessons.push({
        id,
        // Номер сквозной по курсу (его же ставит сверка с сидом), порция —
        // словом в хвосте. Двойной номер «1.2 Тема» из этого места и давал в
        // списке «7. 2 Тема»: сверка снимала только первое число (lib/lessonKey).
        title: numberedTitle(`${unit.title}${split ? ` · часть ${k + 1}` : ''}`, lessons.length + 1),
        number: lessons.length + 1,
        kind: 'lesson',
        // Дата занятия у сида не проставлена (её ставит учитель под свою группу),
        // а длительность известна заранее — из неё считаются часы курса в списке
        // и длина события в расписании, когда дата появится. Порции делят время
        // юнита между собой: занятий стало больше, часов курса — столько же.
        scheduledDuration: Math.round((spec.lessonMinutes ?? DEFAULT_LESSON_MINUTES) / parts.length),
        description: [
          `Цель: ${unit.goal}`,
          `Грамматика: ${unit.grammar}`,
          `Почему здесь: ${unit.grammarWhy}`,
          `Лексика: ${unit.vocabTheme}`,
          split ? `Часть ${k + 1} из ${parts.length} по этой теме` : '',
          `Артефакт: ${unit.artifact}`,
        ].filter(Boolean).join('\n'),
        ...(first
          ? theoryOf(unit, spec.figures?.[unit.shortId])
          : { theory: portionTheory(unit, vocab, k + 1, parts.length), theoryImages: [] }),
        videoUrl: first ? unit.videoUrl : undefined,
        hwTitle: split
          ? `Юнит ${unit.n}. ${unit.title} · часть ${k + 1}`
          : `Юнит ${unit.n}. ${unit.title}`,
        hwTarget: unit.artifact,
        hwTasks: [
          // Живая речь — до отработки: см. homeworkVideos в LanguageCourseSpec.
          ...(first ? (spec.homeworkVideos?.[unit.shortId] ?? []) : [])
            .map((task, i) => editorTask(task, `${id}-hv${i + 1}`, spec.lang)),
          // Возврат к пройденному — до нового материала. У первой порции это
          // прошлые юниты (reviewTasks), у продолжений — вчерашняя порция.
          ...review.head,
          // ЗНАКОМСТВО ПЕРВЫМ (Р3). Раньше карточки слов размазывались по всей
          // домашке (interleaveCards), и половина заданий про слово шла до
          // того, как слово вообще показали. Порция — это три-четыре слова:
          // карточки на них занимают полминуты и стоят там, где им место, — в
          // начале, экраном без правильного ответа.
          ...vocab.map((word, i) => vocabCard(word, `${id}-v${i + 1}`, spec.lang, spec.native)),
          ...placeLate(work, review.late, LESSON_CAP - (
            (first ? (spec.homeworkVideos?.[unit.shortId] ?? []).length : 0)
            + review.head.length + vocab.length + work.length + exam.length
          )),
          ...exam,
        ],
      })

      // Ни одного задания, где ученик что-то ПОРОЖДАЕТ, — добираем одним
      // припоминанием по пройденному (см. productionTask). Считаем по готовому
      // списку, а не по замыслу: продукция могла прийти и от автора, и от
      // блока повторения, и дублировать её незачем.
      const built = lessons[lessons.length - 1]
      if (!(built.hwTasks ?? []).some(isFreeProduction)) {
        built.hwTasks = [
          ...(built.hwTasks ?? []),
          ...productionTask(earlier, `${id}-fp`, spec.lang, spec.native),
        ]
      }
    })

    introduced.push(...unit.vocab)
    lessonIdsOfUnit.set(unit.n, ids)
  })

  const modules: CEModule[] = spec.modules.map((m, i) => ({
    id: `${spec.key}-m${i + 1}`,
    label: m.title,
    expanded: i === 0,
    // Модуль собирает ВСЕ занятия своих юнитов: у разрезанного юнита их
    // несколько, и продолжения обязаны стоять в том же модуле, что и вход.
    lessonIds: m.units.flatMap(n => lessonIdsOfUnit.get(n) ?? []),
  }))

  // ── Артефакт модуля: единственное сложное задание курса ──
  //
  // У каждого юнита в спеке заявлено, что ученик СДЕЛАЕТ своими руками
  // («Записанное вслух чтение 10 фраз», «Диалог из 6 реплик», «Таблица 10
  // глаголов»). До этого места артефакт жил подписью `hwTarget` и нигде не
  // сдавался: строка на экране, за которой ничего не стоит.
  //
  // ПОЧЕМУ ХАРД. Артефакт нельзя проверить машиной — это связная работа, и
  // ценность её в разборе от учителя. Ровно для этого сделан хард-уровень:
  // вкладка на задание, переписка раундами (решение → комментарий → принято),
  // вердикт с оценкой 1–5 и стикер за чистую сдачу. Без `isHard` вход в него у
  // языковых курсов просто не показывался (см. lessonHasHardLevel).
  //
  // ПОЧЕМУ РАЗ В МОДУЛЬ, А НЕ РАЗ В ЮНИТ. Артефакт заявлен у каждого юнита, но
  // юнитов в курсе до сотни, и хард по каждому — это сотня проверок вручную на
  // одного ученика. Модуль — крупный шаг программы (их 3–14 на курс), и раз в
  // модуль большая работа с разбором приходит примерно раз в три-четыре
  // недели. Остальные артефакты остаются целью занятия, как и были.
  spec.modules.forEach(m => {
    const ids = m.units.flatMap(n => lessonIdsOfUnit.get(n) ?? [])
    const last = lessons.find(l => l.id === ids[ids.length - 1])
    const lastUnit = spec.units.find(u => u.n === m.units[m.units.length - 1])
    if (!last || !lastUnit?.artifact?.trim()) return
    last.hwTasks = [
      ...(last.hwTasks ?? []),
      editorTask(
        {
          type: 'extended',
          isHard: true,
          question: `Итог модуля «${m.title}». Сдайте работу: ${lastUnit.artifact}. `
            + 'Учитель разберёт её и вернётся с комментарием — при необходимости не один раз.',
        },
        `${last.id}-art`,
        spec.lang,
      ),
    ]
  })

  const s = courseSummary(spec)
  return {
    id: courseId,
    title: spec.title,
    subject: spec.subject,
    level: spec.level,
    status: 'draft',
    color: accent,
    bg: accentSoft,
    groupIds: [],
    studentIds: [],
    modules,
    lessons,
    description: [
      `${s.units} юнитов (${lessons.length} занятий), ${s.vocabCount} слов, ` +
        // Заданий — СОБРАННЫХ, а не заявленных в спеке. `courseSummary` считает
        // только авторские задания юнитов, а к ученику едут ещё и все
        // сгенерированные: лестница, экзамен порции, повторения, разбор пар.
        // Разница десятикратная — курс, обещавший 225 заданий, даёт 2080, — и
        // именно эта строка уезжает в описание сохранённого курса.
        `${countTasks(lessons)} заданий. ` +
        `Ориентир — ${s.guidedHours} учебных часов.`,
      s.scopeNote,
    ].filter(Boolean).join(' '),
  }
}
