// ─────────────────────────────────────────────────────────────────────────────
// Правила: разбор конструкции на одном листе
//
// ЗАЧЕМ ОТДЕЛЬНАЯ СУЩНОСТЬ. Грамматика в проекте уже есть — полем `grammar` у
// юнита курса. Но там она описана человеческим текстом для конспекта: «учимся
// говорить о двух одновременных действиях». Этого хватает уроку и не хватает
// ничему другому. Нельзя ни найти правило, не помня, в каком оно юните, ни
// сравнить две похожие конструкции, ни вернуться к нему через месяц — а именно
// это с правилами и делают.
//
// ОТКУДА ФОРМА. Самый живучий формат разбора грамматики — рукописный конспект
// на развороте: слева конструкция, справа похожая на неё, внизу таблица
// сравнения. Он живуч не из-за красоты: в нём ЖЁСТКИЙ порядок блоков, и потому
// два разных правила можно сравнить, не перечитывая оба целиком. Поля здесь —
// это те самые блоки.
//
// ПОЧЕМУ ЛОВУШКИ И СРАВНЕНИЕ — ОТДЕЛЬНЫЕ ПОЛЯ, А НЕ ТЕКСТ. Ошибка, набранная
// внутри абзаца, читается как пример и запоминается как правильная форма.
// Отдельным полем её можно нарисовать перечёркнутой и поставить рядом верную —
// то есть показать ровно то, ради чего её и приводят.
//
// ЧЕГО ЗДЕСЬ НЕТ. Упражнений. Правило объясняет, отработка живёт в домашке и в
// карточках; смешав это в одном экране, получаешь учебник, который не читают и
// по которому не занимаются.
// ─────────────────────────────────────────────────────────────────────────────

import type { SurvivalLevel } from './survivalPhrases'

/** Превращение формы: что было, что стало и как НЕ надо. */
export interface RuleForm {
  from: string
  to: string
  /** Ошибочная форма — та, которую образуют по аналогии. Рисуется перечёркнутой. */
  wrong?: string
}

/** Пример употребления — живое предложение с переводом. */
export interface RuleExample {
  term: string
  /** Романизация или транскрипция. */
  reading?: string
  ru: string
}

/** Типичная ошибка: как говорят и как надо. */
export interface RuleTrap {
  wrong: string
  right: string
  /** Почему так нельзя — одной фразой. */
  why: string
}

/** Строка сравнения с похожей конструкцией. */
export interface RuleVersusRow {
  /** По какому признаку сравниваем: «Подлежащее», «Время», «Регистр». */
  point: string
  /** Как у этой конструкции. */
  this: string
  /** Как у соседней. */
  that: string
}

/** Сравнение с конструкцией, с которой её путают. */
export interface RuleVersus {
  /** Сама соседняя конструкция: «-(으)면서». */
  other: string
  /** Чем она занимается — одной строкой. */
  otherAbout: string
  rows: RuleVersusRow[]
}

/** Разбор одной конструкции. */
export interface GrammarRule {
  /** Стабильный ключ — по нему запоминается прочитанное. */
  id: string
  /** Порядковый номер внутри языка, 1-based. */
  n: number
  level: SurvivalLevel
  /** Сама конструкция, как её пишут в учебниках: «-는 동안(에)». */
  form: string
  /** Как называется по-русски: «пока, в течение». */
  title: string
  /** Значение одной фразой — то, что человек ищет глазами первым. */
  meaning: string
  /** Как образуется: формула строкой. */
  build: string
  /** Превращения формы — то, на чём ошибаются. */
  forms?: RuleForm[]
  /** Когда так говорят. */
  use: string[]
  examples: RuleExample[]
  traps?: RuleTrap[]
  /** С чем путают. */
  versus?: RuleVersus;
  /** Что унести с собой. */
  remember: string[]
}

/** Полка правил: группа с общей задачей. */
export interface RuleShelf {
  title: string
  subtitle: string
  rules: GrammarRule[]
}

/** Правила одного языка. */
export interface GrammarBook {
  key: string
  lang: string
  shelves: RuleShelf[]
}

/** Все правила книги подряд, в порядке полок. */
export const allRules = (book: GrammarBook | undefined): GrammarRule[] =>
  book ? book.shelves.flatMap(s => s.rules) : []

/** Правило по id. */
export const ruleById = (book: GrammarBook | undefined, id: string): GrammarRule | undefined =>
  allRules(book).find(r => r.id === id)
