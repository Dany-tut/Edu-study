// Наборы японских слов
//
// ЗАПИСЬ С ИЕРОГЛИФАМИ, А НЕ ОДНОЙ КАНОЙ. Разговорник (survivalJa) написан
// хираганой — там это оправдано: фразы выживания нужны человеку в первую неделю,
// когда иероглифов он не знает вовсе. Наборы слов решают другую задачу — дать
// лексику, которую человек встретит в тексте, — а в тексте 食べる записано
// иероглифом. Список, набранный одной каной, учит виду слова, которого в жизни
// не бывает, и на первой же вывеске оказывается бесполезен.
//
// ЧТЕНИЕ РОМАДЗИ, КАК ВЕЗДЕ В ПРОЕКТЕ. Хепбёрн с долготой через макрон (ō, ū) —
// так же записаны чтения в курсах JLPT и в разговорнике; вторая система записи
// в соседнем файле сделала бы «おおきい» то ōkii, то ookii в зависимости от того,
// куда ученик нажал.
//
// ГЛАГОЛЫ В СЛОВАРНОЙ ФОРМЕ. -ます стоит учить как форму, а не как слово: из
// словарной формы выводится всё остальное, из вежливой — ничего.
// ─────────────────────────────────────────────────────────────────────────────

