// ─────────────────────────────────────────────────────────────────────────────
// Схемы конспектов грамматических курсов
//
// ЗАЧЕМ. Аудит: у пяти курсов из девятнадцати в конспектах не было ни одной
// схемы — «Английский B2→C1», немецкий A1→B1 и три русских. Рисовать их руками
// значило бы написать сотню почти одинаковых картинок; у разговорников ту же
// дыру уже закрыли генератором из формулы темы (survivalFigures.ts), и здесь
// делается то же самое из данных, которые у юнита уже есть.
//
// ИЗ ЧЕГО СТРОИТСЯ
//
//   • Если `grammar` юнита сам по себе развилка («will / going to / Present
//     Continuous»), схема рисуется прямо из неё: блоки в ряд с подписями.
//     Так устроен английский — там грамматика юнита и ЕСТЬ выбор между
//     формами, и показать его картинкой полезнее, чем перечислить строкой.
//
//   • Иначе берётся ШАБЛОН конструкции (`pattern.template`) с его переводом:
//     «Ich … aus …» → «Я из …». Так устроен немецкий: грамматика там описана
//     прозой, а конструкция живёт отдельным полем.
//
// ЧЕГО СХЕМА НЕ ДЕЛАЕТ. Не показывает ПОДСТАНОВКИ дрилла (`pattern.items`),
// хотя они лежат рядом и просятся в таблицу. Дрилл — это задание из той же
// домашки, и напечатанная в конспекте пара «подставили → получилось»
// превращает его в списывание. Схема даёт скелет со знаком «…» на месте
// подстановки — ровно то, что нужно перед упражнением, и ничего сверх.
//
// ПОЧЕМУ ТРЁХ РУССКИХ КУРСОВ ЗДЕСЬ НЕТ. У них ни то ни другое не годится:
// `grammar` — проза, а `pattern.template` — инструкция («Замените затычку
// точным словом»), а не конструкция. Табличка «термин → толкование» из словаря
// тоже отпадает: карточка в курсе родного языка ПЕРЕВЁРНУТА (на лице
// толкование, ответом служит термин), и такая схема напечатала бы в конспекте
// ответы к собственным карточкам. Их схемы написаны руками — см.
// russianFigures.ts.
// ─────────────────────────────────────────────────────────────────────────────

import { formulaStrip } from './lessonFigures'
import { parseFormula } from './survivalFigures'
import type { CourseFigures, LangUnit } from './languageCourse'

/**
 * Схемы курса по его юнитам.
 *
 * Юнит, из которого ничего не выводится, схему не получает: пустое место
 * честнее картинки, нарисованной ради счётчика.
 */
export function unitFigures(units: LangUnit[]): CourseFigures {
  const out: CourseFigures = {}

  for (const unit of units) {
    const chunks = parseFormula(unit.grammar ?? '')

    // Грамматика-развилка: рисуем её саму.
    if (chunks.length >= 2) {
      out[unit.shortId] = [{
        src: formulaStrip(unit.title, chunks.slice(0, 5), {
          note: unit.grammarWhy,
        }),
        // Подпись НЕ повторяет заголовок урока: он и так стоит выше, а у
        // половины юнитов сам содержит двоеточие — выходило «Рассказ о
        // прошлом: четыре времени: из чего выбирать».
        caption: 'Из чего выбирать в этом юните',
        after: 2,
      }]
      continue
    }

    // Иначе — скелет конструкции юнита. Многоточие в шаблоне и есть место
    // подстановки: его-то ученик и заполняет в дрилле, поэтому оно остаётся
    // пустым и здесь.
    const tpl = unit.pattern?.template?.trim()
    if (!tpl) continue
    const parts = tpl.split(/\s*…\s*/).filter(Boolean)
    // Шаблон без единого «…» — это инструкция, а не конструкция (так написаны
    // русские курсы). Рисовать из неё схему нечего.
    if (parts.length < 2 && !tpl.includes('…')) continue

    out[unit.shortId] = [{
      src: formulaStrip(
        unit.title,
        // Подпись «сюда подставляем» ставится только под ПЕРВЫМ многоточием:
        // повторённая под каждым, она читается как сбой отрисовки, а не как
        // пояснение. Остальные места и так помечены акцентом.
        (() => {
          let firstGap = true
          return tpl.split(/(…)/).filter(x => x.trim()).map(x => {
            if (x !== '…') return { text: x.trim() }
            const chunk = { text: '…', note: firstGap ? 'сюда подставляем' : undefined, key: true }
            firstGap = false
            return chunk
          }).slice(0, 5)
        })(),
        { note: unit.pattern?.gloss },
      ),
      caption: 'Скелет конструкции: на месте многоточия — подстановка',
      after: 2,
    }]
  }

  return out
}
