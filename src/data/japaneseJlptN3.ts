// ─────────────────────────────────────────────────────────────────────────────
// Японский JLPT N4 → N3
//
// Продолжение курса «Японский с нуля — до JLPT N5». Вход: ученик читает кану
// свободно, знает ~60 кандзи, владеет ます-формой, прошедшим временем, て-формой
// и базовыми частицами.
//
// ЧТО МЕНЯЕТСЯ ПО СРАВНЕНИЮ С N5
// 1. て-форма перестаёт быть только соединением действий: на ней вырастает
//    половина уровня — てしまう, ておく, てある, てみる, てあげる/てくれる/てもらう.
//    Модуль 1 целиком об этом, потому что без него N4 не берётся.
// 2. Появляется направление действия (授受). В японском нельзя просто сказать
//    «он мне помог» — нужно выбрать глагол в зависимости от того, кто кому и в
//    чью пользу. В русском этой категории нет вовсе, и она даётся отдельным
//    модулем вместе с пассивом и каузативом.
// 3. Модальность расщепляется: そうだ, ようだ, らしい, みたい, はず, わけ —
//    шесть способов сказать «кажется», и различаются они источником сведений.
//    Это любимый материал 文法-части N3.
// 4. Кандзи выходят на первый план: к N3 нужно около 650 знаков. Курс даёт
//    порции по 12–15 в юните, сгруппированные по смыслу и по общему элементу,
//    а не по алфавиту — так они удерживаются.
//
// ПРО ЭКЗАМЕН
// JLPT по-прежнему проверяет только распознавание: говорения и письма в нём
// нет. Но структура на N3 меняется: если N4 и N5 оцениваются по двум разделам
// (языковые знания с чтением — и аудирование), то N3 оценивается по трём —
// 言語知識, 読解 и 聴解 считаются отдельно, и провал одного раздела не
// компенсируется другими. Речь курс всё равно тренирует отдельно и намеренно.
//
// ЮРИДИЧЕСКОЕ
// Все тексты и задания написаны с нуля; официальные материалы JLPT не
// копируются. Порядок черт при добавлении заданий на письмо — из KanjiVG
// (CC BY-SA) со ссылкой.
// ─────────────────────────────────────────────────────────────────────────────

