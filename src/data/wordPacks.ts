// ─────────────────────────────────────────────────────────────────────────────
// Наборы слов: лексика пачками, а не по одному слову из урока
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ РАЗГОВОРНИКА И ОТ КУРСОВ
// В проекте уже есть две двери к лексике, и обе отвечают на другой вопрос.
// Курс-сид выдаёт слова юнита — их ровно столько, сколько нужно уроку, и они
// подобраны под грамматику, а не под смысл. Разговорник выдаёт ГОТОВЫЕ ФРАЗЫ
// под ситуацию: «где туалет», «счёт, пожалуйста» — их произносят целиком и не
// разбирают. Ни то ни другое не закрывает самый частый запрос человека,
// который учит язык всерьёз: дайте мне сразу все глаголы движения, все вкусы,
// все слова про характер — я вижу систему и учу её пачкой.
//
// Так устроены все живые подборки, которыми пользуются самоучки: страница
// «100 прилагательных» перечитывается десять раз, потому что рядом стоят
// 뜨겁다 и 차갑다, 덥다 и 춥다 — и разница между ними видна САМА. Разложенные
// по разным урокам, те же четыре слова путаются годами.
//
// ЧТО ЭТО НЕ ОТМЕНЯЕТ. Набор не заменяет урок: он не учит спрягать и не
// объясняет, когда так говорят. Он даёт материал в том виде, в каком его
// удобно узнавать и повторять, а разбор остаётся за конспектом и правилами.
//
// ПОЧЕМУ СЛОВО — ЭТО Phrase. Карточка, расписание повторений, романизация,
// прогон свайпом и списком уже написаны для разговорника и работают над типом
// Phrase. Слово от фразы отличается только длиной; заводить ради него второй
// тип значило бы завести вторую копию колоды, которая разъедется с первой на
// первой же правке.
// ─────────────────────────────────────────────────────────────────────────────

import type { Phrase } from './survivalPhrases'
import type { SurvivalLevel } from './survivalPhrases'

/** Набор слов — то, что ученик открывает как одну стопку. */
export interface WordPack {
  /** Стабильный ключ: и id стопки, и ключ прогресса. */
  id: string
  /** Порядковый номер внутри языка, 1-based. */
  n: number
  /** Насколько сложна лексика набора — ось фильтра. */
  level: SurvivalLevel
  title: string
  /**
   * Чем набор держится вместе и почему его стоит взять именно пачкой.
   *
   * Это не «описание темы» для галочки: витрина из пятнадцати одинаковых
   * плиток не даёт выбрать, а строчка «в корейском разные слова для холодной
   * погоды и холодного напитка» выбирает набор за человека.
   */
  about: string
  /** Тема из общей разметки языков (languageTaxonomy) — ось фильтра. */
  topic: string
  words: Phrase[]
}

/** Наборы одного языка. */
export interface WordPackBook {
  /** Ключ книги — префикс ключей прогресса, уникален среди языков. */
  key: string
  /** BCP-47 языка. */
  lang: string
  /** Полки: группа наборов с общей задачей. Порядок — порядок показа. */
  shelves: { title: string; subtitle: string; packs: WordPack[] }[]
}

/** Полка витрины: группа наборов и сколько в ней слов. */
export interface WordPackShelf {
  title: string
  subtitle: string
  packs: WordPack[]
  count: number
}

/** Полки книги со счётчиками. Пустые выбрасываются — язык может быть неполон. */
export function wordPackShelves(book: WordPackBook | undefined): WordPackShelf[] {
  if (!book) return []
  return book.shelves
    .filter(s => s.packs.length > 0)
    .map(s => ({ ...s, count: s.packs.reduce((n, p) => n + p.words.length, 0) }))
}

/** Все наборы книги подряд, в порядке полок. */
export function allPacks(book: WordPackBook | undefined): WordPack[] {
  return book ? book.shelves.flatMap(s => s.packs) : []
}

/** Набор по id. */
export const packById = (book: WordPackBook | undefined, id: string): WordPack | undefined =>
  allPacks(book).find(p => p.id === id)
