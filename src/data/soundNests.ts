const ALL: SoundNest[] = [...KO, ...JA, ...EN, ...PT, ...DE]

/**
 * Базовый код языка: pt-BR → pt.
 *
 * Правило то же, что у разговорника (survivalBooks.ts), и оно должно быть тем
 * же: реестр предметов отдаёт «pt-BR», но код языка приходит сюда и из других
 * мест, а два соседних модуля с разными правилами разъедутся на первом же
 * «en-US» — причём молча, потерянным разделом, а не ошибкой.
 */
const base = (lang: string) => lang.split('-')[0].toLowerCase()

const BY_LANG = ALL.reduce<Record<string, SoundNest[]>>((acc, nest) => {
  (acc[nest.lang] ??= []).push(nest)
  // Тот же список доступен и по базовому коду: гнёзда pt-BR отвечают на «pt».
  const b = base(nest.lang)
  if (b !== nest.lang) (acc[b] ??= []).push(nest)
  return acc
}, {})

const pick = (lang: string): SoundNest[] => BY_LANG[lang] ?? BY_LANG[base(lang)] ?? []

/** Все гнёзда языка, в порядке ввода по курсу. */
export function nestsForLang(lang: string): SoundNest[] {
  return [...pick(lang)].sort((a, b) => a.fromUnit - b.fromUnit)
}

/** Есть ли у языка гнёзда вообще — вкладка не показывается там, где их нет. */
export const hasNests = (lang: string): boolean => pick(lang).length > 0

/**
 * Гнёзда, открытые ученику на его глубине по курсу.
 *
 * `reach` — номер последнего пройденного юнита. Ноль (курса нет, прогресса нет)
 * означает «показать всё»: тренажёром пользуются и те, кто не привязан к
 * курсу-сиду, и прятать от них материал не за что.
 */
export function nestsUpTo(lang: string, reach: number): SoundNest[] {
  const list = nestsForLang(lang)
  if (reach <= 0) return list
  return list.filter(n => n.fromUnit <= reach)
}

/** Гнездо по id. */
export const nestById = (id: string): SoundNest | undefined => ALL.find(n => n.id === id)

/**
 * Слово гнезда как строка вопроса для колоды повторений.
 *
 * Ключ карточки — prompt, и он обязан быть уникальным в пределах ученика
 * (см. dedupe в addCards). Само слово таким ключом быть не может: 밤 стоит
 * и в гнезде на 받침, и в гнезде омонимов, и попало бы в колоду один раз из
 * двух. Поэтому в ключ входит гнездо.
 */
export const nestPrompt = (nest: SoundNest, word: NestWord): string =>
  `${word.term} — какое из ${nest.title}?`
