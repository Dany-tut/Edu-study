// ─────────────────────────────────────────────────────────────────────────────
// Гнёзда созвучий: слова, которые различаются одним признаком
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ, А НЕ ЕЩЁ ОДИН СПИСОК СЛОВ В ЮНИТЕ
// Минимальные пары в курсе уже есть: юнит 2 корейского целиком про тройки
// согласных, там 방–빵 и 불–풀 (koreanTopik.ts). Но пара там живёт РОВНО ОДИН
// РАЗ: прозвучала в двух заданиях урока и больше не возвращается. А путаница
// 물/불/풀/볼 не лечится одним уроком — она лечится тем, что гнездо всплывает
// снова через три дня, через неделю и через месяц, пока не перестанет
// ошибаться. Поэтому гнездо — это не задание, а МАТЕРИАЛ: у него есть свой
// список слов, свой разбор и своё место в интервальных повторениях.
//
// ПОЧЕМУ «ГНЕЗДО», А НЕ «ПАРА»
// Классическая минимальная пара меняет ровно один признак: 불 (ㅂ) — 풀 (ㅍ).
// Но ученик путает не по фонологической оси, а по слуху: 물, 불, 풀 и 볼 для
// русского уха сливаются все четыре сразу, хотя 볼 отличается уже гласной, а не
// согласной. Разбивать это на три отдельные пары значило бы учить различению
// внутри пары и оставить кашу из четырёх. Гнездо собирает всё, что реально
// сливается, и подписывает у каждого слова, чем оно отличается от соседей.
//
// ПОЧЕМУ СЛОВА, А НЕ СЛОГИ
// Отличать 물 от 불 в вакууме бессмысленно: различие смыслоразличительное, и
// смысл — это половина опоры. Поэтому в гнезде стоят только настоящие слова с
// переводом, а не абстрактные слоги. Слог без значения ученик различает
// механически и на следующий день не узнаёт его в речи.
//
// ЧТО ЗДЕСЬ НЕ ЛЕЖИТ
// Правила чтения (연음, назализация) — это не созвучие, а преобразование одного
// слова; они разбираются в юните 4 курса и заданиями генерируются оттуда.
// Омонимы (배 — живот, груша и корабль) сюда попадают отдельным видом гнезда:
// звучат одинаково НАМЕРЕННО, и учить надо не различение, а контекст.
// ─────────────────────────────────────────────────────────────────────────────

/** Слово внутри гнезда. */
export interface NestWord {
  /** Слово на изучаемом языке. */
  term: string
  /** Чтение — романизация или транскрипция. */
  reading: string
  /** Перевод. Несколько значений — через точку с запятой. */
  ru: string
  /**
   * Чем это слово отличается от соседей по гнезду.
   *
   * Пишется от лица различия, а не слова: не «напряжённая согласная», а
   * «напряжённая ㅃ — без выдоха, с нажимом». Ученик читает подпись ровно в тот
   * момент, когда ошибся, и ему нужно действие, а не термин.
   */
  tip?: string
}

/**
 * Что именно сливается в этом гнезде.
 *
 * `consonant` — начальная согласная, `vowel` — гласная, `batchim` — согласная в
 * конце слога, `length` — долгота (японский, английский), `homonym` — не
 * сливается, а совпадает: одно звучание, разные значения.
 */
export type NestAxis = 'consonant' | 'vowel' | 'batchim' | 'length' | 'homonym'

export interface SoundNest {
  id: string
  /** Код языка: ko, ja, en, pt-BR. */
  lang: string
  /** Заголовок — сами слова через точку: «물 · 불 · 뿔 · 풀». */
  title: string
  axis: NestAxis
  /** Разбор: почему это путается и на что слушать. Одно-два предложения. */
  why: string
  /**
   * С какого юнита курса гнездо имеет смысл.
   *
   * Гнездо на 받침 бессмысленно раньше, чем 받침 введён: ученик не различит то,
   * чего ещё не умеет прочитать. Тренажёр открывает гнёзда по факту
   * пройденного, а не вываливает все двенадцать в первый день (см. lib/reach).
   */
  fromUnit: number
  /**
   * Различается ли гнездо на слух вообще.
   *
   * `false` — слова звучат одинаково, и вопрос «какое прозвучало» у них не
   * имеет верного ответа. Так устроены не только омонимы: корейские ㅐ и ㅔ
   * в современной речи слились, и 개 с 게 — это разные слова с одним звучанием,
   * хотя ось у гнезда гласная, а не омонимия. Без явного поля такое гнездо
   * молча выдавало бы ученику неотвечаемый прогон.
   *
   * Не задано — считается, что различается.
   */
  audible?: boolean
  words: NestWord[]
}

