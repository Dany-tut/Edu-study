// Корейский после TOPIK I (подготовка к TOPIK II, уровни 3급–4급)
//
// Продолжение курса «Корейский с нуля — до TOPIK I». Вход: ученик уверенно
// говорит в 해요체, знает падежные частицы, прошедшее и будущее время, умеет
// строить простое сложное предложение (~고, ~지만, ~아/어서, ~(으)면).
//
// ЧТО МЕНЯЕТСЯ ПО СРАВНЕНИЮ С НАЧАЛЬНЫМ УРОВНЕМ
// 1. Речь перестаёт быть перечислением фактов. Главная работа уровня — оттенки:
//    ~네요 (удивление), ~잖아요 (ты же знаешь), ~더라고요 (я сам это заметил),
//    ~(으)ㄹ 텐데 (предположение с сожалением). Без них корейский звучит как
//    робот, даже когда грамматика верна.
// 2. Косвенная речь (модуль 2) — водораздел уровня. На ней держатся пересказ,
//    просьба через третье лицо и половина заданий 듣기 в TOPIK II.
// 3. Появляется письменная норма. 쓰기 53–54 пишутся не в 해요체, а в 문어체
//    (~ㄴ다/는다), и ученик, который весь 1급 писал вежливо-разговорно, теряет
//    на этом баллы механически. Разбирается отдельным юнитом.
// 4. Лексика уходит в сино-корейскую: 환경, 경제, 정보, 사회 — слова из газет и
//    экзаменационных текстов, где ханча-корни повторяются и потому предсказуемы.
//
// ПРО ЭКЗАМЕН
// TOPIK II — три части: 듣기 (50 вопросов, 60 минут), 쓰기 (4 задания, 50 минут)
// и 읽기 (50 вопросов, 70 минут), максимум 300 баллов. Уровень присваивается по
// сумме: 3급 — от 120, 4급 — от 150, 5급 — от 190, 6급 — от 230. Курс целится
// в 3급–4급; 쓰기 разбирается по всем четырём заданиям, потому что именно оно
// проваливается у тех, кто готовился только тестами.
//
// ЮРИДИЧЕСКОЕ
// Все тексты и задания написаны с нуля; реальные материалы прошлых TOPIK не
// копируются. Примеры для расширения брать из Tatoeba (CC BY) со ссылкой.
// ─────────────────────────────────────────────────────────────────────────────

