const ALIKE_ENOUGH = 0.5

/** Отдельная буква хангыля — не слог: собирать её не из чего, её обводят. */
const isChamo = (s: string) => /^[㄰-㆏]$/.test(s)

/**
 * Стадия письма (Р6).
 *
 * `B` — знак идёт вместе с транскрипцией: ученик уже видит хангыль, но не
 * обязан его читать, чтобы решить задание про значение. `C` — знак сам по себе.
 * Стадии A (только звук и транскрипция) у нас нет отдельным режимом: её роль
 * играет карточка знакомства, где транскрипция стоит своим полем.
 */
export type WritingStage = 'B' | 'C'

/** Подпись слова по стадии письма. */
export const stageLabel = (w: VocabItem, stage: WritingStage): string =>
  stage === 'B' && w.reading ? `${w.term} (${w.reading})` : w.term

/**
 * Скелет ответа — опора ступени 5 (Р7).
 *
 * Первый знак открыт, остальные закрыты точками: «안 · · ·». Ученик видит длину
 * и начало и достаёт остальное из памяти — это припоминание, а не узнавание
 * (ступень 4) и не свободная продукция (ступень 6).
 *
 * ПРОБЕЛЫ СОХРАНЯЮТСЯ: у фразы из двух слов их число — половина подсказки
 * («안녕히 계세요» — это не одно длинное слово, а два коротких).
 *
 * ТОЧКИ, А НЕ ПРОЧЕРКИ. Прочерк «____» синтез речи читает вслух как
 * «андерскор андерскор» (см. voiceText в lib/speech.ts).
 *
 * Пусто у слова из одного знака: там скелет и есть сам ответ.
 */
export function answerSkeleton(answer: string): string | undefined {
  const words = answer.trim().split(/\s+/).filter(Boolean)
  if (words.length === 0) return undefined
  if (words.reduce((n, w) => n + Array.from(w).length, 0) < 2) return undefined
  let first = true
  return words
    .map(word => Array.from(word).map(ch => {
      if (!first) return '·'
      first = false
      return ch
    }).join(' '))
    .join('   ')
}

/**
 * Спутываемые слова (Р5).
 *
 * Слова, поданные одним смысловым или звуковым кластером, учатся МЕДЛЕННЕЕ
 * несвязанных: формы конкурируют за одно значение (Tinkham 1993, 1997;
 * Waring 1997). 안녕히 가세요 и 안녕히 계세요, введённые в один вечер, дают не два
 * слова, а одну кашу.
 *
 * Считаем спутываемыми, если верно любое:
 *   • перевод совпадает (или короткий перевод входит в другой короткий:
 *     «нет» / «нет (не имеется)»);
 *   • общее начало или конец: ≥ 2 знака И ≥ 40% короткого слова
 *     (안녕히 가세요 / 안녕히 계세요);
 *   • минимальная пара: та же длина, различие ровно в одном знаке, слово
 *     короче тринадцати знаков (물 / 불).
 */
export function confusable(a: VocabItem, b: VocabItem): boolean {
  const at = (a.term ?? '').trim()
  const bt = (b.term ?? '').trim()
  if (!at || !bt || at === bt) return false

  const ar = (a.ru ?? '').trim().toLowerCase()
  const br = (b.ru ?? '').trim().toLowerCase()
  // Один перевод — всегда конфликт. Вхождение считается только у КОРОТКИХ
  // значений («нет» внутри «нет (не имеется)»): у курса родного языка на этом
  // месте стоит толкование в десять слов, и там общий кусок — это обычная
  // русская фраза, а не спутываемость.
  if (ar && br && ar === br) return true
  if (ar && br && ar.length <= 24 && br.length <= 24 && (ar.includes(br) || br.includes(ar))) return true

  const A = Array.from(at)
  const B = Array.from(bt)

  // Общее начало / конец. Двух знаков мало самих по себе: в русской фразе
  // «по-» общее у половины слов. Считаем спутываемым, когда общий кусок ещё и
  // ЗАНИМАЕТ большую часть короткого слова — как 안녕히 가세요 / 안녕히 계세요,
  // где совпадает больше половины.
  const short = Math.min(A.length, B.length)
  const heavy = (n: number) => n >= 2 && n / short >= 0.4
  let head = 0
  while (head < A.length && head < B.length && A[head] === B[head]) head++
  if (heavy(head)) return true
  let tail = 0
  while (tail < A.length - head && tail < B.length - head && A[A.length - 1 - tail] === B[B.length - 1 - tail]) tail++
  if (heavy(tail)) return true

  // Минимальная пара: одинаковая длина, ровно одно расхождение. Только у
  // коротких форм: две фразы по сорок знаков, различающиеся одной буквой, —
  // это опечатка в данных, а не спутываемость.
  //
  // СЛОГ ХАНГЫЛЯ РАЗБИРАЕТСЯ НА БУКВЫ. Один слог — это до трёх букв в одной
  // клетке, и посимвольное сравнение объявляло минимальной парой ЛЮБЫЕ два
  // односложных слова: 물 «вода» и 밥 «еда» различаются одним знаком, хотя не
  // совпадают ни одной буквой. Из-за этого корейские курсы разъезжались на
  // порции по одному слову — 34 порции из 59 в курсе хангыля, 33 из 151 в
  // TOPIK I, — а порция из одного слова не даёт ни сопоставления, ни выбора из
  // четырёх, то есть до целевой ступени 4 не доходит вовсе.
  //
  // По буквам всё встаёт на место: 물/불 (ㅁㅜㄹ / ㅂㅜㄹ) — расхождение одно,
  // пара настоящая; 물/밥 (ㅁㅜㄹ / ㅂㅏㅂ) — расхождений три, слова разные.
  // Кане и латинице разбор не нужен: там знак и есть звук.
  const units = (list: string[]) =>
    list.some(ch => /[가-힯]/.test(ch)) ? list.flatMap(chamoOf) : list
  const AU = units(A)
  const BU = units(B)
  if (AU.length === BU.length && AU.length > 0 && AU.length <= 12) {
    let diff = 0
    for (let i = 0; i < AU.length; i++) if (AU[i] !== BU[i]) diff++
    if (diff === 1) return true
  }
  return false
}

/**
 * Разложить словарь по порциям так, чтобы спутываемые слова не встретились в
 * одном занятии (Р5).
 *
 * КАК. Идём по словам в авторском порядке и кладём каждое в первую порцию, где
 * есть место и нет ничего спутываемого с ним. Не нашлось такой — слово уходит в
 * следующую по счёту порцию (за пределы `count`, если иначе никак): лучше лишнее
 * короткое занятие, чем два похожих слова в одном.
 *
 * ПОРЯДОК СЛОВ ВНУТРИ ПОРЦИИ АВТОРСКИЙ. Перетасовывать их нельзя: автор ставит
 * рядом слова одной сцены («здравствуйте» и «меня зовут»), и порядок — часть
 * содержания.
 *
 * ДЕТЕРМИНИРОВАНО: ни случайности, ни времени — один и тот же сид обязан
 * собираться одинаково в любой день (иначе у курса при каждой сборке новые id
 * уроков).
 */
export function spreadConfusable(vocab: VocabItem[], size: number): VocabItem[][] {
  if (vocab.length <= size) {
    // Даже одна порция может содержать пару-конфликт — тогда её честно рвём.
    const conflicted = vocab.some((w, i) => vocab.slice(0, i).some(x => confusable(w, x)))
    if (!conflicted) return [vocab]
  }
  const count = Math.max(1, Math.ceil(vocab.length / size))
  const out: VocabItem[][] = Array.from({ length: count }, () => [])

  for (const word of vocab) {
    // Ровные порции: сначала самая пустая из подходящих, чтобы не получилось
    // «четыре и хвост из одного» (Р1).
    const fits = out
      .map((part, i) => ({ part, i }))
      .filter(({ part }) => part.length < size && !part.some(x => confusable(word, x)))
      .sort((a, b) => a.part.length - b.part.length || a.i - b.i)[0]
    if (fits) { fits.part.push(word); continue }

    // Места нет нигде — заводим ещё одну порцию.
    //
    // РАНЬШЕ ЗДЕСЬ ДОКЛАДЫВАЛИ В ПЕРЕПОЛНЕННУЮ: если конфликта со словом не
    // было, оно уходило в первую же порцию без спутываемых — независимо от
    // того, сколько слов там уже лежит. Так появлялись занятия на ПЯТЬ новых
    // слов при потолке в четыре (Р1) — девять таких на девять курсов. Порция
    // сверх потолка стоит дороже, чем лишнее короткое занятие: это ровно тот
    // дефект, ради которого порции и заводились.
    out.push([word])
  }
  return out.filter(part => part.length > 0)
}

/** Слоги-обманки для сборки: похожие на слоги самого слова, а не случайные. */
function bankDistractors(term: string, others: VocabItem[]): string[] {
  if (isHangul(term)) return syllableDistractors(term, 3)
  // Не хангыль: берём знаки соседних слов порции — они хотя бы из той же
  // системы письма, в отличие от случайных символов.
  const own = new Set(Array.from(term))
  const out: string[] = []
  for (const w of others) {
    for (const ch of Array.from(w.term ?? '')) {
      if (own.has(ch) || out.includes(ch)) continue
      out.push(ch)
      if (out.length === 3) return out
    }
  }
  return out
}

/**
 * Ступень 3 для алфавитного письма: собрать форму, не читая её заново.
 *
 * ФРАЗА ОТ ТРЁХ СЛОВ → БЛОКИ. «to look forward to» из четырёх плиток-слов:
 * собирается порядок, а он у английской фразы и есть трудность (`blockOrder`).
 * Двух плиток мало: «root cause» из двух блоков — это подбрасывание монеты, и
 * ошибиться в нём можно только случайно.
 *
 * ОСТАЛЬНОЕ → ПЕРЕПУТАННЫЕ БУКВЫ. `unscramble` показывает слово с перепутанными
 * знаками, ученик пересобирает его правильно. Берём САМОЕ ДЛИННОЕ слово
 * термина: у «root cause» это «cause», и написание отрабатывается на нём.
 * Короче пяти букв не берём — «flat» пересобирается вслепую.
 *
 * СЛОВА СО ЗНАКАМИ пропускаем: перепутать буквы в «what’s» — значит требовать
 * угадать, куда встал апостроф.
 */
function latinAssembly(w: VocabItem, stage: WritingStage): SeedTask[] {
  const term = w.term.trim()
  const words = term.split(/\s+/).filter(Boolean)
  const question = stage === 'B' && w.reading
    ? `Соберите: «${w.ru}» (${w.reading})`
    : `Соберите: «${w.ru}»`

  if (words.length >= 3) {
    return [{ type: 'blockOrder', question, sequenceItems: words, ttsText: term }]
  }
  const longest = words
    .filter(x => /^[\p{L}]+$/u.test(x) && Array.from(x).length >= 5)
    .sort((a, b) => b.length - a.length)[0]
  if (longest) {
    return [{
      type: 'unscramble',
      question: words.length > 1
        ? `Написано неправильно. Соберите слово из «${w.term.trim()}» — ${w.ru}`
        : `Написано неправильно. Соберите слово «${w.ru}»`,
      answer: longest,
      ttsText: longest,
    }]
  }
  return []
}

export interface LadderOptions {
  /** Курс родного языка: карточка перевёрнута, спрашиваем точность слова. */
  native?: boolean
  /** Стадия письма урока (Р6). */
  stage?: WritingStage
  /**
   * Слова, уже пройденные в курсе к этому занятию, — запас обманок (Р9).
   *
   * ЗАЧЕМ. Порция бывает из одного слова: спутываемые формы разводятся по
   * разным занятиям (Р5), и в теме вроде «Числа» — где спутываемо ВСЁ —
   * порция схлопывается до единицы. Обманку внутри такой порции взять негде,
   * лестница возвращала пустоту, и урок выходил из одной карточки: ни звука,
   * ни сборки, ни узнавания. Двенадцать таких уроков подряд в kosv, двадцать
   * один в kohg.
   *
   * Обманка отсюда ЗАКОННА и даже лучше своей: по Р9 обманкой должно быть
   * освоенное слово, а не сосед по списку, увиденный минуту назад.
   */
  seen?: VocabItem[]
}

/**
 * Ступени 1–3 по каждому слову порции, кругами.
 *
 * Круг 1 — узнавание значения из ДВУХ вариантов (Р9: первое узнавание всегда
 * из двух, обманка — знакомое слово: сосед по порции либо пройденное раньше).
 * Круг 2 — узнавание на слух: прозвучало одно из двух слов, какое?
 * Круг 3 — сборка написания: плитками-слогами у незнакомого письма, блоками
 * слов и перепутанными буквами у латиницы (см. latinAssembly).
 *
 * Возвращает СИДЫ без id — их проставляет сборщик курса (editorTask).
 */
export function ladderTasks(words: VocabItem[], opts: LadderOptions = {}): SeedTask[] {
  const { native = false, stage = 'C', seen = [] } = opts
  const pool = words.filter(w => w.term?.trim() && w.ru?.trim())
  if (pool.length === 0) return []
  // Запас обманок: сначала соседи по порции, потом пройденное раньше — от
  // свежего к старому, чтобы обманка была узнаваемой.
  const spare = seen
    .filter(w => w.term?.trim() && w.ru?.trim())
    .filter(w => !pool.some(x => x.term === w.term))
    .reverse()
  // Обманку не из чего взять вовсе — лестница вырождается в подсказку.
  if (pool.length + spare.length < 2) return []

  const label = (w: VocabItem) => stageLabel(w, stage)
  /**
   * Единственная обманка задания. Сосед по порции, если он есть и не
   * спутываем; иначе — пройденное слово. Слово с тем же переводом обманкой
   * быть не может: верных ответов стало бы два.
   */
  const partner = (i: number): VocabItem => {
    const w = pool[i]
    const ring = [...pool.slice(i + 1), ...pool.slice(0, i)]
    const ok = (x: VocabItem) =>
      x.term !== w.term && x.ru.trim().toLowerCase() !== w.ru.trim().toLowerCase()
    // Смещение по номеру слова: иначе одна и та же обманка стоит во всех
    // заданиях порции, и к третьему ученик отвечает вычёркиванием.
    const fromSpare = spare.filter(ok)
    return ring.find(ok)
      ?? fromSpare[i % Math.max(1, fromSpare.length)]
      ?? ring[0]
      ?? w
  }

  const round1: SeedTask[] = pool.map((w, i) => {
    const other = partner(i)
    // Верный ответ то слева, то справа: иначе к третьему заданию порции
    // ученик отвечает по позиции, а не по значению.
    const right = i % 2 === 0
    const choices = right ? [w.ru, other.ru] : [other.ru, w.ru]
    return {
      type: 'single',
      question: native
        ? `Что точно значит «${label(w)}»?`
        : `Что значит ${label(w)}?`,
      choices,
      correctChoices: [right ? 0 : 1],
    }
  })

  // Звук нужен только там, где слово звучит не так, как пишется по-русски:
  // у курса родного языка эта ступень не несёт ничего.
  //
  // ДВА РАЗНЫХ ЗАДАНИЯ ВМЕСТО ОДНОГО. Если среди пройденного нашлось СОЗВУЧНОЕ
  // слово (물/불, quite/quiet) — это различение на слух: прозвучало одно из
  // двух, какое. Если не нашлось, различать нечего, и вопрос «что прозвучало?»
  // проверял бы не слух, а зрение. Тогда спрашиваем ЗНАЧЕНИЕ услышанного —
  // ровно то, что Р2 и называет ступенью 2: «услышал → выбрал из 2–3».
  const round2: SeedTask[] = native ? [] : pool.map((w, i) => {
    const twin = [...pool, ...spare]
      .filter(x => x.term !== w.term && x.ru.trim().toLowerCase() !== w.ru.trim().toLowerCase())
      .map(x => ({ x, score: soundAlike(w.term, x.term) }))
      .filter(c => c.score >= ALIKE_ENOUGH)
      .sort((a, b) => b.score - a.score)[0]?.x
    const first = i % 2 === 0
    if (twin) {
      return {
        type: 'minimalPair',
        question: 'Что прозвучало?',
        pairA: first ? label(w) : label(twin),
        pairB: first ? label(twin) : label(w),
        correctPair: first ? 'A' : 'B',
        ttsText: w.term,
        allowSlow: true,
      }
    }
    // Различать нечего — спрашиваем ЗНАЧЕНИЕ услышанного. Тип тот же, и это
    // намеренно: на экране те же две плитки и тот же плеер сверху, меняется
    // только то, что на плитках написано — не формы, а переводы. Отдельным
    // `single` это раздуло бы и без того самый частый тип курса до трети всех
    // заданий, а выглядело бы как обычный выбор, где звук легко не заметить.
    const other = partner(i)
    return {
      type: 'minimalPair',
      question: 'Что вы услышали?',
      pairA: first ? w.ru : other.ru,
      pairB: first ? other.ru : w.ru,
      correctPair: first ? 'A' : 'B',
      ttsText: w.term,
      allowSlow: true,
    }
  })

  // Сборка написания — ступень между «узнал» и «напиши сам» (Р7: клавиатура
  // только после плиток).
  //
  // ЛАТИНИЦА ТОЖЕ СОБИРАЕТСЯ. Раньше этот круг для английского не строился
  // вовсе — «латиница читается сразу», — и ступень 3 у половины курсов
  // отсутствовала: ученик шёл с узнавания сразу на припоминание. Но собирать
  // здесь нужно не ЧТЕНИЕ, а форму: порядок слов в «to look forward to» и
  // написание длинного слова — ровно та генерация с опорой, ради которой
  // ступень и стоит (Slamecka & Graf 1978). Поэтому фраза собирается блоками
  // из слов, а длинное слово — пересобирается из перепутанных букв.
  const round3: SeedTask[] = native ? [] : pool.flatMap(w => {
    const term = w.term.trim()
    if (!FOREIGN_SCRIPT.test(term)) return latinAssembly(w, stage)
    const units = Array.from(term.replace(/\s+/g, ''))
    const question = stage === 'B' && w.reading
      ? `Соберите слово «${w.ru}» (${w.reading})`
      : `Соберите слово «${w.ru}»`
    // Отдельная буква: собирать нечего — её ПИШУТ. Обводка по чертам и есть
    // ступень 3 для алфавитного урока (Р6, стадия письма): рука повторяет форму,
    // пока звук ещё в голове.
    if (isChamo(term)) {
      return [{ type: 'trace', question: `Обведите букву ${term} — ${w.ru}`, chamo: term, ttsText: term, allowSlow: false } as SeedTask]
    }
    // Один знак собирать не из чего: у хангыля это работа для сборки слога из
    // букв, у остальных письменностей — вообще не задание.
    if (units.length < 2) {
      return isHangul(term) ? [{ type: 'buildSyllable', question, syllable: term } as SeedTask] : []
    }
    return [{
      type: 'charBank',
      question,
      answer: term,
      distractors: bankDistractors(term, pool.filter(x => x.term !== w.term)),
      ttsText: term,
    } as SeedTask]
  })

  return [...round1, ...round2, ...round3]
}
