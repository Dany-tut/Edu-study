// ─────────────────────────────────────────────────────────────────────────────
// Видео в ДОМАШКЕ языковых курсов
//
// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ВИДЕО УРОКА (data/languageVideos.ts). Там объяснение
// правила: носитель или преподаватель разбирает конструкцию медленно и
// специально для учебника. Здесь — живая речь на нормальной скорости: серия
// мультика, подкаст, стрим, разговорное шоу. Одно другое не заменяет. Курс с
// одними разборами выпускает человека, который знает правила и не понимает
// ни слова в первом же сериале.
//
// КАК ЭТО РАБОТАЕТ У УЧЕНИКА. Ролик открывается прямо в домашке нашим плеером
// (тип задания `videoWatch`), просмотр считается отрезками — перемотка в конец
// не засчитывает ничего. У длинного материала стоит порог в минутах: серию,
// подкаст на полчаса и двухчасовой стрим целиком в домашку на вечер не ставят.
// Сразу за просмотром идёт короткое задание на понимание: видео без него —
// это «включил фоном», а не работа.
//
// ЖЁСТКИЕ ПРАВИЛА ЭТОГО ФАЙЛА (те же, что и у видео уроков):
//
//  1. КАЖДЫЙ ID ПРОВЕРЕН oembed'ом — название и канал сверены с темой юнита.
//     Прогон: node scripts/checkVideos.mjs (он обходит всю папку src).
//  2. ТОЛЬКО ССЫЛКА, НИКАКИХ КОПИЙ. Встраивание ролика плеером YouTube законно
//     и предусмотрено сервисом, автор получает свои просмотры. Скачивание,
//     перезалив и «вырезанный кусок фильма у нас в бакете» — нет.
//  3. ОФИЦИАЛЬНЫЕ КАНАЛЫ. Мультик берётся с канала правообладателя
//     (뽀로로/Pororo), а не с чьей-то перезаливки: перезаливку снимают, и
//     домашка ломается вместе с ней.
//  4. УРОВЕНЬ ЧЕСТНЫЙ. Материал ставится туда, где ученик уже понимает хотя бы
//     общий смысл. На хангыле это ещё не понимание речи — там задача другая
//     («услышать, что язык устроен из знакомых слогов»), и формулировка
//     задания это прямо говорит, а не притворяется аудированием.
// ─────────────────────────────────────────────────────────────────────────────

