// Диагностика «Английский — восстановление B2» (Конструктор → Тестирование, ключ eng-restore).
//
// Отличается от eng-placement принципом нарезки. Placement режет вопросы по
// УРОВНЯМ (A2 · Grammar, B1 · Grammar…) и отвечает на вопрос «какой у ученика
// уровень». Эта диагностика режет по СИСТЕМАМ ЯЗЫКА и отвечает на другой
// вопрос: «что именно осыпалось у ученика, который уровень уже когда-то имел».
// Такое бывает после долгого перерыва: узнавание держится, производство — нет.
//
// ЧТО ЭТОТ ТЕСТ МЕРЯЕТ. Доступ к конкретным формам, а НЕ уровень CEFR. Все
// тридцать шесть пунктов — ловушки: у каждого дистрактор нарочно правдоподобен
// и обычно проще верного ответа. Из-за этого процент нельзя читать как уровень:
// систематически упрощающий человек набирает НИЖЕ случайного тыка (25% при
// четырёх вариантах), а вовсе не потому, что он ниже A2. Пороги вердикта ниже
// отсчитываются от случайного угадывания, а не от нуля.
//
// ДЛИНА. Тридцать шесть вопросов, по три на систему. Шестьдесят давали более
// тонкую картину по каждой системе, но проходились в один присест тяжело, а
// это лишь ПЕРВАЯ из четырёх частей замера — усталость к концу искажает как раз
// то, ради чего тест и нужен. Три пункта дают четыре ступени на систему
// (0/3…3/3): для решения «разворачивать день или сжимать» этого хватает, для
// тонких градаций внутри системы — уже нет.
//
// Код системы в префиксе section до « · » (ART, MOD, NFN…) одновременно
// является номером дня в 14-дневной программе восстановления, см. SYSTEM_DAY.
// Разбивка по разделам у учителя за счёт этого сразу читается как план:
// провалившаяся система = день, который нужно расширить.
//
// Контексты примеров намеренно бытовые и профессиональные (урок химии, метро,
// аптека, касса), а не учебные: конструкция должна узнаваться в той обстановке,
// где ей предстоит работать.

import type { DiagQuestion, DiagResults } from './diagnosticData'
import type { PlacementVerdict } from './placementTests'

// Система → день программы. Порядок = порядок дней.
// Система → день программы восстановления. После пересборки курса под реальную
// диагностику порядок другой: первые три дня целиком заняты перфектом (одна
// конструкция, три точки отсчёта), а придаточные с выделением и инверсия со
// связками из спринта убраны — это надстройка над кирпичом, которого у ученика
// с такой картиной ещё нет. День null значит «тест это меряет, но в четырнадцать
// дней не входит»; вердикт такие системы в «расширить день» не записывает.
export const SYSTEM_DAY: Record<string, { day: number | null; name: string }> = {
  PRF: { day: 2,    name: 'Перфект' },
  TNS: { day: 4,    name: 'Времена и вид' },
  ART: { day: 5,    name: 'Артикли и исчисляемость' },
  PAS: { day: 6,    name: 'Пассив и каузатив' },
  CND: { day: 7,    name: 'Условные и wish' },
  FUT: { day: 8,    name: 'Будущее' },
  PRP: { day: 9,    name: 'Предлоги и фразовые' },
  MOD: { day: 10,   name: 'Модальность' },
  REP: { day: 11,   name: 'Косвенная речь и вопросы' },
  NFN: { day: 12,   name: 'Неличные формы' },
  REL: { day: null, name: 'Придаточные и cleft' },
  DSC: { day: null, name: 'Дискурс и порядок слов' },
}

export const SYSTEM_ORDER = Object.keys(SYSTEM_DAY)


// Вердикт: не лесенка уровней, а карта поломок. Шаги ladder — это системы в
// порядке дней программы, поэтому чипы результата читаются как расписание.
const RESTORE_PASS = 0.6

export function englishRestoreVerdict(results: DiagResults): PlacementVerdict {
  const ladder = SYSTEM_ORDER.map(code => {
    let correct = 0, total = 0
    for (const [section, r] of Object.entries(results)) {
      if (section.split(' · ')[0] === code) { correct += r.correct; total += r.total }
    }
    return { level: code, correct, total, passed: total > 0 && correct / total >= RESTORE_PASS }
  })

  const answered = ladder.filter(s => s.total > 0)
  const correctAll = answered.reduce((a, s) => a + s.correct, 0)
  const totalAll = answered.reduce((a, s) => a + s.total, 0)
  const pct = totalAll > 0 ? Math.round((correctAll / totalAll) * 100) : 0

  const broken = answered
    .filter(s => s.correct / s.total < 0.5)
    .sort((a, b) => a.correct / a.total - b.correct / b.total)
    .slice(0, 3)
  const brokenNote = broken.length
    ? ` Слабее всего: ${broken.map(s => { const d = SYSTEM_DAY[s.level]; return d.day ? `${d.name.toLowerCase()} (день ${d.day})` : `${d.name.toLowerCase()} (вне спринта)` }).join(', ')} — дни программы разворачиваем полностью, а то, что вне спринта, оставляем на потом.`
    : ' Провалившихся систем нет — программу можно вести в ускоренном темпе, упирая на скорость извлечения, а не на разбор правил.'

  // Курс рекомендуется по результату, а не один на всех: тест ведёт в спринт
  // восстановления (ensp, 14 дней = коды систем этой же диагностики), и только
  // верхняя полоса, где восстанавливать уже нечего, уходит в надстройку B2→C1.
  // Раньше здесь стоял enac на любой балл — и экран выдавал «уровень A2» рядом
  // с «курс от B2 к C1».
  const RESTORE = { courseKey: 'ensp', courseTitle: 'Английский: возвращение B2 за 14 дней' }
  const ADVANCED = { courseKey: 'enac', courseTitle: 'Английский: от B2 к C1' }
  const course = RESTORE

  // Пороги отсчитываются от 25% — это результат случайного тыка при четырёх
  // вариантах. Ниже него человек не «угадывает хуже случайного», а уверенно
  // выбирает правдоподобное неверное: значит, формы не просто забыты, а
  // замещены упрощением. Это другое состояние, и лечится оно иначе.
  if (pct < 25) return {
    level: 'Формы недоступны',
    note: `${pct}% — это ниже случайного угадывания (25%), и такое получается не от незнания, а от устойчивой подмены: вместо составной формы выбирается простая. Сложные времена, неличные формы, пассив и порядок слов сейчас не в доступе. Программу берём с сокращённым охватом и большим числом повторов: не двенадцать систем за четырнадцать дней, а ядро до автоматизма.${brokenNote}`,
    ...course, ladder,
  }
  if (pct < 45) return {
    level: 'Ядро частично',
    note: `${pct}% — часть форм отзывается, но выбор между близкими вариантами ещё не работает. Охват программы стоит сузить и добавить повторов, иначе четырнадцать дней уйдут на знакомство, а не на закрепление.${brokenNote}`,
    ...course, ladder,
  }
  if (pct < 65) return {
    level: 'Спящий B1+ / B2',
    note: `${pct}% на тесте из одних ловушек — типичная картина после долгого перерыва: знания на месте, доступа к ним нет. Лечится извлечением (перевод под таймер, диктант), а не повторным прохождением теории.${brokenNote}`,
    ...course, ladder,
  }
  if (pct < 85) return {
    level: 'B2 · детали плывут',
    note: `${pct}% — система цела, ломаются детали и скорость. Упор переносим с разбора правил на темп: перевод на время, аудирование, говорение.${brokenNote}`,
    ...course, ladder,
  }
  return {
    level: 'B2+ · подступ к C1',
    note: `${pct}% на тесте из одних ловушек — грамматика держится уверенно. Восстанавливать нечего: программу стоит развернуть в сторону беглости, идиоматики и скорости восприятия на слух.${brokenNote}`,
    ...ADVANCED, ladder,
  }
}
