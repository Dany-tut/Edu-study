-- Обсуждения в ленте — только для учеников со своим входом
--
-- ПОЧЕМУ. Политики 0057/0058 обещали «видно только своей группе», но для роли
-- anon это обещание не выполнялось и выполниться не могло: у анонима нет
-- личности, поэтому проверка вырождалась в «в группе есть хоть один
-- легаси-ученик» — а такая группа есть почти любая. На практике это значило,
-- что реплика ученика одного учителя читается учениками другого. Для детской
-- платформы это не «неаккуратно», а прямо то, чего миграция 0057 обещала не
-- допускать.
--
-- Починить это внутри RLS нельзя: база не знает, КТО спрашивает, пока ученик
-- ходит по общему anon-ключу. Поэтому обсуждения закрываются для anon целиком
-- и живут только там, где у ученика есть свой auth-аккаунт (auth_user_id).
-- Ученик без входа ленту по-прежнему читает и слушает — он не пишет и не видит
-- тред, и клиент говорит ему об этом словами.
--
-- ЧТО ВЕРНЁТ ДОСТУП: выдать легаси-ученикам логины (приглашение → claim). После
-- этого их видимость станет настоящей — «своя группа», а не «все группы».

drop policy if exists anon_select_fc on public.feed_comments;
drop policy if exists anon_insert_fc on public.feed_comments;

drop policy if exists anon_select_fl on public.feed_likes;
drop policy if exists anon_insert_fl on public.feed_likes;
drop policy if exists anon_delete_fl on public.feed_likes;

-- Роль anon в этих таблицах не участвует вовсе: без политик select вернёт
-- пусто, а запись — 42501. Снимаем и табличные гранты, чтобы намерение было
-- видно в схеме, а не только в отсутствии политик.
revoke all on public.feed_comments from anon;
revoke all on public.feed_likes    from anon;
