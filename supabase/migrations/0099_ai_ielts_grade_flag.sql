-- Рубильник расхода на оценку Writing и Speaking пробника IELTS моделью.
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ. Как и импорт карточек, оценку запускает ЧЕЛОВЕК, когда
-- захочет: каждое сданное эссе и каждый Speaking — отдельное обращение к
-- модели. Расход предсказуем только сверху (не больше трёх обращений на
-- пробник), поэтому и выключатель свой. Выключено — Listening и Reading
-- считаются как раньше, ключом в браузере, а Writing и Speaking пробник
-- сохраняет без балла и честно говорит, что оценка выключена.
--
-- Префикс `ai_` обязателен: по нему Админка → Обзор → «Расход на ИИ» рисует
-- строку переключателем. Связка прежняя: работает при поднятых ОБОИХ флагах —
-- общем `ai_enabled` и своём.
insert into public.app_flags (key, enabled, about) values
  ('ai_ielts_grade', true,
   'Оценка Writing и Speaking в пробниках IELTS моделью по критериям экзамена. Выключено: Listening и Reading считаются как раньше, а письмо и речь сохраняются без балла.')
on conflict (key) do nothing;
