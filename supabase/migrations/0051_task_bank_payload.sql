-- ─────────────────────────────────────────────────────────────────────────────
-- Банк заданий: одна JSONB-колонка под данные типа вместо колонки на каждый тип
--
-- ПРОБЛЕМА. Таблица заводит отдельную колонку под каждый тип задания:
-- match_left/match_right для сопоставления, sequence_items для порядка,
-- choices для выбора. Пока типов было семь, это работало. Языковых типов
-- восемь, и у каждого свои поля: у диктанта аудио и текст для синтеза, у
-- сборки предложения эталон и обманки, у минимальных пар два варианта и ответ,
-- у карточки лицо и оборот, у описания картинки список фактов.
--
-- Пойти прежним путём — это +15 колонок сейчас и ещё столько же при следующем
-- типе. Каждая будет null у 95% строк.
--
-- РЕШЕНИЕ. Одна колонка payload jsonb. Ровно так уже хранятся задания в
-- lessons.homework, и ровно так устроен TaskPayload в коде: единая структура,
-- где каждый тип использует своё подмножество полей. Новый тип задания больше
-- не требует миграции.
--
-- Старые колонки НЕ трогаем: по ним читают существующие строки и работает
-- фильтрация. Новые поля идут только в payload.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.task_bank
  add column if not exists payload jsonb not null default '{}'::jsonb;

comment on column public.task_bank.payload is
  'Данные, специфичные для типа задания (TaskPayload, src/data/taskTypes.ts): '
  'sentence/distractors у сборки предложения, audio_url/tts_text у аудио, '
  'pair_a/pair_b/correct_pair у минимальных пар, front/back у карточки, '
  'passage у чтения. Заведена вместо колонки-на-тип: новый тип задания '
  'не требует миграции схемы.';

-- Поиск заданий по типу внутри payload (например, «все диктанты»).
create index if not exists task_bank_payload_gin on public.task_bank using gin (payload);
