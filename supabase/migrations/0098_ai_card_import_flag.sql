-- Рубильник расхода на разбор источника карточек моделью.
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ. Импорт карточек по фото и по ссылке — первое платное
-- обращение к модели, которое запускает ЧЕЛОВЕК и когда захочет, а не ночная
-- сборка по расписанию. Поэтому и выключатель ему нужен свой: остальные задачи
-- (лента, аналитика) тратят предсказуемо, эта — ровно столько, сколько раз
-- нажали кнопку. Выключено — обе кнопки («Фото», «Ссылка») в редакторах просто
-- не показываются, а ручной ввод и «Вставить списком» работают как раньше.
--
-- Префикс `ai_` обязателен: по нему Админка → Обзор → «Расход на ИИ» отделяет
-- рубильники денег от обычных функций и рисует их переключателями. Отдельного
-- кода в админке новая строка не требует — блок собирается из всех `ai_*`.
--
-- Связка прежняя: работает, только если подняты ОБА флага — общий и свой.
insert into public.app_flags (key, enabled, about) values
  ('ai_card_import', true,
   'Разбор источника карточек моделью: фото списка слов и страница по ссылке превращаются в пары слово–перевод. Выключено: в редакторах остаются только ручной ввод и вставка списком.')
on conflict (key) do nothing;
