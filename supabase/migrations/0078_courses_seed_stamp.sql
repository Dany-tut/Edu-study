-- Отпечаток сида, с которого синхронизирован курс.
--
-- ЗАЧЕМ. Готовый курс живёт своей жизнью: в него дописывают задания и правят
-- уроки. Учитель, сохранивший его месяц назад, об этом не узнаёт — пока сам не
-- откроет курс и не нажмёт «Из сида». Так и вышло со сложными заданиями: их
-- добавили во все девятнадцать курсов, а восемь сохранённых копий остались без
-- сложного уровня, и заметить это было неоткуда.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ СВЕРКА НА МЕСТЕ. Настоящая сверка (lib/seedSync.ts)
-- требует собрать сид целиком — сотни килобайт на курс. На списке курсов, где
-- их полтора десятка, это ровно та загрузка, ради избавления от которой
-- карточки сидов вынесены в отдельный лёгкий файл. Отпечаток — короткая строка,
-- сравнение стоит ничего.
--
-- ПОЧЕМУ ОТПЕЧАТОК, А НЕ ВЕРСИЯ И НЕ ДАТА. Версии у сида нет: он меняется
-- коммитом, а не релизом. Дата не годится тоже — правка контента и правка кода
-- вокруг него неразличимы по времени. Отпечаток считается по самому
-- содержанию (см. stampOf в scripts/stampSeedCards.mjs).
--
-- NULL У СТАРЫХ КУРСОВ — ЭТО ВЕРНО. Он означает «неизвестно, с чего
-- синхронизировано», и плитка честно предложит свериться: для восьми курсов,
-- ради которых всё и затевалось, это ровно тот ответ, который нужен.
--
-- Колонка ничего не ломает: она nullable, значения по умолчанию нет, старые
-- строки не трогаются. Откат — drop column.

alter table public.courses
  add column if not exists seed_stamp text;

comment on column public.courses.seed_stamp is
  'Отпечаток содержимого сида на момент последней синхронизации (SEED_CARDS[key].stamp). NULL — синхронизации не было или она была до появления отпечатков.';
