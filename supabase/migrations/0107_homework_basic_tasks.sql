-- Базовые задания домашки целиком, а не только номерами из банка.
--
-- «Создать домашку» писала в homework только task_ids — задания из банка. Свои
-- задания учителя («+ тип задания»), импорт из Google Форм и правки заданий из
-- банка при публикации молча выбрасывались: учитель видел «Опубликовано!», а
-- ученик получал пустую или урезанную домашку. Сложные задания уже хранятся
-- целиком в hard_tasks; базовым — то же самое.
--
-- Пусто ('[]') — старая домашка: ученик собирает базу из task_ids, как раньше.
alter table public.homework
  add column if not exists basic_tasks jsonb not null default '[]'::jsonb;
