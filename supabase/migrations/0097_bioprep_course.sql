-- ─────────────────────────────────────────────────────────────────────────────
-- Каталог курса «Биология: подготовка к университету» (bioprep-ru).
--
-- Уровень 0 лестницы: 40 уроков в пяти блоках, охват A-level / IB HL.
--
-- НУМЕРАЦИЯ С НУЛЯ. lesson_number — это индекс, а не порядковый номер: интерфейс
-- печатает «Занятие №{lesson_number + 1}», а редактор конспекта в Конструкторе
-- вычисляет short_id как `<курс>-<индекс в списке>`. С нумерацией от единицы
-- учитель, правя конспект первого урока, писал бы в несуществующий short_id, а
-- дальше — каждый раз в соседний урок.
--
-- Конспекты
-- и домашки лежат в коде (src/data/bioPreULessons.ts) и подставляются, пока
-- lessons.content пуст, — как у AP Chemistry и «Биологии клетки».
--
-- Идемпотентна: повторный прогон ничего не создаёт заново.
-- ─────────────────────────────────────────────────────────────────────────────

do $$
declare
  v_course_id uuid;
  v_owner uuid;
  v_mod uuid[] := array[]::uuid[];
  r record;
  v_id uuid;
begin
  select created_by into v_owner from courses where short_id = 'apchem-ru' limit 1;

  insert into courses (short_id, kind, title, subject, level, description, status, color, bg, created_by)
  values (
    'bioprep-ru', 'course',
    'Биология: подготовка к университету',
    'Биология',
    'Pre-U (A-level / IB HL)',
    'Сорок уроков полного школьного курса на уровне, с которым поступают на естественно-научные программы: химия жизни, клетка, обмен веществ, генетика, физиология человека, разнообразие, эволюция и экология. Вход в университетский курс «Биология клетки».',
    'draft', '#1E9E63', '#DFF3E8', v_owner
  )
  on conflict (short_id) do nothing;

  select id into v_course_id from courses where short_id = 'bioprep-ru';

  -- Пять блоков. Создаются один раз; порядок задан position.
  for r in
    select * from (values
      ('Блок 1. Химия жизни и клетка', 0),
      ('Блок 2. Транспорт и энергетика', 1),
      ('Блок 3. Генетика и деление', 2),
      ('Блок 4. Организм человека', 3),
      ('Блок 5. Разнообразие, эволюция, экология', 4)
    ) as t(label, pos) order by pos
  loop
    select id into v_id from course_modules
      where course_id = v_course_id and label = r.label limit 1;
    if v_id is null then
      insert into course_modules (course_id, label, position)
      values (v_course_id, r.label, r.pos) returning id into v_id;
    end if;
    v_mod := v_mod || v_id;
  end loop;

  insert into lessons (course_id, module_id, short_id, title, lesson_number, position, kind, shape)
  select v_course_id, v_mod[d.block], 'bioprep-ru-' || d.n, d.title, d.n, d.n, 'lesson',
         case when d.n in (0, 39) then 'diamond' else 'circle' end
  from (values
    (0,  1, 'Что такое жизнь: признаки и уровни организации'),
    (1,  1, 'Вода и её свойства'),
    (2,  1, 'Углеводы'),
    (3,  1, 'Липиды'),
    (4,  1, 'Белки: строение и функции'),
    (5,  1, 'Нуклеиновые кислоты'),
    (6,  1, 'Ферменты'),
    (7,  1, 'Клетка: прокариоты и эукариоты'),
    (8,  1, 'Плазматическая мембрана'),
    (9, 2, 'Транспорт через мембрану'),
    (10, 2, 'Осмос и водный баланс клетки'),
    (11, 2, 'АТФ и энергия в клетке'),
    (12, 2, 'Клеточное дыхание'),
    (13, 2, 'Фотосинтез'),
    (14, 3, 'ДНК, хромосомы и репликация'),
    (15, 3, 'От гена к белку'),
    (16, 3, 'Клеточный цикл и митоз'),
    (17, 3, 'Мейоз'),
    (18, 3, 'Законы Менделя'),
    (19, 3, 'Дигибридное скрещивание и сцепление генов'),
    (20, 3, 'Мутации'),
    (21, 3, 'Наследственные болезни человека'),
    (22, 3, 'Биотехнология и генная инженерия'),
    (23, 4, 'Ткани, органы и системы органов'),
    (24, 4, 'Пищеварение'),
    (25, 4, 'Дыхание и газообмен'),
    (26, 4, 'Кровь и кровообращение'),
    (27, 4, 'Иммунитет'),
    (28, 4, 'Выделение и водный баланс'),
    (29, 4, 'Нервная система'),
    (30, 4, 'Гормональная регуляция и гомеостаз'),
    (31, 4, 'Опора и движение'),
    (32, 5, 'Классификация живого'),
    (33, 5, 'Бактерии и вирусы'),
    (34, 5, 'Растение как организм'),
    (35, 5, 'Размножение и развитие'),
    (36, 5, 'Эволюция'),
    (37, 5, 'Популяционная генетика'),
    (38, 5, 'Экология'),
    (39, 5, 'Биосфера и человек')
  ) as d(n, block, title)
  where not exists (select 1 from lessons l where l.short_id = 'bioprep-ru-' || d.n);
end $$;
