-- Рубильники платных обращений к модели.
--
-- ЗАЧЕМ. Ночная сборка ленты ходит в Anthropic за переводами и пересказами, а
-- «Аналитика» раз в месяц — за разбором телеметрии. Это единственные места, где
-- платформа тратит деньги сама, без участия человека, и до сих пор выключить их
-- можно было только вынув ключ из секретов GitHub — то есть разом и навсегда.
-- Флаг даёт то, чего не хватало: выключить всё одним движением, оставить только
-- переводы, или наоборот. Решение принимают в проде и отменяют в проде.
--
-- ПОЧЕМУ ЗДЕСЬ, А НЕ В НОВОЙ ТАБЛИЦЕ. app_flags уже ровно про это: строка на
-- флаг, читают все (anon в том числе — а ночная сборка ходит именно анонимно),
-- пишет только админ. Префикс `ai_` — не украшение: по нему админка отделяет
-- рубильники расхода от обычных функций, и по нему же их читают скрипты.
--
-- ВАЖНО ПРО СВЯЗКУ. Работа идёт, только если подняты ОБА флага: общий `ai_` и
-- свой у задачи. Общий — «стоп-кран», свой — «что именно нам сейчас нужно».
insert into public.app_flags (key, enabled, about) values
  ('ai_enabled', true,
   'Общий рубильник ИИ: пока выключен, платформа не делает ни одного платного запроса к модели — ни переводов, ни пересказов, ни разбора аналитики.'),
  ('ai_feed_translate', true,
   'Перевод постов ленты на русский (ночная сборка). Выключено: у новых постов кнопка перевода показывает разбор по словам, старые переводы остаются.'),
  ('ai_feed_adapt', true,
   'Пересказ материалов ленты на трёх уровнях языка (ночная сборка). Выключено: новых пересказов не появляется, старые остаются.'),
  ('ai_analytics_digest', true,
   'Ежемесячный разбор телеметрии моделью во вкладке «Аналитика». Выключено: разбор не собирается ни по расписанию, ни по кнопке.')
on conflict (key) do nothing;
