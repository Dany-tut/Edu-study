// Сторож урока: сверяет собранные курсы-сиды с золотым стандартом
// docs/MEMORY_STANDARD.md (правила Р1, Р3, Р4, Р5, Р9, Р11, Р13, Р15, Р18).
//
// ЗАЧЕМ. Правила методики нельзя держать в голове автора: курсов девять,
// юнитов в них под сотню, а нарушение не падает и не подсвечивается — урок
// просто выходит невыучиваемым. Ровно так и появились десять слов одной
// порцией и сопоставление пар вторым заданием: никто этого не хотел, просто
// генератор так складывал, а проверить было нечем.
//
// ЧТО ПРОВЕРЯЕМ (по каждому уроку каждого сида):
//   Р1  порция нового: ≤ 4 карточки-знакомства (≤ 3 у курса «с нуля»);
//   Р3  знакомство идёт до первого задания по этому слову;
//   Р4  сопоставление: ≤ 4 пары и не раньше, чем слова показаны;
//   Р5  в одном уроке нет спутываемых слов (общий префикс/суффикс, один
//       перевод, минимальная пара);
//   Р9  в СГЕНЕРИРОВАННЫХ заданиях по словарю (лестница, узнавание, картинки)
//       не больше одной обманки, которой ученик ещё не видел;
//   Р13 не больше двух заданий одного типа подряд — кроме карточек знакомства:
//       порция и есть три-четыре карточки подряд, это замысел (Р3);
//   Р15 верный ответ не стоит систематически первым в списке вариантов;
//   Р18 урок доходит хотя бы до ступени 5, а знакомство и узнавание не
//       занимают больше половины ВРЕМЕНИ занятия (см. src/data/taskStage.ts).
//
// ЧЕГО НЕ ПРОВЕРЯЕМ. Смысла заданий и качества формулировок — это не работа
// сторожа. Он ловит структуру: то, что видно из данных и всегда неверно.
//
// Запуск: npm run check:lesson
import { COURSE_SEEDS } from '../src/data/courseSeeds.ts'
import { confusable, paradigmAffixes } from '../src/data/vocabLadder.ts'
import { taskStage, stageMix } from '../src/data/taskStage.ts'

const PORTION = 4
const PORTION_SCRATCH = 3
const MAX_PAIRS = 4
const MAX_SAME_TYPE_RUN = 2

/**
 * Р18 — потолок нижнего яруса лестницы.
 *
 * Половина ВРЕМЕНИ урока, а не половина заданий: тап по варианту стоит восемь
 * секунд, развёрнутый ответ — три минуты, и счёт в штуках говорит про урок
 * ровно обратное правде (замер 26.08.2026: по счёту узнавание выглядело как
 * 52–58% урока, по времени — 17–27%).
 *
 * Половина, а не «поменьше»: по девятнадцати сидам среди занятий длиннее
 * четырёх минут худшее держит 41%. Потолок здесь ловит сползание, а не
 * переписывает то, что уже сходится.
 */
const LOW_TIME_CAP = 0.5

/**
 * Короче четырёх минут долю не меряем — по той же причине, по которой Р15
 * считается по всему курсу, а не по уроку: на маленьком числе доля шумит.
 * Порция из двух слов на три минуты состоит из двух карточек знакомства и
 * трёх «что значит» — её 52% это не перекос, а размер выборки.
 *
 * Порог 240 секунд накрывает 96% занятий (2372 из 2461): под ним остаются
 * только хвостовые порции и первые занятия курсов.
 */
const MIN_LADDER_SECONDS = 240

/**
 * Запас к ожидаемой доле первого места (Р15).
 *
 * Ожидаемое считается по самому курсу: у вопроса на N вариантов верный ответ
 * попадает на первое место с вероятностью 1/N, и у курса из одних вопросов «из
 * двух» ожидание честные 50%. Сравнивать с фиксированным числом нельзя — оно
 * или пропускает перекос, или ругается на курс, где вопросы короткие.
 *
 * Десять пунктов — это уже не разброс, а привычка автора писать
 * `[верный, ...обманки]` и `correct = 0`.
 */
const FIRST_PLACE_SLACK = 0.10

/** Курсы «с нуля» — у них порция меньше (см. LanguageCourseSpec.scratch). */
const SCRATCH_KEYS = new Set(['kohg', 'jajl'])

/**
 * Курсы РОДНОГО языка: карточка в них перевёрнута (см. LanguageCourseSpec.native).
 *
 * ЗАЧЕМ СТОРОЖУ ЭТО ЗНАТЬ. На лице карточки родного курса стоит ТОЛКОВАНИЕ, а
 * слово — на обороте. Читая их как «слово / перевод», сторож сравнивал на
 * спутываемость два толкования — и находил общее начало там, где его находит
 * любая пара русских фраз одной темы («канцелярская замена…» / «канцелярское…»).
 * Генератор (spreadConfusable) сравнивает настоящие слова и таких пар не видит:
 * сторож обязан мерить ровно то же, что генератор.
 */
const NATIVE_KEYS = new Set(['ruzh', 'ruvo', 'rulit'])

let problems = 0
const fail = (where, msg) => { console.log(`  ✗ ${where}: ${msg}`); problems++ }

/** Слово карточки: у обычного курса на лице term, у родного — толкование. */
const cardWord = (task, native = false) => ({
  term: ((native ? task.back : task.front) ?? '').trim(),
  ru: ((native ? task.front : task.back) ?? '').trim(),
  reading: task.reading,
})

/**
 * Текст, в котором задание могло упомянуть слово. Лицо и оборот карточки тоже
 * здесь: иначе «показанным» не считалось бы само знакомство, и любая обманка
 * из слов урока выглядела бы незнакомой.
 */
/** Отдельные поля задания — из них собирается память курса для Р9. */
const taskFields = task => [
  task.question, task.answer, task.sentence, task.syllable,
  task.front, task.back, task.reading, task.ttsText,
  task.pairA, task.pairB, ...(task.choices ?? []), ...(task.pairs ?? []).flatMap(p => [p.left, p.right]),
].filter(Boolean).map(x => String(x).trim())

const taskText = task => [
  task.question, task.answer, task.sentence, task.syllable,
  task.front, task.back, task.reading, task.ttsText,
  task.pairA, task.pairB, ...(task.choices ?? []), ...(task.pairs ?? []).flatMap(p => [p.left, p.right]),
].filter(Boolean).join(' ')

/**
 * Задания, которые слово НЕ проверяют: посмотреть ролик, написать эссе,
 * рассказать голосом. Правило Р3 про них не говорит — оно про проверку раньше
 * показа, а здесь проверки нет вовсе (тему в формулировке упомянуть можно).
 */
const NOT_A_TEST = new Set(['videoWatch', 'extended', 'speaking', 'whiteboard', 'imageDescribe', 'imageCompare'])

for (const seed of COURSE_SEEDS) {
  let course
  try {
    course = await seed.build(`check-${seed.key}`)
  } catch (e) {
    fail(seed.key, `курс не собрался: ${e.message}`)
    continue
  }
  const cap = SCRATCH_KEYS.has(seed.key) ? PORTION_SCRATCH : PORTION
  const native = NATIVE_KEYS.has(seed.key)
  let lessons = 0

  // Серии языка (английские «to …», корейские дни недели и ~하다-глаголы) ищутся
  // по СЛОВАРЮ ВСЕГО КУРСА, а не по одному занятию: в занятии из трёх слов
  // серия из пяти не видна, и её общий кусок читался бы как ловушка (Р5).
  const paradigm = paradigmAffixes(
    course.lessons.flatMap(l => (l.hwTasks ?? [])
      .filter(t => t.type === 'flashcard')
      .map(cardWord)
      .filter(w => w.term && w.ru)),
  )
  // Всё, что ученик видел в этом курсе РАНЬШЕ: обманка из прошлого занятия —
  // знакомое слово, и правило Р9 её не запрещает (запрещает незнакомое).
  //
  // МНОЖЕСТВО, А НЕ СКЛЕЕННАЯ СТРОКА. Строка росла до мегабайтов (у курсов
  // выживания под двести уроков), и `includes` по ней на каждый вариант
  // превращал проверку в десятки минут. Здесь достаточно точного совпадения:
  // варианты собираются генератором из тех же полей, что легли в множество.
  const seenBefore = new Set()
  // Р15 — счётчики места верного ответа по всему курсу.
  let choiceTotal = 0
  let firstPlace = 0
  /** Сумма 1/N по вопросам: сколько первых мест дал бы честный разброс. */
  let expectedFirst = 0

  for (const lesson of course.lessons) {
    const tasks = lesson.hwTasks ?? []
    if (tasks.length === 0) continue
    lessons++
    const where = `${seed.key} · ${lesson.title}`

    // Р15 — где стоит верный ответ. Только одиночный выбор: у множественного
    // верных несколько, и «первое место» там ничего не значит.
    for (const task of tasks) {
      const choices = task.choices ?? []
      if (task.type !== 'single' || choices.length < 2) continue
      choiceTotal++
      expectedFirst += 1 / choices.length
      if ((task.correctChoices ?? [])[0] === 0) firstPlace++
    }

    const cards = tasks.filter(t => t.type === 'flashcard')
    const words = cards.map(t => cardWord(t, native)).filter(w => w.term && w.ru)

    // Р1 — порция нового.
    if (cards.length > cap) {
      fail(where, `новых слов ${cards.length}, потолок ${cap} (Р1)`)
    }

    // Р5 — спутываемое в одном уроке. Серия (дни недели, ~하다-глаголы) общим
    // куском не считается: её и учат вместе, различая переменную часть.
    for (let i = 0; i < words.length; i++) {
      for (let j = i + 1; j < words.length; j++) {
        if (confusable(words[i], words[j], paradigm)) {
          fail(where, `спутываемые слова в одном уроке: «${words[i].term}» и «${words[j].term}» (Р5)`)
        }
      }
    }

    // Позиция первого показа слова — для Р3 и Р9.
    const shownAt = new Map()
    tasks.forEach((task, i) => {
      if (task.type !== 'flashcard') return
      const w = cardWord(task, native)
      if (w.term && !shownAt.has(w.term)) shownAt.set(w.term, i)
    })

    tasks.forEach((task, i) => {
      // Р3 — задание по слову раньше его карточки. Блок повторения (`-rv…`)
      // не в счёт: он спрашивает слова ПРОШЛЫХ занятий, и то, что слово заодно
      // встречается в карточках сегодняшнего, — совпадение, а не нарушение.
      const review = /-rv\d+$/.test(task.id ?? '')
      for (const [term, at] of shownAt) {
        if (at <= i || review || NOT_A_TEST.has(task.type)) continue
        if (task.type !== 'flashcard' && taskText(task).includes(term)) {
          fail(where, `задание ${i + 1} (${task.type}) спрашивает «${term}», а карточка слова идёт ${at + 1}-й (Р3)`)
        }
      }

      // Р4 — размер сопоставления.
      if (task.type === 'matching' && (task.pairs?.length ?? 0) > MAX_PAIRS) {
        fail(where, `сопоставление на ${task.pairs.length} пар, потолок ${MAX_PAIRS} (Р4)`)
      }

      // Р9 — незнакомые обманки. Считаем только у заданий, СОБРАННЫХ по
      // словарю (id `-l…`, `-r…`, `-pic…`): там обманка обязана быть знакомым
      // словом. Авторские задания живут по другим правилам — там варианты это
      // формы одной конструкции или названия времён, и «не встречалось раньше»
      // ничего не значит.
      const generated = /-(l|r|pic)\d+$/.test(task.id ?? '')
      if (generated && task.type === 'single' && (task.choices?.length ?? 0) > 0) {
        const seenText = tasks.slice(0, i).map(taskText).join(' ')
        const strange = task.choices.filter(c => {
          const s = String(c).trim()
          // Считаем только варианты на ИЗУЧАЕМОМ письме (латиница, хангыль,
          // кана, иероглифы). Русское значение ученик читает и без урока —
          // незнакомым оно быть не может, и у курсов родного языка (где все
          // варианты русские) правило просто не срабатывает.
          if (!s || !/[A-Za-z가-힯぀-ヿ一-鿿]/.test(s)) return false
          return !seenBefore.has(s) && !seenText.includes(s)
        })
        if (strange.length > 1) {
          fail(where, `в задании ${i + 1} незнакомых вариантов ${strange.length}: ${strange.join(', ')} (Р9)`)
        }
      }
    })

    // Поля этого урока — в память курса, по одному значению на строку.
    for (const task of tasks) {
      for (const piece of taskFields(task)) seenBefore.add(piece)
    }

    // ── Р18. Урок обязан подниматься по лестнице ──
    //
    // Две половины одного правила. Первая: занятие доходит хотя бы до ступени
    // 5 — припоминания. Урок, замерший на выборе и сборке, ученик проходит,
    // ничего не достав из памяти сам (1.3, эффект генерации), и выглядит это
    // как пройденный урок. Вторая: нижний ярус (знакомство и узнавание) не
    // съедает больше половины времени.
    //
    // Ступень 6 в потолок урока НЕ ставится намеренно: по Р2 целевая ступень
    // внутри занятия — четвёртая, а продукция берётся повторениями следующих
    // уроков и колодой. Требовать её от каждого занятия значило бы спорить со
    // своим же стандартом.
    const top = Math.max(...tasks.map(taskStage))
    if (top < 5) {
      fail(where, `урок не поднимается выше ступени ${top}: ни припоминания, ни продукции (Р18)`)
    }
    const mix = stageMix(tasks)
    if (mix.seconds >= MIN_LADDER_SECONDS && mix.low > LOW_TIME_CAP) {
      fail(where, `на знакомство и узнавание уходит ${Math.round(mix.low * 100)}% времени урока, `
        + `потолок ${Math.round(LOW_TIME_CAP * 100)}% (Р18)`)
    }

    // Р13 — однотипные подряд. Исключены три вещи, где серия — это замысел:
    // карточки знакомства (порция и есть блок из трёх-четырёх карточек, Р3);
    // КРУГ — одна ступень по одному заданию на каждое слово порции, и тип у
    // круга по определению один (Р2): так устроена и лестница (`-l…`), и
    // экзамен порции (`-r…`), где каждое слово получает свой выбор из четырёх;
    // и группа вопросов к ОДНОМУ отрывку — решатель показывает текст один раз
    // на всю группу, это одно упражнение из нескольких вопросов, а не пять
    // одинаковых экранов подряд.
    let run = 1
    for (let i = 1; i < tasks.length; i++) {
      const ladder = /-[lr]\d+$/.test(tasks[i].id ?? '')
      const samePassage = !!tasks[i].passage && tasks[i].passage === tasks[i - 1].passage
      if (tasks[i].type === 'flashcard' || ladder || samePassage) { run = 1; continue }
      run = tasks[i].type === tasks[i - 1].type ? run + 1 : 1
      if (run > MAX_SAME_TYPE_RUN) {
        fail(where, `${run} заданий типа «${tasks[i].type}» подряд, потолок ${MAX_SAME_TYPE_RUN} (Р13)`)
        break
      }
    }
  }
  // Р15 — место верного ответа. Считаем по всему курсу, а не по уроку: в одном
  // уроке вопросов с выбором три-четыре, и «два из трёх на первом месте» — это
  // не перекос, а совпадение. Перекос виден только на всём курсе.
  if (choiceTotal >= 20) {
    const share = firstPlace / choiceTotal
    const chance = expectedFirst / choiceTotal
    if (share > chance + FIRST_PLACE_SLACK) {
      fail(seed.key, `верный ответ на первом месте в ${Math.round(share * 100)}% вопросов с выбором `
        + `(${firstPlace} из ${choiceTotal}); сам набор вопросов даёт ${Math.round(chance * 100)}% — `
        + `позиция считается от слова, а не пишется нулём (Р15)`)
    }
  }

  console.log(`${seed.key}: уроков ${lessons}`)
}

console.log(problems === 0
  ? '\nВсе уроки проходят стандарт.'
  : `\nНарушений: ${problems}`)
process.exit(problems === 0 ? 0 : 1)
