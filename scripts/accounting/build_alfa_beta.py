"""Учебные отчёты alfa.xls и beta.xls для уроков x06-03 и x06-13 (EXT06).

Структура как у 1С:ЗУП «Штатные сотрудники»: .xls (BIFF8), лист «Лист_1»,
шапка в строках 1–9, заголовки таблицы в строке 10, подразделение — строка-
подзаголовок, ставки текстом («1/4»). Данные вымышленные и совпадают с
таблицами-рисунками в ext06.ts. Запуск: python scripts/accounting/build_alfa_beta.py
"""
from pathlib import Path
import xlwt

OUT = Path(__file__).resolve().parents[2] / 'public/courses/accounting'
HEAD = lambda org: [['Штатные сотрудники'], ['Период: октябрь 2026'], [f'Организация: {org} (учебная)']] + [[]] * 6

FILES = {
    'alfa.xls': HEAD('Альфа') + [
        ['Строка отчёта', 'Сотрудник', 'Количество ставок', 'Оклад', 'Надбавка'],
        ['Управление'], [None, 'Иванов Иван Иванович', '1/4', 20000, 5000],
        ['Дорожный участок'], [None, 'Петров Пётр Петрович', '1', 40000, 8000],
    ],
    'beta.xls': HEAD('Бета') + [
        ['Строка отчёта', 'Код', 'Должность', 'Сотрудник', 'Оклад', 'Надбавка', 'Количество ставок'],
        ['Транспорт'], [None, '001', 'Диспетчер', 'Орлова Мария Сергеевна', 30000, 3000, '1/2'],
        [None, '002', 'Водитель', 'Ким Олег Сергеевич', 45000, 6000, '1'],
        ['Производство'], [None, '003', 'Мастер', ' иванов  иван   иванович ', 50000, 7000, '3/4'],
    ],
}

for name, grid in FILES.items():
    wb = xlwt.Workbook(encoding='utf-8')
    s = wb.add_sheet('Лист_1')
    for r, row in enumerate(grid):
        for c, v in enumerate(row):
            if v is not None:
                s.write(r, c, v)
    wb.save(str(OUT / name))
    print(name, (OUT / name).stat().st_size)
