def is_workday(d: date) -> bool:
    if d in WORKING_SATURDAYS:
        return True
    return d.weekday() < 5 and d not in HOLIDAYS


def shift_forward(d: date) -> date:
    while not is_workday(d):
        d += timedelta(days=1)
    return d


def last_workday_of_year(y: int) -> date:
    d = date(y, 12, 31)
    while not is_workday(d):
        d -= timedelta(days=1)
    return d


