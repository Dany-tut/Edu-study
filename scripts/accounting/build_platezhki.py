# ---- независимый расчёт эталонов -------------------------------------------
def expected(i, r):
    d, name, inv, total, adv, pay, dog_p, dog_i, vat, vat_n, acc_p, acc_d = r
    p1 = pay == total - adv
    p2 = dog_p == dog_i
    if vat == 'Без НДС':
        p3 = False  # в назначении указана сумма НДС при поставщике без НДС
    else:
        p3 = abs(vat_n - round(pay * 22 / 122, 2)) < 0.005
    p4 = acc_p == acc_d
    p5 = sum(1 for x in ROWS if (x[1], x[2], x[5]) == (name, inv, pay)) == 1
    return [p1, p2, p3, p4, p5]
EXP = [expected(i, r) for i, r in enumerate(ROWS)]
ERR_BY_CHECK = [sum(1 for e in EXP if not e[k]) for k in range(5)]
ERR_TOTAL = sum(ERR_BY_CHECK)
ROWS_WITH_ERR = sum(1 for e in EXP if not all(e))
assert ERR_BY_CHECK == [1, 1, 2, 1, 2], ERR_BY_CHECK
assert ROWS_WITH_ERR == 7

