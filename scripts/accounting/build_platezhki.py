    cnt_all = sum(1 for x in DUP if x[1:] == (n, inv, sm))
    cnt_up = sum(1 for x in DUP[:i - 1] if x[1:] == (n, inv, sm))
    e1 = 'дубль?' if cnt_all > 1 else ''
    e2 = 'повтор' if cnt_up > 1 else ''
    D_EXP.append((e1, e2))
    dp.cell(i, 7, e1)
    dp.cell(i, 8, e2)
    dp.cell(i, 9, f'=IF(AND(E{i}=G{i},F{i}=H{i}),"OK","ОШИБКА")')
