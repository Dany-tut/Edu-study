def xls_bytes(grid):
    import xlwt
    wb = xlwt.Workbook(encoding='utf-8')
    s = wb.add_sheet(SHEET)
    for r, row in enumerate(grid):
        for c, v in enumerate(row):
            if v is not None:
                s.write(r, c, v)
    b = io.BytesIO()
    wb.save(b)
    return b.getvalue()


def xlsx_bytes(rows, headers):
    wb = Workbook()
    s = wb.active
    s.title = 'Лист1'
    s.append(headers)
    for r in rows:
        s.append([v if v != '' else None for v in r])
    b = io.BytesIO()
    wb.save(b)
    return b.getvalue()


