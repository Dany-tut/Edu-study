# ─── Независимый расчёт эталонов в Python ────────────────────────────────────
def norm(s):
    return ' '.join(str(s or '').replace('\xa0', ' ').split())


def expected():
    rows = []
    for i, d in enumerate(DATA):
        r = 2 + i
        if d is None:
            continue
        m, org, pid, fio, rate, flag, _ = d
        rows.append(dict(r=r, m=norm(m), org=norm(org), id=norm(pid),
                         fio=norm(fio).upper().replace('Ё', 'Е'), rate=rate,
                         flag=norm(flag).upper()))
    by_id = defaultdict(list)
    for x in rows:
        if x['id']:
            by_id[x['id']].append(x)
    keys = defaultdict(int)
    for x in rows:
        keys[(x['id'], x['org'], x['rate'], x['flag'])] += 1
    for x in rows:
        same = by_id.get(x['id'], [])
        if not x['id']:
            p = 'Нет ID'
        elif not x['org']:
            p = 'Нет организации'
        elif x['m'] and x['m'] != MONTH:
            p = 'Другой месяц'
        elif x['org'] not in ORGS:
            p = 'Организации нет в списке Итогов'
        elif not isinstance(x['rate'], (int, float)) or x['rate'] <= 0:
            p = 'Ставка не число или ≤ 0'
        elif not x['flag']:
            p = 'Пустой признак'
        elif x['flag'] not in ('ОСН', 'СОВ', 'ДЕКРЕТ'):
            p = 'Неизвестный признак'
        elif keys[(x['id'], x['org'], x['rate'], x['flag'])] > 1:
            p = 'Дубль строки'
        elif sum(1 for y in same if y['org'] == x['org']) > 1:
            p = 'Несколько строк ID в одной организации'
        elif any(y['fio'] != x['fio'] for y in same):
            p = 'У ID разные ФИО'
        else:
            p = ''
        x['prob'] = p
    for x in rows:
        same = by_id.get(x['id'], [])
        n_main = sum(1 for y in same if y['flag'] in ('ОСН', 'ДЕКРЕТ'))
        n_sov = sum(1 for y in same if y['flag'] == 'СОВ')
        n_prob = sum(1 for y in same if y['prob'])
        bad = bool(x['prob']) or not x['id'] or n_prob > 0 or n_main != 1 or len(same) != n_main + n_sov
        x['status'] = 'Проверить' if bad else x['flag']
        if not bad:
            x['reason'] = ''
        elif x['prob']:
            x['reason'] = x['prob']
        elif n_prob > 0:
            x['reason'] = 'Ошибка в другой строке этого ID'
        elif n_main == 0:
            x['reason'] = 'Нет ОСН/ДЕКРЕТ'
        elif n_main > 1:
            x['reason'] = 'Несколько ОСН/ДЕКРЕТ'
        else:
            x['reason'] = 'Есть строка без признака'
        x['count'] = 1 if x['status'] in ('ОСН', 'ДЕКРЕТ') else 0
    ids = sorted(by_id)
    unresolved = [i for i in ids if any(y['status'] == 'Проверить' for y in by_id[i])]
    per_org = {}
    for o in ORGS:
        rr = [x for x in rows if x['org'] == o]
        per_org[o] = dict(
            records=len(rr), rates=sum(x['rate'] for x in rr),
            osn=sum(x['status'] == 'ОСН' for x in rr), sov=sum(x['status'] == 'СОВ' for x in rr),
            dek=sum(x['status'] == 'ДЕКРЕТ' for x in rr), chk=sum(x['status'] == 'Проверить' for x in rr),
            counted=sum(x['count'] for x in rr), uniq=len({x['id'] for x in rr if x['id']}))
    return dict(rows=rows, records=len(rows), uniq=len(ids), counted=sum(x['count'] for x in rows),
                unresolved=len(unresolved), noid=sum(1 for x in rows if not x['id']),
                rates=sum(x['rate'] for x in rows), chk_rows=sum(x['status'] == 'Проверить' for x in rows),
                per_org=per_org, agg=sum(a[2] for a in AGG))


