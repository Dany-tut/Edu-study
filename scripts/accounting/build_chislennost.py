def report_grid(f, salt=0):
    """2D-список ячеек листа «Лист_1» (строка 1 = индекс 0). None — пустая ячейка."""
    name, title, fio_c, rate_c, depts = f
    width = max(fio_c, rate_c) + 1
    grid = [[None] * width for _ in range(9)]
    grid[0][0] = 'Штатные сотрудники'
    grid[1][0] = 'Дата отчёта: 31.10.2026'
    grid[2][0] = f'Организация: {title}' if title else None
    grid[4][0] = 'Отбор: Сотрудник.Состояние = Работает'
    head = [None] * width
    k = 0
    for c in range(1, width + 1):
        if c == fio_c:
            head[c - 1] = HDR_FIO
        elif c == rate_c:
            head[c - 1] = HDR_RATE
        elif c == 1:
            head[c - 1] = 'Подразделение'
        else:
            head[c - 1] = OTHER_HEADERS[k % len(OTHER_HEADERS)]
            k += 1
    grid.append(head)
    n = 0
    rnd = random.Random(len(name) * 7 + salt)
    for dept, emps in depts:
        row = [None] * width
        row[0] = dept
        grid.append(row)
        for fio, rate in emps:
            n += 1
            row = [None] * width
            row[fio_c - 1] = fio
            row[rate_c - 1] = rate
            for c in range(2, width + 1):
                if c in (fio_c, rate_c):
                    continue
                h = head[c - 1]
                if h == 'Табельный номер':
                    row[c - 1] = f'00-{rnd.randint(100, 999):06d}'
                elif h == 'Должность':
                    row[c - 1] = rnd.choice(POSTS)
                elif h in ('Оклад', 'ФОТ', 'Тариф', 'Надбавка'):
                    row[c - 1] = rnd.randint(30, 90) * 1000
                elif h == 'Вид занятости':
                    row[c - 1] = 'Основное место работы'
            grid.append(row)
    total = [None] * width
    total[0] = f'Итого сотрудников: {n}'
    grid.append(total)
    return grid


def paste_grid(files):
    """Лист «Вставка исходника»: столбец A — имя файла на первой строке блока, отчёт — с B."""
    out = []
    for f in files:
        g = report_grid(f)
        for i, row in enumerate(g):
            out.append([f[0] if i == 0 else None] + row)
        out.append([None])
    return out


# ─── Независимый расчёт на Python ────────────────────────────────────────────
def norm(s):
    return ' '.join(str('' if s is None else s).replace('\xa0', ' ').split())


def key(s):
    return norm(s).upper().replace('Ё', 'Е')


def org_key(s):
    k = key(s)
    for ext in ('.XLSX', '.XLS'):
        k = k.replace(ext, '')
    return k.strip()


def ru_sort_key(s):
    return [RU.index(ch) if ch in RU else 100 + ord(ch) for ch in key(s)]


def parse_rate(v):
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return float(v)
    t = norm(v)
    if not t:
        return None
    try:
        if '/' in t:
            a, b = t.split('/', 1)
            return float(a.replace(',', '.')) / float(b.replace(',', '.'))
        return float(t.replace(',', '.'))
    except (ValueError, ZeroDivisionError):
        return None


