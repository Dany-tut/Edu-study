    dec = dict(LAD_DEC)
    for r, (o, fio, dept, rate, rk) in enumerate(LAD, 2):
        a, b = LAD_GROUPS[r]
        grp = [LAD[i - 2] for i in range(a, b + 1)]
        higher = sum(1 for g in grp if g[3] > rate)
        earlier = sum(1 for g in grp if g[3] == rate and g[4] < rk)
        dorg = dec.get(fio, '')
        cat = 'ДЕКРЕТ' if dorg == o else ('ОСН' if higher == 0 and earlier == 0 else 'СОВ')
        out[r] = dict(F=higher, G=earlier, H=dorg, I=cat, L=int(cat == 'ОСН'), M=int(cat == 'СОВ'), N=int(cat == 'ДЕКРЕТ'), O=0)
    people = {}
    for fio in dict.fromkeys(x[1] for x in LAD):
        rows = [r for r in out if LAD[r - 2][1] == fio]
        people[fio] = dict(B=len(rows), C=dec.get(fio, ''), D=sum(out[r]['L'] + out[r]['N'] for r in rows))
    sver = {o: sum(out[r]['L'] for r in out if LAD[r - 2][0] == o) for o in ('ВЕСТА', 'Деметра', 'ХАД')}
