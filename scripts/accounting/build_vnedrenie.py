# ── Проверка: эталоны в Python ────────────────────────────────────────────────
avg = lambda xs: sum(xs) / len(xs)
ref = []
total_h = 0
for i, (name, n, b, a) in enumerate(TIME, 2):
    save = avg(b) - avg(a)
    yh = round(save * n / 60, 1)
    total_h += yh
    ref.append((f'{name}: до, среднее, мин', avg(b), f"='Замер времени'!I{i}"))
    ref.append((f'{name}: после, среднее, мин', avg(a), f"='Замер времени'!J{i}"))
    ref.append((f'{name}: экономия в год, ч', yh, f"='Замер времени'!L{i}"))
ref.append(('Экономия в год по пяти проектам, ч', round(total_h, 1), "='Замер времени'!L7"))
ref.append(('Сокращение времени проекта А, доля', round((210 - 15) / 210, 3), "='Замер времени'!M2"))
ref.append(('Строк «СТОП» в «Полнота и точность»', 1, "='Полнота и точность'!F10"))
ref.append(('Параллельный прогон: строк с разницей', 2, "='Параллельный прогон'!E7"))
ref.append(('Параллельный прогон: разница ХАД H + G', 0, "='Параллельный прогон'!E6"))
ref.append(('Параллельный прогон: разниц без причины', 0, "='Параллельный прогон'!G8"))
ref.append(('Образцы: ИНН не с «00»', sum(1 for o in ORGS if not o[3].startswith('00')), "=COUNTIF('Образцы'!E2:E11,\"ПРОВЕРИТЬ\")"))
