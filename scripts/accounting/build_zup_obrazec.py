RULES = [('Основное место работы', 'ОСН'), ('Внешнее совместительство', 'СОВ'), ('Внутреннее совместительство', 'СОВ')]
# эталон: столбец E листа «Сотрудники» практикума
PRACTICUM_E = ['ОСН', 'СОВ', 'СОВ', 'ОСН', 'ДЕКРЕТ', 'ОСН', '', '', 'СОВ', 'ОСН']


def rule(kind: str, state: str) -> str:
    if not kind:
        return ''
    if kind == 'Основное место работы' and 'уход' in state.lower():
        return 'ДЕКРЕТ'
    return dict(RULES).get(kind, '')


HEAD = Font(bold=True)
FILL = PatternFill('solid', fgColor='EAF1FB')
WRAP = Alignment(wrap_text=True, vertical='top')


def header(ws, cols):
    ws.append(cols)
    for c in ws[1]:
        c.font = HEAD
        c.fill = FILL
        c.alignment = WRAP


