def org_file(rows, cols=('Организация', 'ID человека', 'ФИО', 'Ставка', 'Признак')) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = 'Лист1'
    ws.append(list(cols))
    for r in rows:
        ws.append(r)
    bio = io.BytesIO()
    wb.save(bio)
    return bio.getvalue()


def build_zip():
    code2id = dict(IDMAP)
    by_org: dict[str, list] = {}
    for r in RAW:
        by_org.setdefault(r[0], []).append([r[0], code2id[r[1]], r[2], r[4], rule(r[5], r[6])])
    names = {'Альфа': 'alfa', 'Бета': 'beta', 'Гамма': 'gamma'}
    readme = (
        'Учебная папка месяца 2026-10 для урока m14-08 (Power Query: «Из папки»). Данные вымышлены.\n'
        'Распакуйте архив, например, в C:\\Выгрузки\\2026-10 и укажите этот путь в коде запросов.\n'
        'В папке 2026-10: alfa-2026-10.xlsx (4 строки), beta-2026-10.xlsx (3), gamma-2026-10.xlsx (3) — всего 10 строк, 7 ID.\n'
        'Папка oshibka: gamma-2026-10-oshibka.xlsx — тот же файл, но столбец «Ставка» переименован в «Ставка, ед.».\n'
        'Тренировка журнала: скопируйте файл из oshibka в папку месяца — «Журнал ошибок» должен показать «Нет нужных столбцов: Ставка».\n'
        'Эталон без файла с ошибкой: запрос «Выгрузки» — 10 строк; на «Итогах» шаблона — 10 записей, 7 уникальных людей.\n'
    )
    with zipfile.ZipFile(ZIP, 'w', zipfile.ZIP_DEFLATED) as z:
        for org, rows in by_org.items():
            z.writestr(f'2026-10/{names[org]}-2026-10.xlsx', org_file(rows))
        z.writestr('oshibka/gamma-2026-10-oshibka.xlsx',
                   org_file(by_org['Гамма'], ('Организация', 'ID человека', 'ФИО', 'Ставка, ед.', 'Признак')))
        z.writestr('README.txt', readme)
    print('saved', ZIP, {k: len(v) for k, v in by_org.items()})


if __name__ == '__main__':
    build_xlsx()
