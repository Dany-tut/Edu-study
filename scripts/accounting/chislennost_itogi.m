// Запрос «Итоги» — пустой запрос, который ссылается на запрос «Расчёт».
// Даёт по каждому периоду и организации столбцы годовой таблицы руководителя: D, F, G и проверку H.
let
    Источник = Расчёт,
    Итоги = Table.Group(Table.SelectRows(Источник, each [Организация] <> null), {"Период", "Организация"}, {
        {"D итого строк", each Table.RowCount(_), Int64.Type},
        {"F ДЕКРЕТ", each List.Count(List.Select([Категория], each _ = "ДЕКРЕТ")), Int64.Type},
        {"G СОВ", each List.Count(List.Select([Категория], each _ = "СОВ")), Int64.Type},
        {"ОСН", each List.Count(List.Select([Категория], each _ = "ОСН")), Int64.Type},
        {"Проверить", each List.Count(List.Select([Категория], each _ = "Проверить")), Int64.Type},
        {"Сумма ставок", each List.Sum([Ставка]), type number}}),
    СH = Table.AddColumn(Итоги, "H = D − F − G", each [D итого строк] - [F ДЕКРЕТ] - [G СОВ], Int64.Type),
    СКонтролем = Table.AddColumn(СH, "Контроль H − ОСН", each [#"H = D − F − G"] - [ОСН], Int64.Type)
in
    СКонтролем

