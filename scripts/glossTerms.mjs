// Что из карточки урока считается СЛОВОМ для словаря тапа.
//
// Правила лежат отдельно, потому что их двое пользуются и расходиться им
// нельзя: buildGlossSeed.mjs по ним собирает словарь, checkGloss.mjs по ним же
// проверяет, что каждое такое слово тапается целиком. Разъедься они — сторож
// начнёт требовать то, чего генератор не кладёт.

/** Курсы родного языка: на лице карточки толкование, а слово русское. */
export const NATIVE_KEYS = new Set(['ruzh', 'ruvo', 'rulit'])

/** Письменность без пробелов внутри слова. */
const DENSE = new Set(['ko', 'ja'])

/**
 * Потолок длины слова — защита от фраз, записанных без пробелов: в
 * разговорниках попадаются карточки вроде ここでこうきょうりょうきんがはらえますか,
 * и такая запись в словаре склеила бы целое предложение в один тап.
 */
const MAX_DENSE = 10
const MAX_LATIN = 24

/** Своя письменность языка: карточка без неё (голое число, значок) не слово. */
export const SCRIPT = {
  en: /[A-Za-z]/,
  'pt-BR': /[A-Za-zÀ-ÖØ-öø-ÿ]/,
  de: /[A-Za-zÄÖÜäöüß]/,
  ko: /[가-힣ㄱ-ㅎㅏ-ㅣ]/,
  ja: /[぀-ヿ㐀-䶿一-鿿々ー]/,
}

/**
 * Учебная запись, а не слово: «(으)려고» — окончание со скобками вокруг
 * необязательной части, «…はどこですか» — шаблон фразы с местом для подстановки.
 * В тексте они в таком виде не встречаются никогда.
 */
const NOT_A_WORD = /[()（）[\]…、。，,.!?？！:;・]/

/**
 * Знаки по краям снимаются: на карточке разговорника стоит «화이팅!» и
 * «얼마예요?», а в словаре слово живёт без восклицания — иначе оно не найдётся
 * ни в одном тексте, где на его месте стоит запятая.
 */
const EDGE = /^[~～〜\s.,!?！？。、…·—–-]+|[~～〜\s.,!?！？。、…·—–]+$/g

/** Слово карточки без учебной оправы. */
export const bare = raw => String(raw ?? '').replace(EDGE, '').trim()

/**
 * Перевод карточки как словарная строка.
 *
 * У глагольных карточек на обороте стоит ещё и форма, ради которой слово взято
 * («идти → 가요»): в карточке это подсказка, в словаре — мусор, потому что
 * тапают по слову, а не по его спряжению.
 */
export const meaning = raw => String(raw ?? '').split(/\s*(?:→|➝|->)\s*/)[0].replace(/\s+/g, ' ').trim()

/**
 * Слова одной карточки: «あける / あく» — это два слова с общим переводом, а
 * «～てしまう» — то же てしまう с учебной тильдой на месте основы.
 *
 * Фразы и предложения сюда не попадают: тап по слову фразы должен разбирать
 * фразу, а не выделять её целиком.
 */
export function cardTerms(front, lang) {
  const own = SCRIPT[lang]
  if (!own) return []
  const max = DENSE.has(lang) ? MAX_DENSE : MAX_LATIN
  return String(front ?? '')
    .split(/\s+\/\s+/)
    .map(bare)
    .filter(t => t && !/\s/.test(t) && !NOT_A_WORD.test(t) && t.length <= max && own.test(t))
}
