import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// Static JSX, never runtime HTML: the same original paths used by the Figma kit.
const root = new URL('../', import.meta.url)
const glyphs = JSON.parse(readFileSync(new URL('design/ios-concepts/loop-kit/glyphs.json', root), 'utf8'))
const body = svg => svg.replace(/^<svg\b[^>]*>/, '').replace(/<\/svg>$/, '')
// The feed needs a plain like-heart, in addition to the curriculum's HeartPulse.
glyphs.push({ name: 'Heart', svg: `<svg>${body(glyphs.find(g => g.name === 'HeartPulse').svg).replace(/<g\b[\s\S]*<\/g>/, '')}</svg>` })
const teacher = `<svg><g transform="translate(6 -1) scale(.6)">${body(glyphs.find(g => g.name === 'User').svg)}</g><g transform="translate(2 13) scale(.85 .6)">${body(glyphs.find(g => g.name === 'BookOpen').svg)}</g></svg>`
const artwork = [...glyphs, { name: 'TeacherBook', svg: teacher }]
const jsx = svg => body(svg)
  .replace(/\s*stroke-width="2\.3"/g, '')
  .replace(/([a-z]+)-([a-z-]+)=/g, (_, a, b) => a + b.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join('') + '=')
  .replaceAll('#5C47BD', 'currentColor')
  .replaceAll('#F4A55A', 'var(--loop-detail, #F4A55A)')
  .replaceAll('#ECE5FF', 'var(--loop-soft, #ECE5FF)')
const banner = '// Generated by scripts/buildLoopIcons.mjs. Edit the original Loop SVG sources, then regenerate.\n'
const check = process.argv.includes('--check')
function emit(path, source) {
  const url = new URL(path, root)
  if (check) {
    if (readFileSync(url, 'utf8') !== source) throw new Error(`${path} is stale; run npm run icons:generate`)
  } else writeFileSync(url, source)
}
emit('src/components/icons/loopArtwork.tsx', banner + artwork.map(g =>
  `export const LoopArtwork${g.name} = <>${jsx(g.svg)}</>\n`,
).join('\n'))
emit('src/components/icons/appIcons.tsx', banner + `
// Only the icons used by the app. The desktop constructor imports its full
// picker namespace directly from Lucide, keeping that catalog in its lazy chunk.
export type { LucideIcon, LucideProps, IconNode } from 'lucide-react'
import { createLucideIcon as createDesktopIcon } from 'lucide-react'
import type { IconNode } from 'lucide-react'
import { createResponsiveIcon } from './LoopIcon'
${glyphs.map(g => `import { ${g.name} as Desktop${g.name} } from 'lucide-react'\nimport { LoopArtwork${g.name} } from './loopArtwork'`).join('\n')}
import { LoopArtworkTeacherBook } from './loopArtwork'

${glyphs.map(g => `export const ${g.name} = /* @__PURE__ */ createResponsiveIcon('${g.name}', Desktop${g.name}, LoopArtwork${g.name})`).join('\n')}

export function createLucideIcon(name: string, iconNode: IconNode) {
  const Desktop = createDesktopIcon(name, iconNode)
  return name === 'TeacherBook' ? createResponsiveIcon(name, Desktop, LoopArtworkTeacherBook) : Desktop
}
`)
console.log(`${check ? 'Verified' : 'Generated'} ${artwork.length} Loop drawings and ${glyphs.length} responsive exports in ${fileURLToPath(root)}`)
