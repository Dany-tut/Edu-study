// Сторож разбора вставленного списка и угадывания языка.
//
// ЗАЧЕМ. Учитель приносит слова не по одному: он копирует список из чужого
// набора, из таблицы, из конспекта — и весь этот путь держится на трёх чистых
// функциях с неочевидными правилами:
//
//   parseBulk    — «слово — перевод» в строку ИЛИ парами строк; разделитель
//                  выбирается порогом: меньше трети строк с тире — считаем, что
//                  перед нами пары строк.
//   readPasted   — отделяет заголовок от карточек: в парах-в-строку это строка
//                  без разделителя, в парах-строками — лишняя строка при
//                  нечётном счёте.
//   guessLang    — язык по письменности терминов; латиница делится на немецкий,
//                  португальский и английский по надстрочным знакам, а при
//                  мешанине письменностей молчит.
//
// Все три ломаются МОЛЧА. Сдвинешь порог на четверть — вставка из Quizlet
// начнёт склеивать слово с переводом; ошибёшься в чётности — весь список
// съедет на строку и каждая карточка станет «перевод — следующее слово»; так
// же тихо соседний язык подменит предмет у набора. Ни типизация, ни сборка
// этого не видят: функции остаются валидными, просто отвечают неверно.
//
// ПОЧЕМУ СКРИПТОМ, А НЕ ТЕСТОВЫМ РАННЕРОМ. В проекте нет тестового раннера, и
// заводить его ради трёх функций — значит принести конфиг, зависимости и второй
// способ «проверить», который никто не запускает. Проверки здесь живут
// скриптами (check:i18n, check:gloss, check:prose), запускаются одной командой
// и падают с человеческим объяснением. Этот — такой же.
//
// Запуск: npm run check:cards

import { readFileSync } from 'node:fs'

// ── Разбор исходников ────────────────────────────────────────────────────────
//
// Функции берутся ИЗ КОДА, а не переписываются здесь: копия правил разошлась бы
// с оригиналом на первой же правке, и сторож охранял бы сам себя.
//
// Типы снимает esbuild (он и так собирает проект), а не регулярка: первая же
// самодельная попытка приняла `{ term: lines[i] }` за аннотацию типа и съела
// половину строки — сторож «проверял» код, которого в проекте нет.

import { transformSync } from 'esbuild'

/** Кусок файла от объявления до закрывающей скобки в нулевой колонке. */
function cut(src, head, what) {
  const start = src.indexOf(head)
  if (start < 0) {
    console.error(`❌ ${what} не найдено — переименовали или унесли в другой файл.`)
    process.exit(1)
  }
  const end = src.indexOf('\n}\n', start)
  return src.slice(start, end + 3).replace(/^export /, '')
}

const MANAGER = readFileSync('src/components/teacher/CardGroupsManager.tsx', 'utf8')
const GUESS = readFileSync('src/lib/guessLang.ts', 'utf8')

const ts = [
  MANAGER.match(/const PAIR = [^\n]+/)?.[0] ?? '',
  cut(MANAGER, 'export function parseBulk(', 'parseBulk'),
  cut(MANAGER, 'export function readPasted(', 'readPasted'),
  GUESS.match(/const (HANGUL|KANA|HAN|CYRILLIC|LATIN) = [^\n]+/g).join('\n'),
  cut(GUESS, 'function latinFlavor(', 'latinFlavor'),
  cut(GUESS, 'export function guessLang(', 'guessLang'),
  'export { parseBulk, readPasted, guessLang }',
].join('\n\n')

const { code } = transformSync(ts, { loader: 'ts', format: 'esm' })
const { parseBulk, readPasted, guessLang } =
  await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)

// ── Случаи ───────────────────────────────────────────────────────────────────

const cases = []
const check = (name, got, want) => cases.push({ name, ok: JSON.stringify(got) === JSON.stringify(want), got, want })

// Классика: пара в строку, разные разделители.
check('тире', parseBulk('hunter — охотник').map(c => [c.term, c.ru]), [['hunter', 'охотник']])
check('табуляция', parseBulk('hunter\tохотник').map(c => [c.term, c.ru]), [['hunter', 'охотник']])
// Дефис ВНУТРИ слова разделителем не считается — иначе половина английских
// карточек развалилась бы посередине.
check('дефис внутри слова', parseBulk('well-known — всем известный').map(c => c.term), ['well-known'])

// Пары строками — так копируется чужой набор со страницы.
check('пары строк', parseBulk('Систематика\nнаука о классификации\nГистология\nткани').map(c => [c.term, c.ru]),
  [['Систематика', 'наука о классификации'], ['Гистология', 'ткани']])

// ГРАНИЦА ПОРОГА — ровно то, что ломается при правке «на глаз». Четыре строки,
// тире ровно в одной (внутри определения): при пороге в треть это пары строк и
// две карточки, при пороге в четверть — одна карточка из строки с тире, а три
// остальных слова исчезают молча.
check('порог: тире внутри определения не переключает режим',
  parseBulk('Систематика\nнаука о классификации — и о связях\nГистология\nткани').map(c => c.term),
  ['Систематика', 'Гистология'])

// Заголовок в пачке пар-в-строку не должен ломать разбор остальных строк.
check('заголовок среди пар', parseBulk('Unit 3\nhunter — охотник\nsalt — соль').length, 2)

// Заголовок отделяется: в парах-в-строку — по отсутствию разделителя.
check('название из пар-в-строку', readPasted('Разделы биологии\nЦитология — клетка\nГистология — ткани').title,
  'Разделы биологии')
// В парах-строками — по нечётному числу строк.
check('название из пар-строками', readPasted('Разделы биологии\nЦитология\nклетка\nГистология\nткани').title,
  'Разделы биологии')
// Чётный список без заголовка названия не выдумывает.
check('без названия', readPasted('Цитология\nклетка\nГистология\nткани').title, undefined)

// Язык — по письменности ТЕРМИНОВ.
check('корейский', guessLang(['안녕하세요', '사랑', '물']), 'ko')
check('японский', guessLang(['こんにちは', '水', '火']), 'ja')
check('русский', guessLang(['Систематика', 'Гистология', 'Микология']), 'ru')
check('английский', guessLang(['hunter', 'salt and burn', 'well-known']), 'en')
check('немецкий', guessLang(['der Löffel', 'die Straße', 'das Mädchen']), 'de')
check('португальский', guessLang(['coração', 'irmã', 'feijão']), 'pt-BR')
// Мешанина письменностей — молчим: подставленный наугад язык не виден глазом и
// всплывает озвучкой, читающей корейское слово по-английски.
check('вперемешку — молчит', guessLang(['hunter', '안녕', 'водоросли', 'こんにちは']), null)
check('пусто — молчит', guessLang([]), null)

// ── Вывод ────────────────────────────────────────────────────────────────────

const bad = cases.filter(c => !c.ok)
for (const c of bad) {
  console.error(`❌ ${c.name}\n   ждали: ${JSON.stringify(c.want)}\n   вышло: ${JSON.stringify(c.got)}`)
}
if (bad.length) {
  console.error(`\n${bad.length} из ${cases.length} — разбор вставки сломан.`)
  process.exit(1)
}
console.log(`✅ разбор вставки и угадывание языка: ${cases.length} случаев`)
